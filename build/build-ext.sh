#!/bin/sh
# Собирает расширенный бинарник под одну архитектуру — в одной из двух РОЛЕЙ.
#
# Роли появились вместе со звездой xsteer, и не ради удобства. Хабу нужна криптография, то
# есть mbedtls, то есть расширенная сборка; а на роутере хабу делать нечего — подкоманды,
# поднимающей слушателя на публичном порту, там быть не должно. Отсюда две роли:
#
#   router (по умолчанию) — движок, клиент VLESS/Reality и клиент xsteer. Едет в пакет.
#   server                — движок, хаб xsteer. Едет в архив для VPS.
#
# Гейт стоит на СПИСКАХ ФАЙЛОВ, а не внутри их тел, и это важно: цель ext-syntax в Makefile
# гоняет -fsyntax-only по всем файлам расширенной части, и файл, целиком спрятанный под #ifdef, проходил
# бы проверку «пустым» — то есть ровно тот откат, ради которого ext-syntax и появилась.
# Поэтому цикл спицы живёт в xsclient.c, цикл хаба в xshub.c, а различаются только списки.
#
# Вынесено из build.sh отдельным файлом, а не оставлено строкой в `docker run -c`: там всё
# это жило внутри двойных кавычек с экранированием, и флаги -I терялись при подстановке —
# ошибка выглядела как «mbedtls/sha256.h не найден», то есть будто заголовков нет в образе.
# Скрипт в файле читается буквально, и подобный класс ошибок в нём невозможен.
#
# Пути к исходникам ниже АБСОЛЮТНЫЕ, и это не стиль: сборка делает cd в каталог mbedtls
# (см. WORK), после чего относительный путь не находится — ошибка выглядела как
# «FileNotFound: src/proto/tls/tls13.c», то есть будто файла нет вовсе.
set -eu

TARGET="$1"
MCPU="${2:-}"
OUT="$3"
# Версия приходит четвёртым аргументом, а не читается из VERSION: скрипт работает внутри
# контейнера после cd в каталог mbedtls, и относительный путь к файлу оттуда не находится.
# Умолчание нужно ради ручного запуска с тремя аргументами.
VERSION="${4:-dev}"
# Роль: router (умолчание) или server. Пятым аргументом, чтобы прежние вызовы с четырьмя
# аргументами продолжали значить то же, что значили.
ROLE="${5:-router}"
# Ревизия сборки — шестым аргументом и по той же причине, что версия: git внутри образа нет,
# а каталога .git там нет и подавно (смонтирован только рабочий каталог). Умолчание честное:
# «неизвестна» лучше числа, которое ничему не соответствует, — печатает её `steer --version`
# (R-045).
REV="${6:-неизвестна}"

MBED_INC=/opt/mbedtls/include
EXT_INC=/src/src/proto/tls
# Имя файла НЕ mbedtls_config.h, и это не вкусовщина.
#
# build_info.h делает `#include MBEDTLS_CONFIG_FILE` кавычками, а кавычки ищутся сначала
# рядом с включающим файлом — то есть в /opt/mbedtls/include/mbedtls/, где лежит
# mbedtls_config.h самой библиотеки. Наш файл с тем же именем не выигрывал у него НИКОГДА:
# mbedtls собиралась с ПОЛНОЙ конфигурацией по умолчанию, со своим TLS-стеком, DTLS, RSA,
# X.509 и таблицами OID, а весь src/ext/mbedtls_config.h был мёртвым текстом.
#
# Обнаружилось по строкам «id-ce-certificatePolicies» в готовом бинарнике: их там быть не
# могло, X509 в нашей конфигурации выключен. Цена молчаливая — 240 КБ флеша на overlay в
# 6,9 МБ.
CFG='-DMBEDTLS_CONFIG_FILE="steer_mbedtls_config.h"'

WORK="/tmp/mb-$(echo "$TARGET$MCPU" | tr -c 'a-zA-Z0-9' '_')"
mkdir -p "$WORK"
cd "$WORK"

# Оптимизация: -O2, а не -Os, и только для этой половины сборки.
#
# Через AEAD проходит ВЕСЬ трафик туннеля, и потолок шифрования — это потолок скорости. -Os
# на крипто экономит десятки килобайт и стоит десятков процентов пропускной способности:
# обмен, который для базового движка выгоден (там размер решает, влезет ли пакет), а здесь
# ровно наоборот. Базовый пакет собирается с -Os по-прежнему, см. build.sh.
OPT=-O2

# mbedtls компилируется ЦЕЛИКОМ: линковщик возьмёт только используемое, а ручной отбор
# модулей превращается в игру «кто кого тянет» — проверено на rsa_alt_helpers, который
# исключался шаблоном *_alt* и ломал сборку неочевидным образом.
# АППАРАТНЫЙ AES НА x86_64: ОДИН ФАЙЛ СОБИРАЕТСЯ С ТРЕМЯ ФЛАГАМИ, И ЭТО ЗАМЕР, А НЕ ВКУС.
#
# MBEDTLS_AESNI_C в конфигурации включён, CPUID на сервере говорит AES=1 CLMUL=1, — и всё
# равно AES-128-GCM давал 309 МБ/с (4662 нс на пакет 1439 Б). Причина в том, КАКОЙ из двух
# путей mbedtls выбирает: без флагов набора команд она берёт ассемблерный путь
# (MBEDTLS_AESNI_HAVE_CODE 1), а быстрый путь на intrinsics (2) включается только когда
# компилятору РАЗРЕШЕНО их выпускать. Замер на этой машине (Ryzen 9 7950X3D, mbedtls 3.6.2):
#
#     как было (ассемблер)                     309 МБ/с   2.47 Гбит/с
#     -maes -mpclmul                           307 МБ/с   — без -msse4.1 ничего не меняется
#     -maes -mpclmul -msse4.1                  450 МБ/с   3.60 Гбит/с   (+45%)
#
# SSE4.1 обязателен потому, что код GHASH на intrinsics пользуется вставкой и извлечением
# 64-битных половин регистра, а это его команды. Требование безобидное: SSE4.1 старше AES-NI
# (2008 против 2010), то есть процессора с AES-NI и без SSE4.1 не существует.
#
# ПОЧЕМУ ЭТО НЕ ЛОМАЕТ СТАРЫЕ ПРОЦЕССОРЫ. Флаги даются РОВНО ОДНОМУ файлу — aesni.c, — а весь
# код в нём вызывается только после проверки mbedtls_aesni_has_support() по CPUID. Остальная
# библиотека и весь движок по-прежнему собираются под baseline, то есть бинарник запускается
# там, где запускался. Дать флаги всей библиотеке было бы и не быстрее (замерено: те же
# 439-450 МБ/с), и опасно: компилятор выпустил бы новые команды в коде без проверок.
#
# У ЭТОГО РЕШЕНИЯ ЕСТЬ ЦЕНА, И ОНА НЕ ОЧЕВИДНА: РАСХОЖДЕНИЕ ВНУТРИ САМОЙ mbedtls.
#
# Ключ -maes ставит компилятору макрос __AES__, а из него mbedtls выводит MBEDTLS_AESNI_HAVE_CODE.
# В aesni.c (с флагами) он равен 2 — «интринсики», и они читают массив раундовых ключей
# выровненной командой SSE, то есть требуют адреса, кратного шестнадцати. В aes.c (без флагов)
# он равен 1 — «ассемблерная вставка», которой выравнивание не нужно, — и mbedtls_aes_rk_offset,
# который как раз и выравнивает ключи внутри контекста, там выключается вовсе.
#
# Итог: контекст AES, оказавшийся по адресу, кратному четырём, а не шестнадцати, роняет
# setkey общей защитой памяти. Ловушка тихая — падение зависит от того, как сложился кадр
# стека, — и стоила разбора с SIGSEGV по нулевому адресу. Наши контексты выровнены явно (см.
# STEER_AES_ALIGN16 в src/proto/tgws/tgws.c); собственные контексты mbedtls живут в куче, а malloc и
# так даёт нужное выравнивание. Если когда-нибудь появится ещё один свой mbedtls_aes_context —
# выравнивать его обязательно.
#
# Что это даёт на туннеле: одиночный поток 930-970 → 1120-1140 Мбит/с (+19%) на живом стенде
# tests/run-xsteer-stream.sh. Остаток разрыва с реализацией на Go (у неё AES-GCM 4211 МБ/с —
# в тринадцать раз быстрее) в mbedtls не закрывается вовсе: она шифрует и считает GHASH ПО
# ОДНОМУ 16-байтному блоку на вызов функции, без чередования, и это её устройство, а не
# настройка.
AESNI_FLAGS=
case "$TARGET" in
    x86_64-*) AESNI_FLAGS="-maes -mpclmul -msse4.1" ;;
esac

# ОШИБКА КОМПИЛЯЦИИ МОДУЛЯ НЕ ГЛУШИТСЯ. Прежде строка кончалась на `2>/dev/null || true`, и
# провал модуля был неотличим от его отсутствия в наборе: stderr выброшен, код возврата
# подавлен. Модуль доживал до компоновки и превращался там в неопределённую ссылку на символ —
# а строка, объясняющая почему, была стёрта на предыдущем шаге. «Собираем всё» не требует
# «молчим обо всём»: компилируется по-прежнему вся библиотека, но каждый отказ называется на
# месте, вместе с текстом компилятора.
#
# Формулировка отказа содержит «не удалась» осознанно: ровно это слово читает барьер релиза
# (.github/workflows/release.yml грепает build.log по 'FAILED|не удалась|packaging failed'),
# поэтому релиз с недособранной криптографией остановится сам, а локальная сборка идёт дальше
# до компоновки, как и раньше.
if [ ! -f .done ]; then
    mb_failed=
    for f in /opt/mbedtls/library/*.c; do
        m=$(basename "$f" .c)
        case "$m" in net_sockets|debug|timing) continue ;; esac
        extra=
        [ "$m" = aesni ] && extra="$AESNI_FLAGS"
        # shellcheck disable=SC2086
        if ! zig cc -target "$TARGET" ${MCPU:+-mcpu=$MCPU} $OPT $extra -c \
            -I"$MBED_INC" -I"$EXT_INC" $CFG "$f" -o "$m.o" 2>"$m.err"; then
            mb_failed="$mb_failed $m"
            echo "mbedtls: сборка модуля $m не удалась ($TARGET):" >&2
            sed 's/^/    /' "$m.err" >&2
        fi
        rm -f "$m.err"
    done
    # Метка .done ставится ТОЛЬКО на полном наборе: иначе один сбойный модуль запоминался бы
    # навсегда, и следующая сборка в том же /tmp пропускала цикл целиком.
    if [ -n "$mb_failed" ]; then
        echo "mbedtls: сборка не удалась у модулей:$mb_failed — компоновка ниже упрётся в неопределённые ссылки" >&2
    else
        touch .done
    fi
fi

# -s обязателен: zig cc при -Os убирает отладочную информацию сам, при -O2 — оставляет,
# и бинарник разом вырастает с 540 КБ до 4,9 МБ. На overlay в 6,9 МБ это разница между
# «пакет ставится» и «места нет», причём отладочная информация на роутере не нужна никому.
# Списки файлов ролей — из build/sources.mk (профили extended, server, tgws), одни на все
# сборки: Makefile, build.sh, этот скрипт и рецепты SDK читают один манифест.
export SOURCES_MK=/src/build/sources.mk
. /src/build/sources.sh
case "$ROLE" in
  router) FILES="$(profile_src extended /src/)" && ROLEDEF="$(profile_var PROFILE_DEFS_extended)" ;;
  # У серверной сборки STEER_EXTENDED НЕ определён нарочно: на VPS нет ни спеки, ни выходов,
  # ни каналов, и клиентские подкоманды там обязаны отказывать штатной заглушкой, а не
  # ссылаться на код, которого в этой сборке нет.
  server) FILES="$(profile_src server /src/)" && ROLEDEF="$(profile_var PROFILE_DEFS_server)" ;;
  # Мини-сборка для микропакета tgws: мост и то, на чём он стоит (записи TLS 1.3, примитивы
  # Reality для браузерного Hello), и больше ничего. Ни клиента VLESS, ни звезды xsteer, ни
  # подписки — их подкоманды отвечают штатной заглушкой, как в базовой сборке.
  tgws) FILES="$(profile_src tgws /src/)" && ROLEDEF="$(profile_var PROFILE_DEFS_tgws)" ;;
  *) echo "неизвестная роль: $ROLE (router|server|tgws)" >&2; exit 2 ;;
esac
[ -n "${FILES:-}" ] || { echo "нет списка файлов для роли $ROLE" >&2; exit 2; }
STEER_INC="$(for d in $(profile_var INC_DIRS); do printf -- '-I/src/%s ' "$d"; done)"

# shellcheck disable=SC2086
zig cc -target "$TARGET" ${MCPU:+-mcpu=$MCPU} -static $OPT -s \
    -I"$MBED_INC" -I"$EXT_INC" $STEER_INC $CFG $ROLEDEF -DSTEER_VERSION="\"$VERSION\"" \
    -DSTEER_REV="\"$REV\"" \
    -o "$OUT" \
    $FILES \
    "$WORK"/*.o
