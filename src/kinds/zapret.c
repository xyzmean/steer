/* kind=zapret — выход, у которого НЕТ устройства и нет своей таблицы маршрутизации: трафик уходит
 * обычным путём, но по дороге его разбирает свой экземпляр nfqws со своей стратегией обхода
 * DPI. Отдельный ВИД, а не свойство канала, и доводы те же, что у xsteer, только вывернутые
 * в третью сторону.
 *
 * ЗАЧЕМ. До сих пор обход DPI на роутере был устроен «на весь роутер разом»: одна стратегия в
 * /etc/config/zapret на весь трафик. Но стратегия, которая открывает YouTube, не та, что
 * открывает Discord, и не та, что нужна играм, — а выбирать приходилось одну. Выход даёт то же
 * самое, что уже дают туннели: правило «эти домены — сюда», где «сюда» это конкретная
 * настройка обхода. Тогда YouTube идёт через свою стратегию, Discord через свою, а остальное
 * не трогается вовсе.
 *
 * ПОЧЕМУ НЕ ЧЕРЕЗ on_fail=zapret, который уже есть. Тот отвечает на другой вопрос: «куда
 * девать трафик выхода, когда его туннель умер». Он ничего не настраивает и ничем не управляет
 * — только не мешает системному обходу работать. Здесь же обход и есть назначение выхода.
 *
 * ЧЕМ ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ ВИДОВ. Метка выходу нужна (иначе его трафик не отличить в
 * postrouting), а таблица маршрутизации — нет: пакет уходит тем же маршрутом, что ушёл бы
 * без правила. Поэтому out_has_device про него ложь, а out_needs_mark — правда, и это первый
 * вид, у которого две эти вещи разошлись.
 *
 * Здесь же — вопросы к процессам nfqws (/proc): и «жив ли обработчик моей очереди», и «работает
 * ли системный обход» для on_fail=zapret у выходов с устройством. Обход /proc один на оба. */
#define _GNU_SOURCE
#include <stdio.h>
#include <string.h>
#include <unistd.h>
#include <fcntl.h>
#include <dirent.h>
#include <ctype.h>

#include "spec.h"
