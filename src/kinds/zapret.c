/* kind=zapret — выход, у которого НЕТ устройства и нет своей таблицы маршрутизации: трафик уходит
 * обычным путём, но по дороге его разбирает свой экземпляр nfqws со своей стратегией обхода
 * DPI. Отдельный ВИД, а не свойство канала, и доводы те же, что у xsteer, только вывернутые
 * в третью сторону.
 *
 * ЗАЧЕМ. До сих пор обход DPI на роутере был устроен «на весь роутер разом»: одна стратегия в
 * /etc/config/zapret на весь трафик. Но стратегия, которая открывает YouTube, не та, что
 * открывает Discord, и не та, что нужна играм, — а выбирать приходилось одну. Выход даёт то же
 * самое, что уже дают туннели: правило «эти домены — сюда», где «сюда» это конкретная
 * настройка обхода. Тогда YouTube идёт через свою стратегию, Discord через свою, а остальное
 * не трогается вовсе.
 *
 * ПОЧЕМУ НЕ ЧЕРЕЗ on_fail=zapret, который уже есть. Тот отвечает на другой вопрос: «куда
 * девать трафик выхода, когда его туннель умер». Он ничего не настраивает и ничем не управляет
 * — только не мешает системному обходу работать. Здесь же обход и есть назначение выхода.
 *
 * ЧЕМ ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ ВИДОВ. Метка выходу нужна (иначе его трафик не отличить в
 * postrouting), а таблица маршрутизации — нет: пакет уходит тем же маршрутом, что ушёл бы
 * без правила. Поэтому out_has_device про него ложь, а out_needs_mark — правда, и это первый
 * вид, у которого две эти вещи разошлись.
 *
 * Здесь же — вопросы к процессам nfqws (/proc): и «жив ли обработчик моей очереди», и «работает
 * ли системный обход» для on_fail=zapret у выходов с устройством. Обход /proc один на оба. */
#define _GNU_SOURCE
#include <stdio.h>
#include <string.h>
#include <unistd.h>
#include <fcntl.h>
#include <dirent.h>
#include <ctype.h>

#include "spec.h"

static int zapret_parse(struct output *o, const struct out_keys *k, struct err *e) {
#ifdef STEER_ANDROID
    /* На телефоне zapret нет (решение владельца: «zapret не надо») — см. out_skips_zapret в
     * spec.h. */
    (void)k;
    return err_set(e, "outputs.%s: kind zapret — в сборке под Android zapret нет", o->name);
#else
    snprintf(o->zp.opts, sizeof(o->zp.opts), "%s", k->opts_file);
    /* Устройства нет и не будет: трафик уходит обычным маршрутом, а выход меняет
     * только то, ЧТО с ним по дороге сделает nfqws. Названное устройство здесь —
     * почти наверняка описка (человек копировал выход-туннель), и принять его
     * молча значило бы обещать маршрутизацию, которой не будет. */
    if (o->device[0] || o->devices_n)
        return err_set(e, "outputs.%s: у kind zapret нет устройства — трафик идёт обычным путём",
            o->name);
    /* Путь выводится из имени выхода — тот же довод, что у conf у xsteer: два
     * имени, которым позволено разойтись, пользы не приносят. Имя уже проверено
     * name_ok, поэтому путь собирается из проверенного. */
    if (!o->zp.opts[0])
        snprintf(o->zp.opts, sizeof(o->zp.opts), STEER_ETC_DIR "/zapret/%.200s.opts", o->name);
    /* Абсолютный путь и годность к JSON: путь печатается в status и в diag, а
     * запускает процесс procd со своим рабочим каталогом — относительный «работал
     * бы из шелла» и не работал бы у службы. Тот же барьер, что у conf. */
    else if (o->zp.opts[0] != '/' || !label_ok(o->zp.opts))
        return err_set(e, "outputs.%s: opts_file должен быть абсолютным путём без кавычек", o->name);
    return 0;
#endif
}

/* on_fail=zapret у выхода kind=zapret — это «при отказе обхода включить обход».
 * Молча принять значило бы записать в настройку круг, который ничего не значит. */
static int zapret_check(const struct spec *sp, const struct output *o, struct err *e) {
    (void)sp;
    if (o->on_fail == FAIL_ZAPRET)
        return err_set(e, "outputs.%s: on_fail zapret у выхода kind zapret ничего не значит "
            "(нужен drop или direct)", o->name);
    return 0;
}

/* Есть ли в системе процесс, командная строка которого содержит NEEDLE.
 *
 * Один обход /proc на двух спрашивающих — системный обход (zapret_running) и выход kind=zapret,
 * которому нужен не «работает ли обход вообще», а «жив ли обработчик МОЕЙ очереди». Два обхода
 * /proc с двумя копиями разбора cmdline разошлись бы на первой же правке (буфер, замена нулей,
 * пропуск не-цифр).
 *
 * Почему вообще /proc, а не вопрос ядру: списка «кто слушает очередь nfqueue N» ядро не
 * отдаёт ни через netlink, ни через /proc/net/netfilter/nfnetlink_queue (там номер очереди
 * и pid, но только для очередей, через которые уже прошёл пакет, — то есть у поднятого и
 * ещё не нагруженного обработчика запись отсутствует). Командная строка с --qnum=N
 * отвечает на тот же вопрос и отвечает всегда.
 *
 * digit_end — требовать, чтобы сразу за NEEDLE не стояла цифра: так «--qnum=830» перестаёт
 * находиться в «--qnum=8300». */
static int cmdline_find(const char *needle, int digit_end) {
    DIR *d = opendir("/proc");
    if (!d) return 0;
    struct dirent *dir;
    int found = 0;
    char path[300];
    char buf[512];

    while ((dir = readdir(d)) != NULL && !found) {
        if (!isdigit(dir->d_name[0])) continue;
        snprintf(path, sizeof(path), "/proc/%s/cmdline", dir->d_name);
        int fd = open(path, O_RDONLY | O_CLOEXEC);
        if (fd >= 0) {
            ssize_t n = read(fd, buf, sizeof(buf) - 1);
            if (n > 0) {
                buf[n] = '\0';
                for (ssize_t i = 0; i < n; i++) {
                    if (buf[i] == '\0') buf[i] = ' ';
                }
                for (const char *q = strstr(buf, needle); q; q = strstr(q + 1, needle)) {
                    char after = q[strlen(needle)];
                    if (digit_end && after >= '0' && after <= '9') continue;
                    found = 1;
                    break;
                }
            }
            close(fd);
        }
    }
    closedir(d);
    return found;
}

int zapret_running(void) { return cmdline_find("nfqws", 0); }

/* Жив ли обработчик ИМЕННО ЭТОЙ очереди.
 *
 * Ищется «--qnum=N» целиком, вместе с ключом, и это не педантизм: подстрока «8300» нашлась
 * бы и в чужом пути, и в номере другой очереди (83001), а ответ «выход работает» о мёртвом
 * обходе — худший из возможных, потому что трафик при этом уходит и выглядит ушедшим. */
int nfqws_on_queue(int queue) {
    char needle[32];
    snprintf(needle, sizeof(needle), "--qnum=%d", queue);
    return cmdline_find(needle, 1);
}

/* Устройства нет, поэтому и поля свои. Печатается всё, что о выходе вообще можно знать снаружи,
 * и ничего сверх того:
 *
 *   mark, queue  — по ним управляющий слой находит СВОЙ процесс на СВОЕЙ очереди.
 *                  Номер очереди выводится из метки (см. out_zapret_queue), и
 *                  печатать его надо именно потому, что вывод — наше внутреннее
 *                  дело: второй, повторяющий его расчёт снаружи разошёлся бы.
 *   opts_file    — какой файл стратегии отдан процессу. Без него «стратегия не та»
 *                  выясняется только чтением командной строки процесса.
 *   up           — жив ли обработчик очереди. Спрашивается у /proc, а не у ядра:
 *                  списка «кто слушает очередь N» ядро не отдаёт, а процесс с
 *                  --qnum=N в командной строке отвечает на тот же вопрос точно.
 *
 * Признак живости здесь всё же печатается, в отличие от obfs, и разница
 * оправданна: у obfs он стоил бы pgrep на каждый круг опроса ради поля, которое
 * дублирует diag; здесь без него у выхода не было бы вообще НИ ОДНОГО признака
 * работы — устройства нет, счётчик канала растёт одинаково при живом и мёртвом
 * обходе (пакеты уходят и так, разница в том, доходят ли они). */
static void zapret_status(FILE *out, const struct spec *sp, const struct output *o) {
    (void)sp;
    int q = out_zapret_queue(o);
    fprintf(out, ",\"mark\":\"0x%08x\",\"queue\":%d,\"opts_file\":\"%s\""
           ",\"up\":%s,\"on_fail\":\"%s\"",
           o->mark, q, o->zp.opts,
           nfqws_on_queue(q) ? "true" : "false",
           o->on_fail == FAIL_DROP ? "drop" : "direct");
}

/* Обход DPI своим обработчиком на свою очередь.
 *
 * У такого выхода НЕТ НИ ОДНОГО обычного признака работы: устройства нет, таблицы
 * маршрутизации нет, а счётчик канала растёт одинаково при живом и мёртвом обходе —
 * пакеты уходят и так, разница лишь в том, доходят ли они. То есть «не открывается
 * YouTube» здесь не отличить от «всё в порядке» ничем, кроме этих проверок.
 *
 * Три вопроса, и каждый про свой отказ: нет пакета zapret (обработчика взять негде),
 * нет файла стратегии (обработчику нечего применять), обработчик не запущен (при
 * on_fail=drop это ещё и остановленный трафик канала, что человек читает как
 * «интернета нет», а не как «обход упал»). */
static void zapret_diag(kind_diag_fn *diag, const struct spec *sp, const struct output *o) {
    (void)sp;
    char what[200], why[400];
    int q = out_zapret_queue(o);

    if (access(NFQWS_PATH, X_OK) != 0) {
        snprintf(what, sizeof(what), "выход %.40s: обход DPI не установлен", o->name);
        snprintf(why, sizeof(why),
                 "нет " NFQWS_PATH " — поставьте пакет zapret. Правило очереди при этом "
                 "стоит, и при on_fail=%s трафик канала %s",
                 o->on_fail == FAIL_DROP ? "drop" : "direct",
                 o->on_fail == FAIL_DROP ? "остановлен" : "идёт без обхода");
        diag("zapret", "fail", what, why);
        return;
    }
    if (access(o->zp.opts, R_OK) != 0) {
        snprintf(what, sizeof(what), "выход %.40s: файла стратегии нет", o->name);
        snprintf(why, sizeof(why),
                 "%.200s не читается — стратегию выбирают в splify2, вкладка Zapret. "
                 "Без файла обработчик не поднимается вовсе",
                 o->zp.opts);
        diag("zapret", "fail", what, why);
        return;
    }
    int alive = nfqws_on_queue(q);
    snprintf(what, sizeof(what), "выход %.40s: обработчик очереди %d %s",
             o->name, q, alive ? "работает" : "не запущен");
    snprintf(why, sizeof(why), "%s",
             alive ? ""
             : o->on_fail == FAIL_DROP
               ? "перезапустите движок: /etc/init.d/steer restart. До тех пор трафик "
                 "канала ОСТАНОВЛЕН — так выражен on_fail=drop, очередь стоит без bypass"
               : "перезапустите движок: /etc/init.d/steer restart. До тех пор трафик "
                 "канала идёт без обхода — так выражен on_fail=direct");
    diag("zapret", alive ? "ok" : "fail", what, why);
}

/* `steer zapret-instances` — что поднимать для выходов kind=zapret: по строке на выход, поля
 * через табуляцию — имя, номер очереди, файл ключей. Отдельной командой, а не полем `outputs`,
 * потому что читает её init-скрипт, а не человек, и читает построчно: разбирать в shell
 * ответ `status` (JSON, сотни байт на выход, jsonfilter на каждое поле) значило бы
 * платить за каждую перезагрузку сети разбором, который тут не нужен.
 *
 * Номер очереди печатает движок, а не считает init-скрипт. Вывод номера из метки —
 * наше внутреннее дело (out_zapret_queue), и второй, повторяющий его расчёт в shell
 * разошёлся бы при первой правке: процесс встал бы на очередь, в которую ядро ничего
 * не отдаёт, и выглядело бы это как «стратегия применилась и не действует».
 *
 * ВЫХОД БЕЗ ФАЙЛА СТРАТЕГИИ НЕ НАЗЫВАЕТСЯ ВОВСЕ, и это не экономия, а исправление
 * наблюдаемого отказа.
 *
 * Так выглядит только что заведённый выход: интерфейс создаёт его пустым, стратегию к
 * нему выбирают следующим действием. Пока файла нет, обёртка steer-nfqws выходит с
 * кодом 2 сразу, procd поднимает её снова через свои пять секунд — и так бесконечно.
 * Замерено на живом роутере (10.8.1.1, OpenWrt 25.12.5): три записи в daemon.err за
 * пятнадцать секунд, то есть примерно семнадцать тысяч строк в сутки на выход, который
 * человек просто не докрутил. Журнал после этого бесполезен для всего остального, а
 * вкладка «Логи» — главный способ, которым сообщество разбирается со своими роутерами.
 *
 * Служба, которая не может встать без действия человека, — это не служба в отказе, а
 * служба, которой ещё нет. Сказать об этом всё равно надо, поэтому причина печатается в
 * stderr: init-скрипт читает только stdout, а в журнале строка окажется ОДИН раз за
 * запуск, а не раз в пять секунд. Человеку то же самое говорят двое: apply («выбрана ли
 * стратегия во вкладке Zapret?») и diag («файла стратегии нет»).
 *
 * Обратная сторона названа честно: файл, удалённый у РАБОТАЮЩЕГО выхода, тоже уберёт
 * экземпляр при следующем `start`. Это верно — ключей для запуска всё равно больше нет.
 *
 * Код возврата — как у needs-dnsd: 0, если поднимать есть что. */
int zapret_instances(const struct spec *sp) {
    int n = 0;
    for (size_t i = 0; i < sp->out_n; i++) {
        const struct output *o = &sp->out[i];
        if (kind_of(o) != &kind_zapret) continue;
        if (access(o->zp.opts, R_OK) != 0) {
            /* С УРОВНЕМ, а не голым «steer: ». Голый префикс в этом движке
             * зарезервирован за отказами вызывающему (die и разбор аргументов), которые
             * кончаются кодом 2 и до журнала не доходят; барьер в buildmatch.sh это и
             * сторожит. Эта строка — сообщение, а не отказ: команда продолжает работу и
             * называет остальные выходы. */
            fprintf(stderr, "steer[warn] zapret %s: файла стратегии %s нет — "
                            "поднимать нечем, выберите стратегию\n", o->name, o->zp.opts);
            continue;
        }
        printf("%s\t%d\t%s\n", o->name, out_zapret_queue(o), o->zp.opts);
        n++;
    }
    return n ? 0 : 1;
}

const struct kind_ops kind_zapret = {
    .name = "zapret",
    .caps = KC_MARK | KC_CTMARK | KC_SKIP_ZAPRET,
    .keys = KK_OPTS,
    .parse = zapret_parse,
    .check = zapret_check,
    .status = zapret_status,
    .diag = zapret_diag,
};
