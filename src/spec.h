/* СКОЛЬКО ВЫХОДОВ ВЛЕЗАЕТ В ПОЛЕ МЕТКИ.
 *
 * Раньше выход получал БИТ: метка была `база << номер`, и восемь бит поля значили ровно
 * восемь помеченных выходов. Поле расширить нельзя — слева от нашего диапазона бит 28 у
 * мини-сборки, 29 и 30 у zapret, а справа 16-23 занимают Tailscale и pbr (и уже заходят в
 * наше поле на битах 20-23, см. выше), — поэтому выходу
 * выдаётся ЗНАЧЕНИЕ: `база * (место + 1)`. Правило разметки пишет `mark and ~МАСКА or
 * метка`, а правило маршрутизации сравнивает `mark and МАСКА == метка`, и обоим
 * безразлично, одинокий там бит или число: в поле помещается столько выходов, сколько в
 * нём умещается ненулевых значений, то есть 255 вместо 8.
 *
 * Упирается это не в метку, а в номера таблиц маршрутизации: полный движок занимает
 * 300..315, дальше стоит мини-сборка (TABLE_BASE в spec.c). Поэтому мест ровно столько,
 * сколько выходов вообще разрешено объявить, — MAX_OUTPUTS. */
#define STEER_MARK_FIELD_MAX ((1u << STEER_MARK_BITS) - 1u)
#define STEER_MARK_SLOTS \
    (STEER_MARK_FIELD_MAX < (unsigned)MAX_OUTPUTS ? STEER_MARK_FIELD_MAX \
                                                  : (unsigned)MAX_OUTPUTS)

/* ---- вложенные выходы: `via` ----------------------------------------------------------
 *
 * ЗАЧЕМ. Туннель одного выхода бывает нужно пустить ВНУТРИ другого: WireGuard, у которого UDP
 * к серверу режут, — внутри VLESS (пример владельца: выход awg с `via` на выход vless), или
 * наоборот, VLESS, чей сервер виден только из сети WireGuard, — внутри интерфейса. Каналы
 * здесь ни при чём: они решают, в какой выход идёт трафик КЛИЕНТОВ, а `via` решает, куда
 * идёт трафик САМОГО ТУННЕЛЯ — его соединение с сервером.
 *
 * КАК. Ровно тем же механизмом, которым движок и так ведёт трафик в выход: меткой. У выхода-
 * цели уже есть своя метка, ip rule «fwmark метка/маска → таблица выхода» и маршрут по
 * умолчанию в его устройство. Сокет наверх внутреннего выхода получает метку выхода-цели
 * (SO_MARK у клиентов vless, xsteer и обфускатора; WGDEVICE_A_FWMARK у выхода awg), и ядро
 * уводит его пакеты в таблицу цели при поиске маршрута — ещё до того, как пакет родился:
 * connect() на помеченном сокете выбирает и устройство, и адрес источника по таблице цели.
 * Никаких новых правил nft и ip rule для этого не нужно, и вывод generate() от `via` не
 * зависит вовсе — трафик туннеля локальный (хук output), а каналы роутера живут на
 * prerouting, каналы телефона — на output только для приложений (skuid от 10000), а
 * помощники движка работают под root.
 *
 * ЧТО С ОТКАЗОМ. Если выход-цель лёг, внутренний туннель по нему не доедет — поэтому сторож
 * считает внутренний выход нерабочим, пока лежит цель, и применяет ЕГО on_fail к его
 * каналам (failover.c). Проб и таймеров ради этого не заводится: ответ «цель жива» у сторожа
 * уже есть в том же проходе, выходы просто обходятся в порядке зависимостей. Сам транспорт
 * внутреннего туннеля при этом подчиняется on_fail ЦЕЛИ: при drop в её таблице blackhole и
 * соединение не встанет, при direct её правило снято и транспорт уйдёт обычным путём.
 *
 * Глубина цепочки — не больше MAX_VIA_DEPTH переходов: каждый слой — это заголовки и
 * шифрование ещё раз, и цепочка длиннее трёх означает скорее описку, чем замысел. */
#define MAX_VIA_DEPTH 3

/* Выход, у которого ЕСТЬ СВОЙ СОКЕТ НАВЕРХ, — только ему `via` и имеет смысл: метку ставит тот,
 * кто открывает соединение с сервером. vless и xsteer — наш процесс; interface с obfs — наш
 * обфускатор (его сырой сокет к серверу обфускации несёт UDP WireGuard); awg — ядро WireGuard,
 * но настраивает его движок, и метку сокета туннеля он задаёт сам (WGDEVICE_A_FWMARK, src/awg.c).
 * Обычный interface — НЕТ: его сокет открывает ядро WireGuard по настройке netifd, и метку ему
 * ставить не нам. Одной функцией, чтобы новый вид добавлялся одной строкой, а не поиском по
 * проверкам. */
static inline int out_via_capable(const struct output *o) {
    return o->kind == OUT_VLESS || o->kind == OUT_XSTEER || o->kind == OUT_AWG
        || (o->kind == OUT_INTERFACE && o->obfs.on);
}

/* Годится ли выход в цели `via`: у него должны быть устройство и таблица маршрутизации, иначе
 * метке некуда вести. Это ровно out_has_device (interface, vless, xsteer, awg) — direct, zapret
 * и tgws отпадают (у первых двух
 * пакет уходит обычным маршрутом, у tgws перехват стоит на prerouting и трафика самого роутера
 * не касается). Отдельным именем, а не прямым вызовом, чтобы смысл читался в проверке. */
static inline int out_via_target_ok(const struct output *o) {
    return out_has_device(o);
}

/* Выход-цель `via` или NULL, если его нет. Поиск по g_out, а не out_by_name: этот заголовок
 * включают стенды без парсера (failovermatch), и функция из spec.c у них не собралась бы. */
static inline const struct output *out_via(const struct output *o) {
    if (!o->via[0]) return NULL;
    for (size_t i = 0; i < g_out_n; i++)
        if (!strcmp(g_out[i].name, o->via)) return &g_out[i];
    return NULL;
}

/* Сколько переходов via от выхода до выхода без via: 0 — туннель идёт напрямую. Нужна тем, кто
 * обходит выходы в порядке зависимостей (сторож, супервизор помощников): цель — раньше
 * зависящего. Спека круги и цепочки длиннее MAX_VIA_DEPTH отвергает (via_check в spec.c);
 * предел здесь — только чтобы стенд, собирающий выходы в обход парсера, не зациклился. */
static inline int out_via_depth(const struct output *o) {
    int d = 0;
    for (const struct output *t = out_via(o); t && d < MAX_VIA_DEPTH; t = out_via(t)) d++;
    return d;
}

/* МЕТКА, КОТОРОЙ МЕТИТЬ СОБСТВЕННЫЙ ТРАФИК ТУННЕЛЯ ВЫХОДА o (сокет наверх клиента vless/xsteer/
 * обфускатора, WGDEVICE_A_FWMARK у выхода awg).
 *
 * При `via` — метка выхода-цели: по ней ip rule цели уводит пакет в её таблицу, то есть в её
 * устройство. Метка у цели появляется в registry_assign, поэтому звать эту функцию можно только
 * после него — до реестра она вернула бы «мимо каналов», то есть «напрямую», молча.
 *
 * Без `via` — обычное «мимо каналов». На роутере это ноль (сокет не метится вовсе): трафик самого
 * роутера каналы не трогают, они на prerouting. На телефоне — STEER_SELF_MARK, значение «сам
 * движок»: маршрута на него нет (пакет идёт обычным путём сети netd), зато его узнают заворот DNS
 * приложений (не заворачивает туннель с сервером на 53-м порту обратно к резолверу) и список
 * соединений. Поля netd в этом значении нулевые, а FwmarkServer при connect() переписывает
 * только свои поля — наши биты 22-27 он оставляет, как оставляет их резолверу.
 *
 * Возвращается ЗНАЧЕНИЕ поля (биты STEER_MARK_MASK), без чужих битов: сокет, которому ставят
 * метку целиком, других битов не несёт, а кто ставит её поверх своей (netd), тот сам сохраняет
 * свои поля. */
static inline uint32_t out_underlay_mark(const struct output *o) {
    const struct output *v = out_via(o);
    /* Цель без метки (реестр ещё не прочитан) — «напрямую»: метка 0 значила бы ровно то же, но
     * на телефоне «мимо каналов» — это значение «сам движок», а не ноль. */
    if (v && v->mark) return v->mark;
#ifdef STEER_ANDROID
    return STEER_SELF_MARK;
#else
    return 0;
#endif
}

/* ИМЯ ТАБЛИЦЫ ПРАВИЛ — НЕ КОНСТАНТА, потому что движок на роутере бывает не один.
 *
 * Рядом с полным движком ставится микропакет tgws: своя спека, своё состояние, свой бинарник
 * с другим именем. Таблица же у обоих называлась `steer`, а `nft -f` со своим определением
 * таблицы ЗАМЕЩАЕТ её целиком — то есть кто применил спеку последним, тот и стёр правила
 * другого. Из-за этого микропакет отказывался работать рядом с полным движком вовсе; отказ
 * владелец потребовал убрать: «stgws должен работать параллельно со steer, не глядя,
 * установлен он или нет».
 *
 * Имя берётся из STEER_NFT_TABLE, умолчание прежнее. Проверка символов не педантизм: имя
 * уходит в командную строку nft, и пробел или кавычка в нём означали бы чужую команду.
 *
 * В заголовке, а не в steer.c: имя нужно и сторожу (failover.c, набор failopen), а сторож
 * собирается и без steer.c — стенды включают его файл напрямую. Кэш у каждой единицы
 * трансляции свой, но переменная окружения на процесс одна, так что ответ у всех одинаков. */
static inline const char *nft_table(void) {
    static const char *cached;
    if (cached) return cached;
    const char *e = getenv("STEER_NFT_TABLE");
    cached = "steer";
    if (e && *e && strlen(e) < 32) {
        const char *p = e;
        for (; *p; p++)
            if (!((*p >= 'a' && *p <= 'z') || (*p >= 'A' && *p <= 'Z') ||
                  (*p >= '0' && *p <= '9') || *p == '_' || *p == '-'))
                break;
        if (!*p) cached = e;
    }
    return cached;
}

/* ---- nftables старого ядра: раскладка правил для Linux 4.9 ---------------------------
 *
 * ЗАЧЕМ. Набор правил движка написан под nftables современного ядра, и на 4.9 (телефон
 * Xiaomi beryllium, ядро LineageOS 4.9.337) он не загружается даже с включённым nf_tables:
 * `nft -f` атомарен, и одна непонятная ядру строка снимает всю транзакцию — не встают ни
 * наборы, ни метки, ни заворот DNS. Сверено по исходникам ядра 4.9, а не по документации;
 * вот чего там нет из того, что нам нужно:
 *
 *   - цепочек `type nat` в семействе inet: nf_tables_inet.c регистрирует только filter, nat
 *     есть лишь у ip и ip6 (nft_chain_nat_ipv4/ipv6). Появились в inet с 5.2. Вместе с ними
 *     в inet недоступны redirect и dnat;
 *   - наборов `flags interval,timeout`: у nft_set_rbtree (единственный интервальный) в 4.9
 *     features = INTERVAL|MAP, сроки жизни умеет только nft_set_hash (MAP|TIMEOUT);
 *   - `notrack`: в nft_ct.c upstream 4.9 и в ядре телефона его нет (с 4.10); Debian перенёс
 *     его в своё 4.9, поэтому он спрашивается у ядра отдельно (NFTC_NOTRACK);
 *   - `exthdr … exists`: флага NFT_EXTHDR_F_PRESENT нет (с 4.10), и это хуже отказа — ядро
 *     молча отбрасывает незнакомый атрибут и грузит ДРУГОЕ правило: `exthdr frag exists`
 *     становится сравнением поля `frag nexthdr` с единицей (снято на стенде tools/vm49);
 *   - получения одного элемента (`nft get element`): NFT_MSG_GETSETELEM отвечает только на
 *     дамп, иначе -EOPNOTSUPP (с 4.15) — это ломает не загрузку, а explain;
 *   - нескольких базовых цепочек nat на одном хуке: до 4.18 первая же цепочка nat, где
 *     ничего не совпало, ставит соединению «пустую» трансляцию, и остальные цепочки того же
 *     хука его больше не видят. Три наших цепочки на prerouting (DNS, fakeip, мост Telegram)
 *     на 4.9 означали бы, что работает только первая.
 *
 * Имена наборов и цепочек там ограничены 31 символом (NFT_*_MAXNAMELEN 32) — имена групп
 * рассчитаны на это давно (см. group_set_name), а суффикс статической части набора ниже
 * укладывается в тот же предел.
 *
 * Возвращает набор флагов NFTC_*; ноль — современное ядро, прежний набор правил байт в байт.
 * Выбор — пробой ядра (`nft -c` пробной таблицы inet с цепочкой nat), с переопределением
 * переменной STEER_NFT_COMPAT: modern, legacy (необязательное — nat в ip6 и notrack — всё
 * равно спрашивается у ядра) или legacy-min (без них и без проб: ровно то, что умеет ядро
 * телефона в конфиге LineageOS, и один и тот же текст для стендов). Ответ запоминается на
 * процесс. Определена в spec.c. */
#define NFTC_LEGACY 1   /* раскладка для 4.9: nat в ip/ip6, наборы со сроками отдельно */
#define NFTC_IP6NAT 2   /* при NFTC_LEGACY: ядро принимает nat в ip6 (заворот DNS по IPv6) */
#define NFTC_NOTRACK 4  /* при NFTC_LEGACY: ядро знает выражение notrack (Debian перенёс его в 4.9) */
int nft_compat(void);

/* Имя статической (интервальной) половины доменного набора в раскладке legacy: «<имя>_n».
 * Динамическая половина, куда резолвер кладёт адреса со сроком, сохраняет имя группы — тогда
 * резолверу, explain и diag не нужно второе правило именования, а переименование не трогает
 * перенос счётчиков (он идёт по комментарию правила, то есть по имени группы). */
static inline void nft_static_set_name(char *dst, size_t n, const char *group) {
    snprintf(dst, n, "%.63s_n", group);
}

/* ---- биты, которыми объясняются с zapret ------------------------------------
 *
 * Все три принадлежат НЕ НАМ: значения задал zapret, и мы их только соблюдаем. Взяты они не
 * из документации, а из живого набора правил на роутере — /etc/config/zapret объявляет
 * `DESYNC_MARK 0x40000000` и `DESYNC_MARK_POSTNAT 0x20000000`, и оба бита стоят в условиях
 * его цепочек (postnat_hook, predefrag, predefrag_nfqws; полная выписка — у генерации
 * цепочки zapret_queue в src/steer.c).
 *
 * ZAPRET_SKIP_MARK мы СТАВИМ САМИ, и это единственный способ сказать системному обходу «этот
 * трафик не твой»: его цепочка входит по условию `meta mark & 0x40000000 == 0`.
 *
 * Ставится он трафику ВСЯКОГО выхода, кроме kind=direct (кому именно и почему — у
 * out_skips_zapret выше). Сначала он стоял только у kind=zapret, где без него трафик
 * разбирали бы двое — сначала общий обход своей стратегией, потом наш экземпляр своей, — и
 * вышло бы не то, что выбрал человек, ни в одном из двух смыслов. Потом выяснилось, что у
 * туннельных выходов беда не меньше, только другая: обходу там разбирать нечего (снаружи
 * виден сам туннель), а рассинхронизировать ВНЕШНИЕ пакеты он всё равно принимается, и
 * рукопожатие туннеля может не сойтись. Проверить это глазами нельзя ни в том, ни в другом
 * случае: правила у обоих выглядят исправно.
 *
 * НО ДО НАШЕГО ОБРАБОТЧИКА ЭТОТ БИТ ДОЕЗЖАТЬ НЕ ДОЛЖЕН: nfqws считает своим порождённым
 * любой пакет, у которого с его --dpi-desync-fwmark есть общий бит, а в ZAPRET_OWN_MARK бит
 * 0x40000000 входит. Поэтому цепочка очереди снимает его с пакета перед `queue` — см.
 * zapret_queue в steer.c и почему без этого выход не обрабатывал ни одного пакета.
 *
 * ZAPRET_OWN_MARK — то, чем метит свои пакеты НАШ экземпляр (ключ --dpi-desync-fwmark). В нём
 * подняты ОБА бита, и каждый нужен по своей причине. 0x40000000 уводит порождённые пакеты и
 * от общего обхода, и — главное — в цепочку predefrag_nfqws, где их снимают с учёта
 * conntrack: без этого ядро отбрасывает их как INVALID, то есть обход перестаёт работать
 * совсем. Такая цепочка есть у zapret, но она пропадает вместе с его службой, поэтому своя
 * (zapret_predefrag) стоит и в нашей таблице — см. генерацию в steer.c. 0x20000000
 * (ZAPRET_MINE_BIT) выводит их из НАШЕЙ очереди.
 *
 * Почему нельзя одним битом: у исходного пакета и у порождённого 0x40000000 есть у обоих, и
 * различить их в цепочке нечем — один бит на двоих дал бы либо круг (свой пакет снова в свою
 * очередь), либо неразобранный исходный.
 *
 * Диапазон свободен от нас: наши восемь бит — 0x0FF00000, зонные метки fw4 живут в младшем
 * слове (проверено на роутере: кроме перечисленного и нашей маски, в наборе правил меток
 * нет). */
#define ZAPRET_SKIP_MARK 0x40000000u
#define ZAPRET_OWN_MARK  0x60000000u
#define ZAPRET_MINE_BIT  0x20000000u

/* Сколько первых пакетов соединения отдавать обработчику.
 *
 * Без предела в userspace уезжает КАЖДЫЙ пакет соединения: весь поток видео идёт через
 * копирование в nfqws и обратно, и на 880 МГц это не «немного дороже», а другой порядок
 * пропускной способности. Обходу нужны только первые пакеты — там SYN, ClientHello и QUIC
 * Initial. Девять — число самого zapret (NFQWS_TCP_PKT_OUT и NFQWS_UDP_PKT_OUT в его
 * /etc/config/zapret, умолчание), и брать другое значило бы спорить с автором обхода о его
 * же стратегиях: они писались под этот предел. */
#define ZAPRET_FIRST_PACKETS 9

/* Номер очереди nfqueue у выхода kind=zapret ВЫВОДИТСЯ ИЗ МЕТКИ, а не задаётся в спеке.
 *
 * Второе поле в спеке означало бы второй источник правды о том, какой процесс какой трафик
 * разбирает, и первое же расхождение выглядело бы как «стратегия применилась, но не
 * действует». Метка выхода уже уникальна и уже переживает перезапуск (реестр в
 * /var/lib/steer/registry), поэтому номер очереди из неё выводится однозначно и стабильно.
 *
 * База 8300 выбрана подальше от того, чем пользуется сам zapret: его init-скрипт на OpenWrt
 * раздаёт номера с 200, и пересечение означало бы, что два процесса слушают одну очередь —
 * ядро отдаст пакет одному из них, и какому именно, зависит от порядка запуска. */
#define ZAPRET_QUEUE_BASE 8300

/* МЕСТО ВЫХОДА В РЕЕСТРЕ, выведенное из его метки. Метка — это `база * (место + 1)`,
 * поэтому место читается делением. Прежняя раздача давала биты (`база << номер`), и метка
 * из старого реестра даёт здесь не номер бита, а его степень двойки: 0, 1, 3, 7, 15 и
 * дальше. Это НЕ ошибка — от места требуется только быть своим у каждого выхода, а
 * распорядитель (registry_assign) держит занятые места и новому выходу их не выдаёт. */
static inline int out_mark_slot(const struct output *o) {
    uint32_t m = o->mark / STEER_MARK_BASE;
    return m ? (int)(m - 1) : 0;
}

/* Номер очереди выхода. Из метки: место выхода в реестре — это и есть его номер. */
static inline int out_zapret_queue(const struct output *o) {
    return ZAPRET_QUEUE_BASE + out_mark_slot(o);
}

/* ---- выход kind=tgws: Telegram через веб-сокет --------------------------------------
 *
 * ЧТО ЭТО. Telegram ходит в свои дата-центры по TCP на их адреса, и там его и режут. Но у
 * веб-клиента есть второй путь: тот же протокол MTProto, завёрнутый в WebSocket поверх TLS
 * к `wss://kwsN.web.telegram.org/apiws`, а эти имена стоят за Cloudflare — блокировать их
 * означает блокировать Cloudflare. Выход этого вида ПЕРЕХВАТЫВАЕТ соединения приложения с
 * дата-центрами и уводит их этим путём, поэтому в самом приложении ничего настраивать не
 * надо (в отличие от прокси, которому в клиенте прописывают адрес и секрет).
 *
 * ПОЧЕМУ ПОТОК ИДЁТ НАСКВОЗЬ, А НЕ ПЕРЕШИФРОВЫВАЕТСЯ. Обфускация MTProto к дата-центру
 * ключей не согласовывает: клиент шлёт 64 случайных байта, и ключ с вектором — это байты
 * [8..40] и [40..56] ПРЯМО ИЗ НИХ, без секрета (секрет подмешивается только у MTProxy, см.
 * core.telegram.org/mtproto/mtproto-transports). Дата-центр за веб-сокетом ждёт ровно такой
 * же пакет. Значит поток клиента годится как есть: мы отдаём его 64 байта первым бинарным
 * кадром и дальше переливаем байты в обе стороны, ничего не расшифровывая. Читать переписку
 * нечем и не нужно — прикладной слой всё равно закрыт auth_key.
 *
 * ЧТО ВСЁ-ТАКИ ПРАВИТСЯ. В хвосте [56..64] лежат метка транспорта и НОМЕР ДЦ (signed LE,
 * отрицательный — медийный). У прямого соединения номера там нет, там случайные байты, а
 * точке `apiws` он нужен. Мы его вписываем: расшифровываем хвост теми же сырыми ключами,
 * подставляем номер и шифруем обратно. Ключи при этом не меняются — они выводятся из байт
 * [8..56], которых мы не трогаем, — поэтому остаток потока остаётся верным.
 *
 * ОТКУДА НОМЕР ДЦ. Из АДРЕСА НАЗНАЧЕНИЯ, а не из рукопожатия: у прямого соединения его в
 * рукопожатии нет. Адреса дата-центров публичные и меняются редко; неизвестный адрес мы не
 * перехватываем вовсе — пусть идёт как шёл. Это единственный безопасный ответ: увести
 * соединение не в тот дата-центр значит сломать то, что работало.
 *
 * ЗВОНКИ СЮДА НЕ ПОПАДАЮТ. Голос идёт отдельным каналом по UDP (P2P или через рефлекторы),
 * MTProto участвует только в установке звонка. Перехват здесь только TCP, и это не
 * недоделка: завернуть UDP в этот веб-сокет нечем. Кому нужны звонки — тому туннель. */
#ifdef STEER_TGWS
/* Свой ряд портов: у мини-сборки бит нулевой, и с общей базой она села бы на 8480 — порт
 * первого выхода полного движка, если тот тоже kind=tgws (так его заводит brb). */
#define TGWS_PORT_BASE 8490
#else
#define TGWS_PORT_BASE 8480
#endif

/* Порт, на котором ждёт мост этого выхода. Выводится из метки по той же причине, что номер
 * очереди у zapret: второе поле в спеке — это второй источник правды. */
static inline int out_tgws_port(const struct output *o) {
    return TGWS_PORT_BASE + out_mark_slot(o);
}

/* Где лежит nfqws. Путь пакета zapret на OpenWrt (remittor/zapret-openwrt) — тот же, что у
 * оригинала bol-van. Литералом, а не поиском в PATH: у procd своё окружение, и «нашли не то»
 * здесь означало бы чужой процесс на нашей очереди. */
#define NFQWS_PATH "/opt/zapret/nfq/nfqws"

/* Поставить и снять правило маршрутизации выхода. Одна пара функций на четыре места, где эти
 * команды нужны (apply, уборка мёртвых правил, отказ выхода, привязка устройства): пока
 * команды стояли строками в каждом месте, добавление маски означало бы четыре шанса забыть
 * её в одном.
 *
 * rule_drop снимает ОБЕ формы — с маской и прежнюю без неё. Прежняя остаётся в ядре после
 * обновления движка, а два правила на одну метку дают порядок по приоритету, а не по
 * замыслу. Снимает в цикле: `ip rule add` дубликаты не проверяет, и копий может быть
 * несколько. */
void rule_add(unsigned mark, int table);
/* Снять установленные соединения выхода: следующий их пакет пройдёт обычным путём и получит
 * решение о маршруте заново. Нужна потому, что при включённой выгрузке потоков пакеты
 * установленного соединения до нашей цепочки не доходят — подробности у определения. */
void conntrack_evict(unsigned mark);
/* Снять записи conntrack, у которых (метка & mask) == val, — самим движком, через ctnetlink
 * (dnsd.c). Сколько снято, или -1, если разговора с ядром не вышло (нет сокета
 * NETLINK_NETFILTER или подсистемы conntrack в нём) — тогда conntrack_evict пробует внешний
 * инструмент. Живёт в dnsd.c, рядом с другим разговором с conntrack. */
int ctnl_evict_mark(uint32_t val, uint32_t mask);
/* Отметить выход «пущен напрямую» (on=1) или снять отметку — см. out_failopen_capable. */
void failopen_mark(const struct output *o, int on);
/* Жив ли обработчик очереди nfqueue с этим номером — то есть работает ли выход kind=zapret.
 * Живёт рядом с conntrack_evict потому, что там же лежит второй обход /proc (zapret_running),
 * и общий разбор командной строки у них один. */
int nfqws_on_queue(int queue);
void rule_drop(unsigned mark, int table);
/* Правило выхода — ровно одной копией, НЕ СНИМАЯ стоящую: недостающее добавляется, лишние
 * копии и прежние формы снимаются уже после. Зачем так, а не rule_drop + rule_add, — у
 * определения в failover.c («без мгновения пустоты»). */
void rule_ensure(unsigned mark, int table);
/* Маршрут по умолчанию таблицы выхода — в устройство dev (или запрет, если dev == NULL) одной
 * заменой, без сброса таблицы; всё прочее в таблице снимается после. 0 — встал; иначе
 * таблица осталась, как была, и решать вызывающему. Там же, в failover.c. */
int table_bind(const struct output *o, const char *dev);

/* Привязать таблицу выхода к устройству: правило по метке и маршрут по умолчанию. Живёт в
 * failover.c, но нужна и клиенту VLESS: он привязывает своё устройство сам, потому что
 * только он знает момент, когда оно готово нести трафик. */
void bind_device(struct output *o, const char *dev);

/* ---- подъём выхода vless: состояние, у которого раньше не было имени --------------------
 *
 * Устройство туннеля vless появляется НЕ СРАЗУ. При `node: -1` («первый рабочий» — умолчание
 * и то, что рекомендует интерфейс) клиент перебирает узлы подписки с таймаутом восемь секунд
 * на узел, и устройство создаётся только после выбора. Пока перебор идёт, устройства нет — и
 * диагностика печатала «устройства нет, туннель не поднят», то есть в точности то же, что при
 * настоящем отказе. На подписке из трёх десятков нерабочих узлов это минуты видимого «не
 * работает» на исправной настройке, и наоборот: настоящий отказ выглядел медленной проверкой
 * (I-100).
 *
 * Поэтому клиент рассказывает о ходе перебора файлом в state_dir, а status и diag его читают.
 * Файл, а не ubus: движок ubus-сервисом не является, а управляющий слой уже читает его вывод.
 *
 * УСТАРЕВАНИЕ обезврежено по-разному для двух состояний, и это главное в этой паре функций.
 * `probing` верен, только пока жив написавший его процесс, — проверяется по /proc/<pid>;
 * `failed` обязан пережить смерть процесса (клиент выходит с кодом 1, procd поднимает его
 * заново каждые пять секунд), поэтому верен, пока свеж. Отсутствие файла и устаревший файл
 * читаются как «не знаем» и возвращают PROBE_NONE — то есть прежнее поведение, а не жёлтая
 * метка на исправном роутере. */
enum probe_state {
    PROBE_NONE = 0,   /* нечего сказать: файла нет, он устарел или писавший процесс мёртв */
    PROBE_RUNNING,    /* перебор идёт: проверяется узел `node` из `total` */
    PROBE_FAILED,     /* перебор кончился: ни один узел не ответил (total>0) либо узлов нет */
    /* Выбранный НОМЕР узла за пределами подписки: узлы в ней есть, а такого номера нет.
     *
     * Отдельное состояние, а не разновидность PROBE_FAILED, и это не педантизм — это
     * исправление вранья, снятого с живого роутера. Раньше сюда писался `failed` с total=0,
     * то есть ровно та же запись, что у «в подписке нет пригодных узлов». Диагностика по ней
     * и говорила: «подписка скачана, но узлов нужного вида в ней нет» — на подписке из
     * ДВАДЦАТИ ДЕВЯТИ живых узлов, где человек всего лишь написал `node: 31`. Такой ответ
     * отправляет перекачивать подписку и менять провайдера вместо того, чтобы поправить одно
     * число; сам движок при этом знает правду и печатает её в `vless-probe`.
     *
     * `node` здесь — номер, который написал ЧЕЛОВЕК (первый из выбранных), `total` — сколько
     * пригодных узлов в подписке на самом деле. Двух этих чисел рядом достаточно, чтобы
     * причина читалась без journal. */
    PROBE_NO_SUCH_NODE,
};

struct probe_status {
    enum probe_state state;
    /* Номер узла: у PROBE_RUNNING — проверяемый (с единицы), у PROBE_NO_SUCH_NODE — тот,
     * что выбрал человек (как написан в спеке), у PROBE_FAILED — 0. */
    int node;
    int total;        /* сколько пригодных узлов нашлось в подписке */
};

/* Записать ход перебора. node с единицы; total — сколько пригодных узлов. */
void probe_report(const char *out_name, enum probe_state st, int node, int total);
/* Убрать запись: устройство поднялось, объяснять больше нечего. */
void probe_clear(const char *out_name);
/* Прочитать. PROBE_NONE, если сказать нечего. */
struct probe_status probe_read(const char *out_name);

