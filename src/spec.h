/* Кому ПРИНАДЛЕЖИТ устройство: выход, чей процесс его создал (vless, xsteer). NULL, если
 * такого нет, — тогда устройством владеет система, и отвечает за него сам выход.
 *
 * Заведено потому, что одно и то же устройство может быть названо ДВАЖДЫ: сначала выходом,
 * который его создаёт, а потом — в `devices` другого выхода, собирающего из разнородных
 * туннелей пул с порядком предпочтения (локация подписки, wireguard, хаб xsteer в одном
 * списке). Так его собирает интерфейс splify2, и так его может написать человек руками.
 *
 * Всё, что решается ВИДОМ выхода, но относится к устройству, обязано спрашивать здесь, а не
 * у выхода, который устройство назвал: мера здоровья и способ оживления (failover.c), нужен
 * ли masquerade (apply и diag в steer.c). Иначе у пула kind=interface с устройством
 * VLESS-туннеля проба была бы ICMP, который через него не идёт принципиально, а диагностика
 * требовала бы masquerade, которого этому устройству не нужно.
 *
 * Ищется только среди выходов out_engine_managed: устройство, которым владеет netifd, ничьей
 * собственностью здесь не считается, и обычный wireguard в пуле проверяется как прежде.
 * Совпадение имён (выход kind=xsteer, названный «wg0» при живом интерфейсе wg0) остаётся
 * ошибкой настройки: два разных устройства с одним именем система и сама не различит.
 *
 * Объявлена здесь, а определена в failover.c — тот же случай, что bind_device: спрашивают её
 * из трёх мест, а живёт она там, где появилась первая нужда. Переносить определение в spec.c
 * нельзя без потерь: стенд failovermatch компилирует failover.c со своими выходами и без
 * парсера, и копия функции в стенде стала бы вторым источником правды, который разойдётся с
 * первым молча. */
const struct output *device_owner(const char *dev);
/* Тот же вопрос с готовым запасным ответом: владелец устройства, а если владельца нет — сам
 * выход. Отдельно от device_owner, потому что все три места зовут именно эту форму, и
 * `owner ? owner : o` в каждом из них — три шанса забыть его в одном. */
const struct output *out_for_device(const struct output *o, const char *dev);

/* Развернуть выбор узлов выхода в порядок перебора при подписке из `usable` пригодных узлов.
 * Пишет в dst номера кандидатов по предпочтению и возвращает, сколько написал.
 *
 * Живёт рядом с разбором спеки, а не в клиенте vless: это ЗНАЧЕНИЕ поля `nodes`, а не деталь
 * подъёма туннеля, и проверить его стендом надо там, где стенд не требует ни mbedtls, ни
 * сети. Клиент и `vless-probe` зовут одну и ту же функцию — иначе диагностика показывала бы
 * перебор, отличный от настоящего.
 *
 * Номер вне подписки ПРОПУСКАЕТСЯ, а не роняет выход: подписка обновляется, узлов в ней
 * становится меньше, и устаревший номер не повод выключить локации, которые на месте.
 * Возврат 0 при непустом `nodes` означает, что не осталось ни одного, — вот это уже отказ,
 * потому что перебирать вместо выбранного что попало значит увести трафик в локацию,
 * которую человек не выбирал. */
size_t out_node_list(const struct output *o, size_t usable, int *dst, size_t max);

/* ---- метка пакета: НАШИ биты, а не всё слово --------------------------------
 *
 * Слово метки — общий ресурс системы. В нём работают mwan3 (маской 0x3F00), pbr, sqm и всё,
 * что метит пакеты для политики маршрутизации. Пока движок ставил метку перезаписью слова
 * (`meta mark set 0x00100000`) и искал её точным совпадением (`ip rule add fwmark ...`), это
 * ломалось в обе стороны и молча: чужую метку мы стирали, а свою теряли, если её затирали
 * после нас, — и во втором случае помеченный пакет уходил по таблице main, то есть напрямую,
 * минуя таблицу, где при on_fail=drop лежит запрет (I-135).
 *
 * Поэтому диапазон объявлен и стал частью контракта (docs/contract-v1.md): восемь бит с
 * двадцатого. Восемь — потому что столько выходов может получить метку (MAX_OUTPUTS = 16, из
 * них метку получают недирект-выходы, и распорядитель отдаёт по биту на выход, см.
 * registry_assign). Маска ВЫВОДИТСЯ из базы и числа бит: три записанных руками числа
 * разошлись бы при первом изменении любого из них. */
#define STEER_MARK_BASE 0x00100000u
#define STEER_MARK_BITS 8
#define STEER_MARK_MASK (((1u << STEER_MARK_BITS) - 1u) * STEER_MARK_BASE)

/* Поставить и снять правило маршрутизации выхода. Одна пара функций на четыре места, где эти
 * команды нужны (apply, уборка мёртвых правил, отказ выхода, привязка устройства): пока
 * команды стояли строками в каждом месте, добавление маски означало бы четыре шанса забыть
 * её в одном.
 *
 * rule_drop снимает ОБЕ формы — с маской и прежнюю без неё. Прежняя остаётся в ядре после
 * обновления движка, а два правила на одну метку дают порядок по приоритету, а не по
 * замыслу. Снимает в цикле: `ip rule add` дубликаты не проверяет, и копий может быть
 * несколько. */
void rule_add(unsigned mark, int table);
/* Снять установленные соединения выхода: следующий их пакет пройдёт обычным путём и получит
 * решение о маршруте заново. Нужна потому, что при включённой выгрузке потоков пакеты
 * установленного соединения до нашей цепочки не доходят — подробности у определения. */
void conntrack_evict(unsigned mark);
void rule_drop(unsigned mark, int table);

/* Привязать таблицу выхода к устройству: правило по метке и маршрут по умолчанию. Живёт в
 * failover.c, но нужна и клиенту VLESS: он привязывает своё устройство сам, потому что
 * только он знает момент, когда оно готово нести трафик. */
void bind_device(struct output *o, const char *dev);

/* ---- подъём выхода vless: состояние, у которого раньше не было имени --------------------
 *
 * Устройство туннеля vless появляется НЕ СРАЗУ. При `node: -1` («первый рабочий» — умолчание
 * и то, что рекомендует интерфейс) клиент перебирает узлы подписки с таймаутом восемь секунд
 * на узел, и устройство создаётся только после выбора. Пока перебор идёт, устройства нет — и
 * диагностика печатала «устройства нет, туннель не поднят», то есть в точности то же, что при
 * настоящем отказе. На подписке из трёх десятков нерабочих узлов это минуты видимого «не
 * работает» на исправной настройке, и наоборот: настоящий отказ выглядел медленной проверкой
 * (I-100).
 *
 * Поэтому клиент рассказывает о ходе перебора файлом в state_dir, а status и diag его читают.
 * Файл, а не ubus: движок ubus-сервисом не является, а управляющий слой уже читает его вывод.
 *
 * УСТАРЕВАНИЕ обезврежено по-разному для двух состояний, и это главное в этой паре функций.
 * `probing` верен, только пока жив написавший его процесс, — проверяется по /proc/<pid>;
 * `failed` обязан пережить смерть процесса (клиент выходит с кодом 1, procd поднимает его
 * заново каждые пять секунд), поэтому верен, пока свеж. Отсутствие файла и устаревший файл
 * читаются как «не знаем» и возвращают PROBE_NONE — то есть прежнее поведение, а не жёлтая
 * метка на исправном роутере. */
enum probe_state {
    PROBE_NONE = 0,   /* нечего сказать: файла нет, он устарел или писавший процесс мёртв */
    PROBE_RUNNING,    /* перебор идёт: проверяется узел `node` из `total` */
    PROBE_FAILED,     /* перебор кончился: ни один узел не ответил (total>0) либо узлов нет */
};

struct probe_status {
    enum probe_state state;
    int node;         /* номер проверяемого узла, с единицы; 0 у PROBE_FAILED */
    int total;        /* сколько пригодных узлов нашлось в подписке */
};

/* Записать ход перебора. node с единицы; total — сколько пригодных узлов. */
void probe_report(const char *out_name, enum probe_state st, int node, int total);
/* Убрать запись: устройство поднялось, объяснять больше нечего. */
void probe_clear(const char *out_name);
/* Прочитать. PROBE_NONE, если сказать нечего. */
struct probe_status probe_read(const char *out_name);

