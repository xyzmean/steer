/* Чтение скомпилированных наборов правил sing-box (`.srs`) — см. srs.c. */
#ifndef STEER_SRS_H
#define STEER_SRS_H

#include <stdio.h>

/* Разобрать файл `.srs` и напечатать его содержимое НАШИМ синтаксисом списка.
 *
 * Домены уходят в файл `dom_path`, подсети в `pfx_path`; NULL вместо любого из них
 * означает stdout. Пути, а не открытые потоки: открыть и закрыть их — часть работы этой
 * функции, и сообщения об отказе тогда живут там же, где остальные её отказы, а не в
 * диспетчере подкоманд.
 *
 * Списка два, потому что у нас это два разных вида списка: `domains_files` читает dnsd,
 * `prefixes_files` уезжает в набор nftables.
 *
 * Возврат: 0 — разобрано целиком; 1 — файл не наш или испорчен; 2 — в наборе есть
 * правило, которое мы понимаем, но выразить не можем (см. шапку srs.c). Во всех
 * ненулевых случаях причина печатается в stderr, и напечатанное на stdout НЕ годится
 * к применению: половина набора — это не набор.
 */
/* `meta_path` — третий выход: сужение канала по протоколу и портам (`proto=`, `ports=`),
 * если набор его несёт. NULL означает «не нужно», и тогда набор С СУЖЕНИЕМ отвергается
 * кодом 2: отдать его подсети, потеряв «только udp 50000-65535», значит увести в туннель
 * весь TCP к 104.16.0.0/12 — молча. */
int srs_dump(const char *path, const char *dom_path, const char *pfx_path,
             const char *meta_path);

#endif
