/* `steer srs-read` — набор правил sing-box (`.srs`) нашим синтаксисом списка (см. srsread.c). */
#ifndef STEER_SRSREAD_H
#define STEER_SRSREAD_H

/* Разобрать файл `.srs` и напечатать его содержимое НАШИМ синтаксисом списка.
 *
 * Домены уходят в файл `dom_path`, подсети в `pfx_path`; NULL вместо любого из них означает
 * stdout. `meta_path` — третий выход: сужение по протоколу и портам (`proto=`, `ports=`), если
 * набор его несёт; NULL означает «не нужно», и тогда набор С СУЖЕНИЕМ отвергается кодом 2:
 * отдать его подсети, потеряв «только udp 50000-65535», значит увести в туннель весь TCP к
 * 104.16.0.0/12 — молча.
 *
 * Возврат: 0 — разобрано; 1 — файл не наш или испорчен; 2 — в наборе есть то, что тремя файлами
 * не выражается (исключения, ограничение по клиенту или приложению) либо сужение без
 * --meta-out. Во всех ненулевых случаях причина печатается в stderr, и напечатанное НЕ годится
 * к применению.
 *
 * Сам канал этого больше не требует: `.srs` подключается к нему ключом `srs_files` и читается
 * движком напрямую (src/model/srs.c). Команда осталась для отладки — посмотреть глазами, что
 * приехало из двоичного файла, — и для управляющего слоя, пока он раскладывает наборы сам. */
int srs_dump(const char *path, const char *dom_path, const char *pfx_path,
             const char *meta_path);

#endif
