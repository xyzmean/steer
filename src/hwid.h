/* Идентификатор роутера и описание устройства — В БАЗОВОЙ СБОРКЕ ТОЖЕ.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ТАМ, ГДЕ ЛЕЖАЛ. Он лежал в src/ext/subfetch.c, потому что
 * заводился ради одного читателя — заголовка `x-hwid` для панели подписки, а панель бывает
 * только в расширенной сборке. Читателей стало двое: второй — телеметрия, и она обязана
 * работать на роутере без расширенной сборки движка и вовсе без движка. Пока идентификатор
 * жил в расширенной части, `steer sub-hwid` там отвечал отказом «нужен пакет
 * steer-extended», то есть телеметрия молча потеряла бы ровно те роутеры, ради которых
 * заводится: у половины обращений в поддержку движок не установлен.
 *
 * ЗНАЧЕНИЕ ОБЯЗАНО ОСТАТЬСЯ ПРЕЖНИМ, байт в байт. Оно уже разошлось по панелям подписок:
 * человек видит там свою коробку по строке «splify2-…» и по ней освобождает слот. Поэтому
 * переезд — это перенос БЕЗ ЕДИНОГО ИЗМЕНЕНИЯ шага вычисления, и стенд сверяет результат с
 * независимым эталоном (`sha256sum` в оболочке), а не с нашим же кодом. */
#ifndef STEER_HWID_H
#define STEER_HWID_H

#include <stddef.h>

/* Значение переменной окружения или умолчание. Живёт здесь, потому что здесь три шва
 * стенда (каталог устройств, файл описания системы, файл модели), а второй экземпляр той же
 * трёхстрочной функции — это второе место, где решается, что считать пустым значением. */
const char *steer_env_or(const char *name, const char *dflt);

/* «splify2-<20 шестнадцатеричных знаков>» — sha256 от «splify2:<mac>».
 * 0 — считать не из чего: ни одного физического порта с постоянным MAC. */
int steer_hwid(char *out, size_t n);

/* Описание устройства для панели и для отчётов: «OpenWrt 24.10.0», «Xiaomi AX3000T». */
void steer_dev_os(char *out, size_t n);
void steer_dev_model(char *out, size_t n);

/* Идентификатор для ТЕЛЕМЕТРИИ — «sp-<32 шестнадцатеричных знака>».
 *
 * ЗАЧЕМ ОТДЕЛЬНОЕ ЗНАЧЕНИЕ, А НЕ ТОТ ЖЕ HWID. HWID роутер уже отправляет ЧУЖОМУ серверу —
 * заголовком `x-hwid` панели подписки. Положив его же в свою базу, мы создали бы общий ключ:
 * продавец подписок, увидевший нашу базу, сопоставил бы её строки со своими платящими
 * клиентами. Второе значение из того же MAC этого не даёт: совпадение искать не по чему.
 *
 * ЗАЧЕМ МЕДЛЕННО. Прообраз короткий и предсказуемый: строка из MAC-адреса, где неизвестны
 * 48 бит, причём первые 24 — это OUI из публичного реестра (реально встречается несколько
 * сотен). Одиночный sha256 перебирается за минуты на одной видеокарте, то есть база
 * идентификаторов была бы базой восстановимых MAC-адресов, а MAC следует за железом при
 * перепродаже роутера. PBKDF2 с двумястами тысячами проходов поднимает эту цену на шесть
 * порядков: те же 2^40 вариантов стоят уже около 4·10^17 сжатий.
 *
 * ЧЕГО ЭТО НЕ ЗАКРЫВАЕТ, и это надо сказать вслух, а не спрятать за «медленным хешем».
 * Сам HWID остаётся быстрым хешем от MAC и по-прежнему уезжает панели подписки. Значит тот,
 * у кого есть СПИСОК HWID (продавец подписок), может перебором восстановить из него MAC —
 * это те же 2^40 быстрых вычислений, что и раньше, — а восстановив, посчитать наш `tid` уже
 * по одному медленному хешу на адрес и сопоставить базы. Отдельный прообраз этому не мешает:
 * он мешает только случайному совпадению значений, а не осмысленному сопоставлению.
 *
 * Что медленный счёт действительно даёт: НАША база сама по себе перестаёт быть списком
 * восстановимых MAC-адресов. Утёкшая или запрошенная у нас, она не превращается в перечень
 * железа — а именно этим она была бы с одиночным sha256.
 *
 * ЧТО ЭТО НЕ ДАЁТ, и это надо знать. Соли, своей у каждого роутера, здесь нет НАРОЧНО:
 * соль негде хранить так, чтобы она пережила сброс к заводским настройкам, а идентификатор
 * пережить его обязан — иначе каждый сброс приходит в панель новым роутером. Значит соль
 * общая и публичная, и цена перебора — ОДНОРАЗОВАЯ для того, кто возьмётся: посчитанная
 * таблица покрывает сразу все роутеры. Это размен, а не защита от всего: он делает
 * восстановление дорогим, а не невозможным.
 *
 * Число проходов переопределяется через STEER_DEVID_ITERS — только ради стендов: полный
 * счёт занимает на роутере секунды, и гонять его в каждой проверке незачем. */
int steer_dev_id(char *out, size_t n);

/* PBKDF2-HMAC-SHA256 — то, чем считается предыдущее. Отдельно объявлен, чтобы стенд мог
 * сверить его с известными ответами RFC 6070, а не только через готовый идентификатор, где
 * половина вывода обрезана. */
void steer_pbkdf2_sha256(const unsigned char *pw, size_t pwlen,
                         const unsigned char *salt, size_t saltlen,
                         unsigned iters, unsigned char *out, size_t outlen);

/* Подкоманда `dev-id`: печатает {"tid":…}. Отдельно от sub-hwid по цене — см. hwid.c. */
int cmd_dev_id(void);

/* Подкоманда `sub-hwid`: печатает {"hwid":…,"os":…,"model":…}. Ничего не скачивает и никуда
 * не ходит. В базовой сборке отвечает тем же, что и в расширенной, — это и есть смысл
 * переезда. */
int cmd_sub_hwid(void);

/* SHA-256 одним вызовом. Своя реализация вместо mbedtls — потому что базовая сборка с
 * mbedtls не связывается вовсе (её и ставят туда, где расширенной части нет), а тащить
 * библиотеку ради одного хеша значило бы поменять состав зависимостей пакета ради поля
 * телеметрии. Тот же размен, что с puff.c: вложить маленькое и проверяемое вместо того,
 * чтобы связываться с большим. */
void steer_sha256(const unsigned char *in, size_t n, unsigned char out[32]);

#endif
