/* Обвязка командной строки: одна таблица команд, из которой растут и справка, и
 * разбор аргументов.
 *
 * Почему таблицей, а не цепочкой strcmp в main(). Раньше справка была одним куском
 * текста в начале main(), а разбор — общим циклом ниже; они расходились молча. Так в
 * usage жила строка про флаг, которого разбор не знал, и наоборот: `steer apply
 * --dryrun` (опечатка) не был ни флагом, ни ошибкой — общий цикл клал неизвестное
 * слово в позиционный аргумент, apply его не читал, и правила применялись НА САМОМ
 * ДЕЛЕ вместо обещанного показа. Теперь список флагов команды — это данные: по нему
 * печатается синопсис и по нему же проверяется каждый аргумент, так что разойтись им
 * больше негде.
 */
#ifndef STEER_CLI_H
#define STEER_CLI_H

#include <stdio.h>

/* Позиционных аргументов ни у одной команды больше одного, но запас в структуре
 * дешевле, чем разбор «сколько их пришло» вокруг единственного указателя. */
#define CLI_MAXPOS 2

struct cli_cmd {
    const char *name;
    const char *group;   /* заголовок раздела в общей справке */
    const char *args;    /* позиционные в синопсисе; "" — их нет */
    const char *brief;   /* одна строка для списка команд */
    const char *detail;  /* абзац для `steer help <команда>`; NULL — нечего добавить */
    const char *flags;   /* имена флагов через пробел, в порядке показа */
    int npos;            /* сколько позиционных ОБЯЗАТЕЛЬНО */
    int passthru;        /* аргументы разбирает сама подкоманда (fit, dnsd) */
    int ext;             /* есть только в расширенной сборке */
    /* Есть только в СЕРВЕРНОЙ сборке (архив для VPS). Отдельно от ext, потому что это
     * другой артефакт, а не другой пакет: сказать человеку «нужен steer-extended» там, где
     * нужен архив хаба, значило бы послать его не туда. Команда при этом НАЗВАНА в справке
     * любой сборки — «неизвестная команда» заставила бы искать опечатку вместо артефакта. */
    int srv;
    /* Сколько позиционных ДОПУСТИМО. Ноль означает «столько же, сколько обязательно», —
     * поэтому строки, написанные до появления этого поля, значат ровно то же, что значили.
     *
     * Понадобилось ровно одной команде: `xsteer` работает и с именем выхода (тогда всё берётся
     * из спеки), и без него (тогда устройством владеет netifd, а настройки приходят флагами).
     * Выражать это двумя командами было бы хуже: одна и та же работа под двумя именами
     * расходится в справке и в поведении. */
    int npos_max;
};

/* Значения, собранные общим разбором. Умолчания расставляет cli_parse. */
struct cli_args {
    const char *spec;
    const char *state_dir;   /* NULL — оставить то, что уже стоит в g_state_dir */
    const char *kind;
    /* --devices: печатать имена УСТРОЙСТВ вместо имён выходов.
     *
     * Нужно управляющему слою: имя устройства выводится из имени выхода, но может быть
     * задано в спеке и явно, поэтому «имя выхода вместо имени устройства» — это молчаливо
     * неверный список ровно там, где по нему настраивают фаервол. Спрашивать движок надёжнее,
     * чем повторять правило вывода имени в shell. */
    int devices;
    const char *forward;
    const char *config;      /* конфигурация xsteer в стиле wg */
    const char *device;      /* готовое устройство TUN (режим netifd) */
    /* Транспорт xsteer. Трёхзначно нарочно: 1 — «--stream», -1 — «--no-stream», 0 — не
     * назван. Различие нужно потому, что режим можно задать и в спеке, а ключ обязан её
     * перебивать в обе стороны — иначе выключить руками заданный в спеке поток было бы
     * нечем. */
    int stream, stream_port;
    const char *pos[CLI_MAXPOS];
    int npos;
    int dry_run, verbose, obfs, node, timeout, listen;
};

const struct cli_cmd *cli_lookup(const char *name);

/* Справка. cmd == NULL — общий список команд. Поток отдельным параметром: по запросу
 * (`steer --help`) справка идёт в stdout и код возврата 0, при ошибке — в stderr и 2.
 * Иначе `steer --help | less` показывал бы пустую страницу. */
void cli_help(FILE *out, const struct cli_cmd *cmd);
void cli_usage_short(FILE *out);
void cli_version(FILE *out);

/* Есть ли среди аргументов просьба о справке. Проверяется до разбора: у `fit` и `dnsd`
 * свои парсеры, и --help должен работать одинаково во всех командах. */
int cli_wants_help(int argc, char **argv);

/* «Нет такой команды» с подсказкой по ближайшему имени. Не возвращается. */
void cli_unknown(const char *name);

/* Разбирает argv[from..argc-1] по списку флагов команды. Любая неточность —
 * неизвестный флаг, потерянное значение, лишний позиционный аргумент, не-число там,
 * где ждали число — это выход с кодом 2 и внятной строкой, а не молчание. */
void cli_parse(const struct cli_cmd *cmd, int argc, char **argv, int from,
               struct cli_args *out);

#endif
