/* xsteer: эпохи — периодическая смена транспортных ключей ради ПРЯМОЙ СЕКРЕТНОСТИ, без
 * нового рукопожатия, без разрыва соединения и без единого байта на проводе.
 *
 * ЗАЧЕМ. Рукопожатие Noise IK даёт прямую секретность один раз: вскрыв статический ключ пира
 * потом, записанный трафик уже не расшифровать. Но транспортные ключи после Split живут всё
 * соединение, и утечка ОПЕРАТИВНОЙ памяти в конце сессии вскрывает её целиком с самого
 * начала — хоть терабайт. Ратчет закрывает это: ключи прошлых эпох стёрты и из текущих не
 * выводятся.
 *
 * ПОЧЕМУ НЕ РУКОПОЖАТИЕМ И НЕ РАЗРЫВОМ. Разрыв соединения ради смены ключей рвёт все
 * внутренние сессии TCP на ровном месте — ровно та плата, которую xsclient.c платит сейчас
 * при xs_retire_due, и в потоке платить её больше не нужно. Повторное рукопожатие внутри
 * потока стоило бы новых записей: настоящий xhttp после установки соединения не шлёт ничего,
 * кроме записей данных (17 03 03 LL LL), и запись иного вида — или узнаваемый обмен
 * фиксированных размеров посередине потока — это ровно тот признак, за который цепляется
 * определитель.
 *
 * ПОЭТОМУ РАТЧЕТ НЕЯВНЫЙ, И ЭТО ГЛАВНОЕ СВОЙСТВО. Номер эпохи НЕ ПЕРЕДАЁТСЯ вовсе: обе
 * стороны считают одни и те же байты потока (смещение и без того служит nonce) и выводят
 * номер эпохи делением смещения на её длину. На проводе не меняется НИ ОДНОГО БАЙТА: ни
 * нового типа записи, ни служебного кадра, ни лишнего круга, ни изменения размеров и времён.
 * Отличить поток с ротацией от потока без неё нельзя даже зная, что она есть, — сравнивать
 * не с чем.
 *
 * ГДЕ ВКЛЮЧЕНО, И ПОЧЕМУ НЕ ВЕЗДЕ. Только в режиме потока (xsstream.h). В поддельном TCP
 * смещение берётся из относительного номера последовательности, а его выбирает ОТПРАВИТЕЛЬ
 * сегмента — то есть посторонний, попавший в окно приёма, назвал бы далёкое смещение и
 * заставил нас ратчетить вперёд, потеряв текущие ключи. Там смена ключей остаётся прежней:
 * ретайр соединения по объёму (xs_retire_due в xswire.h).
 *
 * ЧЕГО ЭТОТ РАТЧЕТ НЕ ДАЁТ, СКАЗАНО ПРЯМО. Он привязан к ОБЪЁМУ, а не ко времени:
 * соединение, которое сутки стоит почти без трафика, остаётся в одной эпохе (keepalive
 * двигает смещение на десятки байт в минуту). Это осознанный выбор: смена по времени
 * требует либо часов, сходящихся у сторон, либо пробных расшифровок, а объём — величина,
 * которую обе стороны знают точно и одинаково. Риск утечки растёт вместе с объёмом, то есть
 * ровно там, где ратчет и работает.
 *
 * Порт noise/epoch.go реализации на Go. Совпадение обязательно до последнего байта: пир на
 * роутере разговаривает с тем же хабом, что десктоп, и номер эпохи не передаётся — значит
 * разойтись в выводе ключей означало бы «рукопожатие прошло, а на 64-м мегабайте туннель
 * молча умер».
 */
#ifndef STEER_XSEPOCH_H
#define STEER_XSEPOCH_H
#include <stdint.h>
#include <stddef.h>
#include "tls13.h"

/* Длина эпохи в байтах потока. Шестьдесят четыре мегабайта: на гигабитном канале это эпоха в
 * полсекунды, а стоимость смены (два HKDF и разворот шифра) — микросекунды, то есть незаметна
 * даже при восьми сменах в секунду. Меньше делать нет смысла: выигрыш в секретности упирается
 * уже не в размер эпохи, а в то, как быстро память попадает к противнику. */
#define XS_EPOCH_BYTES ((uint64_t)1 << 26)

/* На сколько эпох вперёд разрешено прыгнуть за один раз. В потоке смещения точны и прыжок
 * всегда единичный; предел стоит от испорченного смещения, чтобы одна запись не заставила
 * считать миллион HKDF. */
#define XS_EPOCH_JUMP_MAX 64

/* Состояние ратчета на ОДНО направление. Живёт рядом с ключами этого направления и
 * принадлежит тому же потоку. */
struct xs_epoch {
    int      on;             /* 0 — поведение ровно прежнее, байт в байт */
    uint64_t epoch;          /* номер текущей эпохи; на проводе его нет */
    uint8_t  root[32];       /* корень текущей эпохи: ратчетится вперёд и стирается за собой */
    /* Прошлая эпоха остаётся ОДНОЙ ступенью назад: в потоке порядок гарантирован и она не
     * нужна, но запись, застрявшая на границе, не должна стоить обрыва. Дальше одной ступени
     * не храним — иначе ратчет не даёт того, ради чего сделан. */
    struct tls13_keys prev;
    int      prev_ok;
};

/* Включить ратчет. Корень выведен рукопожатием (xs_hs_roots), свой на каждое направление.
 *
 * Обе стороны обязаны включить его ДО первой записи данных: номер эпохи считается из
 * смещения, и сторона, включившая ратчет позже, разошлась бы с другой на те записи, что
 * успели уехать. */
void xs_epoch_start(struct xs_epoch *e, const uint8_t root[32]);

/* Освободить прошлые ключи. Зовётся при закрытии соединения; повторный вызов безопасен. */
void xs_epoch_stop(struct xs_epoch *e);

/* Зашифровать запись со смещением off. Пока on == 0 — ровно tls13_aead_seal и ничего больше.
 *
 * Ключи ratchet-ится ЗДЕСЬ, а не отдельным вызовом снаружи: эпоха определяется смещением
 * записи, и «сначала подвинуть эпоху, потом зашифровать» двумя вызовами означало бы, что
 * между ними можно вклиниться с другим смещением. */
int xs_epoch_seal(struct xs_epoch *e, struct tls13_keys *k, uint64_t off,
                  const uint8_t *aad, size_t aad_n,
                  uint8_t *buf, size_t n, uint8_t *tag);

/* Расшифровать запись со смещением off. Запись прошлой эпохи расшифровывается прошлыми
 * ключами и состояние НЕ откатывает; запись эпохи старше прошлой отвергается как чужая — её
 * ключи стёрты, и в этом весь смысл ратчета. */
int xs_epoch_open(struct xs_epoch *e, struct tls13_keys *k, uint64_t off,
                  const uint8_t *aad, size_t aad_n,
                  uint8_t *buf, size_t n);

/* Номер текущей эпохи: нужен журналу и стенду. На проводе его нет, и увидеть смену иначе
 * негде. */
static inline uint64_t xs_epoch_now(const struct xs_epoch *e) { return e->epoch; }

#endif
