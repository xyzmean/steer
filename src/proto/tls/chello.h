/* Разбор ClientHello: где внутри него лежат поля, которые несут рукопожатие xsteer.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ И ТОЛЬКО РАЗБОР. Собирает Hello по-прежнему reality.c — там
 * побайтово воспроизведён отпечаток Chrome, и второй сборщик означал бы, что отпечаток
 * живёт в двух местах и однажды разъедется. А вот РАЗБОРА в проекте не было вовсе: клиенту
 * он не нужен, Hello он только отправляет. Хабу xsteer он нужен обязательно, потому что
 * смещения полей в Hello заранее неизвестны: порядок расширений перемешивается на каждом
 * соединении (Chrome 110+ делает так же), а значит и session_id, и key_share, и набивка
 * ECH лежат каждый раз в разных местах.
 *
 * ЗДЕСЬ ГРАНИЦА ДОВЕРИЯ. На публичный порт хаба приходит что угодно от кого угодно, и это
 * первый код, который смотрит на присланные байты. Поэтому: ни одного чтения за пределами
 * буфера, все длины проверяются перед использованием, ни одной записи в разбираемый буфер.
 * Ни сети, ни mbedtls — стенд (tests/chellomatch.c) проверяет всё это в памяти, включая
 * обрезанные и намеренно испорченные Hello.
 */
#ifndef STEER_CHELLO_H
#define STEER_CHELLO_H
#include <stdint.h>
#include <stddef.h>

/* Группа x25519 в supported_groups и key_share. */
#define CHELLO_GROUP_X25519 0x001D
/* Фальшивое расширение ECH, в набивке которого едет запечатанный статический ключ. */
#define CHELLO_EXT_ECH      0xFE0D

/* Смещения даются ОТ НАЧАЛА ЗАПИСИ (то есть от байта 0x16), потому что именно запись
 * приходит из сокета и именно по ней считается AAD аутентификатора. Ноль в поле смещения
 * означает «этого в Hello нет». */
struct chello_ref {
    size_t hs_off, hs_n;    /* сообщение рукопожатия внутри записи: сюда смотрит AAD */
    size_t sid_off;         /* legacy_session_id, ровно 32 байта */
    size_t ks_off;          /* публичный ключ x25519 в key_share, ровно 32 байта */
    size_t ech_off, ech_n;  /* набивка ECH: где и сколько */
    /* Первый набор шифров TLS 1.3 из списка клиента, GREASE пропущен. Через него
     * согласуется AEAD: выбор делает пир, потому что узкое место — роутер, а не VPS. */
    uint16_t suite;
    char sni[128];
};

/* 0 — разобрано, -1 — это не ClientHello или он битый. */
int chello_parse(const uint8_t *rec, size_t n, struct chello_ref *out);

/* Значение GREASE — те, что браузер вставляет нарочно, чтобы посредники не считали
 * неизвестное недопустимым (RFC 8701). Пропускать их обязательно: иначе «первым набором
 * шифров» окажется заведомо несуществующий, и согласование AEAD сломается на ровном месте. */
static inline int chello_is_grease(uint16_t v) {
    return (v & 0x0F0F) == 0x0A0A && (v >> 8) == (v & 0xFF);
}

#endif
