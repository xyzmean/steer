#ifndef STEER_ERR_H
#define STEER_ERR_H

/* Правило 5, docs/architecture.md, раздел 2: модели и компилятору die() не нужен. Они
 * возвращают код ошибки и заполняют эту структуру, а завершает процесс только точка входа —
 * command-обработчики в daemon/, cli/, tools/, kinds/awg.c и proto (xsteer, tgws, vless).
 *
 * Один буфер, а не malloc: сообщение живёт мгновение (от места отказа до err_die в той же
 * команде), и распределение памяти под то, что тут же печатается и отбрасывается, было бы
 * тратой ради необходимости освобождать то, чего не нужно освобождать. 1024 байта — с запасом
 * над любым из существующих сообщений (самые длинные собираются в буферы по 512, см. parse.c). */
struct err {
    char msg[1024];
};

/* Форматирует ТОЧНО как прежний die(): тот же fmt с ОДНИМ %s. Кладёт результат в e->msg и
 * возвращает -1, чтобы годилось прямо в `return err_set(e, fmt, a);` — ровно там, где раньше
 * стояло `die(fmt, a);`. */
int err_set(struct err *e, const char *fmt, const char *a);

/* Пробрасывает уже отформатированную ошибку глубже, если она уже записана (e->msg[0] непусто —
 * то есть отказал внутренний вызов, который сам сформировал текст), иначе форматирует ту,
 * что даёт вызывающий, — ровно как раньше `if (helper(...) != 0) die(fmt, a);`, только helper
 * теперь может УЖЕ умереть своими словами, и тогда вызывающему нечего добавить. e зануляется
 * ОДИН РАЗ на весь разбор (в load_spec), и после первого отказа никто не пишет в него снова —
 * поэтому проверка e->msg[0] однозначно отличает «уже сказано» от «сказать нечего». */
static inline int err_prop(struct err *e, const char *fmt, const char *a) {
    return e->msg[0] ? -1 : err_set(e, fmt, a);
}

/* Печатает "steer: %s\n" в stderr и завершает процесс кодом 2 — байт в байт то же, что печатал
 * die(). Зовут только точки входа, после того как модель или компилятор вернули -1. */
void err_die(const struct err *e);

/* Прежний немедленный отказ: печатает "steer: " + fmt%a + "\n" в stderr и exit(2). Остаётся
 * только для точек входа (разбор аргументов командной строки, «такой команды нет» и подобное) —
 * там, где сообщать об ошибке некому, кроме как немедленно завершившись. Модель (src/model) и
 * компилятор (src/compile) больше её не вызывают — см. правило 5. */
void die(const char *fmt, const char *a);

#endif
