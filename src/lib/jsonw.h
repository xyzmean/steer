#ifndef STEER_JSONW_H
#define STEER_JSONW_H
#include <stdio.h>

/* Экранирование строки JSON — одно на всё дерево. Было переписано заново в четырёх местах
 * (hwid.c, dnsd.c, ext/subfetch.c, ext/tunnel.c — docs/architecture.md, «Мелкие повторы»),
 * и все четыре копии совпадали посимвольно, кроме одной: у журнала имён резолвера строка
 * приходит из чужого DNS-сообщения, а не из данных, которые движок сам составил, поэтому ей
 * мало кавычки и обратной косой — экранировать нужно и верхнюю половину байтов, иначе один
 * странный запрос сделал бы весь ответ невалидным JSON. Отсюда две функции, а не одна. */

/* Кавычка и обратная косая — обратной косой, байты < 0x20 — \u%04x, остальное как есть:
 * движок сам пишет UTF-8, разбирать его тут незачем. s == NULL печатается как "". */
void jsonw_str(FILE *f, const char *s);

/* То же самое плюс байты >= 0x7f — тоже \u%04x. Для строк, которые не гарантированно
 * печатный ASCII/UTF-8 (имя из чужого DNS-сообщения, скопированное как есть). NULL сюда не
 * приходит ни у одного вызывающего — как и у прежних копий, вызов с NULL не проверяется. */
void jsonw_str_ascii(FILE *f, const char *s);

#endif
