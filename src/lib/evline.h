#ifndef STEER_EVLINE_H
#define STEER_EVLINE_H
#include <stddef.h>

/* ФОРМАТ СОБЫТИЙ ПОМОЩНИКОВ — контракт между демоном steerd (читает daemon/supd.c, демон с
 * --supervise, шаг 4, docs/architecture.md, «4а. Устройство 1.8», «Дети и здоровье») и
 * помощниками, которых он поднимает (клиент VLESS, клиент xsteer, мост tgws, обфускатор obfs).
 * Демон даёт помощнику дескриптор трубы в переменной окружения STEER_EVENT_FD; помощник пишет в
 * неё события, демон читает и решает, жив ли выход и что о нём сказать `status`/`diag`/`subscribe`.
 *
 * ОДНА СТРОКА JSON НА СОБЫТИЕ, с завершающим \n: `{"ev":"up"}\n`. Пишется ОДНИМ write() —
 * труба это гарантирует атомарным (POSIX: запись до PIPE_BUF байт не перемешается с чужой,
 * даже из другого потока того же помощника — см. tgws.c, где события шлют разные потоки
 * serve()). Труба НЕ БЛОКИРУЕТ: дескриптор переводится в O_NONBLOCK при открытии, и если она
 * полна (демон отстал или не читает), запись просто не проходит — событие теряется молча,
 * помощник не встаёт и не ждёт. Демон получит следующее.
 *
 * СОБЫТИЯ, ИХ ПОЛЯ И ПОМОЩНИКИ, КОТОРЫЕ ИХ ПИШУТ:
 *
 *   ev        поля              кто пишет           когда
 *   ------    ---------------   -----------------   ---------------------------------------
 *   up        —                 vless, xsteer,      узел/сессия/мост поднялись и готовы
 *                                tgws, obfs          нести трафик
 *   down      why (строка)      vless, xsteer,      узел/сессия/мост отказали или упали;
 *                                tgws, obfs          why — короткая причина, для человека
 *   node      n, total (числа)  vless               перебор подписки: проверяется узел n
 *                                                    из total (нумерация с единицы)
 *   nonode    node, total       vless               выбранного человеком номера нет в
 *             (числа)                               подписке (node — как он его написал,
 *                                                    total — сколько узлов пригодно)
 *   health    dc, media (числа), tgws                мост оценил путь как неживой: через
 *             domain (строка),                      domain для ДЦ dc (media — обычный или
 *             cool (число)                          медийный) данные не идут, путь отставлен
 *                                                    на cool секунд
 *
 * Событие пишется ТОЛЬКО при смене состояния — не на каждый пакет и не на каждый проход
 * цикла. Без STEER_EVENT_FD (ручной запуск, стенды, старое поведение) evline_open() выключает
 * себя, и evline_emit() ничего не делает — остальное поведение помощника не меняется.
 *
 * Читает эти строки (evline_parse) демон — шаг 2 и дальше; в 1.8 шаг 1 только пишет. */

enum evline_type { EVLINE_STR = 0, EVLINE_INT = 1 };

/* Взять STEER_EVENT_FD из окружения. Нет переменной, она не число, отрицательна или не
 * называет открытый дескриптор — события выключены навсегда для этого процесса, и
 * evline_emit() дальше ничего не делает (ни разбора аргументов, ни системных вызовов).
 * Идемпотентна: повторный вызов не переоткрывает трубу. evline_emit() зовёт её сама при
 * первом обращении, если помощник не позвал явно, — вызывать её отдельно нужно, только
 * если важно решить включённость до первого события. */
void evline_open(void);

/* Одно событие. Дальше — пары (ключ, EVLINE_STR, const char *значение) или
 * (ключ, EVLINE_INT, long значение), сколько нужно, и завершающий (const char *)NULL —
 * БЕЗ него разбор аргументов уйдёт за пределы того, что передали. Строки печатаются через
 * jsonw_str_ascii (экранирует и управляющие байты, и байты вне ASCII — why может прийти
 * из текста, который движок не составлял сам целиком, см. jsonw.h). Событие без полей:
 * `evline_emit("up", (const char *)NULL);`. Выключено (evline_open() ничего не нашло) —
 * функция возвращается сразу же. Труба полна — write() теряет событие молча. */
void evline_emit(const char *ev, ...);

/* ---- разбор строки, для читателя (демон) --------------------------------------------- */

#define EVLINE_MAXFIELDS 6
#define EVLINE_KEYLEN 16
#define EVLINE_VALLEN 200

struct evline_field {
    char key[EVLINE_KEYLEN];
    enum evline_type type;
    union {
        long i;
        char s[EVLINE_VALLEN];
    } v;
};

struct evline {
    char ev[EVLINE_KEYLEN];
    int n;                              /* сколько полей в f, помимо самого ev */
    struct evline_field f[EVLINE_MAXFIELDS];
};

/* Разобрать ОДНУ строку (конечный \n, если есть, игнорируется). 0 — разобралось и есть
 * строковое поле "ev"; -1 — не похоже на нашу строку (не объект JSON, нет "ev", "ev" не
 * строка). Полей сверх EVLINE_MAXFIELDS — отбрасываются молча: контракт версии 1 не носит
 * больше двух-трёх полей на событие (таблица выше), а вырасти он может только вместе с
 * этим числом. Разбирает ТОЛЬКО то, что сама evline_emit и печатает (плоский объект,
 * строки и целые числа) — это не общий разбор JSON. */
int evline_parse(const char *line, struct evline *out);

/* Найти поле по имени. NULL/0, если поля нет или оно другого типа. */
const char *evline_str(const struct evline *e, const char *key);
int evline_int(const struct evline *e, const char *key, long *out);

#endif
