/* xsteer: записи по НАСТОЯЩЕМУ потоку TCP — рамка, смещения, буфер чтения.
 *
 * ЗАЧЕМ ЭТО ЕСТЬ, ЕСЛИ ЕСТЬ ПОДДЕЛЬНЫЙ TCP. Поддельный TCP (src/obfs.c) требует сырого
 * сокета и правила против RST собственного ядра. Там, где ни того, ни другого нет, весь
 * протокол недоступен целиком: у провайдера, режущего сырые сокеты; в контейнере без
 * CAP_NET_RAW; на канале, где посредник перезаписывает номера последовательности. Режим
 * потока снимает это условие — записи едут по ОБЫЧНОМУ соединению TCP, которое открывает
 * ядро, — и заодно даёт совместимость с реализацией на Go, где десктопные пиры умеют
 * ТОЛЬКО его (на Windows отправка TCP через сырой сокет запрещена системой с XP SP2).
 *
 * ЧТО ЭТО МЕНЯЕТ НА ПРОВОДЕ, И НЕОЖИДАННО В ЛУЧШУЮ СТОРОНУ. Всё, что xsconn.c кропотливо
 * изображает руками (блуждающее окно, PSH раз в шесть сегментов, разрешение SACK, голые
 * подтверждения, keepalive с разбросом), настоящий стек делает сам и точно. Исчезает и
 * сильнейший остаточный признак: в потоке запись живёт своей длиной, может быть восемь
 * килобайт и свободно пересекать границы сегментов — ровно как у настоящего TLS. Отсюда же
 * и упрощение: ни окна приёма (xs_win), ни сборки разрезанных записей (xs_reasm), ни проб
 * пути здесь не нужно — поток доставляет всё, по порядку и без дыр.
 *
 * ЧЕГО ЗДЕСЬ ПОКА НЕТ. Слушающей половины: наш хаб (xshub.c) ждёт поддельный TCP, а поток
 * слушает только хаб реализации на Go (`xsteer hub --stream-port`). Поэтому пир в режиме потока
 * ходит пока к нему; перенос слушающей половины — отдельная работа, и рамка записей в этом файле
 * написана так, чтобы она взяла её как есть (ни одного поля, привязанного к роли).
 *
 * ЧТО ЭТО МЕНЯЕТ ВНУТРИ, И ЭТО ЦЕНА. Внешний транспорт становится надёжным, то есть
 * внутренний TCP пользователя едет поверх TCP. От этого протокол и уходил: потеря наружу
 * превращается в задержку, а не в потерю, и внутренний TCP успевает пере-отправить то, что
 * уже в пути. Насколько это дорого — вопрос замера, а не спора, поэтому режим выбирается
 * ключом, а не заменяет поддельный TCP.
 *
 * ФОРМАТ НЕ МЕНЯЕТСЯ НИ НА БАЙТ. Записи те же (17 03 03 LL LL), nonce тот же: смещение
 * первого байта записи в потоке. В поддельном TCP оно берётся из относительного номера
 * последовательности, здесь — из собственного счётчика; счёт с единицы в обоих случаях,
 * потому что нулевой nonce занят подтверждением рукопожатия (см. xshake.h).
 *
 * СМЕЩЕНИЯ ШЕСТИДЕСЯТИЧЕТЫРЁХБИТНЫЕ, И ЭТО УСЛОВИЕ СТОЙКОСТИ, А НЕ ЗАПАС НА БУДУЩЕЕ.
 * Смещение — это nonce. Тридцати двух бит хватает на четыре гигабайта, после чего счётчик
 * заворачивается и тот же nonce уходит с тем же ключом; для AES-GCM и ChaCha20-Poly1305
 * повтор nonce означает не ослабление, а полную потерю стойкости — вскрывается и подделка,
 * и содержимое. Четыре гигабайта в одном соединении это один фильм, то есть достижимо. В
 * поддельном TCP от заворота спасает ретайр по объёму (xs_retire_due): соединение
 * закрывается на гигабайте, и туннель молчит один круг обмена. Здесь этого не нужно:
 * счётчик шире, заворот недостижим, а прямую секретность даёт смена ключей эпохами
 * (xsepoch.h) — без разрыва и без единого байта на проводе.
 *
 * ПОЧЕМУ СОКЕТ НЕБЛОКИРУЮЩИЙ, А НЕ БЛОКИРУЮЩИЙ, КАК В GO. В Go у соединения две горутины,
 * и запись, упёршаяся в переполненную очередь сокета, останавливает только отправку. Здесь
 * поток один на соединение (то же решение и по той же причине, что в xsclient.c: 95%
 * стоимости пакета — это AEAD), поэтому блокирующая запись остановила бы и ЧТЕНИЕ: при
 * насыщенной отдаче встал бы приём. Поэтому сокет неблокирующий, а недописанный хвост
 * записи хранится здесь же и досылается перед следующей — см. xs_stream_flush.
 *
 * РАЗМЕРЫ БУФЕРОВ САМОГО СОКЕТА МЫ НЕ ЗАДАЁМ, И ЭТО РЕШЕНИЕ, А НЕ УПУЩЕНИЕ. Тот же урок,
 * что записан в src/ext/client.c: любой явный setsockopt(SO_RCVBUF/SO_SNDBUF) ОТКЛЮЧАЕТ
 * автоподстройку окна в Linux и заодно режется по net.core.{r,w}mem_max (по умолчанию
 * 212992). В реализации на Go это измерено на живом хабе: пришпиленные два мегабайта дали
 * приёмный буфер 425984 байт вместо автоподстроечных четырёх мегабайт, то есть потолок
 * 47 Мбит/с против 466 при задержке 72 мс. Автоподстройка растёт по фактическому
 * произведению полосы на задержку — то есть лучше любой нашей постоянной.
 */
#ifndef STEER_XSSTREAM_H
#define STEER_XSSTREAM_H
#include <stdint.h>
#include <stddef.h>
#include "xswire.h"

/* Одна запись целиком: заголовок, полная нагрузка и тег. */
#define XS_STREAM_REC_MAX (XS_REC_HDR + XS_MAX_RECORD + XS_TAG)

/* Буфер чтения — шестьдесят четыре килобайта.
 *
 * Без него на каждую запись приходится ДВА системных вызова чтения (заголовок, потом тело),
 * то есть при мелких записях обратного направления — по два вызова на каждый внутренний
 * пакет. С буфером одно чтение ядра наполняет его целиком, и десятки записей разбираются из
 * памяти без единого лишнего вызова; это главный выигрыш скорости в режиме потока, где
 * горячий путь упирается не в AEAD, а в вызовы. Тот же приём и тот же довод, что у буфера
 * чтения в tls13.c, только больше: там записи Vision по 300 байт, здесь — до восьми
 * килобайт, и семь полных записей должны влезать с запасом.
 *
 * Цена — 64 КБ на соединение, и платится она ТОЛЬКО в режиме потока: структура выделяется
 * при подъёме соединения, а не лежит в каждом воркере (см. xsclient.c). */
#define XS_STREAM_RBUF (1 << 16)

/* Состояние одного направления пары. Принадлежит ОДНОМУ потоку целиком — тому же, что владеет
 * соединением, — поэтому здесь нет ни замков, ни атомиков: счётчик смещения это nonce, и
 * два потока, взявшие одно значение, повторили бы его. */
struct xs_stream {
    int fd;
    /* Смещения следующего байта в каждую сторону. Начинаются с ЕДИНИЦЫ: нулевое занято
     * подтверждением рукопожатия — тот же инвариант, что в поддельном TCP, где ноль забирал
     * SYN. */
    uint64_t tx_off, rx_off;
    /* Буфер чтения: rn — сколько лежит, roff — сколько из этого уже разобрано. */
    size_t   rn, roff;
    uint8_t  rbuf[XS_STREAM_RBUF];
    /* Недописанный хвост ОДНОЙ записи. Появляется, когда очередь сокета переполнилась
     * посреди записи: половина записи в потоке — это не потеря пакета, а разъехавшийся
     * поток, поэтому хвост обязан уехать раньше следующей записи. */
    uint8_t  wpend[XS_STREAM_REC_MAX];
    size_t   wn, woff;
    /* Обрыв замечен: дальше все операции отказывают, не трогая сокет. */
    int      dead;
};

/* Завести поток на готовом сокете. Сокет обязан быть НЕБЛОКИРУЮЩИМ — см. шапку. */
void xs_stream_init(struct xs_stream *st, int fd);

/* ---- отправка ---------------------------------------------------------------
 *
 * Отправка записи неделима: выдать смещение, зашифровать им и отдать сокету надо как одно
 * действие, иначе две записи уедут под одним nonce. Поэтому смещение спрашивается
 * xs_stream_tx_next() ровно перед xs_stream_send(), и между ними не должно быть ничего. */

/* Смещение, с которым уйдёт следующая запись: им её и надо шифровать. */
static inline uint64_t xs_stream_tx_next(const struct xs_stream *st) { return st->tx_off; }

/* Отдать готовую запись (заголовок + шифротекст + тег) целиком.
 *  0 — принята (возможно, хвост остался в wpend и уедет из xs_stream_flush);
 * -1 — обрыв;
 * -2 — предыдущая запись ещё не дописана. Кадр в этом случае ОТБРАСЫВАЕТСЯ вызывающим, а не
 *      копится: повторных передач у нас нет по построению, а очередь кадров означала бы
 *      задержку вместо потери — то есть подмену одного класса отказов другим, менее
 *      заметным. */
int xs_stream_send(struct xs_stream *st, const uint8_t *rec, size_t n);

/* Дослать хвост, если он есть. 1 — хвоста больше нет, 0 — остался, -1 — обрыв. Зовётся
 * перед попыткой отправки и по готовности сокета к записи. */
int xs_stream_flush(struct xs_stream *st);

/* Есть ли неотправленный хвост: по этому признаку цикл добавляет POLLOUT. */
static inline int xs_stream_busy(const struct xs_stream *st) { return st->wn > st->woff; }

/* Отправить сырые байты (записи рукопожатия) и учесть их в смещении. Учесть ОБЯЗАТЕЛЬНО:
 * иначе смещения сторон разъедутся на длину рукопожатия, и первая же запись данных не
 * расшифруется. Здесь допустимо ждать: рукопожатие идёт до появления данных, и очереди
 * сокета оно не переполняет. */
int xs_stream_write_raw(struct xs_stream *st, const uint8_t *b, size_t n);

/* ---- приём -----------------------------------------------------------------
 *
 * Двухшаговый разбор: сначала «дай мне n байт подряд», потом «эти n байт я забрал». Так
 * запись отдаётся указателем ВНУТРЬ буфера, без единой копии, и тем же приёмом собирается
 * ответ на рукопожатие — по записям, ни байтом больше, чтобы данные, приехавшие вплотную за
 * рукопожатием, остались в буфере и не потерялись. */

/* Дождаться n байт подряд (n <= XS_STREAM_REC_MAX).
 * 1 — есть, *p указывает на них; 0 — пока нет (сокет пуст); -1 — обрыв или ошибка. */
int xs_stream_peek(struct xs_stream *st, size_t n, const uint8_t **p);

/* Забрать n байт, ранее полученных xs_stream_peek: двигает и разбор, и смещение приёма. */
void xs_stream_drop(struct xs_stream *st, size_t n);

/* Одна запись данных целиком.
 *  1 — есть: hdr — пять байт заголовка (он же AAD), body — шифротекст с тегом, rel —
 *      смещение для nonce. Байты записи из потока ЗАБРАНЫ, следующий вызов их не увидит;
 *      указатели живут до следующего вызова любой принимающей функции.
 *  0 — запись приехала не вся;
 * -1 — обрыв;
 * -2 — в потоке не запись xsteer. Соединение после этого продолжать нельзя: границы
 *      следующей записи известны только из длины, которой мы уже не верим. */
int xs_stream_recv(struct xs_stream *st, const uint8_t **hdr, const uint8_t **body,
                   size_t *body_n, uint64_t *rel);

#endif
