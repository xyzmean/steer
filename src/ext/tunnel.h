/* Цикл туннеля: пакеты из TUN в потоки VLESS. Границы реализации — в tunnel.c. */
#ifndef STEER_TUNNEL_H
#define STEER_TUNNEL_H
#include "vless.h"
#include "client.h"
/* Нужен struct output: туннель привязывает таблицу к своему устройству сам, а метка и
 * таблица живут в выходе. Объявления вперёд здесь недостаточно — поля читаются. */
#include "../spec.h"

/* Не меньше целой записи TLS: транспорты поверх HTTP/2 отдают за один раз всё её
 * содержимое, и меньший буфер означал бы «не влезло» на совершенно законном кадре. Плюс
 * запас на заголовок VLESS и набивку Vision, которая бывает на 1400 байт длиннее данных.
 *
 * Прежние 8192 работали случайно: Xray пишет буферами по 8 КБ, поэтому записи крупнее не
 * попадались. Договорённости об этом в TLS 1.3 нет — сервер вправе прислать 16384 в любой
 * момент, и тогда чтение возвращало бы ошибку на исправном соединении. */
#define TUNNEL_BUF (VLESS_MIN_RECV_CAP + 2048)

/* Выход передаётся целиком, а не именем устройства: туннель сам поднимает устройство,
 * сам даёт ему адрес и сам привязывает к нему таблицу маршрутизации — а для этого нужны
 * и метка, и таблица из реестра. Никто снаружи не знает момент, когда TUN готов. */
int tunnel_run(struct output *o, const struct vless_node *node);
#endif
