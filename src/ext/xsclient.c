/* Живёт в failover.c: запуск внешней команды без оболочки (argv массивом, не строкой). */
int run_quiet(const char *const argv[]);

#define LOG_W "steer[warn] xsteer: "
#define LOG_I "steer[info] xsteer: "

/* Пачка на приёме: до XSC_BATCH сегментов за один системный вызов. Шестнадцать, как в
 * obfs.c, и по той же причине — пачка больше упирается уже не в вызовы, а в задержку. */
#define XSC_BATCH 16

/* Обратная связь по сборке разрезанных записей. Десять секунд везём по одному кадру после жалобы
 * той стороны — достаточно, чтобы всплеск потерь прошёл, и мало, чтобы надолго терять выигрыш
 * пачек; сообщаем не чаще раза в две секунды; наращиваем обратно раз в три. */
/* ---- режим потока (xsstream.h) ---------------------------------------------
 *
 * Проба живости раз в две секунды. В потоке согласовывать MTU нечем — сегментацией
 * распоряжается ядро, — но проба нужна не ради размера: хаб отвечает на неё эхом, и это
 * ЕДИНСТВЕННЫЙ признак того, что канал несёт трафик в обратную сторону. Без него полный
 * туннель не отличил бы работающий хаб от хаба, который принимает всё и не отвечает ничем, а
 * разница между ними для человека — это разница между «VPN» и «нет интернета». Кадр
 * крохотный (четыре байта) и стоит столько же, сколько один keepalive.
 *
 * Столько же (2000) стоит в реализации на Go, и по той же причине: сторож считает канал живым,
 * пока кадры от хаба не старше пяти секунд, так что три пропущенные подряд пробы — уже не
 * случайность. */
#define XSC_STREAM_PROBE_MS 2000
/* Сколько ждать установления соединения TCP и рукопожатия. Раздельно: «порт не отвечает» и
 * «отвечает, но не наш хаб» — разные отказы, и человеку полезно знать, какой из них. */
#define XSC_STREAM_DIAL_MS  10000
#define XSC_STREAM_HS_MS    15000

#define XSC_REASM_COOL_MS   10000
#define XSC_REASM_REPORT_MS 2000
#define XSC_REASM_GROW_MS   3000

/* Буферы приёма и отправки лежат В СТРУКТУРЕ ВОРКЕРА, а не рядом с файлом: соединений у пира
 * несколько, каждое обслуживает свой поток, и общий буфер означал бы, что два потока пишут в
 * одну строку. Цена — около 50 КБ на воркера; на роутере с 128 МБ это ничто по сравнению с
 * тем, что общий буфер сломался бы только под нагрузкой и только иногда. */
/* Исходящая пачка. Отдельные строки, а не одна: пока пачка не отправлена, каждый сегмент
 * должен лежать целиком — sendmmsg читает их все за один вызов.
 *
 * Зачем пачка. Первый живой замер дал 0,64 Гбит/с при том, что один проход AEAD на этом
 * железе стоит вчетверо меньше: время уходило не в шифр, а в системные вызовы — по send() на
 * каждый пакет. Приём пачкой был с самого начала, отправка — нет, и перекос был виден именно
 * по замеру, а не по коду. */


/* ТЕКУЩИЙ MTU туннеля — общий на все воркеры, потому что устройство одно. Ставит его воркер 0
 * (он же ведёт пробой пути), остальные ЧИТАЮТ: им это нужно для подрезки MSS и для предела
 * чтения из TUN. Тип int и одно слово: чтение и запись целого слова на всех наших
 * архитектурах неделимы, а согласовывать больше нечего — значение меняется раз в минуты. */
static volatile int g_mtu_now;
/* И отдельно — ПОДТВЕРЖДЁННОЕ пробоем значение. Разница нужна: g_mtu_now в начале равен
 * безопасному низу, и остальные соединения, назвав его хабу, заставляли бы хаб опускать MTU
 * устройства на низ, пока пробой не закончится. Хабу называется только подтверждённое. */
static volatile int g_mtu_pub;

/* Название `spoke` в коде оставлено НАРОЧНО, хотя в текстах, журнале и настройках эта сторона
 * называется ПИРОМ. Причина простая: `xs_peer` в xsconf.h — уже занято, там это пир ИЗ
 * КОНФИГУРАЦИИ, и два разных `peer` в одном файле читались бы хуже, чем одно историческое имя.
 * Здесь `spoke` — состояние НАШЕЙ стороны (соединение, ключи, буферы одного воркера). */
struct spoke {
    /* Конфигурация и секреты — ОДНИ на все воркеры, по указателю. Копия у каждого означала бы
     * четыре копии приватного ключа в памяти вместо одной. */
    const struct xs_conf *conf;
    struct xs_secrets *sec;
    struct tun_dev tun;
    struct xs_conn conn;
    struct tls13_keys tx, rx;
    struct xs_win win;
    int up;                       /* рукопожатие прошло, данные можно нести */
    /* Номер этого соединения у пира. Пока соединение одно, он равен нулю; хаб по нему
     * различает соединения одной и той же пира и не вытесняет соседнее (см. xshake.h). */
    int conn_id;
    int mtu;
    uint8_t hub_pub[32];
    uint32_t hub_addr;
    int hub_port;
    long long handshake_at;
    unsigned long long up_pkts, down_pkts, up_bytes, down_bytes, dropped;
    long long last_drop_warn;
    /* ---- согласование MTU (см. xswire.h) --------------------------------------
     * mtu_cap — предел, заданный человеком в конфигурации: его не превышаем никогда.
     * mtu_limit — наш предел по каналу; agreed — минимум с пределом хаба.
     * confirmed — размер, ПОДТВЕРЖДЁННЫЙ пробой; до подтверждения несём безопасный низ. */
    int mtu_cap, mtu_limit, mtu_agreed, mtu_confirmed;
    /* Границы поиска: lo заведомо проходит, hi заведомо нет (0 — пока неизвестно), cur —
     * размер, который проверяется сейчас. p_verify — стадия «проверяю прежнее значение»
     * повторного пробоя (см. probe_start). */
    int p_lo, p_hi, p_cur, p_tries, p_steps, p_verify;
    long long probe_sent, probe_next;
    int probing;
    char link_if[32];
    char state_path[320];
    const char *out_name;
    const char *dev;
    int managed;
    /* ---- пачки и сборка разрезанных записей (см. xswire.h) ----
     *
     * rb — буфер ОДНОЙ записи вместе с местом под заголовок TCP впереди: кадры читаются из TUN
     * прямо в него, на свои места, поэтому пачка собирается без единой лишней копии. hdrs, siov и
     * smm — заголовки сегментов и векторы для sendmmsg: сегмент собирается из двух кусков (свой
     * заголовок и часть записи), и копировать нагрузку не приходится вовсе. */
    uint8_t rb[20 + XS_REC_HDR + XS_MAX_RECORD + XS_TAG];
    uint8_t hdrs[XS_BATCH_FRAMES_MAX + 8][20];
    struct iovec siov[2 * (XS_BATCH_FRAMES_MAX + 8)];
    struct mmsghdr smm[XS_BATCH_FRAMES_MAX + 8];
    struct xs_reasm reasm;
    unsigned long long last_drops;
    /* batch_max — сколько кадров класть в одну запись СЕЙЧАС. Не постоянная величина: разрезанная
     * запись гибнет целиком при потере любого сегмента, поэтому на рваном пути пачка обязана
     * схлопываться до одного кадра. Растёт по чистой обратной связи, падает мгновенно. */
    int batch_max;
    long long cool_until, last_report, last_grow, keep_next;

    /* Приём и отправка: свои у каждого воркера (см. выше). */
    uint8_t rx_buf[XSC_BATCH][XS_ROW];
    struct mmsghdr mm[XSC_BATCH];
    struct iovec iov[XSC_BATCH];
    /* Буфер отправки одиночного кадра И сборки Hello. Больше строки пакета намеренно: с
     * постквантовым обменом ClientHello занимает около 1760 байт (столько же, сколько браузерный),
     * и в XS_ROW он не влезает — первая версия получала на этом XS_ESMALL с сообщением
     * «рукопожатие не собралось», не называя причину. */
    uint8_t txb[2560];
    /* Какой MTU этот воркер уже назвал хабу: своя сессия у каждого соединения, и хаб должен
     * знать размер по каждой — иначе подрезка MSS на обратном пути её пропустит. */
    int mtu_told;

    /* ---- режим потока (xsstream.h) ----------------------------------------------
     *
     * stream — режим выбран человеком (ключ --stream или поле спеки). Тогда поддельный TCP не
     * поднимается вовсе: ни сырого сокета, ни правила против RST, ни окна приёма, ни сборки
     * разрезанных записей, ни проб пути.
     *
     * st выделяется НА ВРЕМЯ соединения, а не лежит в структуре: в нём буфер чтения на 64 КБ,
     * и платить их в каждом воркере при поддельном TCP, где поток не используется, незачем —
     * на роутере с 128 МБ четыре таких буфера это уже заметно. */
    int stream, stream_port;
    struct xs_stream *st;
    /* Ратчет эпох: по одному на направление. Включается только в потоке — почему, сказано в
     * шапке xsepoch.h (в поддельном TCP смещение выбирает отправитель сегмента). */
    struct xs_epoch ep_tx, ep_rx;
    long long stream_rx;          /* когда последний раз пришла запись: тишина здесь = обрыв */
    /* Склейка соседних сегментов одного потока в одну запись в устройство (см. tun.h).
     * Буферов не держит: кадры внутри расшифрованной записи уже лежат подряд, и склейка
     * ссылается на них векторами. Отдаётся ВСЕГДА в конце обработки записи — пакет не живёт
     * дольше одного круга цикла, то есть задержки не появляется. */
    struct tun_gro gro;
};

/* Воркеры пира. Статические, а не на стеке: в каждом по 50 КБ буферов. */
static struct spoke g_sp[XS_CONNS_MAX];
static int g_conns = 1;
/* Конфигурация и секреты — по одному экземпляру на процесс. */
static struct xs_conf g_cf;
static struct xs_secrets g_sc;

/* Состояние на диск: его читают сторож (жив ли туннель) и status. Отдельным файлом, а не
 * через опрос процесса, потому что проверка процесса — это запуск процесса, а status
 * опрашивают раз в пять секунд. */
static void state_write(struct spoke *s) {
    char tmp[336];
    snprintf(tmp, sizeof(tmp), "%s.tmp", s->state_path);
    FILE *f = fopen(tmp, "w");
    if (!f) return;
    char fp[12];
    xs_key_fp(s->hub_pub, fp);
    /* Счётчики СУММИРУЮТСЯ по всем соединениям: наружу пир одна, и «отдано байт» должно
     * означать отданное туннелем, а не одним из его соединений. Читаем без замка: значения
     * только растут, и расхождение на несколько пакетов в файле состояния безвредно, а замок
     * на пути, который ведёт счёт на каждый пакет, — нет.
     *
     * `up` считается по ЛЮБОМУ живому соединению: туннель работает, пока работает хотя бы
     * одно, и сторож обязан видеть именно это. */
    unsigned long long tp = 0, tb2 = 0, rp = 0, rb = 0, dr = 0;
    int any_up = 0;
    long long hs_at = 0;
    for (int i = 0; i < g_conns; i++) {
        tp += g_sp[i].up_pkts;   tb2 += g_sp[i].up_bytes;
        rp += g_sp[i].down_pkts; rb  += g_sp[i].down_bytes;
        dr += g_sp[i].dropped;
        if (g_sp[i].up) any_up = 1;
        if (g_sp[i].handshake_at > hs_at) hs_at = g_sp[i].handshake_at;
    }
    fprintf(f, "{\"schema\":1,\"out\":\"%s\",\"up\":%s,\"mtu\":%d,\"conns\":%d"
               ",\"hub\":\"%s:%d\""
               ",\"hub_key\":\"%s\",\"handshake_age\":%lld"
               ",\"tx_packets\":%llu,\"tx_bytes\":%llu"
               ",\"rx_packets\":%llu,\"rx_bytes\":%llu,\"dropped\":%llu}\n",
            s->out_name, any_up ? "true" : "false", s->mtu, g_conns,
            s->conf->peer[0].endpoint,
            /* Порт называется ТОТ, к которому мы на самом деле подключены: в режиме потока он
             * может быть задан отдельно, и «в состоянии один порт, в журнале другой» — верный
             * способ искать причину не там. */
            s->stream && s->stream_port ? s->stream_port : s->conf->peer[0].endpoint_port, fp,
            hs_at ? (xs_now_ms() - hs_at) / 1000 : -1,
            tp, tb2, rp, rb, dr);
    fclose(f);
    /* Переименование, а не запись на месте: читатель не должен увидеть половину файла.
     * Секретов в файле нет — печатает его тот же код, что xs_conf_json, и приватного ключа
     * он не видит по построению. */
    rename(tmp, s->state_path);
}

/* Поднять TUN. Два режима, и разница между ними — В ТОМ, КТО ВЛАДЕЕТ УСТРОЙСТВОМ.
 *
 * managed == 0 (выход спеки): устройство создаём и настраиваем мы — адрес из конфигурации,
 * MTU из накладных, — как это делает клиент VLESS.
 *
 * managed == 1 (режим netifd; обработчик протокола и страница LuCI едут в пакете
 * luci-app-splify2, потому что это часть интерфейса, а не движка): устройство уже создано,
 * адрес, MTU и
 * зону firewall ему даёт netifd. Мы его только ОТКРЫВАЕМ и ничего не трогаем: две стороны,
 * настраивающие одно устройство, — это гонка, в которой проигрывает та, что настроила первой,
 * и заметно это будет как «MTU иногда не тот». Но MTU мы ПРОВЕРЯЕМ: если netifd дал больше,
 * чем влезает в конверт, большие пакеты будут пропадать молча — худший класс отказов. */
static int tun_up_queues(struct spoke *s, struct tun_dev *q, int want, const char *dev,
                         int managed) {
    int n = tun_open(q, want, dev);
    if (n < 0) {
        fprintf(stderr, LOG_W "нет /dev/net/tun — установите kmod-tun\n");
        return -1;
    }
    s->tun = q[0];
    /* TUN переводится в НЕБЛОКИРУЮЩИЙ режим, и это не тонкая настройка, а условие
     * работоспособности. Пакеты читаются пачкой, до XS*_BATCH за одно событие poll: на
     * блокирующем дескрипторе второе чтение, когда пакетов больше нет, останавливает весь
     * цикл НАВСЕГДА. Именно так и вышло при первом живом прогоне — хаб печатал «слушаю» и
     * замолкал, не отвечая на SYN, и снаружи это выглядело как «сеть не доходит». */
    for (int i = 0; i < n; i++) {
        int fl = fcntl(q[i].fd, F_GETFL, 0);
        fcntl(q[i].fd, F_SETFL, fl | O_NONBLOCK);
    }

    if (managed) {
        char path[128], buf[32];
        snprintf(path, sizeof(path), "/sys/class/net/%.32s/mtu", dev);
        FILE *mf = fopen(path, "r");
        int dev_mtu = 0;
        if (mf) {
            if (fgets(buf, sizeof(buf), mf)) dev_mtu = atoi(buf);
            fclose(mf);
        }
        /* Зажимаем, а не только предупреждаем: по этому числу считается предельный сегмент. */
        if (dev_mtu > 0) s->mtu = xs_mtu_clamp(dev_mtu);
        fprintf(stderr, LOG_I "%s: устройством владеет netifd, MTU %d (накладные %d)\n",
                dev, s->mtu, XS_OVERHEAD);
        if (dev_mtu > XS_MTU_DEF)
            fprintf(stderr, LOG_W "%s: MTU %d больше предела %d для канала 1500 — большие "
                                  "пакеты будут пропадать; поставьте mtu %d в настройках "
                                  "интерфейса\n", dev, dev_mtu, XS_MTU_DEF, XS_MTU_DEF);
        return n;
    }

    char addr[24], mtu[8];
    struct in_addr in;
    in.s_addr = htonl(s->conf->addr);
    snprintf(addr, sizeof(addr), "%s/%d", inet_ntoa(in), s->conf->addr_plen);
    snprintf(mtu, sizeof(mtu), "%d", s->mtu);
    const char *a1[] = { "ip", "addr", "replace", addr, "dev", dev, NULL };
    const char *a2[] = { "ip", "link", "set", "dev", dev, "mtu", mtu, "up", NULL };
    if (run_quiet(a1) != 0 || run_quiet(a2) != 0) {
        fprintf(stderr, LOG_W "не удалось настроить %s\n", dev);
        return -1;
    }
    fprintf(stderr, LOG_I "%s: адрес %s, MTU %d (накладные %d)\n", dev, addr, s->mtu,
            XS_OVERHEAD);
    return n;
}

/* Одно рукопожатие целиком. Блокирующее по существу: до его конца нести нечего, а
 * усложнять цикл ради параллельности с самим собой незачем. Ждём с таймаутом, потому что
 * молчащий хаб не должен подвесить процесс — procd поднимет заново. */
static int do_handshake(struct spoke *s) {
    struct xs_hs hs;
    size_t hn = 0;
    /* В рукопожатие уходит НАШ ПРЕДЕЛ, а не текущий MTU устройства: согласовывать надо
     * возможности сторон, а не то, что случайно стоит на интерфейсе прямо сейчас. */
    int rc = xs_hs_client_hello(&hs, s->sec, s->hub_pub, s->conf->sni,
                               s->mtu_limit ? s->mtu_limit : s->mtu, s->conn_id,
                               s->txb, sizeof(s->txb), &hn);
    if (rc != 0) { fprintf(stderr, LOG_W "рукопожатие не собралось: %d\n", rc); return rc; }
    /* Hello уезжает ПО СЕГМЕНТАМ, как у браузера: с постквантовым обменом он больше одного
     * сегмента по построению (1759 байт против 537 без него — столько же, сколько у настоящего
     * Chrome). Отправлять его одним куском нельзя: такой пакет либо не дойдёт, либо приедет
     * фрагментированным, и то и другое видно на проводе сразу. */
    {
        size_t max_seg = (size_t)XS_MTU_DEF + XS_OVERHEAD - 40;
        for (size_t off = 0; off < hn; off += max_seg) {
            size_t part = hn - off;
            if (part > max_seg) part = max_seg;
            if (xs_conn_send(&s->conn, 0x18 /* PSH|ACK */, s->txb + off, part, 0) != 0) return -1;
        }
    }

    long long deadline = xs_now_ms() + 5000;
    uint8_t in[XS_ROW * 2];
    size_t got = 0;
    for (;;) {
        long long left = deadline - xs_now_ms();
        if (left <= 0) {
            fprintf(stderr, LOG_W "хаб %s:%d не ответил на рукопожатие\n",
                    s->conf->peer[0].endpoint, s->hub_port);
            xs_hs_wipe(&hs);
            return -1;
        }
        struct pollfd p = { s->conn.fd, POLLIN, 0 };
        if (poll(&p, 1, (int)left) <= 0) continue;
        uint8_t pkt[XS_ROW];
        ssize_t r = recv(s->conn.fd, pkt, sizeof(pkt), 0);
        if (r <= 0) continue;
        struct obfs_seg seg;
        if (obfs_parse(pkt, (size_t)r, &seg) != 0) continue;
        if (seg.sport != s->conn.dport || seg.dport != s->conn.sport) continue;
        if (xs_conn_on_seg(&s->conn, &seg, xs_now_ms()) != 1) continue;
        /* Ответ хаба приходит одним сегментом: он собран так, чтобы влезть (см. xshake.c).
         * Но склеить два сегмента мы всё равно умеем — дешевле, чем однажды не понять почему
         * рукопожатие не проходит на канале с меньшим MSS. */
        if (got + seg.plen > sizeof(in)) { xs_hs_wipe(&hs); return -1; }
        memcpy(in + got, seg.payload, seg.plen);
        got += seg.plen;
        /* ГРАНИЦУ ОТВЕТА ОПРЕДЕЛЯЕТ РАМКА ЗАПИСЕЙ, А НЕ КОД ОТКАЗА РАЗБОРА.
         *
         * Прежде здесь стояло «позвать finish и, если он сказал XS_EFORMAT, ждать остаток».
         * Это работало ровно потому, что ответ хаба всегда влезал в один сегмент, — а на
         * канале с меньшим MSS сломалось бы скрытно: xs_hs_client_finish ВБИРАЕТ прочитанное в
         * транскрипт по мере разбора, поэтому на неполном ответе он успевает вобрать
         * ServerHello, а повторный вызов на дособранном ответе вбирает его ВТОРОЙ РАЗ. Тег
         * подтверждения после этого не сходится при совершенно верной криптографии, и выглядит
         * это как «хаб не признал нас» — то есть причину искали бы в ключах и конфигурации.
         * Теперь finish зовётся один раз и только на целом ответе. */
        /* Фатальное оповещение TLS — это ОТВЕТ, и он говорит больше, чем тишина: хаб нас не
         * признал (не тот ключ, нас нет в его конфигурации). Без этой ветки ждать пришлось бы
         * до конца срока, а человек увидел бы «не ответил на рукопожатие» — то есть неправду. */
        if (got >= 2 && in[0] == 0x15) {
            fprintf(stderr, LOG_W "хаб %s:%d ответил отказом TLS: нас нет в его конфигурации "
                                  "или публичный ключ не тот\n",
                    s->conf->peer[0].endpoint, s->hub_port);
            xs_hs_wipe(&hs);
            return -1;
        }
        if (!xs_hs_response_complete(in, got)) continue;
        size_t used = 0;
        rc = xs_hs_client_finish(&hs, in, got, &s->tx, &s->rx, &used);
        if (rc != 0) {
            fprintf(stderr, LOG_W "хаб не признал нас или ответил не тем: %d\n", rc);
            xs_hs_wipe(&hs);
            return rc;
        }
        break;
    }
    size_t fn = 0;
    rc = xs_hs_client_confirm(&hs, &s->tx, s->txb, sizeof(s->txb), &fn);
    if (rc == 0) rc = xs_conn_send(&s->conn, 0x18, s->txb, fn, 0);
    int peer_mtu = hs.peer.mtu;
    xs_hs_wipe(&hs);
    if (rc != 0) return rc;

    /* СОГЛАСОВАНИЕ MTU, ступень первая: минимум из пределов сторон — «максимальное для обоих
     * устройств». Ступень вторая (проверка самого пути пробами) начинается ниже, потому что
     * канал у обоих может быть шире, чем путь между ними. */
    s->mtu_agreed = s->mtu_limit ? s->mtu_limit : XS_MTU_DEF;
    if (peer_mtu > 0 && peer_mtu < s->mtu_agreed) s->mtu_agreed = peer_mtu;
    if (s->mtu_cap > 0 && s->mtu_cap < s->mtu_agreed) s->mtu_agreed = s->mtu_cap;
    fprintf(stderr, LOG_I "предел согласован: %d (наш канал %s даёт %d, хаб называет %d%s)\n",
            s->mtu_agreed, s->link_if[0] ? s->link_if : "?",
            s->mtu_limit ? s->mtu_limit : XS_MTU_DEF, peer_mtu,
            s->mtu_cap ? ", в настройках задан предел" : "");
    xs_win_reset(&s->win);
    xs_reasm_reset(&s->reasm);
    /* Пачка начинается с двух кадров и растёт по чистой обратной связи: начинать с восьми значило
     * бы платить на рваном пути с первой же секунды.
     *
     * STEER_XS_COMPAT=1 оставляет один кадр в записи навсегда — это аварийный выключатель нового
     * формата на время обновления. Хаб предыдущей версии не умеет ни собирать разрезанную запись,
     * ни разбирать контейнер пачки, и пока он где-то работает, туннель к нему поднимается только
     * так. Переменной, а не настройкой в конфигурации: это временная мера на один рабочий день, а
     * не свойство выхода, и в spec.json ей места нет. */
    s->batch_max = getenv("STEER_XS_COMPAT") ? 1 : 2;
    s->cool_until = 0;
    s->last_drops = s->reasm.dropped;
    s->up = 1;
    s->handshake_at = xs_now_ms();
    fprintf(stderr, LOG_I "рукопожатие с %s:%d прошло, порт %u, шифр %s\n",
            s->conf->peer[0].endpoint, s->hub_port, s->conn.sport,
            s->tx.aead == TLS13_AEAD_AES128 ? "AES-128-GCM" : "ChaCha20-Poly1305");
    return 0;
}

/* Отправить один кадр открытого текста как запись. Служебные кадры (проба, эхо, итог) уходят
 * тем же путём, что данные: у них нет своего канала, и это нарочно — иначе появился бы второй
 * путь на проводе, который DPI различал бы по размеру и ритму. */
static int send_frame(struct spoke *s, const uint8_t *pt, size_t pn, long long now) {
    if (!s->up || pn > (size_t)XS_MTU_DEF) return -1;
    uint32_t rel = xs_conn_rel_next(&s->conn);
    uint8_t *rec = s->txb + XS_HDR_ROOM - XS_REC_HDR;
    memcpy(s->txb + XS_HDR_ROOM, pt, pn);
    if (xs_rec_build(rec, pn + XS_TAG) != 0) return -1;
    if (tls13_aead_seal(&s->tx, rel, rec, XS_REC_HDR, s->txb + XS_HDR_ROOM, pn,
                        s->txb + XS_HDR_ROOM + pn) != 0) return -1;
    size_t seglen = 0;
    uint8_t *seg = xs_conn_ahead(&s->conn, s->txb, XS_REC_HDR + pn + XS_TAG, &seglen, now);
    return send(s->conn.fd, seg, seglen, MSG_NOSIGNAL) < 0 ? -1 : 0;
}

/* Поставить устройству новый MTU. Делает это САМ движок в обоих режимах — и в режиме netifd
 * тоже, потому что согласование по определению узнаёт правильное значение позже, чем netifd
 * поднял интерфейс. Значение, заданное человеком в конфигурации, при этом никогда не
 * превышается: если он написал 1380, мы не поставим 1431, даже если путь его несёт. */
static void mtu_apply(struct spoke *s, const char *dev, int mtu, const char *why) {
    /* Тем же потолком, что и остальные два входа: пробой пути число ОПУСКАЕТ, но приходит оно
     * из провода, и проверять его надо против своих пределов, а не только против другого числа
     * из настроек. */
    mtu = xs_mtu_clamp(mtu);
    if (mtu == s->mtu) return;
    /* Устройство одно на все соединения, поэтому МЕНЯЕТ его только воркер 0 — тот же, что ведёт
     * пробой пути. Иначе несколько потоков дёргали бы `ip link` с разными числами, и на
     * устройстве оставалось бы то, чей вызов пришёл последним. */
    if (s->conn_id) return;
    char val[8];
    snprintf(val, sizeof(val), "%d", mtu);
    const char *a[] = { "ip", "link", "set", "dev", dev, "mtu", val, NULL };
    if (run_quiet(a) != 0) {
        fprintf(stderr, LOG_W "%s: не удалось поставить MTU %d\n", dev, mtu);
        return;
    }
    fprintf(stderr, LOG_I "%s: MTU %d → %d (%s)\n", dev, s->mtu, mtu, why);
    s->mtu = mtu;
    /* Публикуем остальным воркерам: им это нужно для подрезки MSS и для предела чтения из TUN.
     * Читать чужое поле s->mtu они не могут — своё у каждого. */
    g_mtu_now = mtu;
}

/* Начать проверку пути.
 *
 * ПОЧЕМУ ПОВТОРНЫЙ ПРОБОЙ НАЧИНАЕТСЯ С ПРОВЕРКИ УЖЕ НАЙДЕННОГО, А НЕ С ПОПЫТКИ ПОДНЯТЬ.
 * Путь меняется под живой сессией — оператор переключил канал, сменился маршрут, добавился
 * ещё один туннель по дороге, — и меняется он в обе стороны. Поиск, который умеет только
 * поднимать предел, при сузившемся пути оставит нас на прежнем значении: мелкие пакеты
 * ходят, большие пропадают целиком и молча. Поэтому сначала стадия «прежний размер ещё
 * проходит?» (для неизменившегося пути это одна проба и почти нулевая цена), и лишь потом
 * попытка вырасти; не прошла проверка — предел немедленно опускается на безопасный низ, и
 * поиск идёт ВНИЗ от прежнего значения. */
static void probe_start(struct spoke *s, long long now) {
    /* Путь у всех соединений один — тот же канал, тот же хаб, — поэтому проверяет его ОДИН
     * воркер. Четыре независимых пробоя дали бы вчетверо больше служебных кадров и четыре
     * мнения об одном и том же числе. */
    if (s->conn_id) { s->probing = 0; return; }
    s->p_tries = 0;
    s->p_steps = 0;
    s->probe_sent = 0;
    if (s->mtu_confirmed > XS_MTU_FLOOR) {
        s->p_verify = 1;
        s->p_cur = s->mtu_confirmed;
        s->p_lo = XS_MTU_FLOOR;
        s->p_hi = 0;
        s->probing = 1;
    } else {
        s->p_verify = 0;
        s->p_lo = XS_MTU_FLOOR;
        s->p_hi = 0;
        s->p_cur = xs_mtu_next(s->p_lo, s->p_hi, s->mtu_agreed);
        s->probing = s->p_cur > 0;
    }
    (void)now;
}

/* Как часто перепроверять путь. Переменной окружения хватает ровно для стенда: живая звезда
 * меняет путь раз в дни, а стенду нужно увидеть сужение за секунды, и ждать в нём две минуты
 * значило бы, что проверку сужения выключат первой. В настройки это не выносится: числу неоткуда
 * взяться у человека, а неверное сделает пробои заметной долей трафика. */
static long long probe_every(void) {
    const char *e = getenv("STEER_XS_PROBE_MS");
    if (!e) return XS_PROBE_EVERY_MS;
    long v = strtol(e, NULL, 10);
    return v >= 1000 ? (long long)v : 1000;
}

/* Проверка закончена: применить найденное и сообщить хабу. */
static void probe_done(struct spoke *s, const char *dev, long long now) {
    s->probing = 0;
    s->p_verify = 0;
    s->probe_next = now + probe_every();
    if (s->p_lo <= XS_MTU_FLOOR) {
        /* Не подтвердился ни один размер выше низа. Остаёмся на нём — и ГОВОРИМ об этом:
         * молча работать вдвое медленнее возможного это ровно тот отказ, который никто не
         * заметит. Пробы не доходят вовсе либо путь действительно такой узкий. */
        fprintf(stderr, LOG_W "путь не подтвердил ни один размер выше %d — остаюсь на нём. "
                              "Похоже, пробы не доходят вовсе\n", XS_MTU_FLOOR);
        mtu_apply(s, dev, XS_MTU_FLOOR, "путь не подтвердил ничего выше низа");
        s->mtu_confirmed = 0;
        return;
    }
    /* Сравнение — с тем, что СТОИТ НА УСТРОЙСТВЕ, а не с прошлым подтверждённым значением.
     * Разница стоила живого туннеля: после переподключения устройство сидело на безопасном
     * низу, подтверждённое значение осталось прежним, проверка «ничего не изменилось»
     * срабатывала — и туннель оставался на 1200 при пути, несущем 1387, до перезапуска. Ни
     * одной строки в журнале при этом не появлялось. */
    int grew = s->p_lo > s->mtu;
    s->mtu_confirmed = s->p_lo;
    g_mtu_pub = s->p_lo;
    mtu_apply(s, dev, s->p_lo, grew ? "путь подтвердил пробой" : "путь сузился");
    uint8_t fin[8];
    size_t fn2 = xs_mtu_build(fin, sizeof(fin), s->p_lo);
    if (fn2) send_frame(s, fin, fn2, now);
}

/* КЛЮЧИ ОСВОБОЖДАЮТСЯ БЕЗ ОГЛЯДКИ НА s->up, и это не перестраховка. Ключи выводит
 * xs_hs_client_finish, а s->up ставится ПОЗЖЕ — после отправки подтверждения. Значит между
 * этими двумя точками есть отказы (подтверждение хаба не сошлось, само подтверждение не
 * ушло), после которых контексты шифра уже выделены, а условие «if (s->up)» их не
 * освобождает. Следующая попытка входит в split_keys, тот делает memset ключа — указатель на
 * прежний контекст AES теряется, и это утечка, а не отложенное освобождение. Цена: 576 байт
 * на попытку, попытки идут каждые 5 секунд, воркер запасного соединения не сдаётся никогда
 * (worker_give_up). Мерено стендом tests/spokematch.c под LeakSanitizer.
 *
 * Условие лишнее и без этого: tls13_keys_free сам выходит на !ctx_ready. */
static void session_down(struct spoke *s) {
    tls13_keys_free(&s->tx);
    tls13_keys_free(&s->rx);
    memset(&s->tx, 0, sizeof(s->tx));
    memset(&s->rx, 0, sizeof(s->rx));
    s->up = 0;
    xs_conn_close(&s->conn);
}

/* Общий цикл обеих ролей вынесен, чтобы «поднять для выхода спеки» и «поднять на готовом
 * устройстве» отличались ровно тем, чем отличаются: владением устройством и маршрутизацией.
 * Скопировать цикл во второй раз значило бы два места для одной ошибки в пути данных. */
static int spoke_run(struct spoke *s, const char *dev, const char *chain_label, int managed,
                     struct output *o);
static int cmd_xsteer_spec(const char *spec_path, const char *out_name, const char *conf_path,
                           int stream, int stream_port);

int cmd_xsteer(const char *spec_path, const char *out_name, const char *conf_path,
               const char *device, int stream, int stream_port) {
    static struct spoke sd;
    /* Режим транспорта задаётся ключом и только здесь: дальше он едет полем spoke, потому что
     * его читает и цикл, и подъём устройства, и файл состояния.
     *
     * Ключ трёхзначен: 1 — «--stream», -1 — «--no-stream», 0 — не назван. В режиме netifd
     * спеки нет вовсе, поэтому «не назван» и «выключен» здесь одно и то же; различие нужно
     * ниже, где ключ спорит с полем спеки. */
    sd.stream = stream > 0;
    sd.stream_port = stream_port;
    /* Без имени выхода спека не читается ВОВСЕ: на маршрутизаторе, где туннелем владеет
     * netifd, выходов и каналов может не быть, а требовать спеку ради того, чтобы её не
     * использовать, значило бы требовать настройку, которая ни на что не влияет. */
    if (!out_name || !out_name[0]) {
        if (!conf_path || !device) {
            fprintf(stderr, "steer: без имени выхода нужны --config и --device "
                            "(подсказка: steer xsteer --help)\n");
            return 2;
        }
        char err2[256];
        if (xs_conf_load(conf_path, XS_ROLE_SPOKE, &g_cf, &g_sc, err2, sizeof(err2)) != 0) {
            fprintf(stderr, LOG_W "%s\n", err2);
            return 2;
        }
        sd.conf = &g_cf;
        sd.sec = &g_sc;
        sd.out_name = device;
        snprintf(sd.state_path, sizeof(sd.state_path), "%s/xsteer-%.40s.json",
                 g_state_dir, device);
        return spoke_run(&sd, device, device, 1, NULL);
    }
    return cmd_xsteer_spec(spec_path, out_name, conf_path, stream, stream_port);
}

static int cmd_xsteer_spec(const char *spec_path, const char *out_name, const char *conf_path,
                           int stream, int stream_port) {
    load_spec(spec_path);
    struct output *o = out_by_name(out_name);
    if (!o) die("нет такого выхода: %s", out_name);
    if (o->kind != OUT_XSTEER) die("выход %s не kind=xsteer", out_name);
    /* Реестр нужен ДО подъёма: из него берутся метка и номер таблицы выхода, а их привязка к
     * устройству — работа этого процесса (см. bind_device ниже). Вызов идемпотентен и с apply
     * не спорит: тот же файл, те же номера. Без него метка была бы нулевой, и правило
     * `ip rule fwmark 0x0` поймало бы весь трафик роутера. */
    registry_assign();

    static struct spoke s;
    s.out_name = o->name;
    /* Ключ командной строки СИЛЬНЕЕ спеки, а не наоборот: спека описывает постоянную
     * настройку выхода, а ключом человек проверяет руками — и «проверил ключом, а работало по
     * спеке» это потерянный час. Отсутствие ключа (0) при заданном в спеке потоке оставляет
     * поток: выключить его руками можно --no-stream, который приезжает сюда как -1. */
    s.stream = stream ? stream > 0 : o->xs_stream;
    s.stream_port = stream_port ? stream_port : o->xs_stream_port;
    char err[256];
    const char *path = conf_path ? conf_path : o->xs_conf;
    if (xs_conf_load(path, XS_ROLE_SPOKE, &g_cf, &g_sc, err, sizeof(err)) != 0) {
        fprintf(stderr, LOG_W "%s\n", err);
        return 2;
    }
    s.conf = &g_cf;
    s.sec = &g_sc;
    /* Публичный ключ хаба берётся из конфигурации как есть — он там и лежит публичной
     * половиной, в отличие от нашего собственного. */
    memcpy(s.hub_pub, g_cf.peer[0].pub, 32);
    s.hub_port = g_cf.peer[0].endpoint_port;
    struct in_addr hin;
    if (inet_pton(AF_INET, g_cf.peer[0].endpoint, &hin) != 1) {
        fprintf(stderr, LOG_W "адрес хаба не разобран: %s\n", g_cf.peer[0].endpoint);
        return 2;
    }
    s.hub_addr = hin.s_addr;
    s.mtu = g_cf.mtu ? g_cf.mtu : XS_MTU_DEF;
    snprintf(s.state_path, sizeof(s.state_path), "%s/xsteer-%.40s.json",
             g_state_dir, o->name);

    /* Таблицу к устройству привязывает САМ процесс: apply прошёл раньше, дождаться
     * устройства снаружи нельзя, и момент готовности знает только тот, кто его создал. Тот
     * же довод и тот же приём, что у клиента VLESS. В режиме netifd этого не делается вовсе:
     * маршрутизацией там владеет он, а выход описывается в спеке как обычный interface. */
    return spoke_run(&s, o->device, o->name, 0, o);
}

/* Сколько соединений открывать. По одному на ядро, но не больше XS_CONNS_MAX.
 *
 * ЗАЧЕМ ИХ НЕСКОЛЬКО. Одно поддельное соединение обслуживается одним потоком целиком — так
 * счётчик nonce остаётся его личным, без атомиков и замков в самом опасном месте протокола, —
 * и потому упирается ровно в одно ядро (замерено: около 0,6 Гбит/с на этой машине). Второе
 * соединение — второе ядро.
 *
 * И ВТОРАЯ, НЕ МЕНЕЕ ВАЖНАЯ ПРИЧИНА: хаб раскладывает соединения по своим воркерам по младшим
 * битам порта источника, а порт случайный. При одном соединении на пир два пира с
 * вероятностью 1/2 попадают в один воркер хаба, и его многопоточность не работает вовсе —
 * именно это и показал стенд (0,57 Гбит/с вместо 1,18 на том же коде). Соединения с РАЗНЫМИ
 * младшими битами закрывают это: каждый пир занимает все воркеры хаба поровну. */
static int spoke_conns(void) {
    long cores = sysconf(_SC_NPROCESSORS_ONLN);
    int n = cores > 0 ? (int)cores : 1;
    const char *e = getenv("STEER_XS_CONNS");
    if (e) { long v = strtol(e, NULL, 10); if (v >= 1) n = (int)v; }
    if (n > XS_CONNS_MAX) n = XS_CONNS_MAX;
    if (n < 1) n = 1;
    return n;
}

static void *worker_main(void *arg);

/* Что делать соединению, которое не поднялось.
 *
 * Воркер 0 УХОДИТ, и процесс с ним: подъём заново — дело procd, и его пауза respawn заодно не
 * даёт молотить сеть, которой ещё нет. Это поведение было единственным, пока соединение было
 * одно, и менять его нельзя — на нём стоит и сторож, и respawn.
 *
 * Остальные ЖДУТ и пробуют снова: уронить процесс из-за второго соединения значило бы, что
 * лишний поток сделал туннель ХУЖЕ, чем без него — работающее соединение 0 умерло бы вместе с
 * ним. Пауза та же, что у respawn у procd, чтобы ритм попыток был одинаковым. */
static int worker_give_up(struct spoke *s) {
    if (!s->conn_id) return 1;
    struct timespec ts = { 5, 0 };
    nanosleep(&ts, NULL);
    return 0;
}

/* Установка: одно устройство, одно правило nft, одна привязка таблицы — и N воркеров. */
static int spoke_run(struct spoke *s, const char *dev, const char *chain_label, int managed,
                     struct output *o) {
    if (!s->hub_port) {
        /* Режим netifd: подготовка проще, но те же три величины обязаны быть посчитаны. */
        memcpy(s->hub_pub, s->conf->peer[0].pub, 32);
        s->hub_port = s->conf->peer[0].endpoint_port;
        struct in_addr h2;
        if (inet_pton(AF_INET, s->conf->peer[0].endpoint, &h2) != 1) {
            fprintf(stderr, LOG_W "адрес хаба не разобран: %s\n", s->conf->peer[0].endpoint);
            return 2;
        }
        s->hub_addr = h2.s_addr;
        s->mtu = xs_mtu_clamp(s->conf->mtu);
    }
    /* DNS из конфигурации разбор принимает, но применить его здесь нельзя: именами на
     * роутере распоряжается dnsmasq, и вырывать резолвер у него из туннеля значило бы
     * ломать доменные каналы движка. Сказать об этом надо ОДИН РАЗ и прямо — иначе человек,
     * написавший DNS, будет считать, что запросы идут в туннель (см. xsconf.c). */
    if (s->conf->dns_n)
        fprintf(stderr, LOG_W "в конфигурации задан DNS (%d адр.): здесь он НЕ применяется — "
                              "именами распоряжается dnsmasq, заведите доменный канал\n",
                s->conf->dns_n);
    g_conns = spoke_conns();
    /* Очереди TUN: по одной на воркера. Ядро раскладывает пакеты по очередям симметричным
     * хэшем потока, поэтому обе половины одного соединения всегда достаются одному воркеру. */
    struct tun_dev tq[XS_CONNS_MAX];
    int nq = tun_up_queues(s, tq, g_conns, dev, managed);
    if (nq < 0) return 1;
    /* MTU, заданный человеком, — это ПРЕДЕЛ, а не значение: согласование никогда не поднимет
     * выше него. Если он не задан, предел ставит только канал и путь. */
    s->mtu_cap = s->conf->mtu;
    g_mtu_now = s->mtu;
    /* Правило против RST собственного ядра: без него стек роутера сам рвёт нашу сессию.
     * Цепочка своя (вид 'x'), таблица общая с обфускатором — имя её историческое. Правило одно
     * на все соединения: оно описано портом ХАБА, а не нашим.
     *
     * В режиме потока правило НЕ НУЖНО, и это ровно то, чем он и ценен: соединением владеет
     * само ядро, RST на живой сессии оно не пошлёт, и права CAP_NET_ADMIN на nft здесь не
     * требуются вовсе. Ставить его всё равно значило бы просить прав и трогать firewall без
     * причины. */
    if (!s->stream && obfs_guard_up('x', chain_label, s->conf->peer[0].endpoint,
                                    s->hub_port, 0) != 0)
        fprintf(stderr, LOG_W "%s: правило против RST не встало — сессию может оборвать "
                              "собственное ядро (нет nft?)\n", chain_label);
    if (o) bind_device(o, dev);

    /* Воркер 0 — этот же поток: при одном соединении процесс ведёт себя ровно так, как до
     * появления потоков, и отладка одного потока остаётся возможной. */
    for (int i = 0; i < g_conns; i++) {
        if (i) {
            g_sp[i] = *s;                       /* общие величины: конфигурация по указателю */
            memset(&g_sp[i].conn, 0, sizeof(g_sp[i].conn));
            g_sp[i].up = 0;
            g_sp[i].up_pkts = g_sp[i].down_pkts = g_sp[i].up_bytes = g_sp[i].down_bytes = 0;
            g_sp[i].dropped = 0;
            g_sp[i].probing = 0;
            g_sp[i].probe_next = 0;
            g_sp[i].mtu_confirmed = 0;
        } else {
            g_sp[0] = *s;
        }
        g_sp[i].conn_id = i;
        g_sp[i].tun = tq[i % nq];
        g_sp[i].dev = dev;
        g_sp[i].managed = managed;
    }
    if (g_conns > 1)
        fprintf(stderr, LOG_I "%s: соединений к хабу %d (по одному на ядро), очередей TUN %d\n",
                dev, g_conns, nq);
    pthread_t th[XS_CONNS_MAX];
    for (int i = 1; i < g_conns; i++)
        if (pthread_create(&th[i], NULL, worker_main, &g_sp[i]) != 0) {
            fprintf(stderr, LOG_W "поток соединения %d не создался: работаем меньшим числом\n", i);
            g_sp[i].conn_id = -1;
        }
    return (int)(intptr_t)worker_main(&g_sp[0]);
}

/* ---- один кадр открытого текста -------------------------------------------
 *
 * Вынесено в функцию, потому что кадр теперь приходит двумя путями: одиночной записью и внутри
 * пачки, которую разбор отдаёт по одному через обратный вызов. Две копии этой обработки означали бы
 * два места, где можно по-разному ошибиться в том, что делать с внутренним пакетом. */
static void spoke_frame(struct spoke *s, const uint8_t *pt, size_t pn, const char *dev,
                        long long now) {
    enum xs_kind kind = xs_frame_kind(pt, pn);
    if (kind == XS_IPV4 || kind == XS_IPV6) {
        xs_mss_clamp((uint8_t *)(uintptr_t)pt, pn, s->mtu);
        /* Отдача идёт через склейку: восемь пакетов одного потока уезжают одной записью, и
         * ядро проходит стек один раз вместо восьми. Условия склейки строгие, всё
         * несклеиваемое (ICMP, UDP, голые подтверждения, чужой поток) уходит отдельной
         * записью ровно как раньше — см. tun.h. */
        tun_gro_push(&s->tun, &s->gro, (uint8_t *)(uintptr_t)pt, pn);
        s->down_pkts++;
        s->down_bytes += pn;
        return;
    }
    /* Служебный кадр закрывает набор: за ним в устройство ничего не поедет, а держать
     * накопленное дольше записи нельзя. */
    tun_gro_flush(&s->tun, &s->gro);
    if (kind != XS_CTL) return;
    int acked = xs_pack_size(pt, pn);
    if (acked > 0) {
        if (s->probing && acked == s->p_cur) {
            /* Размер вернулся эхом — путь его несёт. Двигаем нижнюю границу и спрашиваем, есть ли
             * смысл проверять дальше. */
            s->p_lo = acked;
            s->p_tries = 0;
            s->p_verify = 0;
            s->p_cur = xs_mtu_next(s->p_lo, s->p_hi, s->mtu_agreed);
            if (!s->p_cur || ++s->p_steps > XS_MTU_TRIES_MAX) probe_done(s, dev, now);
            else s->probe_sent = 0;
        }
        return;
    }
    int lost = xs_loss_value(pt, pn);
    if (lost > 0) {
        /* Хаб не собирает наши записи: путь рвёт сегменты. Схлопываем пачку немедленно — на рваном
         * пути она делает хуже, а не лучше, а восстанавливать потерянное мы не будем (это
         * UDP-туннель под видом TCP). */
        s->batch_max = 1;
        s->cool_until = now + XSC_REASM_COOL_MS;
        fprintf(stderr, LOG_W "хаб не собрал %d записей — везу по одному кадру\n", lost);
    }
}

struct spoke_fctx { struct spoke *s; const char *dev; long long now; };

static void spoke_frame_cb(void *ctx, const uint8_t *f, size_t n) {
    struct spoke_fctx *c = ctx;
    spoke_frame(c->s, f, n, c->dev, c->now);
}

/* ---- режим потока: записи по НАСТОЯЩЕМУ соединению TCP ----------------------
 *
 * Зачем он есть — в шапке xsstream.h. Коротко: поддельный TCP требует сырого сокета и правила
 * против RST собственного ядра, и там, где их нет, недоступен весь протокол целиком; а хаб
 * реализации на Go принимает пиров и так, и так.
 *
 * Чего в этом режиме НЕТ и почему:
 *
 *   - проб ПУТИ. Внешним MTU распоряжается ядро (оно само делает обнаружение MTU пути и режет
 *     поток на сегменты), а размер записи ему безразличен. Первая ступень согласования —
 *     минимум пределов сторон из рукопожатия — остаётся, вторая теряет смысл;
 *   - окна приёма и сборки разрезанных записей. Поток доставляет всё и по порядку, поэтому и
 *     пачка всегда полного размера;
 *   - ретайра по объёму. Он существовал ровно для того, чтобы 32-битное смещение не
 *     завернулось и не повторило nonce; здесь смещение 64-битное, заворот недостижим, а
 *     ключи меняются эпохами — без разрыва внутренних сессий TCP (xsepoch.h).
 */

/* Отдать поток и ключи. Отдельно от session_down: там закрывается поддельное соединение,
 * которого здесь нет вовсе. */
static void stream_down(struct spoke *s) {
    /* Без оглядки на s->up — по той же причине, что в session_down. */
    tls13_keys_free(&s->tx);
    tls13_keys_free(&s->rx);
    memset(&s->tx, 0, sizeof(s->tx));
    memset(&s->rx, 0, sizeof(s->rx));
    /* Прошлые ключи эпох живут в ратчете, и освободить их обязан он: у них свой контекст
     * шифра в куче. Затирается там же и корень — из него выводятся все будущие ключи. */
    xs_epoch_stop(&s->ep_tx);
    xs_epoch_stop(&s->ep_rx);
    s->up = 0;
    if (s->st) {
        if (s->st->fd >= 0) close(s->st->fd);
        free(s->st);
        s->st = NULL;
    }
}

/* Порт хаба для потока: назван ключом или тот же, что у поддельного TCP.
 *
 * ПОЧЕМУ ЭТО МОЖЕТ БЫТЬ РАЗНЫЙ ПОРТ. Слушающий сокет ядра на хабе отвечает SYN-ACK всякому,
 * кто постучится, — включая пиров, которые ведут ПОДДЕЛЬНЫЙ TCP. Тогда на один их SYN
 * приходит два ответа с разными начальными номерами, и сессия рассыпается. Поэтому у хаба,
 * который держит оба режима, они живут на разных портах, и какой из них поставить на :443,
 * решает оператор. */
static int stream_port(const struct spoke *s) {
    return s->stream_port ? s->stream_port : s->hub_port;
}

/* Открыть соединение к хабу.
 *
 * Неблокирующий connect с ожиданием по poll, а не блокирующий: блокирующий висит до таймаута
 * ядра (это минуты), а нам надо вернуться, сказать причину и попробовать снова — ровно как в
 * половине поддельного TCP, где ожидание ограничено числом попыток SYN. */
static int stream_dial(struct spoke *s) {
    int fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0) return -1;
    int fl = fcntl(fd, F_GETFL, 0);
    fcntl(fd, F_SETFL, fl | O_NONBLOCK);
    /* Без задержки Нейгла: мелкий кадр (внутреннее подтверждение, проба, keepalive) не должен
     * ждать, пока наберётся сегмент. Задержка здесь стоила бы кругов внутреннему TCP, который
     * едет внутри и своего ожидания уже не понимает.
     *
     * Размеры буферов сокета при этом НЕ задаются — почему, сказано в шапке xsstream.h: любой
     * явный setsockopt отключает автоподстройку окна и режется по net.core.{r,w}mem_max. */
    int one = 1;
    setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &one, sizeof(one));
    /* СВОЁ соединение к хабу из туннеля исключать НЕ НУЖНО, и это свойство раскладки правил, а
     * не удача. Метку, по которой трафик уходит в таблицу выхода, ставит цепочка в хуке
     * prerouting по адресу ИСТОЧНИКА из локальной сети (см. src/steer.c); пакеты, рождённые
     * самим роутером, prerouting не проходят вовсе, поэтому метки не получают и в туннель не
     * попадают — даже при полном туннеле 0.0.0.0/0. Ни SO_MARK, ни привязки к устройству, ни
     * обхода /32 к адресу хаба здесь поэтому нет. На Windows у реализации на Go всё иначе (там
     * маршрутами владеет система, и сокет приходится привязывать через IP_UNICAST_IF), и
     * разница между платформами объяснена там же, в tun/pin_other.go. */
    struct sockaddr_in to;
    memset(&to, 0, sizeof(to));
    to.sin_family = AF_INET;
    to.sin_port = htons((uint16_t)stream_port(s));
    to.sin_addr.s_addr = s->hub_addr;
    if (connect(fd, (struct sockaddr *)&to, sizeof(to)) != 0 && errno != EINPROGRESS) {
        fprintf(stderr, LOG_W "поток к %s:%d не открылся: %s\n",
                s->conf->peer[0].endpoint, stream_port(s), strerror(errno));
        close(fd);
        return -1;
    }
    struct pollfd p = { fd, POLLOUT, 0 };
    int n = poll(&p, 1, XSC_STREAM_DIAL_MS);
    int err = 0;
    socklen_t el = sizeof(err);
    if (n <= 0 || getsockopt(fd, SOL_SOCKET, SO_ERROR, &err, &el) != 0 || err != 0) {
        /* Причина называется вслух и разными словами: «не ответил вовсе» это закрытый порт
         * или фильтр, а «отказал» — как правило, никого нет на порту. Без этого различия
         * снаружи видно только «туннель не поднялся». */
        if (n == 0)
            fprintf(stderr, LOG_W "%s:%d не отвечает на SYN (%d мс): хаб не запущен, порт "
                                  "закрыт или режим потока на хабе не включён\n",
                    s->conf->peer[0].endpoint, stream_port(s), XSC_STREAM_DIAL_MS);
        else
            fprintf(stderr, LOG_W "поток к %s:%d не открылся: %s\n",
                    s->conf->peer[0].endpoint, stream_port(s), strerror(err ? err : errno));
        close(fd);
        return -1;
    }
    return fd;
}

/* Дождаться n байт подряд, но не дольше срока. 1 — есть, 0 — время вышло, -1 — обрыв. */
static int stream_need(struct spoke *s, size_t n, const uint8_t **p, long long deadline) {
    for (;;) {
        int rc = xs_stream_peek(s->st, n, p);
        if (rc != 0) return rc;
        long long left = deadline - xs_now_ms();
        if (left <= 0) return 0;
        struct pollfd pf = { s->st->fd, POLLIN, 0 };
        poll(&pf, 1, (int)(left > XSC_TICK_MS * 5 ? XSC_TICK_MS * 5 : left));
    }
}

/* Одно рукопожатие по потоку целиком.
 *
 * Хореография та же, что в поддельном TCP (do_handshake), и различается только рамкой: Hello
 * уходит одним вызовом — резать его на сегменты дело ядра, — а ответ собирается ПО ЗАПИСЯМ,
 * ни байтом больше. Последнее обязательно: данные, приехавшие вплотную за рукопожатием, должны
 * остаться в буфере потока, иначе первая же запись данных пропадёт, а выглядеть это будет как
 * «туннель поднялся и молчит».
 *
 * xs_hs_client_finish зовётся РОВНО ОДИН РАЗ и только на целом ответе — см. xs_hs_response_complete. */
static int stream_handshake(struct spoke *s, const char *dev) {
    struct xs_hs hs;
    size_t hn = 0;
    /* Свой предел называется так же, как в поддельном TCP: не больше XS_MTU_DEF и не больше
     * заданного человеком. MTU канала здесь НЕ спрашивается, и это не упущение: наружу поток
     * режет ядро, оно же ведёт обнаружение MTU пути, поэтому канал в 1492 байта не обязывает
     * нас уменьшать внутренний размер — он обязывает ядро сделать сегмент короче. То же самое
     * и в тех же числах называет реализация на Go. */
    int say = XS_MTU_DEF;
    if (s->mtu_cap > 0 && s->mtu_cap < say) say = s->mtu_cap;
    int rc = xs_hs_client_hello(&hs, s->sec, s->hub_pub, s->conf->sni, say, s->conn_id,
                                s->txb, sizeof(s->txb), &hn);
    if (rc != 0) {
        fprintf(stderr, LOG_W "рукопожатие не собралось: %d\n", rc);
        return rc;
    }
    if (xs_stream_write_raw(s->st, s->txb, hn) != 0) {
        fprintf(stderr, LOG_W "Hello не ушёл: %s\n", strerror(errno));
        xs_hs_wipe(&hs);
        return -1;
    }
    /* Ответ хаба заведомо меньше двух строк: ServerHello, фальшивый ChangeCipherSpec, запись
     * «сертификата» правдоподобной длины и подтверждение. Больше этого — не наш собеседник или
     * порча; копить дальше значило бы позволить чужому раздуть память. */
    uint8_t acc[2 * XS_ROW];
    size_t an = 0;
    long long deadline = xs_now_ms() + XSC_STREAM_HS_MS;
    while (!xs_hs_response_complete(acc, an)) {
        const uint8_t *h;
        int pr = stream_need(s, XS_REC_HDR, &h, deadline);
        if (pr <= 0) {
            fprintf(stderr, LOG_W "хаб %s:%d %s на рукопожатие\n", s->conf->peer[0].endpoint,
                    stream_port(s), pr == 0 ? "не ответил" : "оборвал соединение");
            xs_hs_wipe(&hs);
            return -1;
        }
        /* Фатальное оповещение TLS в ответ — это ОТВЕТ, и он говорит больше, чем тишина: хаб
         * нас не признал (не тот ключ, не тот пир в конфигурации). Ждать после него до конца
         * срока значило бы показать человеку «не отвечает» там, где ответ был. */
        if (an == 0 && h[0] == 0x15) {
            fprintf(stderr, LOG_W "хаб %s:%d ответил отказом TLS: нас нет в его конфигурации "
                                  "или публичный ключ не тот\n",
                    s->conf->peer[0].endpoint, stream_port(s));
            xs_hs_wipe(&hs);
            return -1;
        }
        size_t rn = ((size_t)h[3] << 8) | h[4];
        if (an + XS_REC_HDR + rn > sizeof(acc) || rn > XS_MAX_RECORD) {
            fprintf(stderr, LOG_W "хаб %s:%d ответил не тем: %zu байт без узнаваемого конца "
                                  "рукопожатия\n", s->conf->peer[0].endpoint, stream_port(s),
                    an + rn);
            xs_hs_wipe(&hs);
            return -1;
        }
        pr = stream_need(s, XS_REC_HDR + rn, &h, deadline);
        if (pr <= 0) {
            fprintf(stderr, LOG_W "ответ хаба приехал не весь\n");
            xs_hs_wipe(&hs);
            return -1;
        }
        memcpy(acc + an, h, XS_REC_HDR + rn);
        an += XS_REC_HDR + rn;
        xs_stream_drop(s->st, XS_REC_HDR + rn);
    }
    size_t used = 0;
    rc = xs_hs_client_finish(&hs, acc, an, &s->tx, &s->rx, &used);
    if (rc != 0) {
        fprintf(stderr, LOG_W "хаб не признал нас или ответил не тем: %d\n", rc);
        xs_hs_wipe(&hs);
        return rc;
    }
    size_t fn = 0;
    rc = xs_hs_client_confirm(&hs, &s->tx, s->txb, sizeof(s->txb), &fn);
    if (rc == 0 && xs_stream_write_raw(s->st, s->txb, fn) != 0) rc = -1;
    int peer_mtu = hs.peer.mtu;
    /* Корни эпох забираются ДО xs_hs_wipe: он затирает состояние рукопожатия целиком, и
     * первая версия этой правки читала уже занулённые байты — ратчет пошёл бы от нуля у обеих
     * сторон одинаково, то есть отказ не проявился бы вовсе, а прямая секретность исчезла. */
    uint8_t troot[32], rroot[32];
    xs_hs_roots(&hs, troot, rroot);
    xs_hs_wipe(&hs);
    if (rc != 0) {
        volatile uint8_t *a = troot, *b = rroot;
        for (int i = 0; i < 32; i++) { a[i] = 0; b[i] = 0; }
        return rc;
    }
    /* Ратчет включается ДО первой записи данных и на ОБОИХ направлениях: номер эпохи считается
     * из смещения, и сторона, включившая его позже, разошлась бы с другой на те записи, что
     * успели уехать. На проводе от этого не меняется ни один байт. */
    xs_epoch_start(&s->ep_tx, troot);
    xs_epoch_start(&s->ep_rx, rroot);
    {
        volatile uint8_t *a = troot, *b = rroot;
        for (int i = 0; i < 32; i++) { a[i] = 0; b[i] = 0; }
    }

    /* СОГЛАСОВАНИЕ MTU: только первая ступень — минимум пределов сторон. Второй (проверки
     * самого пути пробами) в потоке нет, потому что сегментацией распоряжается ядро. */
    s->mtu_agreed = say;
    if (peer_mtu > 0 && peer_mtu < s->mtu_agreed) s->mtu_agreed = peer_mtu;
    s->mtu_confirmed = s->mtu_agreed;
    s->up = 1;
    s->handshake_at = xs_now_ms();
    s->stream_rx = s->handshake_at;
    s->batch_max = XS_BATCH_FRAMES_MAX;
    fprintf(stderr, LOG_I "рукопожатие с %s:%d прошло потоком, шифр %s, MTU %d, ключи меняются "
                          "каждые %llu МиБ\n",
            s->conf->peer[0].endpoint, stream_port(s),
            s->tx.aead == TLS13_AEAD_AES128 ? "AES-128-GCM" : "ChaCha20-Poly1305",
            s->mtu_agreed, (unsigned long long)(XS_EPOCH_BYTES >> 20));
    /* Устройство и общее значение для остальных воркеров: тот же путь, что после пробоя в
     * поддельном TCP, только значение известно сразу. */
    mtu_apply(s, dev, s->mtu_agreed, "согласовано в рукопожатии (поток)");
    if (!s->conn_id) g_mtu_pub = s->mtu_agreed;
    return 0;
}

/* Одна запись наружу: собрать заголовок, зашифровать смещением и отдать потоку.
 *
 * Смещение спрашивается ровно перед шифрованием и отправкой: выдать его, зашифровать им и
 * отправить нужно как одно действие, иначе две записи уедут под одним nonce. То же неделимое
 * правило, что у xs_conn_rel_next в поддельном TCP. */
static int stream_record(struct spoke *s, uint8_t *rec, size_t pn) {
    uint64_t off = xs_stream_tx_next(s->st);
    if (xs_rec_build(rec, pn + XS_TAG) != 0) return -1;
    if (xs_epoch_seal(&s->ep_tx, &s->tx, off, rec, XS_REC_HDR, rec + XS_REC_HDR, pn,
                      rec + XS_REC_HDR + pn) != 0)
        return -1;
    return xs_stream_send(s->st, rec, XS_REC_HDR + pn + XS_TAG);
}

/* Служебный кадр (проба, итог согласования, keepalive) одиночной записью. Тем же путём, что
 * данные: своего канала у них нет, и это нарочно — иначе появился бы второй путь на проводе,
 * который DPI различал бы по размеру и ритму. */
static int stream_frame(struct spoke *s, const uint8_t *pt, size_t pn) {
    if (!s->up || pn > (size_t)XS_MTU_DEF) return -1;
    uint8_t *rec = s->txb + 20;
    if (pn) memcpy(rec + XS_REC_HDR, pt, pn);
    return stream_record(s, rec, pn);
}

/* Цикл одного соединения в режиме потока. */
static void *stream_main(struct spoke *s) {
    const char *dev = s->dev;
    long long last_state = 0, last_probe = 0, last_tx = 0;
    int keepalive_ms = s->conf->peer[0].keepalive * 1000;

    for (;;) {
        if (!s->up) {
            if (!s->st) {
                s->st = calloc(1, sizeof(*s->st));
                if (!s->st) {
                    fprintf(stderr, LOG_W "не хватило памяти на буфер потока\n");
                    if (worker_give_up(s)) return (void *)1;
                    continue;
                }
                s->st->fd = -1;
            }
            fprintf(stderr, LOG_I "подключаюсь к %s:%d настоящим TCP (режим потока)\n",
                    s->conf->peer[0].endpoint, stream_port(s));
            int fd = stream_dial(s);
            if (fd < 0) {
                stream_down(s);
                if (!s->conn_id) state_write(s);
                if (worker_give_up(s)) return (void *)1;
                continue;
            }
            xs_stream_init(s->st, fd);
            if (stream_handshake(s, dev) != 0) {
                stream_down(s);
                if (!s->conn_id) state_write(s);
                if (worker_give_up(s)) return (void *)1;
                continue;
            }
            /* Хабу называется рабочий размер тем же служебным кадром, что в поддельном TCP: по
             * нему он подрезает MSS обратного трафика ДЛЯ ЭТОЙ сессии. Не сказав, мы получили
             * бы «через одно соединение большие пакеты ходят, через другое нет». */
            uint8_t fin[8];
            size_t fnn = xs_mtu_build(fin, sizeof(fin), s->mtu_agreed);
            if (fnn && stream_frame(s, fin, fnn) == 0) s->mtu_told = s->mtu_agreed;
            last_tx = xs_now_ms();
            state_write(s);
        }

        /* Хвост недописанной записи — единственная причина ждать готовности к записи: пока он
         * не уехал, следующую запись отправлять нельзя (половина записи в потоке это не
         * потерянный пакет, а разъехавшийся поток). */
        int busy = xs_stream_busy(s->st);
        struct pollfd fds[2] = { { s->tun.fd, POLLIN, 0 },
                                 { s->st->fd, (short)(POLLIN | (busy ? POLLOUT : 0)), 0 } };
        int n = poll(fds, 2, XSC_TICK_MS);
        long long now = xs_now_ms();
        if (n < 0 && errno != EINTR) break;
        if (busy && xs_stream_flush(s->st) < 0) {
            fprintf(stderr, LOG_W "поток оборвался при досылке записи\n");
            stream_down(s);
            continue;
        }

        /* ---- наружу: TUN → поток ------------------------------------------------
         *
         * Кадры читаются ПРЯМО в буфер записи, на свои места в контейнере пачки: пачка
         * собирается без единой лишней копии. Резать запись на сегменты не нужно — это работа
         * ядра, и она же снимает предел «запись не длиннее сегмента»: здесь запись живёт своей
         * длиной до восьми килобайт, ровно как у настоящего TLS. */
        if (s->up && !xs_stream_busy(s->st) && n > 0 && (fds[0].revents & POLLIN)) {
            uint8_t *rec = s->rb + 20;
            uint8_t *pay = rec + XS_REC_HDR;
            size_t off = XS_BATCH_HDR;
            int frames = 0;
            unsigned long long payload = 0;
            /* Пачка всегда полного размера: разрезанных записей в потоке не бывает, поэтому
             * обратной связи по сборке (и схлопывания пачки) здесь нет вовсе. */
            while (frames < XS_BATCH_FRAMES_MAX) {
                if (frames > 0 && off + 2 + (size_t)s->mtu + XS_TAG > XS_MAX_RECORD) break;
                ssize_t r = tun_read_packet(&s->tun, pay + off + 2, (size_t)s->mtu);
                if (r <= 0) break;
                xs_mss_clamp(pay + off + 2, (size_t)r, s->mtu);
                pay[off] = (uint8_t)((size_t)r >> 8);
                pay[off + 1] = (uint8_t)((size_t)r & 0xFF);
                off += 2 + (size_t)r;
                payload += (unsigned long long)r;
                frames++;
            }
            if (frames > 0) {
                size_t pn;
                if (frames == 1) {
                    pn = off - XS_BATCH_HDR - 2;
                    memmove(pay, pay + XS_BATCH_HDR + 2, pn);
                } else {
                    pay[0] = XS_CTL_BATCH;
                    pn = off;
                }
                int rc = stream_record(s, rec, pn);
                if (rc == 0) {
                    s->up_pkts += (unsigned long long)frames;
                    s->up_bytes += payload;
                    last_tx = now;
                } else if (rc == -2) {
                    /* Очередь сокета переполнена посреди прошлой записи. Кадры отбрасываются, а
                     * не копятся: повторных передач у нас нет по построению, а очередь означала
                     * бы задержку вместо потери — то есть подмену одного класса отказов другим,
                     * менее заметным. Внутренний TCP разберётся с потерей сам. */
                    s->dropped += (unsigned long long)frames;
                } else {
                    fprintf(stderr, LOG_W "поток оборвался при отправке: %s\n", strerror(errno));
                    stream_down(s);
                    continue;
                }
            }
        }

        /* ---- обратно: поток → TUN ----------------------------------------------- */
        if (s->up && n > 0 && (fds[1].revents & (POLLIN | POLLHUP | POLLERR))) {
            /* Записей за один круг — не больше предела, и это не микрооптимизация.
             *
             * Поток надёжен и при насыщенной загрузке приносит байты быстрее, чем мы успеваем
             * их разобрать; цикл «читать, пока приходит» в таком режиме не кончается вовсе, и
             * чтение TUN не получает управления — то есть отдача встаёт целиком, пока идёт
             * приём. В поддельном TCP от этого спасает сама пачка recvmmsg (цикл выходит на
             * неполной), здесь границу приходится назвать. Сто двадцать восемь записей это
             * около мегабайта за круг: и накладные на poll остаются незаметными, и обратное
             * направление не голодает. */
            int left_recs = XSC_BATCH * XS_BATCH_FRAMES_MAX;
            while (left_recs-- > 0) {
                const uint8_t *hdr, *body;
                size_t bn;
                uint64_t rel;
                int rc = xs_stream_recv(s->st, &hdr, &body, &bn, &rel);
                if (rc == 0) break;
                if (rc < 0) {
                    /* И обрыв, и «в потоке не запись xsteer» кончаются одним: соединением
                     * пользоваться больше нельзя. Границы следующей записи известны только из
                     * длины, которой мы уже не верим, — пропустить один кадр, как в поддельном
                     * TCP, здесь невозможно. */
                    fprintf(stderr, LOG_W "поток закрылся%s\n",
                            rc == -2 ? ": пришла не запись xsteer" : "");
                    stream_down(s);
                    break;
                }
                uint8_t *ct = (uint8_t *)(uintptr_t)body;
                if (xs_epoch_open(&s->ep_rx, &s->rx, rel, hdr, XS_REC_HDR, ct, bn) != 0) {
                    fprintf(stderr, LOG_W "запись не расшифровалась — поднимаю соединение "
                                          "заново\n");
                    stream_down(s);
                    break;
                }
                s->stream_rx = now;
                size_t pn = bn - XS_TAG;
                struct spoke_fctx fc = { s, dev, now };
                if (pn && ct[0] == XS_CTL_BATCH) {
                    if (xs_batch_iter(ct, pn, spoke_frame_cb, &fc) != 0) s->dropped++;
                } else {
                    spoke_frame(s, ct, pn, dev, now);
                }
                /* Склеенное отдаётся ЗДЕСЬ, до следующей записи: её буфер будет
                 * переиспользован, а склейка ссылается на кадры в нём. Заодно это и есть
                 * обещание «ни миллисекунды задержки» — накопленное не переживает обработку
                 * одной записи. */
                tun_gro_flush(&s->tun, &s->gro);
            }
        }

        if (!s->up) continue;

        /* Проба живости. Ответ на неё — единственный признак того, что канал несёт трафик в
         * обратную сторону: сам поток TCP о смерти хаба узнаёт через минуты, а туннель к тому
         * времени уже «не работает, и непонятно почему». */
        if (now - last_probe >= XSC_STREAM_PROBE_MS) {
            uint8_t probe[XS_PROBE_MIN];
            if (xs_probe_build(probe, sizeof(probe), XS_PROBE_MIN) == XS_PROBE_MIN &&
                stream_frame(s, probe, XS_PROBE_MIN) == 0)
                last_tx = now;
            last_probe = now;
        }
        /* Тишина при активной отправке — это обрыв, и признаётся он так же, как в поддельном
         * TCP (xs_conn_tick): «мы отправили ПОСЛЕ того, как получили». Иначе туннель на покое,
         * однажды отправивший пакет, считался бы мёртвым навсегда. */
        if (last_tx > s->stream_rx && now - s->stream_rx >= XSC_DEAD_MS) {
            fprintf(stderr, LOG_W "поток молчит %d мс при активной отправке — поднимаю "
                                  "соединение заново\n", XSC_DEAD_MS);
            stream_down(s);
            continue;
        }
        /* Keepalive: пустая запись. Пир за NAT обязана поддерживать отображение живым, потому
         * что дозвониться до неё хаб не может; настоящий TCP держит соединение своими
         * средствами лишь через часы, а отображение NAT живёт минуты.
         *
         * ИНТЕРВАЛ С РАЗБРОСОМ, а не ровный: пакет одного и того же размера ровно каждые
         * keepalive секунд не встречается ни в одном браузерном соединении и находится
         * подсчётом пауз между мелкими пакетами. */
        if (keepalive_ms && !s->keep_next) s->keep_next = keepalive_ms;
        if (keepalive_ms && now - last_tx >= s->keep_next) {
            if (stream_frame(s, NULL, 0) == 0) last_tx = now;
            uint32_t j = 0;
            xc_random((unsigned char *)&j, sizeof(j));
            s->keep_next = keepalive_ms * 8 / 10 +
                           (long long)(j % (uint32_t)(keepalive_ms * 4 / 10 + 1));
        }
        /* Соединения кроме нулевого: подхватываем согласованный MTU и называем его хабу — у
         * каждого соединения на хабе своя сессия, и подрезку MSS обратного трафика он делает по
         * MTU ТОЙ сессии, в которую отправляет. */
        if (s->conn_id) {
            if (g_mtu_now > 0 && s->mtu != g_mtu_now) s->mtu = g_mtu_now;
            if (g_mtu_pub > 0 && s->mtu_told != g_mtu_pub) {
                uint8_t fin[8];
                size_t fnn = xs_mtu_build(fin, sizeof(fin), g_mtu_pub);
                if (fnn && stream_frame(s, fin, fnn) == 0) s->mtu_told = g_mtu_pub;
            }
        }
        if (!s->conn_id && now - last_state >= 2000) { state_write(s); last_state = now; }
    }
    stream_down(s);
    if (!s->conn_id) xs_conf_wipe(s->sec);
    return (void *)1;
}

/* Цикл одного соединения. */
static void *worker_main(void *arg) {
    struct spoke *s = arg;
    /* Режим потока — отдельный цикл, а не ветки внутри этого. Общего у них ровно рамка
     * (устройство, MTU, keepalive, файл состояния), а различается ВСЁ на пути данных: там нет
     * ни окна приёма, ни сборки записей, ни проб пути, ни ретайра, зато есть досылка хвоста и
     * ратчет эпох. Ветки на каждом шаге сделали бы оба пути труднее для чтения, чем каждый по
     * отдельности. Так же разделены они и в реализации на Go (client/stream.go). */
    if (s->stream) return stream_main(s);
    const char *dev = s->dev;
    long long last_state = 0;
    int keepalive_ms = s->conf->peer[0].keepalive * 1000;

    for (;;) {
        if (!s->up) {
            if (s->conn.state == XSC_CLOSED &&
                xs_conn_open(&s->conn, s->hub_addr, s->hub_port, s->conn_id) != 0) {
                fprintf(stderr, LOG_W "сырой сокет недоступен: %s\n", strerror(errno));
                if (worker_give_up(s)) return (void *)1;
                continue;
            }
            /* Печатается ВСЕГДА и до ожидания. Первая версия молчала до конца рукопожатия,
             * и «пир ничего не делает» было не отличить от «SYN не уходит»: ровно на это
             * ушёл первый прогон живого стенда. Знать надо до замеров, а не после. */
            fprintf(stderr, LOG_I "подключаюсь к %s:%d с порта %u\n",
                    s->conf->peer[0].endpoint, s->hub_port, s->conn.sport);
            /* Ждём установления поддельного TCP, потом здороваемся. */
            long long deadline = xs_now_ms() + XSC_SYN_RETRY_MS * XSC_SYN_RETRIES;
            while (s->conn.state != XSC_EST && xs_now_ms() < deadline) {
                struct pollfd p = { s->conn.fd, POLLIN, 0 };
                poll(&p, 1, XSC_TICK_MS);
                if (p.revents & POLLIN) {
                    uint8_t pkt[XS_ROW];
                    ssize_t r = recv(s->conn.fd, pkt, sizeof(pkt), 0);
                    struct obfs_seg seg;
                    if (r > 0 && obfs_parse(pkt, (size_t)r, &seg) == 0 &&
                        seg.sport == s->conn.dport && seg.dport == s->conn.sport) {
                        if (xs_conn_on_seg(&s->conn, &seg, xs_now_ms()) < 0) {
                            /* RST на поддельный SYN — это ОТВЕТ, и он говорит больше, чем
                             * тишина: на порту либо нет нашего хаба, либо у него не встало
                             * правило против RST, и его же ядро рвёт нам сессию. Сказать это
                             * надо здесь: иначе видно только «не отвечает». */
                            fprintf(stderr, LOG_W "%s:%d ответил RST — на этом порту не наш "
                                                  "хаб, либо у него не встало правило против "
                                                  "RST собственного ядра\n",
                                    s->conf->peer[0].endpoint, s->hub_port);
                            break;
                        }
                    }
                }
                xs_conn_tick(&s->conn, xs_now_ms(), 0);
            }
            if (s->conn.state == XSC_EST) {
    /* Предел по каналу считается от НАСТОЯЩЕГО интерфейса, через который мы уходим, а не от
     * предположения «1500»: на PPPoE это 1492, и разница в 8 байт — ровно тот случай, когда
     * большие пакеты пропадают молча. */
    s->mtu_limit = 0;
    {
        char ifn[32] = "";
        int link = xs_egress_mtu(s->conn.saddr, ifn, sizeof(ifn));
        if (link > 0) {
            s->mtu_limit = xs_mtu(link);
            snprintf(s->link_if, sizeof(s->link_if), "%s", ifn);
        }
    }
            }
            if (s->conn.state != XSC_EST) {
                /* Молчаливого выхода здесь быть не должно. Первая версия просто возвращала 1,
                 * и на живом роутере это выглядело так: «подключаюсь…» — и всё, процесса нет,
                 * причины нет. А причина типовая: на той стороне никто не слушает, либо её
                 * ядро отвечает RST (у хаба не встало правило против RST), либо путь режут. */
                fprintf(stderr, LOG_W "%s:%d не отвечает на поддельный SYN (%d попыток): "
                                      "хаб не запущен, порт закрыт, или у хаба не встало "
                                      "правило против RST собственного ядра\n",
                        s->conf->peer[0].endpoint, s->hub_port, XSC_SYN_RETRIES);
                session_down(s);
                if (!s->conn_id) state_write(s);
                if (worker_give_up(s)) return (void *)1;
                continue;
            }
            if (do_handshake(s) != 0) {
                session_down(s);
                if (!s->conn_id) state_write(s);
                if (worker_give_up(s)) return (void *)1;
                continue;
            }
            /* НАЧИНАЕМ С БЕЗОПАСНОГО НИЗА, и это главный урок, взятый у veil (engine/pmtu.go):
             * пока проба не подтвердила размер, каждый полноразмерный пакет рискует уйти в ту
             * самую чёрную дыру, которую мы ищем. Низ несёт любой реальный путь, поэтому
             * туннель работает сразу, просто пока не на полную.
             *
             * НО ТОЛЬКО НА ПЕРВОМ рукопожатии. Переподключение к тому же хабу по тому же
             * каналу происходит по причинам, к пути не относящимся (тишина, смена ключей,
             * перезапуск хаба), и путь при этом тот самый, который мы уже измерили. Ронять
             * MTU на низ при каждом переподключении значило бы платить провалом скорости за
             * событие, которое к MTU отношения не имеет; проверку прежнего значения делает
             * первая же проба и стоит она 300 мс. Риск назван прямо: если путь всё-таки
             * сузился ИМЕННО в этот момент, полноразмерные пакеты пропадают эти 300 мс. */
            if (!s->mtu_confirmed && s->mtu_agreed > XS_MTU_FLOOR && s->mtu > XS_MTU_FLOOR)
                mtu_apply(s, dev, XS_MTU_FLOOR, "начинаю с безопасного низа, проверяю путь");
            probe_start(s, xs_now_ms());
            state_write(s);
        }

        struct pollfd fds[2] = { { s->tun.fd, POLLIN, 0 }, { s->conn.fd, POLLIN, 0 } };
        int n = poll(fds, 2, XSC_TICK_MS);
        long long now = xs_now_ms();
        if (n < 0 && errno != EINTR) break;

        /* ---- наружу: TUN → поддельный TCP ----------------------------------
         *
         * Кадры читаются ПРЯМО в буфер записи, на свои места в контейнере пачки: так пачка
         * собирается без единой лишней копии. Ждать ради неё нечего — берётся только то, что уже
         * лежит в очереди устройства, поэтому при потоковой загрузке кадры набираются сами, а при
         * интерактивном трафике в пачке один кадр, и он едет без контейнера, как раньше.
         *
         * Зачем это всё и чем оплачено — в xswire.h. Коротко: у настоящего TLS запись не кончается
         * на границе сегмента, а у нас кончалась всегда. */
        if (n > 0 && (fds[0].revents & POLLIN)) {
            int max = s->batch_max;
            if (now < s->cool_until) max = 1;
            if (max < 1) max = 1;
            if (max > XS_BATCH_FRAMES_MAX) max = XS_BATCH_FRAMES_MAX;
            uint8_t *rec = s->rb + 20;
            uint8_t *pay = rec + XS_REC_HDR;
            size_t off = XS_BATCH_HDR;
            int frames = 0;
            unsigned long long payload = 0;
            while (frames < max) {
                /* Проверка ДО чтения: прочитанный кадр девать некуда, если он не влезет, а
                 * откладывать его до следующего круга значило бы менять порядок пакетов. */
                if (frames > 0 && off + 2 + (size_t)s->mtu + XS_TAG > XS_MAX_RECORD) break;
                ssize_t r = tun_read_packet(&s->tun, pay + off + 2, (size_t)s->mtu);
                if (r <= 0) break;
                /* Подрезка MSS в ОБОИХ направлениях, и это не перестраховка: сюда приходят SYN от
                 * узлов локальной сети, а из туннеля — SYN-ACK от узлов интернета, которые
                 * объявляют MSS по СВОЕМУ каналу и ничего не знают про наш. */
                xs_mss_clamp(pay + off + 2, (size_t)r, s->mtu);
                pay[off] = (uint8_t)((size_t)r >> 8);
                pay[off + 1] = (uint8_t)((size_t)r & 0xFF);
                off += 2 + (size_t)r;
                payload += (unsigned long long)r;
                frames++;
            }
            if (frames > 0) {
                size_t pn;
                if (frames == 1) {
                    /* Одиночный кадр едет БЕЗ контейнера: он дешевле на три байта, и таких записей
                     * большинство. Сдвиг на месте стоит одной копии на кадр и только тогда, когда
                     * пачка не собралась. */
                    pn = off - XS_BATCH_HDR - 2;
                    memmove(pay, pay + XS_BATCH_HDR + 2, pn);
                } else {
                    pay[0] = XS_CTL_BATCH;
                    pn = off;
                }
                uint32_t rel = xs_conn_rel_next(&s->conn);
                int segs = -1;
                if (xs_rec_build(rec, pn + XS_TAG) == 0 &&
                    tls13_aead_seal(&s->tx, rel, rec, XS_REC_HDR, pay, pn, pay + pn) == 0) {
                    size_t max_seg = (size_t)s->mtu + XS_OVERHEAD - 40;
                    segs = xs_conn_split_mm(&s->conn, rec, XS_REC_HDR + pn + XS_TAG, max_seg,
                                            s->hdrs, s->siov, s->smm,
                                            sizeof(s->hdrs) / sizeof(s->hdrs[0]), now);
                }
                if (segs <= 0) {
                    s->dropped += (unsigned long long)frames;
                } else {
                    /* ЧАСТИЧНАЯ ОТПРАВКА ДОСЫЛАЕТСЯ, А НЕ СЧИТАЕТСЯ ПОТЕРЕЙ.
                     *
                     * sendmmsg отправляет сколько смог и возвращает это число: очередь сокета
                     * заполняется, и на скорости это происходит постоянно. Первая версия молча
                     * записывала остаток в потери — и это стоило 0,25 Мбит/с при канале 200 на
                     * живом роутере: у нас нет повторной передачи, каждая недосланная датаграмма
                     * это дырка во внутреннем TCP, а теперь ещё и половина разрезанной записи.
                     * «Нет прогресса дважды подряд» считаем настоящей потерей — иначе один
                     * неотправляемый сегмент заклинил бы цикл навсегда. */
                    int sent_off = 0, stuck = 0, gone = 0;
                    while (sent_off < segs) {
                        int sent = sendmmsg(s->conn.fd, &s->smm[sent_off],
                                            (unsigned)(segs - sent_off), 0);
                        if (sent > 0) { sent_off += sent; stuck = 0; continue; }
                        /* ПУТИ НАРУЖУ БОЛЬШЕ НЕТ — это ответ ядра, а не неудача отправки: ждать
                         * тишины XSC_DEAD_MS незачем, соединение надо поднимать заново. Прежде эта
                         * ошибка была неотличима от прочих и лишь растила счётчик потерь, то есть
                         * при пропавшем интернете пир молотил в мёртвый сокет весь порог. */
                        if (xs_path_gone(errno)) { gone = errno; break; }
                        if (++stuck >= 3) break;
                        if (errno != EAGAIN && errno != ENOBUFS && errno != EINTR) break;
                    }
                    if (gone) {
                        /* Снимаем сессию ТЕМ ЖЕ способом, что смена ключей ниже: break вышел бы
                         * только из цикла добора кадров, и мы продолжили бы молотить в мёртвый
                         * сокет — то есть исправление не исправляло бы ничего. */
                        fprintf(stderr, LOG_W "путь наружу пропал (%s) — поднимаю соединение "
                                              "заново, когда он вернётся\n", strerror(gone));
                        session_down(s);
                    }
                    if (sent_off < segs) {
                        s->dropped += (unsigned long long)frames;
                        if (now - s->last_drop_warn >= 1000) {
                            fprintf(stderr, LOG_W "отправка не прошла (%s): %d из %d сегментов "
                                                  "записи\n", strerror(errno), segs - sent_off, segs);
                            s->last_drop_warn = now;
                        }
                    } else {
                        s->up_pkts += (unsigned long long)frames;
                        s->up_bytes += payload;
                    }
                }
            }
            if (s->up && xs_retire_due(xs_conn_rel_next(&s->conn), now - s->conn.born)) {
                fprintf(stderr, LOG_I "смена ключей: поднимаю соединение заново\n");
                session_down(s);
            }
        }

        /* ---- обратно: поддельный TCP → TUN --------------------------------- */
        if (s->up && n > 0 && (fds[1].revents & POLLIN)) {
            for (;;) {
                for (int i = 0; i < XSC_BATCH; i++) {
                    s->iov[i].iov_base = s->rx_buf[i];
                    s->iov[i].iov_len = XS_ROW;
                    memset(&s->mm[i].msg_hdr, 0, sizeof(s->mm[i].msg_hdr));
                    s->mm[i].msg_hdr.msg_iov = &s->iov[i];
                    s->mm[i].msg_hdr.msg_iovlen = 1;
                }
                int got = recvmmsg(s->conn.fd, s->mm, XSC_BATCH, MSG_DONTWAIT, NULL);
                if (got <= 0) break;
                for (int i = 0; i < got; i++) {
                    struct obfs_seg seg;
                    if (obfs_parse(s->rx_buf[i], s->mm[i].msg_len, &seg) != 0) continue;
                    if (seg.sport != s->conn.dport || seg.dport != s->conn.sport) continue;
                    int what = xs_conn_on_seg(&s->conn, &seg, now);
                    if (what < 0) { session_down(s); break; }
                    if (what != 1) continue;
                    /* Сборка записи, которая могла быть разрезана между сегментами. Она же
                     * предфильтр: сегмент, не начинающийся с заголовка записи и не продолжающий
                     * начатую, отбрасывается до всякой криптографии. */
                    const uint8_t *body, *hdr;
                    size_t body_n;
                    uint32_t rel;
                    if (!xs_reasm_feed(&s->reasm, seg.seq, s->conn.isn_rx, seg.payload, seg.plen,
                                       &body, &body_n, &hdr, &rel))
                        continue;
                    if (xs_win_check(&s->win, rel) != 0) continue;
                    uint8_t *ct = (uint8_t *)(uintptr_t)body;
                    /* AAD — заголовок записи, и у разрезанной это байты ПЕРВОГО сегмента: возьми мы
                     * его из последнего, тег не сошёлся бы при верной криптографии. */
                    if (tls13_aead_open(&s->rx, rel, hdr, XS_REC_HDR, ct, body_n) != 0)
                        continue;
                    /* Коммит окна ТОЛЬКО после сошедшегося тега: иначе подделанный пакет с
                     * далёким смещением выбил бы из окна весь честный поток. */
                    xs_win_commit(&s->win, rel);
                    size_t pn = body_n - XS_TAG;
                    struct spoke_fctx fc = { s, dev, now };
                    if (pn && ct[0] == XS_CTL_BATCH) {
                        if (xs_batch_iter(ct, pn, spoke_frame_cb, &fc) != 0) s->dropped++;
                    } else {
                        spoke_frame(s, ct, pn, dev, now);
                    }
                    tun_gro_flush(&s->tun, &s->gro);   /* см. пояснение выше */
                    /* keepalive молча учтён: он уже обновил last_rx. */
                }
                if (got < XSC_BATCH) break;
            }
        }

        if (!s->up) continue;

        /* ---- согласование MTU: проверка пути пробами ------------------------
         *
         * Пока проба не подтвердила размер, на устройстве стоит безопасный низ: до этого
         * момента любой полноразмерный пакет рискует уйти в чёрную дыру, которую мы и ищем.
         * Порядок «сначала опустить, потом поднимать» взят у veil (engine/pmtu.go) — там это
         * уже проходили, и обратный порядок стоил им как раз тех потерь. */
        if (s->probing) {
            if (!s->probe_sent || now - s->probe_sent >= XS_PROBE_WAIT_MS) {
                if (s->probe_sent && ++s->p_tries >= XS_PROBE_TRIES) {
                    /* Не подтвердился после повторов — считаем размер непроходящим. Повторы
                     * обязательны: у пробы нет повторной передачи, и одна случайная потеря не
                     * должна означать «путь этого не несёт». */
                    s->p_hi = s->p_cur;
                    s->p_tries = 0;
                    if (s->p_verify) {
                        /* Прежнее значение больше не проходит. Опускаемся НЕМЕДЛЕННО, не
                         * дожидаясь конца поиска: пока он идёт, каждый полный пакет пропадал
                         * бы. Дальше поиск сам поднимет до нового настоящего предела. */
                        s->p_verify = 0;
                        fprintf(stderr, LOG_W "путь больше не несёт %d — опускаюсь на %d и "
                                              "ищу новый предел\n", s->p_cur, XS_MTU_FLOOR);
                        mtu_apply(s, dev, XS_MTU_FLOOR, "путь сузился, ищу новый предел");
                    }
                    s->p_cur = xs_mtu_next(s->p_lo, s->p_hi, s->mtu_agreed);
                    if (!s->p_cur || ++s->p_steps > XS_MTU_TRIES_MAX) {
                        probe_done(s, dev, now);
                        continue;
                    }
                }
                static uint8_t probe[XS_ROW];
                if (xs_probe_build(probe, sizeof(probe), s->p_cur) == s->p_cur)
                    send_frame(s, probe, (size_t)s->p_cur, now);
                s->probe_sent = now;
            }
        } else if (s->probe_next && now >= s->probe_next) {
            /* Повторная проверка под живой сессией: путь меняется (смена маршрута у
             * провайдера, переход между точками WiFi), и без этого суженный путь глотал бы
             * полноразмерные кадры до конца сессии. */
            probe_start(s, now);
        }
        /* Соединения кроме нулевого: подхватываем согласованный MTU и НАЗЫВАЕМ его хабу.
         * Назвать обязательно: у каждого соединения на хабе своя сессия, и подрезку MSS для
         * обратного трафика хаб делает по MTU ТОЙ сессии, в которую отправляет. Не сказав, мы
         * получили бы «через одно соединение большие пакеты ходят, через другое нет». */
        if (s->conn_id) {
            if (g_mtu_now > 0 && s->mtu != g_mtu_now) s->mtu = g_mtu_now;
            if (g_mtu_pub > 0 && s->mtu_told != g_mtu_pub) {
                uint8_t fin[8];
                size_t fn = xs_mtu_build(fin, sizeof(fin), g_mtu_pub);
                if (fn && send_frame(s, fin, fn, now) == 0) s->mtu_told = g_mtu_pub;
            }
        }
        /* «Активная отправка» — это «мы отправили ПОСЛЕ того, как получили», а не «мы вообще
         * когда-нибудь отправляли». Разница принципиальна: со вторым условием туннель на
         * покое, однажды отправивший пакет, считался бы мёртвым навсегда. */
        if (xs_conn_tick(&s->conn, now, s->conn.last_tx > s->conn.last_rx)) {
            fprintf(stderr, LOG_W "путь молчит %d мс при активной отправке — поднимаю "
                                  "соединение заново\n", XSC_DEAD_MS);
            session_down(s);
            continue;
        }
        /* Обратная связь по сборке: если у НАС не собираются записи, сказать об этом обязаны мы —
         * уменьшить пачку может только та сторона. Молча терпеть значило бы, что на рваном пути
         * пачки делают хуже, а не лучше, и никто об этом не узнает. */
        if (s->reasm.dropped > s->last_drops && now - s->last_report >= XSC_REASM_REPORT_MS) {
            uint8_t lf[8];
            size_t ln = xs_loss_build(lf, sizeof(lf), (int)(s->reasm.dropped - s->last_drops));
            if (ln && send_frame(s, lf, ln, now) == 0) {
                s->last_drops = s->reasm.dropped;
                s->last_report = now;
            }
        }
        /* Рост пачки на чистом пути: медленно вверх, мгновенно вниз (см. spoke_frame). */
        if (!getenv("STEER_XS_COMPAT") && now >= s->cool_until &&
            now - s->last_grow >= XSC_REASM_GROW_MS && s->batch_max < XS_BATCH_FRAMES_MAX) {
            s->batch_max *= 2;
            if (s->batch_max > XS_BATCH_FRAMES_MAX) s->batch_max = XS_BATCH_FRAMES_MAX;
            s->last_grow = now;
        }

        /* Keepalive: пустая запись. Пир за NAT обязана поддерживать отображение живым,
         * потому что дозвониться до неё хаб не может.
         *
         * ИНТЕРВАЛ С РАЗБРОСОМ, а не ровный: пакет одного и того же размера ровно каждые
         * keepalive секунд не встречается ни в одном браузерном соединении и находится подсчётом
         * пауз между мелкими пакетами. Разброс ±20% не стоит ничего. */
        if (keepalive_ms && !s->keep_next) s->keep_next = keepalive_ms;
        if (keepalive_ms && now - s->conn.last_tx >= s->keep_next) {
            uint32_t rel = xs_conn_rel_next(&s->conn);
            uint8_t *rec = s->txb + XS_HDR_ROOM - XS_REC_HDR;
            if (xs_rec_build(rec, XS_TAG) == 0 &&
                tls13_aead_seal(&s->tx, rel, rec, XS_REC_HDR, s->txb + XS_HDR_ROOM, 0,
                                s->txb + XS_HDR_ROOM) == 0) {
                size_t seglen = 0;
                uint8_t *seg = xs_conn_ahead(&s->conn, s->txb, XS_REC_HDR + XS_TAG, &seglen, now);
                (void)!send(s->conn.fd, seg, seglen, MSG_NOSIGNAL);
            }
            uint32_t j = 0;
            xc_random((unsigned char *)&j, sizeof(j));
            s->keep_next = keepalive_ms * 8 / 10 + (long long)(j % (uint32_t)(keepalive_ms * 4 / 10 + 1));
        }
        if (!s->conn_id && now - last_state >= 2000) { state_write(s); last_state = now; }
    }
    session_down(s);
    if (!s->conn_id) xs_conf_wipe(s->sec);
    return (void *)1;
}

/* ---- пиры и ключи ----------------------------------------------------------- */

int cmd_xsteer_peers(const char *spec_path, const char *out_name, const char *conf_path) {
    load_spec(spec_path);
    struct output *o = out_by_name(out_name);
    if (!o) die("нет такого выхода: %s", out_name);
    if (o->kind != OUT_XSTEER) die("выход %s не kind=xsteer", out_name);
    struct xs_conf c;
    struct xs_secrets sec;
    char err[256];
    const char *path = conf_path ? conf_path : o->xs_conf;
    if (xs_conf_load(path, XS_ROLE_SPOKE, &c, &sec, err, sizeof(err)) != 0) {
        fprintf(stderr, LOG_W "%s\n", err);
        return 2;
    }
    /* Секреты не нужны для печати и потому затираются СРАЗУ, до вывода: так «в выводе нет
     * приватного ключа» становится свойством порядка операций, а не обещанием. */
    xs_conf_wipe(&sec);
    xs_conf_json(stdout, &c);
    printf("\n");
    /* Живое состояние лежит рядом, в файле, который пишет сам процесс. Печатаем его как есть
     * — разбирать нечего, а склеивать два JSON в один значило бы завести формат, который
     * придётся согласовывать с интерфейсом отдельно. */
    char sp[320];
    snprintf(sp, sizeof(sp), "%s/xsteer-%.40s.json", g_state_dir, o->name);
    FILE *f = fopen(sp, "r");
    if (!f) return 1;              /* состояния нет: рукопожатий не было */
    char line[1024];
    if (fgets(line, sizeof(line), f)) fputs(line, stdout);
    fclose(f);
    return 0;
}
