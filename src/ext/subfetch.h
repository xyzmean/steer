/* Скачивание и обработка подписки. Зачем это в движке — в subfetch.c. */
#ifndef STEER_SUBFETCH_H
#define STEER_SUBFETCH_H

/* Скачать подписку и разобрать всё, что панель сказала о ней и об устройстве.
 *
 * out_path — куда лечь файлу узлов; info_path — куда лечь остатку трафика (NULL — вывести
 * из out_path тем же правилом, каким его выводит splify2: «.txt» → «.userinfo»).
 *
 * Печатает JSON и возвращает 0, когда файл на месте. Ненулевой код — подписка не
 * скачалась; прежний файл при этом не тронут. */
int cmd_sub_fetch(const char *url, const char *out_path, const char *info_path);

/* Спросить у панели ОДИН остаток трафика, не подменяя подписку.
 *
 * Отдельно от sub-fetch по цене: обзор спрашивает остаток при открытии, а скачивать ради
 * двух чисел десятки килобайт узлов незачем — там, где есть curl, хватает HEAD. Печатает
 * JSON, код возврата 0 всегда, когда спросить было чем: «панель молчит» — это не отказ. */
int cmd_sub_quota(const char *url, const char *info_path);

/* Идентификатор устройства для панели подписки, JSON. Ничего не скачивает и никуда не
 * ходит: человек заводит роутер в панели заранее, и найти там свою коробку он может только
 * по этой строке. */
int cmd_sub_hwid(void);

#endif
