/* PH_PROXY — не наша сессия вовсе: её байты переливаются настоящему серверу и обратно
 * (см. Decoy ниже). Ключей у неё нет и никогда не будет, поэтому ни один путь данных пиров её
 * не касается: send_to отправляет только в PH_EST, а привязка пир→сессия ей не выдаётся. */
enum sess_phase { PH_FREE, PH_SYN, PH_HS, PH_EST, PH_PROXY };

struct sess {
    struct xs_conn conn;
    struct xs_hs hs;
    struct tls13_keys tx, rx;
    struct xs_win win;
    int      phase;
    /* Накопленные байты ClientHello: он приходит НЕСКОЛЬКИМИ сегментами, потому что браузерный
     * Hello больше сегмента (около 1760 байт из-за постквантового ключа), и наш такой же. Предел
     * обязателен: сюда пишет кто угодно из интернета, и «копим, пока не разберётся» без предела —
     * это способ съесть память хаба чужими байтами. */
    uint8_t  hs_buf[4096];
    size_t   hs_len;
    /* Сборка разрезанных записей и обратная связь по ней (см. xswire.h). */
    struct xs_reasm reasm;
    unsigned long long last_drops;
    /* ТРИ ПОЛЯ НИЖЕ ЧИТАЕТ ЧУЖОЙ ПОТОК, и это свойство пути данных, а не оплошность.
     *
     * batch_max, cool_until и mtu пишет ВЛАДЕЛЕЦ сессии (тот воркер, чей осколок сырого сокета
     * ловит её пира), а читает цикл TUN ЛЮБОГО воркера: получатель пакета из ядра определяется
     * маршрутом, а не тем, кто читает устройство. Замок сессии здесь взять нельзя дёшево —
     * цикл TUN читает предел пачки и MTU получателя ДО того, как узнал получателя записи, то
     * есть держал бы чужой замок отправки поперёк чтения устройства, — а перенастройка MTU
     * (hub_retune_mtu) обходит ВСЕ сессии под общим замком, и замок каждой под ним завёл бы
     * второй порядок замков там, где хватает одного слова.
     *
     * Поэтому обращения к ним идут через XSH_LOAD/XSH_STORE. На arm64 и amd64 слово машинного
     * размера не порвётся и без этого, но модель памяти такого не обещает, а «новый MTU
     * применился к половине пакетов пачки» здесь возможно. Порт правки из реализации на Go
     * (I-093), где то же место помечал детектор гонок. */
    int      batch_max;
    long long cool_until;
    long long last_report, last_grow, keep_next;
    int16_t  peer;                 /* индекс пира или -1, пока не опознан */
    int8_t   conn_id;              /* номер соединения этой пира (0..XS_CONNS_MAX-1) */
    /* MTU, о котором договорились с этой пиром. Ноль — ещё не договорились. Хранится на
     * СЕССИЮ, а не на хаб: у разных пиров разные пути, и общее значение означало бы, что
     * худший путь ограничивает всех. */
    int      mtu;
    long long handshake_at;
    /* last_auth — когда по сессии последний раз пришёл ПОДТВЕРЖДЁННЫЙ кадр: запись, у которой
     * сошёлся тег AEAD.
     *
     * ЗАЧЕМ ОТДЕЛЬНО ОТ conn.last_rx. Время последнего приёма в соединении обновляет КАЖДЫЙ
     * принятый сегмент, включая посторонний и нерасшифрованный, — а на публичный порт хаба сыплется
     * сканерный шум. Значит по conn.last_rx сессия, в которую больше не пишет её пир, может
     * считаться живой сколько угодно долго: достаточно, чтобы кто-то посылал в её четвёрку мусор.
     * Слот в наборе соединений пира она при этом занимает, то есть часть его трафика уезжает в
     * никуда. Все решения о живости — уборка, вытеснение при полной таблице, переезд пира на новую
     * точку — обязаны считаться по трафику, доказанному ключом.
     *
     * ЧИТАЕТ ЧУЖОЙ ПОТОК, как batch_max и mtu рядом: переезд пира сверяется по этому полю из того
     * воркера, у которого пир только что поднялся, а сессия принадлежит другому (у пира каждый порт
     * источника достаётся своему воркеру фильтром в ядре). Отсюда XSH_LOAD/XSH_STORE.
     *
     * roam_check — «пир поднялся заново, проверь, ведёт ли ты ещё куда-нибудь». Ставит чужой
     * воркер, разбирается владелец (см. sess_roam_start и обслуживание). Остальные три поля —
     * счётчики пробы, только владельца. */
    long long last_auth;
    long long roam_check;
    int      roam_sent;
    long long roam_next, roam_first;
    unsigned long long up_pkts, down_pkts;
    /* ---- дорожка неопознанного (Decoy = proxy) ------------------------------
     * up_fd    — НАСТОЯЩЕЕ соединение к сайту-прикрытию; -1, если его нет. Неблокирующее и
     *            живёт в том же poll, что сырой сокет и очередь TUN: блокирующего вызова в
     *            цикле воркера нет ни одного, и появиться он здесь не должен тем более —
     *            прикрытие может не ответить вовсе.
     * up_ready — connect завершился И присланное прибором уже отдано прикрытию целиком.
     * up_sent  — сколько байт присланного уже ушло: сокет неблокирующий, значит запись бывает
     *            частичной, и остаток дописывается по следующему POLLOUT.
     * up_at    — последнее движение на дорожке: по нему считаются оба срока выше.
     * up_addr  — К КОМУ ИМЕННО открыто это соединение, в сетевом порядке. Хранится, потому что
     *            прикрытие теперь выбирается именем из SNI (см. decoy_dest_for) и постоянным
     *            DecoyDest уже не описывается: строка журнала, называющая не тот адрес, хуже
     *            отсутствующей. */
    int      up_fd;
    int      up_ready;
    size_t   up_sent;
    long long up_at;
    uint32_t up_addr;
};

/* Расслабленные обращения к полям, которые читает чужой поток: см. шапку struct sess. Порядок
 * между ними не нужен — каждое значение самостоятельно и стоит само за себя. */
#define XSH_LOAD(p)     __atomic_load_n(&(p), __ATOMIC_RELAXED)
#define XSH_STORE(p, v) __atomic_store_n(&(p), (v), __ATOMIC_RELAXED)

