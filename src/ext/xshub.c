/* Сессий вчетверо больше, чем пиров: запас на переподключение пира без разрыва И на
 * неравномерность раскладки по воркерам (порты хэшируются, и одному воркеру может достаться
 * вдвое больше пиров, чем в среднем). */
#define XSH_MAX_SESS (XS_PEERS_MAX * 4)
/* Предел числа воркеров — ЧЕТЫРЕ, и это не «на всякий случай», а результат замера.
 *
 * Цена воркера лежит в ядре: приём идёт сырым сокетом, и ядро на каждый локально доставляемый
 * TCP-пакет КЛОНИРУЕТ skb для КАЖДОГО такого сокета, а фильтр отбрасывает лишние уже потом.
 * То есть при восьми воркерах каждый наш же туннельный пакет клонируется восемь раз, семь
 * клонов выбрасывается, и эта работа растёт линейно, тогда как выигрыш от ядер насыщается.
 * Замер (tests/run-xsteer.sh, два пира, сумма): 1 воркер — 0,67 Гбит/с, 2 — 1,20, 4 — 1,11,
 * 8 — 0,97.
 *
 * ЧТО НУЖНО, ЧТОБЫ РАСТИ ДАЛЬШЕ. Убрать умножение клонов, а для этого — приём не сырым
 * сокетом, а AF_PACKET с PACKET_FANOUT: там ядро отдаёт пакет РОВНО ОДНОМУ сокету группы,
 * выбирая его хэшем потока, то есть сессия по-прежнему принадлежит одному воркеру, но клон
 * один. Это отдельная работа: у AF_PACKET другой приёмный путь (нужно отсекать исходящие
 * пакеты по PKTTYPE и учитывать, что он видит трафик до firewall). */
#define XSH_WORKERS_MAX 4
#define XSH_IDLE_MS  180000
/* Хаб присылает пустую запись, если получал данные, но сам давно ничего не отправлял.
 *
 * Обязательно, а не «полезно»: пир считает путь мёртвым по тишине при активной отправке, и
 * без этого односторонний трафик (она отправляет, отвечать нечем) выглядел бы для неё
 * обрывом. Ровно это и показал живой стенд. Так же устроен WireGuard: keepalive посылает
 * ПРИНИМАЮЩАЯ сторона, и по той же причине. Десять секунд — его же интервал. */
#define XSH_KEEPALIVE_MS 10000
/* ---- когда живую сессию МОЖНО вытеснить (R-067, I-082) -----------------------
 *
 * Шесть периодов keepalive хаба — минута молчания. Число выведено из сроков, которые уже есть,
 * а не выбрано на глаз, и обязано лежать между двумя из них:
 *
 *   СНИЗУ его держит XSC_DEAD_MS (45 с) — срок, по которому пир САМА считает путь мёртвым и
 *     начинает соединяться заново. Сессия, молчавшая дольше него, уже не несёт трафика ни для
 *     кого: пир либо ушла, либо строит на её месте новую. Ниже этого порога вытеснение забирало
 *     бы работающий туннель у живого пира, а по нашу сторону хаб присылает keepalive каждые
 *     10 с и получает от пира её собственный (умолчание PersistentKeepalive — 25 с), то есть
 *     минута тишины не наступает у здоровой сессии никогда.
 *   СВЕРХУ — XSH_IDLE_MS (180 с), по которому сессию убирает обслуживание само. Порог обязан
 *     наступать ЗАМЕТНО раньше, иначе правило не меняет ничего: место освободилось бы и без
 *     него. Втрое раньше — это две минуты, в которые вытеснение работает.
 *
 * ЦЕНА НАЗЫВАЕТСЯ ВСЛУХ: пока таблица воркера полна ЖИВЫМИ и молодыми сессиями, новый пир в
 * приёме получит отказ — до тех пор, пока какая-нибудь из них не замолчит на минуту. Прежде
 * такого отказа не было вовсе, потому что новый брал место у самой давно молчавшей независимо
 * от того, жива она или нет (I-082); цена этого — поток поддельных SYN с меняющихся портов
 * выбивал из таблицы рукопожавшиеся туннели. Отказ виден в журнале, потеря туннеля — нет.
 *
 * ЧИСЛО ОБЩЕЕ С РЕАЛИЗАЦИЕЙ НА GO, и это требование, а не совпадение: сроки там те же (10 с
 * keepalive, 45 с мёртвого пути, 180 с уборки по простою), значит и порог обязан быть тем же —
 * иначе одна и та же звезда вела бы себя по-разному в зависимости от того, на чём поднят хаб, и
 * выяснилось бы это только под потоком SYN. Сравнение СТРОГОЕ (молчит дольше порога), тоже как
 * там. Неподтверждённые вытесняются без всякого срока — их приоритет и есть защита от потока
 * SYN, и он этим правилом не тронут. */
#define XSH_EVICT_QUIET_MS (XSH_KEEPALIVE_MS * 6)
/* ---- переезд пира на новую точку -------------------------------------------
 *
 * XSH_ROAM_PROBE_MS и XSH_ROAM_PROBES: проба «жив ли ещё этот путь» — три пустые записи через
 * 150 мс, то есть решение принимается за 450 мс.
 *
 * ЗАЧЕМ ОНА ВООБЩЕ. Пир, поднявшийся заново, приходит с НОВЫХ портов источника (порт выбирается
 * случайно на каждое подключение), поэтому свои слоты в наборе соединений он вытесняет сам. А
 * осиротевшими остаются те, которые он больше НЕ занимает — стало меньше ядер, другая настройка,
 * другая сборка. Получателя хаб выбирает хешем потока среди живых слотов, значит мёртвый слот — это
 * не задержка, а потеря ДОЛИ ПОТОКОВ ЦЕЛИКОМ, и жил он до XSH_IDLE_MS, то есть три минуты.
 *
 * ПОЧЕМУ ПРОБА, А НЕ ПРОСТО СНЯТЬ. Снять по признаку «пир поднялся заново» значило бы рвать все
 * остальные его соединения на каждом переподключении одного. Верить же тишине нельзя в другую
 * сторону: живая сессия на покое молчит до периода keepalive пира, то есть до двадцати пяти секунд,
 * — и ровно столько трафик уезжал бы в точку, которой нет. Проба снимает обе ошибки: стоит трёх
 * пустых записей и заканчивается за полсекунды.
 *
 * Те же числа стоят в реализации на Go (hub: roamProbeMS, roamProbes). */
#define XSH_ROAM_PROBE_MS 150
#define XSH_ROAM_PROBES   3
/* ---- защита от активного зондирования (Decoy, R-062) ------------------------
 *
 * Числа взяты у реализации на Go (hub/decoy.go), где эта дорожка уже прошла стенд настоящим
 * openssl s_client, и каждое из них про свою цену:
 *
 * XSH_DECOY_MAX — сколько неопознанных проксируется ОДНОВРЕМЕННО на весь хаб. Предел
 *   обязателен: каждое такое соединение — настоящий сокет к сайту-прикрытию, и без предела
 *   поток зондирования превращался бы в нашу же атаку на прикрытие и на собственные
 *   дескрипторы. Тридцать два — то же число, что в Go.
 * XSH_DECOY_CONN_MS — сколько ждём, пока прикрытие ответит на connect. Прибор всё это время
 *   не получает ничего; дольше пяти секунд молчать хуже, чем ответить оповещением, поэтому по
 *   истечении срока дорожка сдаётся и отвечает как прежде.
 * XSH_DECOY_IDLE_MS — сколько живёт дорожка без единого байта. Тридцать секунд: сессии
 *   зондирования не нужен предел простоя хаба (три минуты), а держать сокет к прикрытию
 *   дольше — значит платить за прибор, который уже ушёл.
 * XSH_DECOY_CHUNK — сколько байт ответа прикрытия уезжает одним поддельным сегментом. Меньше
 *   MSS по построению: у нас датаграммная семантика, и сегмент больше MSS просто не дойдёт. */
#define XSH_DECOY_MAX     32
#define XSH_DECOY_CONN_MS 5000
#define XSH_DECOY_IDLE_MS 30000
#define XSH_DECOY_CHUNK   1200

/* Обратная связь по сборке разрезанных записей — те же числа, что у пира, и по тем же причинам. */
#define XSH_REASM_COOL_MS   10000
#define XSH_REASM_REPORT_MS 2000
#define XSH_REASM_GROW_MS   3000

/* ---- потолок MTU ------------------------------------------------------------
 *
 * XSH_MTU_CEIL — потолок СОГЛАСОВАННОГО MTU, один и тот же для числа из провода
 * (XS_CTL_MTU от пира), для числа из конфигурации и для предела, который хаб называет в
 * рукопожатии. Пропускать его нельзя ни на одном из трёх входов: конфигурация принимает MTU
 * до XS_LINK_MAX (xsconf.c, «576..1500»), а на проводе и в рукопожатии число вообще чужое.
 *
 * Числа выведены одно из другого и спорят при КОМПИЛЯЦИИ — то же правило, что у размеров в
 * шапке xswire.h. XSH_MAX_SEG_CEIL это то же выражение, которое считает send_to (mtu плюс
 * наши накладные минус заголовки IP и TCP), но при предельном MTU; вместе с заголовками IP и
 * TCP оно обязано давать РОВНО кадр канала. Пока потолка не было, хаб с MTU канала вместо MTU
 * туннеля в файле (обычная описка: оба числа называются «MTU») и пир, назвавший столько же,
 * давали сегмент 1521 и пакет на проводе 1561 байт — а дальше либо ядро фрагментировало его
 * (фрагментация сама по себе признак протокола, и такие пакеты режут по пути), либо sendmmsg
 * отвечал EMSGSIZE, и к этому пиру не уходило ни одного крупного кадра. Мелкое ходит, крупное
 * молча пропадает — тот же худший класс отказов, что и при MTU ниже пола. */
#define XSH_MTU_CEIL     XS_MTU_DEF
#define XSH_MAX_SEG_CEIL (XSH_MTU_CEIL + XS_OVERHEAD - 40)
XS_STATIC_ASSERT(XS_IP_HDR + XS_TCP_HDR + XSH_MAX_SEG_CEIL == XS_LINK_MAX, hub_seg_fits);

