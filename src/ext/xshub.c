static int g_workers = 1;
/* Аварийный выключатель нового формата: см. пояснение у batch_max в hs_confirm. Читается один раз
 * при старте, а не на каждом пакете. */
static int g_compat;

static struct sess *sess_find(struct worker *w, uint32_t addr, uint16_t port) {
    int i = xs_sidx_find(&w->idx, addr, port);
    return i < 0 ? NULL : &g_sess[i];
}

static void sess_free(struct worker *w, struct sess *s) {
    if (s->phase == PH_FREE) return;
    uint32_t addr = ntohl(s->conn.daddr);
    /* Замок берётся ДО обнуления: в этот самый миг другой воркер может быть внутри отправки в
     * эту сессию (пир↔пир или пакет из TUN), и обнулить ключи у него под руками значило бы
     * шифровать мусором или упасть. Проверку «сессия ещё жива» отправка делает уже под этим же
     * замком, поэтому после освобождения она просто ничего не отправит. */
    pthread_mutex_lock(&g_tx_lock[s - g_sess]);
    xs_sidx_remove(&w->idx, addr, s->conn.dport);
    if (s->peer >= 0) {
        pthread_mutex_lock(&g_ctl);
        for (int c = 0; c < XS_CONNS_MAX; c++)
            if (g_peer_sess[s->peer][c] == (int16_t)(s - g_sess)) g_peer_sess[s->peer][c] = -1;
        pthread_mutex_unlock(&g_ctl);
    }
    tls13_keys_free(&s->tx);
    tls13_keys_free(&s->rx);
    xs_hs_wipe(&s->hs);
    /* Соединение с прикрытием закрывается ЗДЕСЬ, а не в отдельной уборке: сессию освобождают
     * шесть разных путей, и «закрою сокет там, где освобождаю» означало бы утечку дескрипторов
     * на том из них, о котором забудут. Счётчик одновременно проксируемых уменьшается тем же
     * действием, поэтому разойтись с числом живых сокетов ему нечем. */
    if (s->up_fd >= 0) {
        close(s->up_fd);
        s->up_fd = -1;
        pthread_mutex_lock(&g_ctl);
        if (g_decoy_live > 0) g_decoy_live--;
        pthread_mutex_unlock(&g_ctl);
    }
    xs_conn_close(&s->conn);
    memset(s, 0, sizeof(*s));
    s->peer = -1;
    s->conn_id = -1;
    s->conn.fd = -1;
    s->up_fd = -1;
    pthread_mutex_unlock(&g_tx_lock[s - g_sess]);
}

/* sess_roam_start — пир поднялся заново: остальным его соединениям ставится метка «проверься».
 *
 * ПРОВЕРЯЮТСЯ ВСЕ, А НЕ ТОЛЬКО ТЕ, ЧТО НА ДРУГОМ АДРЕСЕ. Сравнивать адреса бесполезно: вернувшийся
 * пир нередко приходит с ТОГО ЖЕ адреса и лишь с новых портов (перезапуск службы, выход из сна,
 * смена настройки), и тогда осиротевшие слоты по адресу не отличить ничем. Первая версия этой
 * правки в реализации на Go сравнивала адреса и пропускала самый частый случай целиком.
 *
 * Разбирается с меткой ВЛАДЕЛЕЦ каждой сессии, в своём обслуживании: она лежит в его индексе, а не
 * в нашем. Мы только ставим метку — снимать сессию из чужой таблицы отсюда было бы гонкой в самом
 * неудачном месте. Замок g_ctl уже взят вызывающим: набор g_peer_sess под ним и читается.
 *
 * Свежий подтверждённый трафик — доказательство живости, проверять нечего; заодно это защищает
 * соседние соединения, поднявшиеся в том же залпе. */
static void sess_roam_start(int peer, int self_idx, long long now) {
    if (peer < 0) return;
    for (int c = 0; c < XS_CONNS_MAX; c++) {
        int16_t idx = g_peer_sess[peer][c];
        if (idx < 0 || idx == (int16_t)self_idx) continue;
        struct sess *o = &g_sess[idx];
        if (now - XSH_LOAD(o->last_auth) < XSH_ROAM_PROBE_MS) continue;
        if (XSH_LOAD(o->roam_check) == 0) XSH_STORE(o->roam_check, now);
    }
}

/* sess_quiet_since — с какого момента сессия молчит.
 *
 * Для ПОДТВЕРЖДЁННОЙ считается по последнему кадру, у которого сошёлся тег (last_auth); для
 * остальных — по последнему принятому сегменту, потому что подтверждённого трафика у них ещё не
 * было по построению. Зачем именно так — в объяснении к полю last_auth.
 *
 * Разница не теоретическая: пока простой считался по conn.last_rx, сессию, в которую пир давно не
 * пишет, держал живой любой сканерный шум в её четвёрку — а слот в наборе соединений пира она при
 * этом занимала, то есть часть его трафика уезжала в никуда. */
static long long sess_quiet_since(const struct sess *s) {
    if (s->phase == PH_EST) {
        long long t = XSH_LOAD(s->last_auth);
        if (t) return t;
    }
    return s->conn.last_rx;
}

/* Кого забрать при полной таблице — и забирать ли вообще.
 *
 * Вынесено из sess_alloc ради стенда: сама sess_alloc открывает сырой сокет (то есть требует
 * прав root и настоящей сети), а решается здесь ровно одно — политика вытеснения, и проверять
 * её надо на двух структурах в памяти, а не на живом хабе под потоком SYN.
 *
 * НЕПОДТВЕРЖДЁННАЯ УХОДИТ ПЕРВОЙ, и это не тонкость. Сессия создаётся на первом же поддельном
 * SYN, то есть кем угодно и без всякой проверки; забирай мы просто «самую давно молчавшую»,
 * поток SYN с меняющихся портов выбил бы из таблицы живые рукопожавшиеся туннели — отказ в
 * обслуживании ценой в один цикл на постороннем хосте.
 *
 * ПОДТВЕРЖДЁННУЮ ЗАБИРАЕМ, ТОЛЬКО ЕСЛИ ОНА ПОЧТИ МЕРТВА — молчит дольше XSH_EVICT_QUIET_MS
 * (см. там же, почему именно этот срок и чем за него плачено). Прежде комментарий обещал, что
 * подтверждённую может забрать только другая подтверждённая, а код отдавал самую давно
 * молчавшую живую по НЕАУТЕНТИФИЦИРОВАННОМУ SYN (I-082) — то есть обещание было неверным. */
static struct sess *sess_evict_pick(struct worker *w, struct sess *oldest_raw,
                                    struct sess *oldest, long long now) {
    if (oldest_raw) return oldest_raw;
    if (oldest && now - sess_quiet_since(oldest) > XSH_EVICT_QUIET_MS) return oldest;
    /* Отказали. Сказать об этом обязательно: снаружи молчаливый отказ выглядит как «пир не
     * подключается», и причину — «таблица воркера полна живыми сессиями» — не видно ниоткуда.
     * Ограничитель обязателен по той же причине, что и у соседей: сюда добирается кто угодно из
     * интернета одним поддельным SYN, и без него одна такая строка заливает журнал VPS. Свой,
     * а не общий с соседями: общий на два события означает, что они глушат друг друга, а хвост
     * «и ещё N таких же» называет число, посчитанное по обоим (I-064). */
    w->d_full++;
    unsigned long long held = 0;
    if (xs_ratelog(&w->rl_full, now, XS_LOG_EVERY_MS, &held)) {
        char tail[64];
        fprintf(stderr, LOG_W "таблица сессий воркера %d полна работающими туннелями — новому "
                              "отказано; место освободится, когда какой-нибудь из них замолчит "
                              "дольше %d с%s\n",
                w->id, XSH_EVICT_QUIET_MS / 1000, xs_held_str(held, tail, sizeof(tail)));
    }
    return NULL;
}

static struct sess *sess_alloc(struct worker *w, const struct obfs_seg *seg, int listen_port,
                               long long now) {
    struct sess *free_slot = NULL, *oldest = NULL, *oldest_raw = NULL;
    /* Только СВОЙ отрезок таблицы: сессия, созданная здесь, будет и приниматься здесь —
     * фильтр на сокете это гарантирует, — а лазить в чужой отрезок значило бы делить таблицу
     * между потоками и брать замок на каждый пакет. */
    for (int i = w->base; i < w->base + w->cap; i++) {
        if (g_sess[i].phase == PH_FREE) { free_slot = &g_sess[i]; break; }
        if (!oldest || sess_quiet_since(&g_sess[i]) < sess_quiet_since(oldest))
            oldest = &g_sess[i];
        /* Отдельно — самая давняя из НЕ дошедших до подтверждения. */
        if (g_sess[i].phase != PH_EST &&
            (!oldest_raw || g_sess[i].conn.last_rx < oldest_raw->conn.last_rx))
            oldest_raw = &g_sess[i];
    }
    /* Свободного нет — решаем, вытеснять ли (политика и её цена — в sess_evict_pick). */
    if (!free_slot) {
        struct sess *victim = sess_evict_pick(w, oldest_raw, oldest, now);
        if (!victim) return NULL;
        sess_free(w, victim);
        free_slot = victim;
    }
    struct sess *s = free_slot;
    memset(s, 0, sizeof(*s));
    s->peer = -1;
    s->conn_id = -1;
    s->up_fd = -1;                  /* ноль — это stdin: дескриптор обязан быть назван явно */
    /* Свой сырой сокет на сессию, подключённый к её адресу: тогда ядро само демультиплексирует
     * отправку, и адрес не приходится указывать на каждый пакет. Тот же приём, что в obfs.c. */
    /* Отвечаем С ТОГО адреса, НА КОТОРЫЙ пир написал: см. obfs_raw_open_from. */
    s->conn.fd = obfs_raw_open_from(seg->saddr, seg->daddr, &s->conn.saddr);
    if (s->conn.fd < 0) { s->phase = PH_FREE; return NULL; }
    obfs_filter_none(s->conn.fd);       /* принимать этому сокету нечего */
    s->conn.daddr = seg->saddr;
    s->conn.sport = (uint16_t)listen_port;
    s->conn.dport = seg->sport;
    s->conn.isn_tx = seg->ack ? seg->ack : (uint32_t)xs_now_ms();
    s->conn.seq = s->conn.isn_tx;
    s->conn.isn_rx = seg->seq;
    s->conn.ack = seg->seq + 1;
    s->conn.born = s->conn.last_rx = s->conn.last_tx = now;
    s->conn.state = XSC_SYN_RCVD;
    s->phase = PH_SYN;
    if (xs_sidx_insert(&w->idx, ntohl(seg->saddr), seg->sport, (int)(s - g_sess)) != 0) {
        sess_free(w, s);
        return NULL;
    }
    return s;
}

/* Вызывается редко (раз на пробой пира) и из ЛЮБОГО воркера, поэтому целиком под общим
 * замком: он же защищает `applied`, иначе два воркера могли бы одновременно решить, что
 * значение сменилось, и дважды дёрнуть `ip link`. */
static void hub_retune_mtu(void) {
    pthread_mutex_lock(&g_ctl);
    int best = 0;
    for (int i = 0; i < XSH_MAX_SESS; i++)
        if (g_sess[i].phase == PH_EST) {
            int m = XSH_LOAD(g_sess[i].mtu);
            if (m > 0 && (!best || m < best)) best = m;
        }
    static int applied;
    if (!best || applied == best) { pthread_mutex_unlock(&g_ctl); return; }
    char val[8];
    snprintf(val, sizeof(val), "%d", best);
    const char *a[] = { "ip", "link", "set", "dev", g_dev, "mtu", val, NULL };
    if (run_quiet(a) == 0) {
        fprintf(stderr, LOG_I "MTU устройства: %d (минимум среди пиров)\n", best);
        applied = best;
    }
    pthread_mutex_unlock(&g_ctl);
}

/* Поднять устройство хаба: адрес, MTU, `up` и маршруты к сетям пиров.
 *
 * ОТДЕЛЬНОЙ ФУНКЦИЕЙ — не ради красоты. Раньше эти команды стояли внутри xs_hub_run, а он
 * целиком построен на I/O (сырой сокет, очереди TUN, потоки), то есть проверить решение
 * «назвать отказ» стендом было нечем. Здесь оно проверяется: hubmatch подменяет run_quiet и
 * читает журнал.
 *
 * Отказы называются по одному, потому что цена у них разная, а следствие у всех трёх одно и
 * то же снаружи: «хаб слушает, трафика нет». Немых отказов на этом пути не остаётся — та же
 * правка, что уже сделана в движке для клиента туннеля (адрес, up, txqueuelen) и для
 * привязки таблицы выхода. */
static void hub_dev_up(const char *dev) {
    char addr[24], mtu[8];
    struct in_addr in;
    in.s_addr = htonl(g_conf.addr);
    snprintf(addr, sizeof(addr), "%s/%d", inet_ntoa(in), g_conf.addr_plen);
    snprintf(mtu, sizeof(mtu), "%d", g_conf.mtu ? g_conf.mtu : XS_MTU_DEF);
    const char *a1[] = { "ip", "addr", "replace", addr, "dev", dev, NULL };
    const char *a2[] = { "ip", "link", "set", "dev", dev, "mtu", mtu, "up", NULL };
    if (run_quiet(a1) != 0)
        fprintf(stderr, LOG_W "%s: адрес %s не встал — ядро сочтёт маршрут на это устройство "
                        "непригодным для локально порождённых пакетов\n", dev, addr);
    /* Одна команда на две настройки, поэтому и отказ один: он означает либо не принятый MTU,
     * либо не поднявшееся устройство, и различить их снаружи нечем. Названы оба, потому что
     * второе останавливает трафик целиком, а первое — только режет пакеты. */
    if (run_quiet(a2) != 0)
        fprintf(stderr, LOG_W "%s: устройство не поднялось или не принят MTU %s — хаб будет "
                        "слушать, а трафик наружу не пойдёт\n", dev, mtu);
    /* Маршруты к сетям пиров: без них ядро не знает, что ответы им идут через это
     * устройство, и выход в интернет работал бы только в одну сторону. */
    for (size_t i = 0; i < g_conf.peer_n; i++)
        for (size_t a = 0; a < g_conf.peer[i].allowed_n; a++) {
            if (!g_conf.peer[i].allowed[a].plen) continue;   /* 0.0.0.0/0 — не наш маршрут */
            char pfx[24];
            in.s_addr = htonl(g_conf.peer[i].allowed[a].net);
            snprintf(pfx, sizeof(pfx), "%s/%d", inet_ntoa(in),
                     g_conf.peer[i].allowed[a].plen);
            const char *r[] = { "ip", "route", "replace", pfx, "dev", dev, NULL };
            /* Названа СЕТЬ, а не только факт: пиров может быть много, и «маршрут не встал»
             * без адреса не говорит, у кого именно связь окажется односторонней. */
            if (run_quiet(r) != 0)
                fprintf(stderr, LOG_W "%s: маршрут к %s не встал — с этой сетью связь будет "
                                "в одну сторону\n", dev, pfx);
        }
}

/* Зашифровать пакет для сессии и отправить. Открытый текст лежит по row + XS_HDR_ROOM —
 * ровно там, где он оказался после расшифровки входящего, поэтому пересылка пир↔пир
 * обходится без единой копии.
 *
 * ПОД ЗАМКОМ ЦЕЛИКОМ, и это несущая конструкция, а не осторожность. Отправлять в одну сессию
 * может любой воркер: пакет пир↔пир пришёл одному, а уходит в сессию другого; пакет из TUN
 * попал в ту очередь, которую выбрало ядро по хэшу потока. Отправка выдаёт следующий
 * относительный номер — он же nonce AEAD, — и два потока, взявшие один номер, повторили бы
 * nonce. Повтор nonce означает не «пакет потерялся», а полную потерю стойкости шифра на этой
 * сессии, причём молча. Поэтому номер, шифрование и сама отправка — одна неделимая операция.
 *
 * Проверка phase == PH_EST стоит ПОСЛЕ взятия замка: пока мы ждали, владелец мог освободить
 * сессию (sess_free берёт тот же замок), и тогда отправлять уже некуда. */
static int send_to(struct worker *w, struct sess *d, uint8_t *row, size_t plen, long long now) {
    pthread_mutex_t *lk = &g_tx_lock[d - g_sess];
    pthread_mutex_lock(lk);
    if (d->phase != PH_EST) { pthread_mutex_unlock(lk); return -1; }
    uint32_t rel = xs_conn_rel_next(&d->conn);
    if (xs_retire_due(rel, now - d->conn.born)) { pthread_mutex_unlock(lk); return -1; }
    uint8_t *rec = row + XS_HDR_ROOM - XS_REC_HDR;
    int rc = -1;
    if (xs_rec_build(rec, plen + XS_TAG) == 0 &&
        tls13_aead_seal(&d->tx, rel, rec, XS_REC_HDR, row + XS_HDR_ROOM, plen,
                        row + XS_HDR_ROOM + plen) == 0) {
        /* Запись режется на сегменты по MTU ЭТОЙ сессии: у пиров он свой у каждого, и превышать
         * согласованный пробами размер нельзя. Пачка больше сегмента по построению, поэтому путь
         * через xs_conn_split_mm теперь общий и для одиночных записей — при одном сегменте он
         * ровно эквивалентен прежнему xs_conn_ahead. */
        int mtu = XSH_LOAD(d->mtu);
        if (mtu <= 0) mtu = XSH_MTU_CEIL;
        size_t max_seg = (size_t)mtu + XS_OVERHEAD - 40;   /* не больше XSH_MAX_SEG_CEIL */
        int segs = xs_conn_split_mm(&d->conn, rec, XS_REC_HDR + plen + XS_TAG, max_seg,
                                    w->hdrs, w->siov, w->smm,
                                    sizeof(w->hdrs) / sizeof(w->hdrs[0]), now);
        if (segs > 0) {
            int off = 0, stuck = 0;
            while (off < segs) {
                int sent = sendmmsg(d->conn.fd, &w->smm[off], (unsigned)(segs - off), 0);
                if (sent > 0) { off += sent; stuck = 0; continue; }
                if (++stuck >= 3) break;
                if (errno != EAGAIN && errno != ENOBUFS && errno != EINTR) break;
            }
            if (off == segs) {
                d->down_pkts++;
                rc = 0;
            }
        }
    }
    pthread_mutex_unlock(lk);
    return rc;
}

/* Обслуживание сессии (подтверждения, keepalive) — тоже под замком отправки: xs_conn_tick сам
 * отправляет голые подтверждения, а они двигают тот же номер последовательности. */
static void sess_tick_locked(struct sess *s, long long now) {
    pthread_mutex_t *lk = &g_tx_lock[s - g_sess];
    pthread_mutex_lock(lk);
    xs_conn_tick(&s->conn, now, 0);
    pthread_mutex_unlock(lk);
}

/* ---- дорожка неопознанного --------------------------------------------------
 *
 * ПОЧЕМУ ПРОКСИРОВАНИЕ ЗДЕСЬ ВОЗМОЖНО, ХОТЯ В ПЛАНЕ БЫЛО НАПИСАНО, ЧТО НЕТ. Прежний довод
 * звучал так: «проксирование требует настоящей точки TCP, а слушающий сокет на том же порту
 * отвечал бы SYN-ACK нашим же пирам». Это верно про слушающий сокет ЯДРА и неверно про нас:
 * поддельным TCP хаб владеет сам, в пользовательском пространстве (src/obfs.c, сырые сокеты), и
 * сокета ядра на порту нет вовсе. Значит хаб может сам открыть НАСТОЯЩЕЕ соединение к
 * сайту-прикрытию и переливать байты в обе стороны через своё поддельное. Пир при этом не
 * задета ничем: её сессия опознана раньше, чем начинается эта дорожка.
 *
 * ЧЕГО ЭТА ДОРОЖКА НЕ ДАЁТ, СКАЗАНО ПРЯМО. Наш поддельный TCP не делает повторных передач:
 * потерянный сегмент рукопожатия TLS означает для прибора зависшее соединение, а не
 * «поддельный сервер». На обычном пути потерь нет, и прибор видит настоящий сайт; на рваном он
 * увидит обрыв — подозрительно, но неотличимо от плохой связи. Второе: прикрытие отвечает
 * ЧЕРЕЗ нас, поэтому круг задержки складывается, и прибор, умеющий мерить время до ServerHello,
 * разницу увидит; лечится выбором прикрытия рядом с хабом.
 *
 * НИ ОДНОГО БЛОКИРУЮЩЕГО ВЫЗОВА. Соединение открывается неблокирующим connect и живёт в том же
 * poll, что сырой сокет и очередь TUN. Иначе один не отвечающий сайт-прикрытие останавливал бы
 * весь воркер вместе со всеми его туннелями — цена защиты оказалась бы выше защищаемого. */

/* Отказ формой настоящего фатального оповещения TLS: так отвечает сервер, которому предложили
 * то, чего он не может. Вынесено в функцию, потому что этих мест стало пять. */
static void hub_alert(struct sess *s) {
    uint8_t alert[16];
    size_t an = xs_hs_alert(alert, sizeof(alert));
    if (an) xs_conn_send(&s->conn, 0x18 /* PSH|ACK */, alert, an, 0);
}

/* Привести имя из чужого ClientHello к тому же виду, в котором лежат имена в таблице:
 * нижний регистр, без завершающей точки. 0 — годится, -1 — нет.
 *
 * ЭТО НЕДОВЕРЕННЫЕ БАЙТЫ ДО ВСЯКОЙ АУТЕНТИФИКАЦИИ, поэтому здесь белый список символов, а не
 * чёрный: всё, что не буква, не цифра, не дефис и не точка, отвергается целиком. Имя, длиннее
 * буфера таблицы, тоже отвергается, а не обрезается — обрезанное совпало бы не с тем. Дальше
 * это имя участвует РОВНО в одном действии: сравнении strcmp с именем из конфигурации; никуда
 * больше — ни в журнал, ни в путь, ни в запрос — оно не идёт. */
static int decoy_name_norm(const char *in, char *out, size_t outn) {
    size_t n = strlen(in);
    if (n && in[n - 1] == '.') n--;
    if (!n || n >= outn) return -1;
    for (size_t i = 0; i < n; i++) {
        char ch = in[i];
        if (ch >= 'A' && ch <= 'Z') ch = (char)(ch + 32);
        if (!((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9') || ch == '-' || ch == '.'))
            return -1;
        out[i] = ch;
    }
    out[n] = '\0';
    return 0;
}

/* Куда отдавать ЭТОГО неопознанного: адрес в СЕТЕВОМ порядке, 0 — некуда (тогда отвечаем как
 * прежде). hello/n — то, что прибор прислал, целиком и как есть.
 *
 * ПОЧЕМУ ИМЯ ВЫБИРАЕТ ПРИБОР. Постоянное прикрытие отдаёт подлинный сертификат только тому, кто
 * спросил имя этого прикрытия; всякий другой видит «просил A — получил сертификат B», а это
 * ровно тот признак, ради устранения которого дорожка и заведена.
 *
 * ИМЯ ВНЕ ТАБЛИЦЫ — ЭТО ПРЕЖНЕЕ ПОВЕДЕНИЕ, А НЕ ОТКАЗ, и это важнее удобства: отказывай мы по
 * незнакомому имени, порт хаба начал бы отвечать ПО-РАЗНОМУ на разные имена, и сама эта разница
 * рассказывала бы прибору, какие имена мы обслуживаем. Не разобрался Hello, нет SNI, имя с
 * посторонними символами — тоже прежнее поведение, по той же причине.
 *
 * Никакого разрешения имён здесь нет и быть не может: таблица разрешена при подъёме
 * (hub_decoy_resolve), а эта функция зовётся из цикла воркера. */
static uint32_t decoy_dest_for(const uint8_t *hello, size_t n) {
    struct in_addr fixed;
    uint32_t fallback = inet_pton(AF_INET, g_conf.decoy_dest, &fixed) == 1 ? fixed.s_addr : 0;
    if (g_decoy_map_n <= 0) return fallback;
    /* ГРАНИЦЫ ПРОВЕРЯЮТСЯ ДО ЕДИНОГО ЧТЕНИЯ. Разбору отдаётся РОВНО ОДНА запись, длиной, которую
     * назвал сам прибор, и только если она уже пришла целиком: chello_parse требует, чтобы
     * заявленная длина совпала с переданной, и передать ему больше (хвост следующей записи) или
     * меньше (недочитанное) значило бы либо разбирать не то, либо получать отказ на верном
     * Hello. Всё остальное — забота самого разбора: он писан как граница доверия и проверяется
     * отдельным стендом на обрезанных и испорченных Hello. */
    if (n < 5 || hello[0] != 0x16) return fallback;
    size_t want = 5 + ((size_t)hello[3] << 8) + hello[4];
    if (want > n) return fallback;
    struct chello_ref ref;
    if (chello_parse(hello, want, &ref) != 0 || !ref.sni[0]) return fallback;
    char nm[XS_DECOY_SNI_LEN];
    if (decoy_name_norm(ref.sni, nm, sizeof(nm)) != 0) return fallback;
    /* Линейный обход: имён не больше восьми, и зовётся это раз на НЕОПОЗНАННОЕ соединение, а не
     * на пакет. Заводить здесь индекс значило бы усложнять то, чего никто не считает. */
    for (int i = 0; i < g_decoy_map_n; i++)
        if (strcmp(nm, g_decoy_map[i].name) == 0) return g_decoy_map[i].addr;
    return fallback;
}

/* Разрешить имена прикрытия в адреса. РОВНО ОДИН РАЗ, при подъёме хаба и до создания первого
 * воркера — дальше таблица только читается, поэтому замка у неё нет.
 *
 * Имя, которое не разрешилось, хаб НЕ РОНЯЕТ: прикрытие — это защита от зондирования, а не
 * условие работы туннелей, и отказаться поднимать звезду из-за недоступного в эту минуту DNS
 * значило бы обменять работающий VPN на неработающую защиту. Такое имя просто не участвует в
 * выборе, и об этом есть строка в журнале — иначе разница «имя есть в файле, но не работает»
 * не обнаруживалась бы ничем, кроме зондирования собственного порта. */
static void hub_decoy_resolve(void) {
    if (g_conf.decoy != XS_DECOY_PROXY) return;
    for (size_t i = 0; i < g_conf.decoy_sni_n && g_decoy_map_n < XS_DECOY_SNI_MAX; i++) {
        struct addrinfo hints, *res = NULL;
        memset(&hints, 0, sizeof(hints));
        /* Только IPv4: наружу движок ходит только по нему (см. «чего протокол не делает»), и
         * адрес AF_INET6 в таблице означал бы соединение, которое не откроется никогда. */
        hints.ai_family = AF_INET;
        hints.ai_socktype = SOCK_STREAM;
        int rc = getaddrinfo(g_conf.decoy_sni[i], NULL, &hints, &res);
        if (rc != 0 || !res || !res->ai_addr || res->ai_addrlen < sizeof(struct sockaddr_in)) {
            fprintf(stderr, LOG_W "прикрытие %s: имя не разрешилось (%s) — по этому имени "
                                  "отдаём %s:%d, как прежде\n",
                    g_conf.decoy_sni[i], rc ? gai_strerror(rc) : "нет адреса IPv4",
                    g_conf.decoy_dest, g_conf.decoy_port);
            if (res) freeaddrinfo(res);
            continue;
        }
        struct sockaddr_in sa;
        memcpy(&sa, res->ai_addr, sizeof(sa));
        freeaddrinfo(res);
        snprintf(g_decoy_map[g_decoy_map_n].name, XS_DECOY_SNI_LEN, "%s", g_conf.decoy_sni[i]);
        g_decoy_map[g_decoy_map_n].addr = sa.sin_addr.s_addr;
        g_decoy_map_n++;
        char t[INET_ADDRSTRLEN];
        inet_ntop(AF_INET, &sa.sin_addr, t, sizeof(t));
        fprintf(stderr, LOG_I "прикрытие %s → %s:%d\n", g_conf.decoy_sni[i], t,
                g_conf.decoy_port);
    }
}

/* Открыть соединение к сайту-прикрытию. 1 — дорожка началась (сессия жива и переходит в
 * PH_PROXY), 0 — не вышло, отвечать придётся как прежде. */
static int decoy_start(struct worker *w, struct sess *s, long long now) {
    if (g_conf.decoy != XS_DECOY_PROXY || !g_conf.decoy_port) return 0;
    /* Предел проверяется ПЕРВЫМ и занимает место сразу: между проверкой и занятием другой
     * воркер успел бы занять последнее место, и «не больше тридцати двух» стало бы «около». */
    pthread_mutex_lock(&g_ctl);
    int taken = g_decoy_live < XSH_DECOY_MAX;
    if (taken) g_decoy_live++;
    pthread_mutex_unlock(&g_ctl);
    if (!taken) {
        unsigned long long held = 0;
        if (xs_ratelog(&w->rl_decoy, now, XS_LOG_EVERY_MS, &held)) {
            char tail[64];
            fprintf(stderr, LOG_W "неопознанных больше %d одновременно — этому отказываю%s\n",
                    XSH_DECOY_MAX, xs_held_str(held, tail, sizeof(tail)));
        }
        return 0;
    }
    /* Прикрытие выбирается ИМЕНЕМ, которое назвал сам прибор, и только из таблицы, разрешённой
     * при подъёме. Порт один и тот же (DecoyDest): прибор постучался на наш слушающий порт, а
     * какой порт у прикрытия — свойство настройки, а не запроса. */
    uint32_t dst = decoy_dest_for(s->hs_buf, s->hs_len);
    if (!dst) goto fail;
    struct sockaddr_in to;
    memset(&to, 0, sizeof(to));
    to.sin_family = AF_INET;
    to.sin_port = htons((uint16_t)g_conf.decoy_port);
    to.sin_addr.s_addr = dst;
    {
        int fd = socket(AF_INET, SOCK_STREAM | SOCK_NONBLOCK | SOCK_CLOEXEC, 0);
        if (fd < 0) goto fail;
        if (connect(fd, (struct sockaddr *)&to, sizeof(to)) != 0 && errno != EINPROGRESS) {
            close(fd);
            goto fail;
        }
        s->up_fd = fd;
    }
    s->up_ready = 0;
    s->up_sent = 0;
    s->up_at = now;
    s->up_addr = dst;
    s->phase = PH_PROXY;
    w->d_decoy++;
    return 1;
fail:
    pthread_mutex_lock(&g_ctl);
    if (g_decoy_live > 0) g_decoy_live--;
    pthread_mutex_unlock(&g_ctl);
    return 0;
}

/* ЕДИНСТВЕННАЯ дорожка для тех, кто не наш, и это её главное свойство.
 *
 * Отвечать оповещением из четырёх разных мест (не разобрали Hello, не похоже на TLS вовсе, нет
 * такого пира, метка времени старее прошлой) означало, что четыре ответа могут разойтись по
 * поведению — а разница в ответе на два разных «не наш» рассказывает прибору, ГДЕ его отвергли.
 * Ровно это и было: три места отвечали оповещением, а повтор метки времени молча закрывал
 * сессию, то есть отвечал «silent» независимо от настройки. */
static void hub_stranger(struct worker *w, struct sess *s, long long now) {
    switch (g_conf.decoy) {
    case XS_DECOY_SILENT:
        break;
    case XS_DECOY_RESET:
        xs_conn_send(&s->conn, 0x14 /* RST|ACK */, NULL, 0, 0);
        break;
    case XS_DECOY_PROXY:
        if (decoy_start(w, s, now)) return;   /* сессию доведёт сама дорожка */
        /* Не вышло открыть соединение — отвечаем как настоящий сервер, у которого не сошлось:
         * это хуже проксирования, но лучше молчания. */
        hub_alert(s);
        break;
    default:
        hub_alert(s);
        break;
    }
    sess_free(w, s);
}

/* Событие на соединении с прикрытием. Возвращает 1, если сессия освобождена.
 *
 * Вынесено из цикла воркера ради стенда: внутри цикла эту дорожку окружают poll и сырой сокет,
 * а проверять её надо на настоящем соединении к настоящему слушающему сокету (tests/hubmatch.c
 * поднимает его на петле). */
static int decoy_event(struct worker *w, struct sess *s, short rev, long long now) {
    if (s->phase != PH_PROXY || s->up_fd < 0) return 0;
    /* ---- connect ещё не завершился ---------------------------------------- */
    if (!s->up_ready) {
        if (rev & (POLLERR | POLLHUP | POLLNVAL)) goto give_up;
        if (!(rev & POLLOUT)) return 0;
        int err = 0;
        socklen_t el = sizeof(err);
        if (getsockopt(s->up_fd, SOL_SOCKET, SO_ERROR, &err, &el) != 0 || err) goto give_up;
        /* ПЕРВЫМ ДЕЛОМ уходит всё, что прислал прибор, — целиком и без единой правки. Именно
         * всё накопленное, а не последний сегмент: Hello браузерного размера приходит
         * несколькими сегментами, и отдать прикрытию только последний значило бы, что оно видит
         * обрубок и отвечает не так, как ответило бы прибору напрямую. */
        while (s->up_sent < s->hs_len) {
            ssize_t n = send(s->up_fd, s->hs_buf + s->up_sent, s->hs_len - s->up_sent,
                             MSG_NOSIGNAL);
            if (n > 0) { s->up_sent += (size_t)n; continue; }
            if (n < 0 && (errno == EAGAIN || errno == EWOULDBLOCK || errno == EINTR)) return 0;
            goto give_up;
        }
        s->up_ready = 1;
        s->up_at = now;
        unsigned long long held = 0;
        if (xs_ratelog(&w->rl_decoy, now, XS_LOG_EVERY_MS, &held)) {
            struct in_addr in, up;
            char tail[64], dst[INET_ADDRSTRLEN];
            in.s_addr = s->conn.daddr;
            up.s_addr = s->up_addr;
            /* Адрес прикрытия печатается ИЗ СЕССИИ, а не из конфигурации: с выбором по имени
             * они расходятся, а строка журнала, называющая не тот адрес, хуже отсутствующей.
             * inet_ntop, а не второй inet_ntoa: у того один статический буфер на вызов. */
            inet_ntop(AF_INET, &up, dst, sizeof(dst));
            fprintf(stderr, LOG_I "неопознанный с %s: отдаю настоящему серверу %s:%d%s\n",
                    inet_ntoa(in), dst, g_conf.decoy_port,
                    xs_held_str(held, tail, sizeof(tail)));
        }
        return 0;
    }
    /* ---- ответ прикрытия — прибору ---------------------------------------- */
    if (rev & POLLIN) {
        /* Не больше XSH_BATCH кусков за событие: остальное дочитается следующим кругом poll, а
         * туннели соседних сессий не ждут, пока прибор скачает страницу. */
        for (int i = 0; i < XSH_BATCH; i++) {
            uint8_t buf[XSH_DECOY_CHUNK];
            ssize_t n = recv(s->up_fd, buf, sizeof(buf), MSG_DONTWAIT);
            if (n == 0) goto closed;                 /* прикрытие закрылось */
            if (n < 0) {
                if (errno == EAGAIN || errno == EWOULDBLOCK || errno == EINTR) break;
                goto closed;
            }
            /* Отправка под тем же замком, что и данные пиров, только БЕЗ шифрования: прибор
             * говорит настоящий TLS с настоящим сервером, и наше дело перенести байты, а не
             * подписать их. Замок здесь не про nonce (у этой сессии ключей нет вовсе), а про то,
             * что номер последовательности двигают ещё и подтверждения из обслуживания. */
            pthread_mutex_lock(&g_tx_lock[s - g_sess]);
            int rc = xs_conn_send(&s->conn, 0x18 /* PSH|ACK */, buf, (size_t)n, 0);
            pthread_mutex_unlock(&g_tx_lock[s - g_sess]);
            s->up_at = now;
            if (rc != 0) goto closed;
            if ((size_t)n < sizeof(buf)) break;
        }
        return 0;
    }
    if (rev & (POLLERR | POLLHUP | POLLNVAL)) goto closed;
    return 0;

give_up:
    /* Прикрытие недоступно, а прибор ещё не получил ни байта — отвечаем как прежде. */
    hub_alert(s);
    sess_free(w, s);
    return 1;
closed:
    /* ЗАКРЫТИЕ ПРИКРЫТИЯ ЗАКРЫВАЕТ И НАС, и это не вежливость. Настоящий сервер HTTPS на запрос
     * HTTP отвечает отказом или закрывает соединение, но делает это БЫСТРО. Пока этого не было
     * (в реализации на Go поймано стендом), прибор, приславший «GET / HTTP/1.1», не получал
     * ничего: прикрытие закрывалось, а наше поддельное соединение оставалось висеть — снаружи
     * это выглядит как открытый порт, который молчит, то есть как ровно тот признак, ради
     * устранения которого вся дорожка и заведена. */
    xs_conn_send(&s->conn, 0x11 /* FIN|ACK */, NULL, 0, 0);
    sess_free(w, s);
    return 1;
}

/* То, что прибор присылает дальше, уходит настоящему серверу. */
static void decoy_up(struct worker *w, struct sess *s, const struct obfs_seg *seg,
                     long long now) {
    if (s->up_fd < 0) { sess_free(w, s); return; }
    if (!seg->plen) return;
    /* Присланное рукопожатие ещё не ушло целиком — дописываем в тот же буфер, иначе продолжение
     * потока обогнало бы своё же начало. Предел буфера тот же, что у сборки Hello: сюда пишет
     * кто угодно из интернета. */
    if (!s->up_ready) {
        if (s->hs_len + seg->plen > sizeof(s->hs_buf)) {
            xs_conn_send(&s->conn, 0x11 /* FIN|ACK */, NULL, 0, 0);
            sess_free(w, s);
            return;
        }
        memcpy(s->hs_buf + s->hs_len, seg->payload, seg->plen);
        s->hs_len += seg->plen;
        return;
    }
    ssize_t n = send(s->up_fd, seg->payload, seg->plen, MSG_NOSIGNAL);
    if (n != (ssize_t)seg->plen) {
        /* Частичная отправка — это обрубок в середине записи TLS: прикрытию честнее закрыть
         * соединение, чем скормить половину. Полный буфер отправки на этом пути означает, что
         * прибор льёт быстрее, чем прикрытие читает, а зондирование так не выглядит. */
        xs_conn_send(&s->conn, 0x11 /* FIN|ACK */, NULL, 0, 0);
        sess_free(w, s);
        return;
    }
    s->up_at = now;
}

/* Разобрать рукопожатие пира и ответить. */
static void hs_step(struct worker *w, struct sess *s, const struct obfs_seg *seg,
                    int listen_port, long long now) {
    (void)listen_port;
    uint8_t peer_static[32];
    /* СОБИРАЕМ HELLO ИЗ СЕГМЕНТОВ. Браузерный ClientHello больше одного сегмента (около 1760 байт
     * из-за постквантового ключа), и наш такой же — иначе размер Hello сам по себе признак.
     * Значит первый сегмент почти всегда неполон, и разбирать его сразу нельзя. */
    if (s->hs_len + seg->plen > sizeof(s->hs_buf)) {
        hub_stranger(w, s, now);
        return;
    }
    memcpy(s->hs_buf + s->hs_len, seg->payload, seg->plen);
    s->hs_len += seg->plen;
    /* НЕ ПОХОЖЕ НА РУКОПОЖАТИЕ TLS ВООБЩЕ — отвечаем сразу, не дожидаясь продолжения.
     *
     * Это про зондирование, а не про аккуратность: прибор первым делом присылает не только
     * настоящий ClientHello, но и «GET / HTTP/1.1», и просто мусор. Копить такие байты до предела
     * значит молчать в ответ на запрос HTTP — чего настоящий сервер не делает никогда, и что
     * отличимо не хуже молчания на Hello. */
    if (s->hs_len >= 2 && (s->hs_buf[0] != 0x16 || s->hs_buf[1] != 0x03)) {
        hub_stranger(w, s, now);
        return;
    }
    if (s->hs_len < 5) return;
    {
        size_t want = 5 + ((size_t)s->hs_buf[3] << 8) + s->hs_buf[4];
        if (s->hs_len < want) return;
    }
    /* Накопленное НЕ ОЧИЩАЕТСЯ до тех пор, пока пир не опознан ОКОНЧАТЕЛЬНО, и это нарочно:
     * дорожка неопознанного отдаёт прикрытию именно присланное целиком, а очистка оставила бы
     * ей последний сегмент вместо всего Hello — прикрытие отвечало бы на обрубок, а имя из SNI
     * не разбиралось бы вовсе. Развилок «не наш» здесь ТРИ, и разбор ниже проходят две из них
     * («нет такого пира» и «повтор msg1»), поэтому очистка стоит после них, а не сразу за
     * разбором. Тот же порядок и по той же причине в реализации на Go (hub/worker.go,
     * handshake). */
    int rc = xs_hs_server_read(&s->hs, &g_sec, s->hs_buf, s->hs_len, peer_static);
    if (rc != 0) {
        hub_stranger(w, s, now);
        return;
    }
    /* Личность известна — ищем пира. Линейный обход: раз на рукопожатие. */
    int found = -1;
    for (size_t i = 0; i < g_conf.peer_n; i++)
        if (memcmp(g_conf.peer[i].pub, peer_static, 32) == 0) { found = (int)i; break; }
    if (found < 0) {
        /* Сюда попадает ЛЮБОЙ, кто сделал себе пару ключей: статический ключ инициатора
         * подтверждается общим секретом с нашим, а он считается из нашего ОТКРЫТОГО ключа.
         * То есть частоту этой строки выбирает посторонний — отсюда ограничитель. */
        unsigned long long held = 0;
        if (xs_ratelog(&w->rl_unknown, now, XS_LOG_EVERY_MS, &held)) {
            char fp[12], tail[64];
            xs_key_fp(peer_static, fp);
            fprintf(stderr, LOG_W "пир %s не описан в конфигурации — отказ%s\n",
                    fp, xs_held_str(held, tail, sizeof(tail)));
        }
        hub_stranger(w, s, now);
        return;
    }
    /* Воспроизведение записанного msg1: метка времени обязана быть новее прошлой от этого
     * пира. Само по себе это не даёт атакующему сессию (подтверждение он не подделает), но
     * даёт хабу три зря потраченных X25519 на каждый повтор.
     *
     * Метки времени общие для всех воркеров: один и тот же пир приходит с разных портов, то
     * есть к разным воркерам, и защита от повтора обязана быть общей. Читаем под замком и
     * решаем уже без него — иначе освобождение сессии происходило бы с занятым замком. */
    pthread_mutex_lock(&g_ctl);
    uint64_t seen_stamp = g_last_stamp[found];
    pthread_mutex_unlock(&g_ctl);
    if (s->hs.peer.stamp && s->hs.peer.stamp < seen_stamp) {
        unsigned long long held = 0;
        if (xs_ratelog(&w->rl_stamp, now, XS_LOG_EVERY_MS, &held)) {
            char tail[64];
            fprintf(stderr, LOG_W "пир %zu: метка времени старее прошлой — похоже на повтор%s\n",
                    (size_t)found + 1, xs_held_str(held, tail, sizeof(tail)));
        }
        /* Повтор записанного msg1 — тоже «не наш», и отвечать на него иначе, чем на прочих
         * неопознанных, значило бы рассказывать прибору, что этот Hello он подобрал правильно.
         * Прежде эта ветка молча закрывала сессию, то есть отвечала «silent» при любой
         * настройке. */
        hub_stranger(w, s, now);
        return;
    }
    s->peer = (int16_t)found;
    s->hs_len = 0;   /* пир опознан: дорожке неопознанного накопленное больше не понадобится */

    size_t on = 0;
    /* Хаб называет свой предел так же, как пир: MTU настоящего канала минус накладные, но
     * не больше заданного в конфигурации. Из этих двух чисел стороны берут минимум. */
    int own_limit = XSH_MTU_CEIL;
    {
        char ifn[32] = "";
        int link = xs_egress_mtu(s->conn.saddr, ifn, sizeof(ifn));
        if (link > 0) own_limit = xs_mtu(link);
    }
    if (g_conf.mtu && g_conf.mtu < own_limit) own_limit = g_conf.mtu;
    /* И ЗДЕСЬ ТОЖЕ ПОТОЛОК, хотя оба слагаемых выше выглядят своими. Канал наружу может быть
     * шире Ethernet — на jumbo-кадрах xs_mtu(9000) даёт 8939, — и назвать пиру такой предел
     * значило бы позвать его отправлять записи, которые не влезают ни в строку буфера (XS_ROW),
     * ни в кадр канала на его стороне. */
    if (own_limit > XSH_MTU_CEIL) own_limit = XSH_MTU_CEIL;
    rc = xs_hs_server_write(&s->hs, own_limit, w->hs, sizeof(w->hs), &on, &s->tx, &s->rx);
    if (rc != 0 || xs_conn_send(&s->conn, 0x18, w->hs, on, 0) != 0) {
        fprintf(stderr, LOG_W "ответ на рукопожатие не ушёл: %d\n", rc);
        sess_free(w, s);
        return;
    }
    s->phase = PH_HS;
    s->conn.last_rx = now;
}

/* Подтверждение пира: после него сессия несёт данные. */
static void hs_confirm(struct worker *w, struct sess *s, const struct obfs_seg *seg,
                       long long now) {
    size_t used = 0;
    if (xs_hs_server_confirm(&s->hs, &s->rx, seg->payload, seg->plen, &used) != 0) {
        fprintf(stderr, LOG_W "подтверждение пира не сошлось\n");
        sess_free(w, s);
        return;
    }
    int peer_mtu = s->hs.peer.mtu;
    /* Метку времени снимаем ДО очистки состояния рукопожатия: xs_hs_wipe затирает его целиком,
     * и первая версия этой правки читала уже занулённое поле — защита от повтора превратилась
     * бы в «последняя метка всегда ноль», то есть в её отсутствие. */
    uint64_t peer_stamp = s->hs.peer.stamp;
    /* Номер соединения пира: он лежит в подписанной части рукопожатия, поэтому ему можно
     * верить. Маска обязательна — иначе значение из будущей версии протокола вышло бы за
     * пределы массива. */
    int conn_id = s->hs.peer.flags & 0x07;
    if (conn_id >= XS_CONNS_MAX) conn_id = 0;
    s->conn_id = (int8_t)conn_id;
    xs_hs_wipe(&s->hs);
    xs_win_reset(&s->win);
    xs_reasm_reset(&s->reasm);
    /* Пачка начинается с двух кадров и растёт по чистой обратной связи: начинать с восьми значило
     * бы платить на рваном пути с первой же секунды.
     *
     * STEER_XS_COMPAT=1 оставляет один кадр навсегда: это аварийный выключатель нового формата на
     * время обновления, когда к хабу ещё приходят пиры предыдущей версии. Сборку Hello из
     * сегментов выключать не нужно — короткий Hello старого пира она разбирает сразу. */
    XSH_STORE(s->batch_max, g_compat ? 1 : 2);
    XSH_STORE(s->cool_until, 0);
    s->last_drops = s->reasm.dropped;
    s->phase = PH_EST;
    s->handshake_at = now;
    /* Одна сессия на пира: новая заменяет прежнюю. Это и есть переподключение пира — он
     * приходит с НОВОГО ПОРТА, а значит, возможно, и к другому воркеру.
     *
     * Прежнюю сессию мы здесь НЕ освобождаем, хотя раньше освобождали. Причина в раскладке:
     * старая сессия может принадлежать другому воркеру, и её запись лежит в ЕГО индексе —
     * вычистить её отсюда значило бы либо трогать чужую таблицу под замком на горячем пути,
     * либо оставить в чужом индексе ссылку на переиспользованную ячейку, то есть отдавать
     * чужие пакеты не той сессии. Вместо этого прежняя сессия остаётся «смещённой» и её
     * убирает СВОЙ владелец в своём же обслуживании (см. цикл обслуживания ниже): признак —
     * привязка пир→сессия указывает не на неё. Трафика она не несёт с этой секунды, потому
     * что пир в неё больше не отправляет. */
    XSH_STORE(s->last_auth, now);
    pthread_mutex_lock(&g_ctl);
    g_last_stamp[s->peer] = peer_stamp;
    g_peer_sess[s->peer][conn_id] = (int16_t)(s - g_sess);
    /* Пир поднялся заново: остальные его соединения могут вести в точку, которой больше нет, — и
     * трафик в них уезжает в никуда. Проверяем это пробой, а не догадкой. */
    sess_roam_start(s->peer, (int)(s - g_sess), now);
    pthread_mutex_unlock(&g_ctl);
    char fp[12];
    xs_key_fp(g_conf.peer[s->peer].pub, fp);
    struct in_addr in;
    in.s_addr = s->conn.daddr;
    fprintf(stderr, LOG_I "пир %s поднялся с %s:%u, MTU %d, шифр %s\n", fp,
            inet_ntoa(in), s->conn.dport, peer_mtu,
            s->tx.aead == TLS13_AEAD_AES128 ? "AES-128-GCM" : "ChaCha20-Poly1305");
    if (peer_mtu && g_conf.mtu && peer_mtu != g_conf.mtu)
        fprintf(stderr, LOG_W "пир %s: MTU %d против нашего %d — большие пакеты будут "
                              "пропадать\n", fp, peer_mtu, g_conf.mtu);
}

/* Выбрать соединение пира для этого пакета. Соединений у пира может быть несколько (по одному
 * на её воркер), и выбор ОБЯЗАН быть постоянным для потока: раскидай мы пакеты одного
 * соединения TCP по разным путям — получатель увидит переставленные пакеты, а это для него
 * неотличимо от потерь и рушит скорость сильнее, чем помогает второе ядро.
 *
 * Хеш берётся от внутренних адресов и портов, слот — по кругу от него до первого живого.
 * Изменение числа живых соединений переставит потоки один раз, и это допустимо: событие
 * редкое (переподключение), а альтернатива — таблица закреплений, которую надо чистить. */
static int16_t peer_pick(int peer, const uint8_t *pt, size_t pn) {
    if (peer < 0) return -1;
    uint32_t h = xs_flow_hash(pt, pn);
    int start = (int)(h % XS_CONNS_MAX);
    for (int k = 0; k < XS_CONNS_MAX; k++) {
        int16_t idx = g_peer_sess[peer][(start + k) % XS_CONNS_MAX];
        if (idx >= 0) return idx;
    }
    return -1;
}

/* Узкое место из двух согласованных MTU. Ноль означает «сторона ещё не назвала свой размер»
 * и в минимуме не участвует: подрезать по нему не по чему. */
static int hub_min_mtu(int a, int b) {
    if (a <= 0) return b;
    if (b <= 0) return a;
    return a < b ? a : b;
}

/* Расшифрованный пакет: проверить право на адрес источника и развести. */
static void route_packet(struct worker *w, struct sess *from, uint8_t *pt, size_t pn, long long now) {
    if (pn < 20) return;
    uint32_t src, dst;
    memcpy(&src, pt + 12, 4);
    memcpy(&dst, pt + 16, 4);
    src = ntohl(src);
    dst = ntohl(dst);
    /* ОБЯЗАТЕЛЬНАЯ проверка: без неё одна скомпрометированная пир подделывает трафик любой
     * другой. Право на адрес даёт конфигурация, а не сам пакет. */
    if (from->peer < 0 || !xs_src_ok(&g_conf.peer[from->peer], src)) return;
    int to = xs_route(&g_router, dst, &w->rcache);
    /* Привязка пир→сессия читается один раз в локальную переменную: между чтением и отправкой
     * владелец сессии может её сменить, и «прочитать дважды» означало бы отправку по индексу,
     * который уже другой. Что сессия к моменту отправки ещё жива, проверяет сама send_to под
     * своим замком — здесь достаточно, чтобы индекс был осмысленным. */
    int16_t di = to >= 0 ? peer_pick(to, pt, pn) : -1;
    if (to >= 0 && to != from->peer && di >= 0) {
        /* Пир↔пир: уменьшаем TTL (иначе петля живёт вечно) и шифруем В ТОЙ ЖЕ строке. */
        if (xs_ttl_dec(pt, pn) != 0) return;
        struct sess *d = &g_sess[di];
        /* Подрезка по УЗКОМУ МЕСТУ пути пир→пир, а это МИНИМУМ MTU обеих сессий: у пиров он
         * свой у каждой (у одной 1431, у другой 1387).
         *
         * Только по получателю недостаточно, и это не перестраховка. MSS в SYN объявляет то,
         * что отправитель готов ПРИНИМАТЬ, то есть ограничивает сегменты, которые вторая
         * сторона пошлёт ОБРАТНО, — а обратный путь идёт через тоннель ОТПРАВИТЕЛЯ. При
         * отправителе 1387 и получателе 1431 подрезка по 1431 оставляла обратному потоку
         * предел шире, чем держит тоннель отправителя, и его полноразмерные ответы молча
         * пропадали: ICMP «нужна фрагментация» внутри тоннеля не рождается. Кроме хаба этот
         * минимум посчитать некому: пира друг о друге ничего не знают.
         *
         * Ноль (размер ещё не согласован) из минимума выпадает, а не отменяет подрезку целиком:
         * известный конец — это уже предел, который надо соблюсти. Когда узкое место сам хаб,
         * согласование опускает обе сессии до его размера, и минимум даёт то же число. */
        int clamp = hub_min_mtu(XSH_LOAD(from->mtu), XSH_LOAD(d->mtu));
        if (clamp > 0) xs_mss_clamp(pt, pn, clamp);
        send_to(w, d, w->row, pn, now);
        return;
    }
    /* Свой адрес или выход наружу — отдаём ядру, в СВОЮ очередь устройства: писать можно в
     * любую, и своя не требует ни выбора, ни согласования с другими потоками. */
    tun_write_ctl(&w->tun, pt, pn);
}

/* Увезти набранные кадры ОДНОЙ записью: один кадр — как есть, несколько — в контейнере.
 *
 * pay указывает на нагрузку записи, off — сколько в ней занято вместе с местом под тип
 * контейнера. Одиночный кадр едет БЕЗ контейнера: он дешевле на три байта, и таких записей
 * большинство. */
static void hub_send_frames(struct worker *w, struct sess *d, uint8_t *pay, size_t off,
                            int frames) {
    size_t pn;
    if (frames == 1) {
        pn = off - XS_BATCH_HDR - 2;
        memmove(pay, pay + XS_BATCH_HDR + 2, pn);
    } else {
        pay[0] = XS_CTL_BATCH;
        pn = off;
    }
    send_to(w, d, w->row, pn, xs_now_ms());
}

/* ---- один кадр открытого текста от пира ------------------------------------
 *
 * Вынесено в функцию, потому что кадр приходит двумя путями: одиночной записью и внутри пачки,
 * которую разбор отдаёт по одному через обратный вызов. Две копии этой обработки означали бы два
 * места, где можно по-разному ошибиться в том, что делать с чужим пакетом. */
static void hub_frame(struct worker *w, struct sess *s, const uint8_t *pt, size_t pn,
                      long long now) {
    s->up_pkts++;
    enum xs_kind kind = xs_frame_kind(pt, pn);
    if (kind == XS_CTL) {
        /* Проба пути: отвечаем эхом с ДОШЕДШИМ размером. Эхо крохотное (три байта), поэтому оно
         * проходит всегда — иначе пир не смог бы отличить «большой кадр не дошёл» от «не дошёл
         * ответ». */
        int psz = xs_probe_size(pt, pn);
        if (psz > 0) {
            uint8_t ack[8];
            size_t an2 = xs_pack_build(ack, sizeof(ack), psz);
            if (an2) {
                memcpy(w->row + XS_HDR_ROOM, ack, an2);
                send_to(w, s, w->row, an2, now);
            }
            return;
        }
        /* Пир не собирает наши записи: путь рвёт сегменты. Схлопываем пачку немедленно — на
         * рваном пути она делает хуже, а не лучше. */
        int lost = xs_loss_value(pt, pn);
        if (lost > 0) {
            XSH_STORE(s->batch_max, 1);
            XSH_STORE(s->cool_until, now + XSH_REASM_COOL_MS);
            unsigned long long held = 0;
            if (xs_ratelog(&w->rl_reasm, now, XS_LOG_EVERY_MS, &held)) {
                char tail[64];
                fprintf(stderr, LOG_I "пир не собрал %d записей — везу по одному кадру%s\n",
                        lost, xs_held_str(held, tail, sizeof(tail)));
            }
            return;
        }
        /* Итог согласования: пир проверил путь и называет рабочий размер. Берём минимум со своим
         * пределом — больше него мы всё равно не отправим. */
        int mv = xs_mtu_value(pt, pn);
        if (mv > 0) {
            /* ПОТОЛОК ОДИН И ТОТ ЖЕ для числа из провода и для числа из конфигурации, и
             * пропускать его нельзя. Прежде конфигурация зажимала пира, а сама не зажималась
             * ничем: MTU=1500 в файле плюс пир, назвавший столько же, давали сегмент больше
             * предельного (см. XSH_MTU_CEIL). Тот же класс, что нижняя граница ниже: число из
             * провода проверяется против СВОИХ пределов, а не только против другого числа из
             * настроек. */
            int own = g_conf.mtu;
            if (own <= 0 || own > XSH_MTU_CEIL) own = XSH_MTU_CEIL;
            int was = XSH_LOAD(s->mtu);
            /* НИЖНЯЯ ГРАНИЦА ОБЯЗАТЕЛЬНА, и она не про разумность значения (I-075). Запись
             * режется на сегменты по MTU этой сессии, и при MTU меньше ~492 предельная запись
             * требует больше сегментов, чем есть векторов у sendmmsg: xs_conn_split_mm
             * отказывает, send_to возвращает -1 ВСЕГДА, и к этой пире не уходит ни данных, ни
             * keepalive, ни обратной связи по сборке. Пира отваливается по своей же тишине, а в
             * журнале хаба нет ни строки. Пол у протокола есть — XS_MTU_FLOOR, ниже него не
             * опускается сам пробой пути, — поэтому меньшее значение это не «узкий путь», а
             * непроверенное число из провода. */
            if (mv < XS_MTU_FLOOR) {
                unsigned long long held = 0;
                if (xs_ratelog(&w->rl_mtu, now, XS_LOG_EVERY_MS, &held)) {
                    char fp2[12], tail[64];
                    xs_key_fp(g_conf.peer[s->peer >= 0 ? s->peer : 0].pub, fp2);
                    fprintf(stderr, LOG_W "пир %s: назвал MTU %d — ниже предела %d, оставляю "
                                          "прежний %d%s\n", fp2, mv, XS_MTU_FLOOR,
                            was ? was : XS_MTU_DEF, xs_held_str(held, tail, sizeof(tail)));
                }
                return;
            }
            XSH_STORE(s->mtu, mv < own ? mv : own);
            /* Печатаем только ИЗМЕНЕНИЕ: кадр приходит после каждого пробоя пира, то есть раз в
             * две минуты на каждого, и строка «согласован тот же MTU» через год работы звезды из
             * тридцати пиров — это четверть миллиона строк ни о чём. */
            if (XSH_LOAD(s->mtu) != was) {
                char fp2[12];
                xs_key_fp(g_conf.peer[s->peer >= 0 ? s->peer : 0].pub, fp2);
                fprintf(stderr, LOG_I "пир %s: согласован MTU %d\n", fp2, XSH_LOAD(s->mtu));
            }
            hub_retune_mtu();
        }
        return;
    }
    /* IPv6 ОТБРАСЫВАЕТСЯ ЯВНО, а не по случайному отказу дальше (I-073). Маршрутизации IPv6 в
     * хабе нет: route_packet разбирает любой кадр как IPv4 — адрес источника читается по
     * смещению 12, а у пакета IPv6 там лежат байты 4-7 его же адреса источника. Обычно такой
     * кадр останавливает проверка права на адрес, и «не поддерживается» выводилось из того, что
     * она случайно отказывает. Но пира, описанная в конфигурации, может подобрать эти байты так,
     * чтобы они попали в её разрешённый диапазон, — и тогда кадр IPv6 уезжает как пакет IPv4: с
     * уменьшением не того байта, пересчётом контрольной суммы, которой в IPv6 нет, и подрезкой
     * MSS не там. Пока маршрутизации нет, отказ обязан быть решением, а не совпадением. */
    if (kind == XS_IPV6) {
        w->d_ipv6++;
        unsigned long long held = 0;
        if (xs_ratelog(&w->rl_ipv6, now, XS_LOG_EVERY_MS, &held)) {
            char fp2[12], tail[64];
            xs_key_fp(g_conf.peer[s->peer >= 0 ? s->peer : 0].pub, fp2);
            fprintf(stderr, LOG_W "пир %s: кадр IPv6 — маршрутизации IPv6 в хабе нет, "
                                  "отброшен%s\n", fp2, xs_held_str(held, tail, sizeof(tail)));
        }
        return;
    }
    if (kind != XS_IPV4) return;
    /* Пакет поедет дальше из строки с местом под заголовки впереди, а пришёл он либо в приёмном
     * буфере, либо в буфере сборки — переносим, если он не там. */
    if (pt != w->row + XS_HDR_ROOM) {
        if (pn > XS_MTU_DEF) return;
        memmove(w->row + XS_HDR_ROOM, pt, pn);
    }
    route_packet(w, s, w->row + XS_HDR_ROOM, pn, now);
}

struct hub_fctx { struct worker *w; struct sess *s; long long now; };

static void hub_frame_cb(void *ctx, const uint8_t *f, size_t n) {
    struct hub_fctx *c = ctx;
    hub_frame(c->w, c->s, f, n, c->now);
}

/* Цикл одного воркера. Всё, что он трогает, — либо его личное (буферы, индекс, свой отрезок
 * таблицы), либо взято под замок отправки. */
/* Ветка SYN приёмного цикла. Возвращает сессию, которой сегмент принадлежит, или NULL,
 * если он отброшен.
 *
 * Отдельной функцией, а не строками внутри worker_loop, ради стенда: до неё нужно дотянуться
 * из tests/hubmatch.c, а внутри цикла её окружают poll и сырой сокет.
 *
 * СЕССИЮ В РАБОТЕ SYN НЕ ТРОГАЕТ — это главное свойство, и оно новое. Поддельный SYN не
 * несёт ни байта аутентификации: такой сегмент собирает кто угодно, кто знает адрес хаба и
 * порт пира. Раньше эта ветка по нему правила isn_rx — базу, из которой xs_reasm_feed
 * считает смещение принятой записи, а из смещения выводится nonce расшифровки. Одно
 * постороннее сообщение останавливало входящий поток целиком, и сессия при этом даже не
 * умирала по XSH_IDLE_MS: last_rx обновляется каждым принятым сегментом, включая
 * нерасшифрованные (I-071).
 *
 * Второе следствие тоньше и живёт в замках. Откат `seq -= 1` сам по себе сходится: SYN-ACK
 * тут же занимает этот номер обратно (xs_conn_send прибавляет единицу за флаг SYN). Но
 * происходит он БЕЗ g_tx_lock, а записи данных в ту же сессию пишет другой воркер именно
 * под этим замком — то есть между откатом и SYN-ACK номер может достаться настоящей записи.
 * Номер и есть смещение, из которого выводится nonce отправки, а повтор nonce — это полная
 * потеря AEAD, о чём шапка xsconn.h говорит прямо.
 *
 * У WireGuard граница проведена там же: состояние живой сессии меняет только УЖЕ
 * ПРОВЕРЕННЫЙ пакет. Инициация рукопожатия несёт mac1 на статическом ключе получателя (а под
 * нагрузкой ещё и cookie), проверяется до всякой дорогой арифметики — и даже пройдя
 * проверку, не трогает текущую пару ключей: та сменяется только после ЗАВЕРШЁННОГО
 * рукопожатия, а прежняя ещё живёт на расшифровку. Наш аутентификатор едет в session_id
 * ClientHello, то есть в сегменте ПОСЛЕ SYN, поэтому на сам SYN опираться нечем, и
 * единственный честный ответ — не менять по нему ничего.
 *
 * Цена отказа мала: пир выбирает порт источника случайно из 28000 (xsconn.c), поэтому SYN в
 * ту же четвёрку от своего же пира после перезапуска — один случай на семь тысяч, и он
 * разрешается сам: сессия уходит по XSH_IDLE_MS, пир соединяется с нового порта. Полный
 * ответ на этот случай — SYN-cookie на неопознанный SYN и подмена сессии только после
 * сошедшегося аутентификатора, как у WireGuard; это отдельная работа, R-059. */
static struct sess *sess_on_syn(struct worker *w, struct sess *s, const struct obfs_seg *seg,
                                long long now) {
    if (s && s->phase != PH_SYN) {
        w->d_syn_est++;
        /* НО ПРОСТО ОТБРОСИТЬ — МАЛО, и вот чего здесь не хватало. Пир, поднявшийся заново без
         * паузы (смена сети, выход из сна, перезапуск службы), может прийти с ТОЙ ЖЕ четвёркой, и
         * тогда его SYN попадал ровно сюда: ответом была тишина до тех пор, пока прежняя сессия не
         * умрёт по простою. Снаружи это «пир не подключается», и ждать приходилось минуты.
         *
         * Поэтому SYN в живую сессию ЗАПУСКАЕТ ПРОБУ. Ответа на сам SYN по-прежнему нет и состояние
         * сессии по-прежнему не меняется (SYN не несёт ни байта аутентификации) — но если прежний
         * путь мёртв, а при вернувшемся пире он мёртв, проба это выясняет за 450 мс и сессия уходит.
         * Повтор SYN придёт через секунду и заведёт новую сессию как обычно.
         *
         * Цена при подделке названа прямо: посторонний, знающий четвёрку живого туннеля, может
         * заставить хаб отправить пиру три пустые записи. Пир на них ответит, проба это увидит,
         * сессия останется. Подделка стоит нападающему одного пакета, а нам — трёх пустых записей;
         * это несравнимо дешевле того, что прежнее решение стоило настоящему пиру. */
        if (s->phase == PH_EST && XSH_LOAD(s->roam_check) == 0) XSH_STORE(s->roam_check, now);
        /* Строку вызывает пришедший из сети пакет, значит её частоту выбирает не хозяин
         * хаба — отсюда ограничитель, как у неопознанного пира выше. */
        unsigned long long held = 0;
        if (xs_ratelog(&w->rl_synest, now, XS_LOG_EVERY_MS, &held)) {
            struct in_addr in;
            char tail[64];
            in.s_addr = seg->saddr;
            fprintf(stderr, LOG_W "SYN в сессию, которая уже работает (%s:%u) — сессия не тронута, "
                                  "проверяю пробой, жив ли её путь%s\n",
                    inet_ntoa(in), seg->sport, xs_held_str(held, tail, sizeof(tail)));
        }
        return NULL;
    }
    if (!s) s = sess_alloc(w, seg, g_conf.listen_port, now);
    else s->conn.seq -= 1;          /* повтор того же SYN-ACK */
    if (!s) return NULL;
    s->conn.ack = seg->seq + 1;
    s->conn.isn_rx = seg->seq;
    s->conn.state = XSC_SYN_RCVD;
    s->conn.last_rx = now;
    w->d_syn++;
    xs_conn_send(&s->conn, 0x12 /* SYN|ACK */, NULL, 0, OBFS_OPT_SCALE);
    return s;
}

static void *worker_loop(void *arg) {
    struct worker *w = arg;
    long long d_last = xs_now_ms();
    for (;;) {
        struct pollfd fds[2 + XSH_MAX_SESS];
        int pmap[XSH_MAX_SESS];
        int nf = 0, np = 0;
        fds[nf].fd = w->rx; fds[nf].events = POLLIN; fds[nf].revents = 0; nf++;
        fds[nf].fd = w->tun.fd; fds[nf].events = POLLIN; fds[nf].revents = 0; nf++;
        /* Соединения с сайтом-прикрытием живут в ТОМ ЖЕ poll, что сырой сокет и очередь TUN:
         * блокирующего вызова в этом цикле нет ни одного, и появиться он здесь не должен тем
         * более — прикрытие может не ответить вовсе. POLLOUT нужен, пока connect не завершился
         * или пока присланное прибором не ушло целиком. */
        for (int i = w->base; i < w->base + w->cap; i++) {
            struct sess *s = &g_sess[i];
            if (s->phase != PH_PROXY || s->up_fd < 0) continue;
            fds[nf].fd = s->up_fd;
            fds[nf].events = (short)(POLLIN | (s->up_ready ? 0 : POLLOUT));
            fds[nf].revents = 0;
            pmap[np++] = i;
            nf++;
        }
        int n = poll(fds, (nfds_t)nf, XSC_TICK_MS * 5);
        long long now = xs_now_ms();
        if (n < 0 && errno != EINTR) break;

        /* Прикрытие обслуживается ПЕРЕД приёмом от пиров, и порядок здесь имеет значение: приём
         * может освободить ту же сессию, и тогда события на её уже закрытом дескрипторе
         * относились бы к чужому сокету с тем же номером. */
        if (n > 0)
            for (int p = 0; p < np; p++)
                if (fds[2 + p].revents)
                    decoy_event(w, &g_sess[pmap[p]], fds[2 + p].revents, now);

        /* ---- со пиров -------------------------------------------------------- */
        if (n > 0 && (fds[0].revents & POLLIN)) {
          for (;;) {
            for (int i = 0; i < XSH_BATCH; i++) {
                w->iov[i].iov_base = w->rx_buf[i];
                w->iov[i].iov_len = XS_ROW;
                memset(&w->mm[i].msg_hdr, 0, sizeof(w->mm[i].msg_hdr));
                w->mm[i].msg_hdr.msg_iov = &w->iov[i];
                w->mm[i].msg_hdr.msg_iovlen = 1;
            }
            int got = recvmmsg(w->rx, w->mm, XSH_BATCH, MSG_DONTWAIT, NULL);
            if (got <= 0) break;
            for (int i = 0; i < got; i++) {
                struct obfs_seg seg;
                w->d_seg++;
                if (obfs_parse(w->rx_buf[i], w->mm[i].msg_len, &seg) != 0) { w->d_bad++; continue; }
                if (seg.dport != (uint16_t)w->listen_port) { w->d_alien++; continue; }
                struct sess *s = sess_find(w, ntohl(seg.saddr), seg.sport);

                if ((seg.flags & 0x02) && !(seg.flags & 0x10)) {         /* SYN */
                    sess_on_syn(w, s, &seg, now);
                    continue;
                }
                if (!s) {
                    /* Данные по сессии, которой нет: пир пережила наш перезапуск. RST
                     * говорит ей об этом сразу — иначе она узнает по тишине, то есть через
                     * XSC_DEAD_MS, и всё это время туннель стоит. Окно 65535, а не ноль:
                     * именно этим наш RST отличается от RST ядра, который гасит правило. */
                    if (w->tx0 >= 0 && !(seg.flags & 0x04)) {
                        uint8_t rst[60];
                        size_t rn = obfs_build(rst, seg.daddr, seg.saddr,
                                               (uint16_t)w->listen_port, seg.sport,
                                               seg.ack, seg.seq + (uint32_t)seg.plen,
                                               0x14 /* RST|ACK */, 0, NULL, 0);
                        struct sockaddr_in to;
                        memset(&to, 0, sizeof(to));
                        to.sin_family = AF_INET;
                        to.sin_addr.s_addr = seg.saddr;
                        sendto(w->tx0, rst, rn, 0, (struct sockaddr *)&to, sizeof(to));
                    }
                    continue;
                }
                /* Замок берётся вокруг УЧЁТА принятого, потому что он теперь может отправить:
                 * голое подтверждение уходит прямо из xs_conn_on_seg (по таймеру их выходило
                 * пятьдесят в секунду там, где нужно тысячи). Отправка двигает номер, а в эту же
                 * сессию может писать другой воркер — пакет пир→пир или пакет из TUN. */
                pthread_mutex_lock(&g_tx_lock[s - g_sess]);
                int what = xs_conn_on_seg(&s->conn, &seg, now);
                pthread_mutex_unlock(&g_tx_lock[s - g_sess]);
                if (what < 0) { sess_free(w, s); continue; }
                if (what != 1) continue;

                if (s->phase == PH_SYN) { w->d_hs++; hs_step(w, s, &seg, g_conf.listen_port, now); continue; }
                if (s->phase == PH_HS) { w->d_hs++; hs_confirm(w, s, &seg, now); continue; }
                /* Не наш вовсе: байты идут настоящему серверу как есть. */
                if (s->phase == PH_PROXY) { decoy_up(w, s, &seg, now); continue; }
                w->d_data++;

                /* Сборка записи, которая могла быть разрезана между сегментами. Она же
                 * предфильтр: сегмент, не начинающийся с заголовка записи и не продолжающий
                 * начатую, отбрасывается до всякой криптографии. */
                const uint8_t *body, *hdr;
                size_t body_n;
                uint32_t rel;
                if (!xs_reasm_feed(&s->reasm, seg.seq, s->conn.isn_rx, seg.payload, seg.plen,
                                   &body, &body_n, &hdr, &rel))
                    continue;
                if (xs_win_check(&s->win, rel) != 0) continue;
                /* Расшифровка НА МЕСТЕ: у целой записи — прямо в приёмной строке, у собранной —
                 * в буфере сборки. Пересылку другому пиру это не удорожает: копия туда всё равно
                 * нужна, и делается она ниже одним memmove на кадр. */
                uint8_t *ct = (uint8_t *)(uintptr_t)body;
                if (tls13_aead_open(&s->rx, rel, hdr, XS_REC_HDR, ct, body_n) != 0)
                    continue;
                xs_win_commit(&s->win, rel);
                /* Живость сессии отмечается ЗДЕСЬ, а не на приёме сегмента: доказательством служит
                 * сошедшийся тег, а не сам факт, что в четвёрку кто-то написал. См. last_auth. */
                XSH_STORE(s->last_auth, now);
                size_t pn = body_n - XS_TAG;
                struct hub_fctx fc = { w, s, now };
                if (pn && ct[0] == XS_CTL_BATCH) {
                    if (xs_batch_iter(ct, pn, hub_frame_cb, &fc) != 0) w->d_bad++;
                } else {
                    hub_frame(w, s, ct, pn, now);
                }
            }
            if (got < XSH_BATCH) break;
          }
        }

        /* ---- из ядра (интернет и локальные ответы) --------------------------
         *
         * Это ГЛАВНОЕ направление загрузки, и именно здесь пачка окупается: подряд идущие пакеты
         * одному и тому же пиру уезжают одной записью, которая больше сегмента и потому режется
         * между ними — ровно так ведёт себя настоящий TLS (см. xswire.h). Ждать ради пачки нечего:
         * берётся только то, что уже прочитано.
         *
         * Пачка собирается на ОДНОГО получателя: у каждой сессии свои ключи и свой номер
         * последовательности, и «одна запись двум пирам» бессмысленна. */
        if (n > 0 && (fds[1].revents & POLLIN)) {
            struct sess *dst = NULL;
            uint8_t *pay = w->row + XS_HDR_ROOM;
            size_t off = XS_BATCH_HDR;
            int frames = 0;
            for (int i = 0; i < XSH_BATCH * XS_BATCH_FRAMES_MAX; i++) {
                int max = dst ? XSH_LOAD(dst->batch_max) : XS_BATCH_FRAMES_MAX;
                if (dst && now < XSH_LOAD(dst->cool_until)) max = 1;
                if (frames >= max) break;
                if (frames > 0 && off + 2 + XS_MTU_DEF + XS_TAG > XS_MAX_RECORD) break;
                ssize_t r = tun_read_packet(&w->tun, pay + off + 2, XS_MTU_DEF);
                if (r <= 20) break;
                uint32_t dip;
                memcpy(&dip, pay + off + 2 + 16, 4);
                int to = xs_route(&g_router, ntohl(dip), &w->rcache);
                int16_t di = to >= 0 ? peer_pick(to, pay + off + 2, (size_t)r) : -1;
                if (di < 0) continue;                          /* нет пира — отбросить */
                struct sess *d = &g_sess[di];
                /* Здесь подрезка ИМЕННО по получателю, а не по минимуму двух, как на пути
                 * пир→пир: пакет пришёл из ядра, и обратный поток пойдёт через тот же
                 * единственный тоннель — тоннель получателя. Второго тоннеля в этом пути нет. */
                int dmtu = XSH_LOAD(d->mtu);
                if (dmtu > 0) xs_mss_clamp(pay + off + 2, (size_t)r, dmtu);
                if (dst && d != dst) {
                    /* Пакет другому пиру закрывает набор. Его самого переносим в начало и делаем
                     * первым кадром следующей записи: откладывать его до следующего круга значило
                     * бы менять порядок пакетов в потоке. */
                    hub_send_frames(w, dst, pay, off, frames);
                    memmove(pay + XS_BATCH_HDR + 2, pay + off + 2, (size_t)r);
                    off = XS_BATCH_HDR;
                    frames = 0;
                }
                dst = d;
                pay[off] = (uint8_t)((size_t)r >> 8);
                pay[off + 1] = (uint8_t)((size_t)r & 0xFF);
                off += 2 + (size_t)r;
                frames++;
            }
            if (frames > 0 && dst) hub_send_frames(w, dst, pay, off, frames);
        }

        if (w->debug && now - d_last >= 1000) {
            fprintf(stderr, LOG_I "воркер %d: сегментов %llu, битых %llu, чужих %llu, SYN %llu, "
                                  "рукопожатий %llu, данных %llu, SYN в живую сессию %llu, "
                                  "кадров IPv6 %llu, неопознанных к прикрытию %llu, "
                                  "отказов при полной таблице %llu\n",
                    w->id, w->d_seg, w->d_bad, w->d_alien, w->d_syn, w->d_hs, w->d_data,
                    w->d_syn_est, w->d_ipv6, w->d_decoy, w->d_full);
            d_last = now;
        }

        /* ---- обслуживание СВОИХ сессий -------------------------------------- */
        for (int i = w->base; i < w->base + w->cap; i++) {
            struct sess *s = &g_sess[i];
            if (s->phase == PH_FREE) continue;
            /* Дорожка неопознанного живёт по своим срокам, и они куда короче простоя туннеля:
             * прибор, которому нечего сказать, не должен занимать сокет к прикрытию три минуты, а
             * прикрытие, не ответившее на connect за пять секунд, хуже честного оповещения. */
            if (s->phase == PH_PROXY) {
                long long lim = s->up_ready ? XSH_DECOY_IDLE_MS : XSH_DECOY_CONN_MS;
                if (now - s->up_at > lim) {
                    if (s->up_ready) xs_conn_send(&s->conn, 0x11 /* FIN|ACK */, NULL, 0, 0);
                    else hub_alert(s);
                    sess_free(w, s);
                    continue;
                }
                /* Подтверждения этой сессии идут тем же порядком, что у пиров: прибор говорит
                 * настоящий TCP, и отсутствие отложенного подтверждения он бы заметил. */
                sess_tick_locked(s, now);
                continue;
            }
            /* Проба переезда: пир поднялся заново, и надо выяснить, ведёт ли ЭТА сессия ещё
             * куда-нибудь. Пустая запись уходит и должна вернуться ответом; молчание после трёх
             * попыток означает, что точка мертва, и слот освобождается немедленно.
             *
             * Освободить надо ИМЕННО привязку пир→сессия, и в первую очередь её: получателя
             * выбирает хеш потока среди живых соединений пира, поэтому мёртвый слот означает не
             * задержку, а потерю доли потоков целиком. Саму сессию доуберёт уборка ниже.
             *
             * ОТВЕТОМ СЧИТАЕТСЯ ЛЮБОЙ ПРИНЯТЫЙ СЕГМЕНТ, а не подтверждённая запись, и это
             * единственно возможная мерка: на пустую запись пир отвечает голым подтверждением TCP
             * через XSC_ACK_MS (40 мс), а записью ему отвечать нечем — кадра «ответь мне» в
             * протоколе нет, и своя пустая запись уйдёт от него только по его же keepalive, то
             * есть через секунды. Мерить пробу подтверждённым трафиком значило бы объявлять
             * мёртвым живое соединение на покое. Слабее это ничего не делает: посторонний,
             * бьющий в четвёрку, мог держать сессию живой против XSC_DEAD_MS и до правки. А
             * уборка по простою считается по подтверждённому — см. sess_quiet_since. */
            if (s->phase == PH_EST && XSH_LOAD(s->roam_check) != 0) {
                if (s->roam_sent > 0 && s->conn.last_rx >= s->roam_first) {
                    /* Ответила — путь жив. Счётчики обнуляются ОБА: следующая проба обязана
                     * начаться с первой попытки, иначе она снимет сессию, не спросив. */
                    XSH_STORE(s->roam_check, 0);
                    s->roam_sent = 0;
                    s->roam_next = s->roam_first = 0;
                } else if (s->roam_sent >= XSH_ROAM_PROBES && now >= s->roam_next) {
                    /* Отпечаток считается ТОЛЬКО когда пир опознан: подсунуть xs_key_fp
                     * непроинициализированный буфер вместо ключа значило бы читать мусор — и
                     * печатать его человеку как имя пира. */
                    char fp[12] = "?";
                    if (s->peer >= 0) xs_key_fp(g_conf.peer[s->peer].pub, fp);
                    struct in_addr in;
                    in.s_addr = s->conn.daddr;
                    fprintf(stderr, LOG_I "пир %s: точка %s:%u не ответила на пробу — снимаю её "
                                          "слот сразу, без ожидания простоя\n",
                            fp, inet_ntoa(in), s->conn.dport);
                    if (s->peer >= 0 && s->conn_id >= 0) {
                        pthread_mutex_lock(&g_ctl);
                        if (g_peer_sess[s->peer][s->conn_id] == (int16_t)i)
                            g_peer_sess[s->peer][s->conn_id] = -1;
                        pthread_mutex_unlock(&g_ctl);
                    }
                    XSH_STORE(s->roam_check, 0);
                    sess_free(w, s);
                    continue;
                } else if (now >= s->roam_next) {
                    if (s->roam_sent == 0) s->roam_first = now;
                    send_to(w, s, w->row, 0, now);
                    s->roam_sent++;
                    s->roam_next = now + XSH_ROAM_PROBE_MS;
                }
            }
            if (now - sess_quiet_since(s) > XSH_IDLE_MS) { sess_free(w, s); continue; }
            /* Смещённая сессия: пир пересоединился с другого порта, привязка пир→сессия
             * указывает уже не на нас. Убирает её именно ВЛАДЕЛЕЦ — тот, в чьём индексе лежит
             * её запись; сделать это из чужого потока значило бы править чужую таблицу. */
            if (s->phase == PH_EST && s->peer >= 0 && s->conn_id >= 0) {
                int16_t cur = g_peer_sess[s->peer][s->conn_id];
                if (cur >= 0 && cur != (int16_t)i) { sess_free(w, s); continue; }
            }
            /* Обратная связь по сборке: если у НАС не собираются записи пира, сказать об этом
             * обязаны мы — уменьшить пачку может только он. */
            if (s->phase == PH_EST && s->reasm.dropped > s->last_drops &&
                now - s->last_report >= XSH_REASM_REPORT_MS) {
                size_t ln = xs_loss_build(w->row + XS_HDR_ROOM, 8,
                                          (int)(s->reasm.dropped - s->last_drops));
                if (ln && send_to(w, s, w->row, ln, now) == 0) {
                    s->last_drops = s->reasm.dropped;
                    s->last_report = now;
                }
            }
            /* Рост пачки на чистом пути: медленно вверх, мгновенно вниз (см. hub_frame). */
            int bm = XSH_LOAD(s->batch_max);
            if (!g_compat && s->phase == PH_EST && now >= XSH_LOAD(s->cool_until) &&
                now - s->last_grow >= XSH_REASM_GROW_MS && bm < XS_BATCH_FRAMES_MAX) {
                bm *= 2;
                if (bm > XS_BATCH_FRAMES_MAX) bm = XS_BATCH_FRAMES_MAX;
                XSH_STORE(s->batch_max, bm);
                s->last_grow = now;
            }
            /* Пустая запись и есть keepalive: длина нагрузки ноль, тип кадра пир опознаёт по
             * пустоте (xs_frame_kind). Отдельного вида кадра для этого не нужно.
             *
             * ИНТЕРВАЛ С РАЗБРОСОМ, а не ровный: пакет одного размера ровно каждые десять секунд не
             * встречается ни в одном браузерном соединении и находится подсчётом пауз между мелкими
             * пакетами. Разброс ±20% не стоит ничего. */
            if (s->phase == PH_EST && !s->keep_next) s->keep_next = XSH_KEEPALIVE_MS;
            if (s->phase == PH_EST && s->conn.last_rx > s->conn.last_tx &&
                now - s->conn.last_tx >= s->keep_next) {
                send_to(w, s, w->row, 0, now);
                uint32_t j = 0;
                xc_random((unsigned char *)&j, sizeof(j));
                s->keep_next = XSH_KEEPALIVE_MS * 8 / 10 +
                               (long long)(j % (uint32_t)(XSH_KEEPALIVE_MS * 4 / 10 + 1));
            }
            sess_tick_locked(s, now);
        }
    }
    return NULL;
}

int cmd_xsteer_hub(const char *conf_path) {
    const char *path = conf_path ? conf_path : "/etc/steer/xsteer/hub.conf";
    char err[256];
    if (xs_conf_load(path, XS_ROLE_HUB, &g_conf, &g_sec, err, sizeof(err)) != 0) {
        fprintf(stderr, LOG_W "%s\n", err);
        return 2;
    }
    if (g_conf.device[0])
        snprintf(g_dev, sizeof(g_dev), "%s", g_conf.device);
    for (int i = 0; i < XS_PEERS_MAX; i++)
        for (int c = 0; c < XS_CONNS_MAX; c++) g_peer_sess[i][c] = -1;
    for (int i = 0; i < XSH_MAX_SESS; i++) {
        g_sess[i].conn.fd = -1;
        g_sess[i].peer = -1;
        g_sess[i].conn_id = -1;
        g_sess[i].up_fd = -1;
    }
    xs_router_build(&g_router, g_conf.peer, g_conf.peer_n);

    int debug = getenv("STEER_XS_DEBUG") != NULL;
    g_compat = getenv("STEER_XS_COMPAT") != NULL;
    if (g_compat)
        fprintf(stderr, LOG_I "STEER_XS_COMPAT: везу по одному кадру в записи — формат предыдущей "
                              "версии, для пиров, которые ещё не обновлены\n");

    /* ---- воркеры ---------------------------------------------------------- */
    /* СКОЛЬКО ПОТОКОВ, и почему не «по числу ядер».
     *
     * Степень двойки обязательна: раскладка делается маской по младшим битам порта источника, а
     * у cBPF нет деления. Округляем ВНИЗ.
     *
     * Верхний предел — не только ядра, но и число ВОЗМОЖНЫХ СЕССИЙ, и это выяснилось замером.
     * Каждый воркер держит свой сырой сокет, а ядро на КАЖДЫЙ локально доставляемый TCP-пакет
     * клонирует skb для каждого такого сокета — и только потом фильтр отбрасывает лишние. То
     * есть лишний воркер платится на всём трафике машины, а приносит пользу только если ему
     * достанется своя сессия. Сессий не больше, чем пиров, умноженных на число соединений,
     * которое пир может открыть.
     *
     * Числа с tests/run-xsteer.sh (два пира по одному соединению, сумма; та же машина):
     *     1 воркер — 0,67 Гбит/с;  2 — 1,20;  4 — 1,11;  8 — 0,97.
     * Видно и пользу, и цену: второй воркер почти удваивает, восьмой уже отнимает.
     *
     * Переменная окружения нужна для замеров: утверждение «многопоток дал столько-то» без
     * возможности вернуться к одному потоку на том же железе проверить нельзя (та же причина,
     * что у STEER_TUN_NOGSO). */
    long cores = sysconf(_SC_NPROCESSORS_ONLN);
    int want = cores > 0 ? (int)cores : 1;
    if (want > (int)g_conf.peer_n * XS_CONNS_MAX) want = (int)g_conf.peer_n * XS_CONNS_MAX;
    const char *env = getenv("STEER_XS_WORKERS");
    if (env) { long v = strtol(env, NULL, 10); if (v >= 1) want = (int)v; }
    if (want > XSH_WORKERS_MAX) want = XSH_WORKERS_MAX;
    if (want < 1) want = 1;
    int n = 1;
    while (n * 2 <= want) n *= 2;
    g_workers = n;

    /* Очереди TUN: по одной на воркера. Ядро само раскладывает пакеты по очередям, хэшируя
     * поток, — и хэш у него симметричный, поэтому обе половины одного соединения попадают в
     * одну очередь. Меньше очередей, чем воркеров, не беда: лишние воркеры возьмут очередь по
     * кругу, просто будут делить её с соседом. */
    struct tun_dev tq[XSH_WORKERS_MAX];
    const char *dev = g_dev;
    int nq = tun_open(tq, n, dev);
    if (nq < 0) {
        fprintf(stderr, LOG_W "нет /dev/net/tun (на LXC и OpenVZ его часто нет вовсе) — "
                              "хаб не может отдавать трафик наружу\n");
        return 1;
    }
    if (nq < n)
        fprintf(stderr, LOG_I "очередей TUN дали %d на %d воркеров — часть будет делить очередь\n",
                nq, n);

    /* TUN переводится в НЕБЛОКИРУЮЩИЙ режим, и это не тонкая настройка, а условие
     * работоспособности. Пакеты читаются пачкой, до XS*_BATCH за одно событие poll: на
     * блокирующем дескрипторе второе чтение, когда пакетов больше нет, останавливает весь
     * цикл НАВСЕГДА. Именно так и вышло при первом живом прогоне — хаб печатал «слушаю» и
     * замолкал, не отвечая на SYN, и снаружи это выглядело как «сеть не доходит». */
    {
        /* Неблокирующими делаются ВСЕ очереди: воркер, у которого очередь блокирующая, встанет
         * на втором чтении так же, как вставал единственный поток до появления очередей. */
        for (int q = 0; q < nq; q++) {
            int tfl = fcntl(tq[q].fd, F_GETFL, 0);
            fcntl(tq[q].fd, F_SETFL, tfl | O_NONBLOCK);
        }
        hub_dev_up(dev);
    }


    for (int i = 0; i < XSH_MAX_SESS; i++) pthread_mutex_init(&g_tx_lock[i], NULL);

    int per = XSH_MAX_SESS / n;
    for (int i = 0; i < n; i++) {
        struct worker *w = &g_w[i];
        w->id = i;
        w->n = n;
        w->mask = (uint16_t)(n - 1);
        w->base = i * per;
        w->cap = per;
        w->listen_port = g_conf.listen_port;
        w->debug = debug;
        w->tun = tq[i % nq];
        xs_sidx_reset(&w->idx);
        /* Свой сырой сокет с раскладкой. Приём — БЕЗ connect: пиров много и заранее они
         * неизвестны; отвечает каждой свой сокет сессии. */
        w->rx = socket(AF_INET, SOCK_RAW, IPPROTO_TCP);
        if (w->rx < 0) { perror("steer: raw"); return 1; }
        int fl = fcntl(w->rx, F_GETFL, 0);
        fcntl(w->rx, F_SETFL, fl | O_NONBLOCK);
        int rcvbuf = 1 << 20;
        setsockopt(w->rx, SOL_SOCKET, SO_RCVBUF, &rcvbuf, sizeof(rcvbuf));
        if (n == 1) obfs_filter_port(w->rx, (uint16_t)g_conf.listen_port);
        else obfs_filter_port_shard(w->rx, (uint16_t)g_conf.listen_port, w->mask, (uint16_t)i);
        /* Сокет для тех, чьей сессии нет: им отвечают RST, чтобы пир узнала о перезапуске
         * хаба сразу, а не по тишине через XSC_DEAD_MS. */
        w->tx0 = socket(AF_INET, SOCK_RAW, IPPROTO_TCP);
        if (w->tx0 >= 0) obfs_filter_none(w->tx0);
    }

    if (obfs_guard_up('x', "hub", NULL, g_conf.listen_port, 1) != 0)
        fprintf(stderr, LOG_W "правило против RST не встало: если порт %d не закрыт политикой "
                              "firewall, ядро будет рвать сессии\n", g_conf.listen_port);

    fprintf(stderr, LOG_I "слушаю поддельный TCP :%d, пиров %zu, устройство %s, воркеров %d "
                          "(по %d сессий)\n",
            g_conf.listen_port, g_conf.peer_n, dev, n, per);
    /* Имена прикрытия разрешаются ЗДЕСЬ — при подъёме, до создания потоков и до первого
     * прохода цикла. Позже это сделать негде: в цикле воркера нет ни одного блокирующего
     * вызова, а getaddrinfo — именно он. */
    hub_decoy_resolve();
    /* Что отвечаем неопознанным — говорится вслух при подъёме: настройка защиты, о которой
     * нельзя узнать из журнала, проверяется только зондированием собственного порта. */
    switch (g_conf.decoy) {
    case XS_DECOY_SILENT:
        fprintf(stderr, LOG_I "неопознанным: не отвечать (отличимо: открытый порт, замолчавший "
                              "на ClientHello)\n");
        break;
    case XS_DECOY_RESET:
        fprintf(stderr, LOG_I "неопознанным: RST\n");
        break;
    case XS_DECOY_PROXY:
        fprintf(stderr, LOG_I "неопознанным: отдавать настоящему серверу %s:%d (не больше %d "
                              "одновременно), имён прикрытия разрешено %d из %zu\n",
                g_conf.decoy_dest, g_conf.decoy_port, XSH_DECOY_MAX, g_decoy_map_n,
                g_conf.decoy_sni_n);
        break;
    default:
        fprintf(stderr, LOG_I "неопознанным: фатальное оповещение TLS (отличимо от настоящего "
                              "сервера с сертификатом; см. Decoy в конфигурации)\n");
        break;
    }

    /* Воркер 0 работает в этом же потоке: при n == 1 процесс ведёт себя ровно так, как до
     * появления потоков вовсе, и отладка одного потока остаётся возможной. */
    pthread_t th[XSH_WORKERS_MAX];
    for (int i = 1; i < n; i++)
        if (pthread_create(&th[i], NULL, worker_loop, &g_w[i]) != 0) {
            fprintf(stderr, LOG_W "поток %d не создался: работаем меньшим числом\n", i);
            g_w[i].rx = -1;
        }
    worker_loop(&g_w[0]);
    obfs_guard_down();
    xs_conf_wipe(&g_sec);
    return 1;
}
