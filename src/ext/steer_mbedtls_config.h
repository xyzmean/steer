/* Урезанная конфигурация mbedtls: только то, что нужно клиенту VLESS/Reality.
 *
 * Полная сборка mbedtls — это ~700 КБ кода: серверная половина TLS, DTLS, RSA, десяток
 * шифров, работа с файлами сертификатов. Клиенту Reality из этого не нужно ничего, кроме
 * TLS 1.3 с X25519 и двумя AEAD, и разница в весе решает, влезет ли пакет на роутер.
 *
 * Отсюда правило для всего файла: включается ровно то, чем пользуется код, и каждое
 * исключение объяснено — иначе через полгода никто не рискнёт это тронуть.
 */
#ifndef STEER_MBEDTLS_CONFIG_H
#define STEER_MBEDTLS_CONFIG_H

/* ---- платформа ------------------------------------------------------------ */
/* Стандартная libc есть (musl), своих оболочек не нужно. */
#define MBEDTLS_PLATFORM_C

/* Ассемблерные вставки библиотеки. Обязательны, и это не «немного быстрее».
 *
 * Их два потребителя, и оба на горячем пути:
 *
 *   bn_mul.h — умножение с накоплением для длинной арифметики. На нём стоит X25519, а его
 *   на каждое соединение считается ТРИ раза (своя пара, секрет Reality, секрет TLS). Есть
 *   вставки под mips32, armv7 и aarch64 — то есть под всё, на чём steer работает;
 *
 *   aesni.h/aesce.c — без MBEDTLS_HAVE_ASM аппаратный AES на x86_64 недоступен вовсе:
 *   сборка падает с «MBEDTLS_AESNI_C defined, but neither intrinsics nor assembly
 *   available», потому что интринсики требуют -maes, а его при -mcpu=baseline нет.
 *
 * В конфигурации библиотеки по умолчанию это включено, и пока наш файл не читался, оно
 * работало само собой. Стоило файлу заработать — и отсутствие строки стало настоящей
 * потерей, а на x86_64 ещё и ошибкой сборки. */
#define MBEDTLS_HAVE_ASM
#define MBEDTLS_HAVE_TIME          /* TLS 1.3 нужен только для проверки срока — но
                                    * сертификат сервера мы не проверяем (см. ниже),
                                    * поэтому время используется лишь как источник
                                    * энтропии в сидировании. */

/* ---- чего здесь НЕТ: TLS-стека библиотеки ----------------------------------
 *
 * Ни MBEDTLS_SSL_TLS_C, ни SSL_CLI_C, ни X.509, ни PK, ни RSA, ни ECDSA, ни ASN.1, ни OID.
 * Раньше они были включены — с объяснением «сертификат сервера надо хотя бы прочитать,
 * чтобы рукопожатие завершилось». Объяснение неверное: рукопожатие ведёт tls13.c, он
 * разбирает записи сам и Certificate просто добавляет в транскрипт как байты, ни разу не
 * вызвав mbedtls_x509_* или mbedtls_ssl_*. Проверяется одной командой:
 *
 *     grep -rho 'mbedtls_[a-z0-9_]*' src/ | sort -u
 *
 * В ответе только sha256/sha512, md, hkdf, gcm, chachapoly, ecp и mpi — ровно то, что
 * включено ниже.
 *
 * Цена ошибки была не в килобайтах, а в том, что её не было видно: собранный бинарник
 * содержал таблицы OID и строки вида «id-ce-certificatePolicies», то есть код, который
 * никогда не исполняется, но занимает флеш на overlay в 6,9 МБ.
 *
 * ---- криптография: только то, чем пользуется код --------------------------- */
#define MBEDTLS_BIGNUM_C
#define MBEDTLS_ECP_C
#define MBEDTLS_ECP_DP_CURVE25519_ENABLED       /* X25519 — на нём Reality и держится. */

/* P-256 здесь БЫЛ и убран. Он нужен в СПИСКЕ ГРУПП нашего ClientHello — потому что он есть
 * у браузеров, — но список этот пишется байтами в reality.c, и библиотека о нём не знает.
 * Считать шифрование на P-256 нам не придётся никогда: key_share мы отправляем только
 * X25519, и сервер, выбравший другую группу, не пройдёт разбор ServerHello вовсе. Кривая в
 * сборке означала только её таблицы в бинарнике. */

/* Шифры AEAD: ровно два, те же, что предлагает браузер. */
#define MBEDTLS_AES_C
#define MBEDTLS_GCM_C                           /* AES-128-GCM: первый набор в списке
                                                 * у Chrome. */
#define MBEDTLS_CHACHA20_C
#define MBEDTLS_POLY1305_C
#define MBEDTLS_CHACHAPOLY_C                    /* На роутере без AES-NI ChaCha
                                                 * заметно быстрее AES, и сервера её
                                                 * обычно предлагают. */
/* Слой cipher нужен GCM: mbedtls_gcm_setkey заводит блочный шифр через него, если сборка
 * не собрана с block_cipher_internal. Проверено отключением — сборка падает на
 * mbedtls_cipher_setup. */
#define MBEDTLS_CIPHER_C

/* Аппаратный AES там, где он есть. Весь трафик туннеля проходит через AEAD ровно один раз,
 * и на Cortex-A53 разница между программным AES и инструкциями доходит до пяти раз.
 *
 * Включать безопасно: mbedtls определяет наличие инструкций ВО ВРЕМЯ РАБОТЫ (getauxval для
 * aarch64, cpuid для x86) и молча уходит на программный путь, если их нет. То есть один
 * бинарник на aarch64_generic остаётся годным и для ядра без расширений криптографии.
 *
 * Выбор шифра при этом НЕ наш: его называет сервер из списка в нашем ClientHello. Здесь
 * раньше стояло рассуждение «поставить ChaCha первой значит изменить отпечаток и стать
 * заметным, поэтому ускоряем то, что выберут, а не выбираем то, что быстрее». Вывод был
 * НЕВЕРЕН, и стоил он дорого: на MIPS туннель отдавал 10 Мбит/с при канале 48.
 *
 * Неверен потому, что браузер в этой ситуации сам меняет порядок. BoringSSL спрашивает
 * EVP_has_aes_hardware() и без инструкций AES ставит ChaCha20 первой — то есть браузерных
 * порядков ДВА, и на процессоре без AES браузерным является именно тот, где ChaCha впереди.
 * Держать AES первым на MIPS значило не «совпадать с Chrome», а изображать Chrome с чужого
 * железа. Порядок выбирается в reality.c по cpu_has_aes(), там же и числа.
 *
 * MIPS в списке нет: расширений AES у 24kc не существует, и там потолок задаёт ChaCha. */
/* STEER_NO_AES_ACCEL отключает ускорение принудительно — этим и пользуется build/bench.sh,
 * чтобы замерить «во сколько раз помогают инструкции AES» на том же железе и той же
 * библиотеке. Без такой возможности утверждение о пятикратной разнице нельзя перепроверить. */
#if !defined(STEER_NO_AES_ACCEL)
#if defined(__aarch64__)
#define MBEDTLS_AESCE_C
#elif defined(__x86_64__) || defined(__i386__)
/* ОДНОГО ЭТОГО ОПРЕДЕЛЕНИЯ НЕДОСТАТОЧНО ДЛЯ БЫСТРОГО AES, и это выяснилось замером.
 * mbedtls выбирает между ассемблерным путём и путём на intrinsics по флагам набора команд, а
 * они задаются сборкой: без `-maes -mpclmul -msse4.1` у файла aesni.c берётся ассемблерный, и
 * AES-128-GCM на x86_64 даёт 309 МБ/с вместо 450. Числа и обоснование — в build/build-ext.sh
 * рядом с AESNI_FLAGS. */
#define MBEDTLS_AESNI_C
#endif
#endif

/* MBEDTLS_GCM_LARGE_TABLE здесь БЫЛ и убран замером.
 *
 * Рассуждение было такое: с аппаратным AES узким местом становится GHASH, а таблица на 8 бит
 * вместо 4 вдвое сокращает шаги. Рассуждение неверно, и это видно в самой библиотеке:
 * gcm_set_acceleration выбирает MBEDTLS_GCM_ACC_AESNI/AESCE, если инструкции есть, и тогда
 * умножение в поле считает PCLMULQDQ или PMULL, а таблица не используется ВООБЩЕ. Замер на
 * x86_64 (build/bench.sh): 331,9 против 328,5 МБ/с на AES-128-GCM, то есть разницы нет.
 *
 * А где инструкций нет — MIPS, armv7 — там нет и аппаратного AES, наш ClientHello ставит
 * ChaCha20 первой, сервер её и выбирает, и GCM не считается вовсе. То есть таблица дорога
 * (4 КБ на направление, 2,6 МБ на 320 соединений) ровно там, где бесполезна.
 *
 * Проверить обратное можно, не трогая этот файл: build/bench.sh собирает вариант с
 * -DMBEDTLS_GCM_LARGE_TABLE отдельно. */

#define MBEDTLS_SHA256_C
#define MBEDTLS_SHA384_C
#define MBEDTLS_SHA512_C
#define MBEDTLS_MD_C
#define MBEDTLS_HKDF_C                          /* Вывод ключей TLS 1.3 и
                                                 * аутентификатора Reality. */

/* ---- энтропия: её здесь нет ------------------------------------------------
 *
 * Случайность берётся у ядра через getrandom(2) напрямую — см. fill_random в reality.c.
 * ENTROPY_C и CTR_DRBG_C были включены, но не вызывались ни разу: DRBG всё равно пришлось
 * бы сидировать тем же getrandom, а лишний слой — это лишнее место для ошибки ровно там,
 * где ошибка не обнаруживается тестом. */

/* ---- чего нет и почему ----------------------------------------------------- */
/* MBEDTLS_SSL_SRV_C          — steer не сервер;
 * MBEDTLS_SSL_PROTO_DTLS     — UDP-TLS не используется;
 * MBEDTLS_FS_IO              — на роутере нечего читать с диска;
 * MBEDTLS_DES_C, CAMELLIA... — устаревшие шифры, которых нет у браузеров;
 * MBEDTLS_DHM_C              — классический DH: у TLS 1.3 его нет вовсе;
 * MBEDTLS_SELF_TEST          — тесты в бинарнике на роутере ни к чему;
 * MBEDTLS_ERROR_C            — текстовые описания ошибок это ~10 КБ строк; коды
 *                              печатаются числом, а расшифровка есть в документации. */

/* check_config.h здесь НЕ включается, хотя раньше включался.
 *
 * С версии 3.0 библиотека включает его сама — и делает это ПОСЛЕ своих файлов доводки
 * конфигурации, где выводятся производные признаки вроде MBEDTLS_MD_CAN_SHA256. Включённый
 * вручную, он проверял конфигурацию до доводки и ругался на пустом месте: «MBEDTLS_MD_C
 * defined, but no hash algorithm» при включённых SHA-256 и SHA-512. Пока файл не читался
 * вовсе (см. выше про имя), этого никто не видел. */
#endif
