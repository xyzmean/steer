/* TUN-устройство и разбор пакетов. Почему TUN, а не SOCKS — в tun.c. */
#ifndef STEER_TUN_H
#define STEER_TUN_H
#include <stdint.h>
#include <sys/uio.h>
#include <stddef.h>
#include <sys/types.h>

#define TUN_ENODEV (-40)   /* нет /dev/net/tun — не установлен kmod-tun */
#define TUN_ESETUP (-41)

struct flow_key {
    uint32_t src, dst;      /* в сетевом порядке, как в пакете: так и уходят в tcp_build */
    /* Порты в ХОСТОВОМ порядке: ip_parse собирает их из байт вручную, то есть
     * преобразование уже сделано. Применять к ним ntohs — значит перевернуть дважды:
     * порт 80 превращался в 20480, соединение уходило не туда, и выглядело это как
     * «сервер не отвечает». Отсюда суффикс в имени — чтобы вопрос не возникал. */
    uint16_t sport, dport;
    uint8_t proto;
    uint8_t tcp_flags;
    uint32_t seq, ack;
    /* Окно, объявленное отправителем пакета. Нужно потому, что повторной передачи у нас
     * нет: обогнать клиента — значит потерять сегмент навсегда и подвесить соединение.
     * Без этого поля обгонять его было нечем и незачем. */
    uint16_t window;
    /* Множитель окна из опций SYN. Заполняется только для SYN — дальше опций не бывает,
     * а множитель на соединение постоянен. Настоящее окно = window << wscale. */
    uint8_t wscale;
    /* Пакет — ПЕРВЫЙ фрагмент неполной датаграммы (флаг MF). Продолжения ip_parse не
     * отдаёт вовсе: заголовка в них нет, разбирать нечего. Нужно из-за UDP — там неполная
     * датаграмма это не «пакет не дойдёт», а «отправим серверу обрубок и не заметим». */
    uint8_t frag;
};

/* Флаги TCP, которые нас интересуют. */
#define TCP_FIN 0x01
#define TCP_SYN 0x02
#define TCP_RST 0x04
#define TCP_PSH 0x08
#define TCP_ACK 0x10

/* MSS, который мы объявляем клиенту в SYN-ACK: MTU устройства минус заголовки IP и TCP.
 *
 * Объявлять обязательно. Без опции MSS клиент обязан считать её равной 536 байтам (RFC
 * 1122), и тогда мегабайт едет 1860 пакетами вместо 690 — а каждый пакет у нас проходит
 * полный цикл разбора, отправки и подтверждения в одном потоке. Замер до и после виден
 * прямо в скорости выгрузки. */
#define TUN_MSS 1460

/* Сколько байт данных отдаём клиенту ОДНИМ write при включённой разгрузке.
 *
 * Больше записи TLS смысла не имеет: за раз от сервера всё равно приезжает не больше её,
 * то есть 16384 байта. Меньше — значит платить за лишние вызовы там, где ядро готово
 * принять всё сразу. */
#define TUN_GSO_MAX 16384

/* Заголовок IP+TCP без опций. Данные к нему не приклеиваются: они уходят отдельным
 * элементом writev, и лишнего копирования потока не остаётся вовсе. */
#define TUN_HDR_LEN 40

/* MTU устройства. Не спрашивается у ядра, а задаётся здесь: устройство поднимаем мы сами и
 * MTU ему не меняем, а TUN_MSS выше посчитан от этого же числа (1500 - 20 - 20). Два
 * значения, выведенных из одного, обязаны стоять рядом — иначе одно поправят, а второе
 * останется. */
#define TUN_MTU 1500

/* Сколько данных IP-уровня влезает в один пакет: MTU минус заголовок IPv4. Датаграмма
 * больше этого нарезается на фрагменты (см. udp_write_to_client). */
#define UDP_MTU_PAYLOAD (TUN_MTU - 20)

/* Самая большая датаграмма, которую мы берёмся нести.
 *
 * Не 65535 не из лени: под неполную датаграмму нужен буфер НА ПОТОК (сборка идёт между
 * чтениями), и 64 КБ на соединение при 320 соединениях — это 20 МБ на роутере с 240.
 * Четыре килобайта покрывают всё, что встречается: QUIC и любой игровой трафик держатся
 * в MTU сами, а самый крупный законный случай — ответ DNS с EDNS0, где клиенты объявляют
 * буфер в 4096 байт. Датаграмма крупнее пропускается целиком, но БЕЗ потери синхронизации
 * потока — иначе одна такая ломала бы соединение навсегда. */
#define UDP_DGRAM_MAX 4096

/* Открытое устройство и то, что удалось у него выпросить.
 *
 * gso — самое важное поле в этом файле. С ним один write отдаёт ядру до 16 КБ как ОДИН
 * сегмент с пометкой «нарежь сам по 1460», и ядро нарезает его уже внутри стека, а
 * контрольные суммы досчитывает по ходу (а на многих LAN-картах их считает железо).
 * Без него те же 16 КБ — это двенадцать write и двенадцать проходов по всем данным ради
 * контрольной суммы TCP, вручную, по два байта за итерацию.
 *
 * Именно так работают sing-box и wireguard-go, и именно этим объясняется большая часть
 * разницы в скорости: не крипто, а стоимость отдачи пакетов клиенту. */
struct tun_dev {
    int fd;
    int gso;
    /* gro — склеиваем ли соседние сегменты в одну запись (см. ниже про tun_gro_push).
     * Отдельно от gso, потому что это РАЗНЫЕ вещи: gso — умеет ли устройство принимать
     * пометку нарезки, gro — пользуемся ли мы ею для склейки. Выключается переменной
     * STEER_TUN_NOGRO, и это не отладочный остаток: утверждение «склейка даёт +30%» без
     * возможности вернуться на прежний путь одной переменной проверить на своём железе
     * нельзя — тот же довод, что у STEER_TUN_NOGSO. */
    int gro;
};

/* Открыть устройство, попросив до max_queues очередей. Возвращает, сколько открылось
 * (не меньше одной), или отрицательный код.
 *
 * Несколько очередей (IFF_MULTI_QUEUE) — это основа многопоточности здесь. Каждый поток
 * получает свой дескриптор на то же устройство, и ядро само раскладывает пакеты по
 * очередям, ХЭШИРУЯ ПОТОК. Хэш симметричный (tun.c ядра берёт
 * __skb_get_hash_symmetric), поэтому обе половины одного TCP-соединения попадают в одну
 * очередь — то есть одному потоку, и всегда тому же.
 *
 * Отсюда главное свойство: общих изменяемых данных между потоками НЕТ. Таблица соединений,
 * счётчики и буферы у каждого свои, блокировок нет ни одной. Альтернатива — общая таблица
 * под мьютексом — означала бы, что на каждый пакет берётся замок, а пакетов семьсот на
 * мегабайт; выигрыш от второго ядра ушёл бы в борьбу за него.
 *
 * Ядро без IFF_MULTI_QUEUE не ошибка: тогда открывается одна очередь и работает один
 * поток, ровно как раньше. */
int tun_open(struct tun_dev *d, int max_queues, const char *name);
int ip_parse(const unsigned char *p, size_t n, struct flow_key *k, size_t *payload_off);

/* Прочитать один пакет, сняв заголовок разгрузки, если устройство его добавляет. */
ssize_t tun_read_packet(const struct tun_dev *d, unsigned char *buf, size_t cap);

/* Заголовок для сегмента данных: суммы в нём НЕ считаются — их поставит tun_write_data,
 * потому что только там известно, считать их нам или это сделает ядро. */
void tcp_hdr_build(unsigned char out[TUN_HDR_LEN],
                   uint32_t src, uint32_t dst, uint16_t sport, uint16_t dport,
                   uint32_t seq, uint32_t ack, unsigned char flags,
                   size_t data_n, uint16_t window);

/* Отдать клиенту заголовок вместе с данными. Данные НЕ копируются.
 *
 * Ждёт готовности устройства при заполненной очереди и повторяет: бросить сегмент нельзя,
 * повторной передачи у нас нет, и потерянный сегмент подвесил бы соединение навсегда.
 * Возвращает 0 или -1. */
int tun_write_data(const struct tun_dev *d, unsigned char hdr[TUN_HDR_LEN],
                   const unsigned char *data, size_t data_n);

/* Служебный пакет, собранный tcp_build: суммы в нём уже посчитаны. Без повторов —
 * потерянный SYN-ACK или ACK клиент пришлёт заново сам. */
void tun_write_ctl(const struct tun_dev *d, const unsigned char *pkt, size_t n);

/* ---- СКЛЕЙКА СОСЕДНИХ СЕГМЕНТОВ В ОДНУ ЗАПИСЬ (GRO наоборот) ----------------
 *
 * ЗАЧЕМ. Отдача пакета в TUN — это не «системный вызов», а ПОЛНЫЙ ПРОХОД внутреннего стека:
 * ядро на каждый write собирает skb, гонит его через ip_rcv, tcp_v4_rcv, кладёт в сокет и
 * будит читателя. Профиль живого туннеля (perf по всей машине) показал ровно это: у стороны,
 * которая отдаёт трафик, СВОЁ шифрование занимает 1% времени, а всё остальное — ядро на
 * tun_get_user, __alloc_skb и обвязку вызова, по одному проходу на каждые 1439 байт.
 *
 * Пометив запись как GSO, тот же проход делается ОДИН РАЗ на восемь пакетов: ядро принимает
 * их как один большой сегмент и нарезает уже внутри стека (а сокету-получателю часто отдаёт
 * целиком, без нарезки вовсе). Это тот же приём, которым wireguard-go обгоняет собственную
 * прежнюю версию, и та же разгрузка, которой пользуется tun_write_data.
 *
 * ПОЧЕМУ БЕЗ БУФЕРА, И ЭТО ГЛАВНОЕ РЕШЕНИЕ ЗДЕСЬ. Соблазн — накопить пакеты в буфере на
 * 16-64 КБ и отдать одним куском. Так делать нельзя: буфер нужен НА ОЧЕРЕДЬ, а очередей
 * столько же, сколько соединений, и на роутере с 128 МБ это заметная память, взятая ради
 * пути, который и без неё работает. Но копить и не надо: кадры внутри одной расшифрованной
 * записи уже лежат в памяти ПОДРЯД, и отдать их можно одним writev, перечислив нагрузки
 * векторами. Поэтому здесь нет ни единого байта буфера — только массив векторов и правка
 * заголовка ПЕРВОГО пакета на месте.
 *
 * ПОЧЕМУ НЕ ДОБАВЛЯЕТСЯ НИ МИЛЛИСЕКУНДЫ ЗАДЕРЖКИ. Склеиваются только кадры, которые УЖЕ
 * прочитаны из одной записи; ничего не ждёт следующей. Вызывающий обязан позвать
 * tun_gro_flush в конце обработки записи — тогда пакет не живёт дольше одного круга цикла.
 * Таймеров, окон ожидания и «подождём ещё немного» здесь нет по построению: на роутере
 * задержка дороже пропускной способности, и обменивать одно на другое молча нельзя.
 *
 * ЧТО СКЛЕИВАЕТСЯ. Только то, что ядро потом нарежет обратно БАЙТ В БАЙТ: IPv4 без опций,
 * TCP без опций, один и тот же поток (адреса и порты), подряд идущие номера
 * последовательности, одинаковые ttl, tos, ack и окно, флаги ровно ACK (или ACK|PSH у
 * последнего — PSH и FIN ядро само ставит только на последний кусок). Всё прочее — ICMP,
 * UDP, фрагменты, SYN, RST, изменившееся окно — уезжает отдельной записью, как раньше.
 * Условия строгие нарочно: склеить лишнее означает отдать клиенту поток, в котором
 * переставлены или испорчены байты, а такой отказ ловится только чтением дампа. */
#define TUN_GRO_FRAMES 8      /* столько кадров кладёт в одну запись отправитель */

struct tun_gro {
    /* vnet_hdr + первый пакет целиком + нагрузки остальных. Отсюда и предел набора: ровно
     * TUN_GRO_FRAMES кадров, потому что первый занимает один вектор вместе со своим
     * заголовком. Размер 2 + TUN_GRO_FRAMES давал бы девять кадров при названии «восемь», и
     * стенд tungromatch на этом расхождении и сработал. */
    struct iovec iov[1 + TUN_GRO_FRAMES];
    int      nio;
    unsigned char *first;     /* первый пакет: у него правятся длина и суммы */
    size_t   total_pay;       /* сумма нагрузок всех склеенных */
    size_t   seg;             /* нагрузка первого — она же gso_size */
    size_t   hdr_n;           /* IP + TCP первого пакета: с опциями бывает 52, а не 40 */
    int      frames;
    uint32_t next_seq;        /* какой номер обязан быть у следующего, хостовый порядок */
    unsigned char vh[16];     /* заголовок разгрузки: живёт до writev */
};

static inline void tun_gro_reset(struct tun_gro *g) { g->frames = 0; g->nio = 0; }

/* Отдать пакет, склеивая с накопленным, когда это законно. Пакет ОБЯЗАН оставаться в памяти
 * неизменным до tun_gro_flush — склейка не копирует его. */
void tun_gro_push(const struct tun_dev *d, struct tun_gro *g, unsigned char *pkt, size_t n);

/* Отдать накопленное. Зовётся в конце обработки записи, всегда. */
void tun_gro_flush(const struct tun_dev *d, struct tun_gro *g);

/* Отдать клиенту датаграмму от имени того, к кому он обращался. Датаграмма больше MTU
 * нарезается на фрагменты — собирает их обратно стек клиента. Возвращает 0 или -1.
 *
 * ip_id — номер IP-пакета: осмыслен только при нарезке (по нему клиент склеивает фрагменты
 * одной датаграммы и не путает их с чужими). */
int udp_write_to_client(const struct tun_dev *d, uint32_t src, uint32_t dst,
                        uint16_t sport, uint16_t dport,
                        const unsigned char *data, size_t n, uint16_t ip_id);

/* ICMP «порт недостижим» в ответ на пакет, который туннель нести не умеет: теперь это не
 * UDP (он поддержан), а всё остальное — ICMP, ESP и прочее. Нужен, чтобы клиент получил
 * ОТКАЗ, а не тишину: тишину он трактует как «ещё не ответили» и ждёт. Подробности — в
 * tun.c. */
size_t icmp_unreach_build(unsigned char *out, size_t cap,
                          const unsigned char *orig, size_t orig_n);

/* mss != 0 добавляет опцию MSS, wscale >= 0 — опцию масштаба окна. Обе осмысленны только
 * в SYN и SYN-ACK, в остальных пакетах их просто не бывает. */
size_t tcp_build(unsigned char *out, size_t cap,
                 uint32_t src, uint32_t dst, uint16_t sport, uint16_t dport,
                 uint32_t seq, uint32_t ack, unsigned char flags,
                 const unsigned char *data, size_t data_n, uint16_t window,
                 unsigned mss, int wscale);
#endif
