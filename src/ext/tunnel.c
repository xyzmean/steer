/* Поднять устройство и дать ему адрес.
 *
 * Делает это движок, а не управляющий слой, потому что устройство создаёт тоже движок:
 * между «TUN появился» и «TUN готов нести трафик» нет никого, кому это можно было бы
 * поручить. Без этого apply не находит рабочего устройства, ставит blackhole (при
 * on_fail=drop) и трафик стоит — притом что процесс запущен, узел выбран и в логе всё
 * выглядит успешным. Ровно тот случай, когда «настроено» и «работает» расходятся молча.
 *
 * Адрес нужен не нам: наш клиент читает из TUN пакеты и открывает по ним потоки, source
 * в них не участвует вовсе. Нужен он ядру и фаерволу — маршрут на устройство без адреса
 * ядро считает непригодным для локально порождённых пакетов.
 *
 * 198.51.100.0/24 — это TEST-NET-2 из RFC 5737: диапазон, отведённый под документацию и
 * НЕ маршрутизируемый в интернете. Поэтому он не может столкнуться ни с чужим сервисом,
 * ни с локальной сетью, которую кто-то себе выбрал. Пул fake-IP (198.18.0.0/15) здесь
 * брать нельзя — он занят под другую задачу, и пересечение перепутало бы одно с другим.
 *
 * Номер адреса берётся из таблицы маршрутизации выхода: она уже уникальна и уже лежит в
 * реестре, то есть переживает перезагрузку. Выдумывать для этого второй счётчик значило
 * бы завести второе место, где номера могут разъехаться. */
static void tun_bring_up(const char *dev, int table) {
    char addr[40];
    snprintf(addr, sizeof(addr), "198.51.100.%d/32", 1 + (table % 200));
    const char *a[] = { "ip", "addr", "replace", addr, "dev", dev, NULL };
    run_quiet(a);
    const char *u[] = { "ip", "link", "set", "dev", dev, "up", NULL };
    run_quiet(u);
    /* Очередь устройства — 500 пакетов по умолчанию, а мы пишем в него по семь тысяч
     * пакетов в секунду. Полная очередь означает EAGAIN и ожидание на каждой записи, то
     * есть скорость, определяемую не каналом, а нашими паузами. Четыре тысячи пакетов —
     * это 5,8 МБ, меньше секунды буферизации на быстром канале и никакой памяти зря:
     * очередь занимает столько, сколько в ней реально лежит. */
    const char *q[] = { "ip", "link", "set", "dev", dev, "txqueuelen", "4096", NULL };
    run_quiet(q);
}

/* ВЫЧЕРПАТЬ сокет соединения, а не прочитать по одной записи за виток цикла.
 *
 * Разница принципиальная. Пока мы не читаем, у сервера закрывается окно, и заново открыть
 * его стоит круга до сервера — десятки миллисекунд. Читая по одной записи на итерацию, мы
 * получаем скорость «запись за круг», то есть задержку вместо полосы: замерено 3 Мбит/с там,
 * где криптография держит 800.
 *
 * Пределов три: окно клиента (иначе потеряем сегмент), объём и число чтений за виток —
 * чтобы одно активное соединение не заморозило остальные.
 *
 * Отдельной функцией, потому что вызывается из двух мест: по событию epoll и по флагу
 * rx_ready. Копия этой логики в двух местах означала бы, что предел порции соблюдается в
 * одном из них и не соблюдается в другом. */
static void drain_conn(struct conn *c, const struct vless_node *node,
                       const struct tun_dev *tun) {
    struct sess *s = SESS(c);
    int reads = 0;
    uint64_t drained_from = g_rx_total;
    c->rx_ready = 0;
    for (;;) {
        if (downstream_pump(c, node, tun) != 0) {
            /* Сервер закрыл. Соединение НЕ закрываем, пока клиент не подтвердит всё
             * отправленное: пока в кольце есть неподтверждённое, его надо повторять, а
             * закрыв соединение, мы уничтожим и кольцо. FIN уйдёт из общего прохода. */
            c->srv_closed = 1;
            c->closed_at = g_now_ns;
            TR("сервер закрыл conn#%ld, ждём подтверждения %u байт\n",
               (long)(c - g_conns), c->rtx.len);
            return;
        }
        if (++reads >= DRAIN_MAX_READS || g_rx_total - drained_from >= DRAIN_MAX_BYTES) {
            if (g_stats) g_st.drain_full++;
            /* Прервались на своём пределе, а данные, может быть, ещё в буфере: отметим, что
             * ждать события на сокете для них не нужно. */
            c->rx_ready = (uint8_t)(vless_has_data(&s->v) != 0);
            return;
        }
        if (!client_can_take_record(c)) {
            c->rx_ready = (uint8_t)(vless_has_data(&s->v) != 0);
            return;
        }
        /* Целая запись уже прочитана у сокета — спрашивать ядро незачем. */
        if (vless_has_data(&s->v)) continue;
        /* Есть ли ещё что читать. Без этой проверки следующее чтение заблокируется на
         * таймауте сокета (восемь секунд) и остановит весь цикл. */
        struct pollfd sp = { .fd = c->fd, .events = POLLIN };
        if (poll(&sp, 1, 0) <= 0 || !(sp.revents & POLLIN)) return;
    }
}

/* Что нужно потоку, чтобы работать: своя очередь устройства, узел и свой номер. Больше
 * ничего — остальное состояние у него собственное (__thread). */
struct worker {
    struct tun_dev tun;
    const struct vless_node *node;
    int id;
    /* Дошёл ли поток до цикла, то есть нёс ли эта очередь трафик хоть секунду. Нужно
     * ровно для одного: различить в журнале «туннель не поднялся» и «туннель работал и
     * умер». Для кода выхода разницы нет — он в обоих случаях ненулевой. */
    int served;
};

static void *worker_loop(void *arg) {
    struct worker *w = arg;
    struct tun_dev tun = w->tun;
    const struct vless_node *node = w->node;
    int tun_fd = tun.fd;
    g_worker = w->id;

    g_st.win_min = 0xFFFFFFFFu;
    uint64_t stats_at = g_stats ? now_ns() : 0;
    uint64_t loop_at = 0;   /* когда вернулось прошлое ожидание — для оценки периода витка */
    conn_table_init();
    unsigned char pkt[TUNNEL_BUF];

    /* epoll, а не poll, и это не вкусовщина.
     *
     * poll получает СПИСОК дескрипторов на каждый вызов: список надо собрать в памяти,
     * скопировать в ядро, а ядро — обойти целиком и опросить каждый дескриптор. При 320
     * живых соединениях и двух тысячах витков в секунду это 640 тысяч опросов в секунду,
     * из которых интересны единицы. На роутере, где один вызов poll на 320 дескрипторов
     * стоит сотни микросекунд, цикл упирался в него раньше, чем в криптографию.
     *
     * epoll хранит набор в ядре и отдаёт ТОЛЬКО готовое: цена вызова не зависит от числа
     * соединений. Взамен приходится следить за составом набора — этим и занят флаг armed:
     * epoll_ctl вызывается на изменение состояния, а не на каждом витке. */
    /* Очередь ОБЯЗАНА закрыться на любом выходе отсюда, и это не гигиена дескрипторов.
     *
     * Ядро раскладывает потоки по очередям как хэш % numqueues, а numqueues считает
     * ПРИСОЕДИНЁННЫЕ очереди, не читаемые. Оставить дескриптор открытым и уйти — значит
     * навсегда отдать долю трафика в очередь, из которой никто не читает: соединения в неё
     * попадают и молча пропадают. Снаружи это «часть сайтов не открывается никогда», причём
     * стабильно одни и те же, потому что хэш постоянен.
     *
     * close() эту очередь отсоединяет (tun_detach в ядре уменьшает numqueues), и потоки
     * расходятся по живым. Проверено опытом, а не по памяти — build/qdetach.c: после
     * закрытия второй из двух очередей все 40 потоков пришли в первую. */
    int ep = epoll_create1(0);
    if (ep < 0) {
        fprintf(stderr, LOG_W "epoll недоступен (%s) — поток не запущен, "
                        "очередь отдана остальным\n", strerror(errno));
        close(tun_fd);
        return NULL;
    }
    /* Метка TUN не может совпасть с номером соединения: слотов MAX_CONNS, метка выше. */
    const uint32_t TUN_TOKEN = MAX_CONNS;
    {
        struct epoll_event e = { .events = EPOLLIN, .data = { .u32 = TUN_TOKEN } };
        if (epoll_ctl(ep, EPOLL_CTL_ADD, tun_fd, &e) != 0) {
            fprintf(stderr, LOG_W "TUN не встал в epoll (%s) — поток не запущен, "
                            "очередь отдана остальным\n", strerror(errno));
            close(ep);
            close(tun_fd);
            return NULL;
        }
    }
    struct epoll_event evs[MAX_CONNS + 1];
    w->served = 1;      /* очередь встала в epoll — дальше она несёт трафик */

    for (;;) {
        /* Время снимается ОДИН раз на виток и лежит в g_now_ns/g_now_s — почему, написано
         * там же, у их объявления. */
        uint64_t now = now_ns();
        g_now_ns = now;
        g_now_s = (time_t)(now / 1000000000ull);

        /* Период витка: сколько прошло с прошлого места ожидания. Считаем РАБОЧУЮ часть,
         * а не время в ожидании: порог RTO должен закрывать то, на что мы заняты, а сон
         * прерывается пришедшим подтверждением сразу. Сглаживание 1/8 — как в оценке RTT в
         * TCP, чтобы одна долгая итерация не задирала порог надолго. */
        if (loop_at) {
            uint64_t busy64 = (now - loop_at) / 1000000;
            uint32_t busy = busy64 > 5000 ? 5000 : (uint32_t)busy64;
            /* Вверх с округлением вверх — то есть заметив занятость, порог поднимается сразу
             * хотя бы на миллисекунду. Вниз с округлением вниз, чтобы не дёргаться. */
            if (busy > g_loop_ms) g_loop_ms += (busy - g_loop_ms + 7) / 8;
            else                  g_loop_ms -= (g_loop_ms - busy) / 8;
        }

        /* ОДИН проход по живым соединениям на весь виток. Раньше их было четырнадцать по
         * ВСЕЙ таблице — см. комментарий у struct conn, там числа.
         *
         * Здесь считается сразу всё, что нужно перед ожиданием: состав набора epoll, число
         * заявок в работе, соединения с уже прочитанными данными и ближайший срок повтора. */
        int pend = 0, forced = 0;
        /* Таймаут — до ближайшего срока повтора, а не всегда секунда: иначе повтор ждал бы,
         * пока цикл проснётся сам. При живом трафике это происходит сразу, а при потере
         * последнего сегмента просыпаться уже нечему — ровно тот случай, для которого
         * таймер и нужен. */
        int wait_ms = 1000;
        for (int li = 0; li < g_live_n; li++) {
            struct conn *c = &g_conns[g_live[li]];
            if (c->pending) { pend++; continue; }

            /* Окно и «в пути» пишем ВСЕГДА, а не только когда отказались читать.
             *
             * Прежде они считались внутри ветки отказа, и при «ждали окна 0/с» в отчёте
             * стояли нули — то есть ровно там, где надо понять, почему поток встал, чисел
             * не было вовсе. А встать он может и не упираясь в окно: сегмент, отброшенный
             * приёмником, мы не повторим никогда, и выглядит это как тишина при свободном
             * окне. Различить два случая можно только видя оба числа. */
            if (g_stats) {
                uint32_t room = client_room(c);
                uint32_t infl = c->our_seq - c->client_ack;
                if (room < g_st.win_min) g_st.win_min = room;
                if (room > g_st.win_max) g_st.win_max = room;
                if (infl > g_st.inflight_max) g_st.inflight_max = infl;
                g_st.wscale_seen = c->client_wscale;
            }

            /* Спрашивать сервер о новых данных, пока клиент не разгрёб прежние, нельзя.
             *
             * Это и есть управление потоком, которого у нас иначе нет: прочитав, мы обязаны
             * сразу записать в устройство, а очередь устройства не бесконечна. Переполнив
             * её, мы теряем сегмент — и клиент ждёт повтора там, где мог бы не ждать.
             *
             * Замер: на роутере без этой проверки передача вставала на втором мегабайте.
             *
             * У закрытых сервером читать нечего вовсе — они живут только чтобы додать
             * клиенту остаток. */
            int want = !c->srv_closed && client_can_take_record(c);
            if (!want && !c->srv_closed && g_stats) g_st.win_skips++;
            if (want != (int)c->armed) {
                struct epoll_event e = { .events = EPOLLIN,
                                         .data = { .u32 = (uint32_t)(c - g_conns) } };
                if (epoll_ctl(ep, want ? EPOLL_CTL_ADD : EPOLL_CTL_DEL, c->fd, &e) == 0 ||
                    !want)
                    c->armed = (uint8_t)want;
            }
            /* Данные уже у нас, и ядро о них не сообщит: разберём их без ожидания. */
            if (want && c->rx_ready) forced++;

            if (c->rtx.len && c->rtx_at) {
                int64_t left = (int64_t)c->rto_ms - (int64_t)((now - c->rtx_at) / 1000000);
                if (left < 0) left = 0;
                if (left < wait_ms) wait_ms = (int)left;
            }
        }
        if (g_stats) g_st.conns = (uint32_t)g_live_n;

        /* Пока есть заявки в работе, просыпаемся часто: готовность установщика приходит не
         * событием на дескрипторе, а флагом в памяти. Двадцать миллисекунд — это худшая
         * добавка к времени соединения, и она в десять раз меньше самого рукопожатия.
         *
         * Отдельная труба для побудки была бы точнее, но это лишний дескриптор и лишняя
         * ветка в разборе событий; для прототипа цена не оправдана. */
        if (pend && wait_ms > 20) wait_ms = 20;
        if (forced) wait_ms = 0;

        int r = epoll_wait(ep, evs, MAX_CONNS + 1, wait_ms);
        uint64_t after_poll = now_ns();
        loop_at = after_poll;
        g_now_ns = after_poll;
        g_now_s = (time_t)(after_poll / 1000000000ull);
        if (g_stats) {
            g_st.poll_ns += after_poll - now;
            g_st.iters++;
            if (after_poll - stats_at >= 2000000000ull) {
                stats_dump(after_poll - stats_at);
                stats_at = after_poll;
            }
        }
        if (r < 0) {
            if (errno == EINTR) continue;
            break;
        }

        /* Готовые заявки: отсюда и уходит SYN-ACK. Разбираем ДО чтения из TUN — клиент,
         * получив подтверждение, тут же пришлёт данные, и пусть они попадут в этот же
         * проход, а не в следующий.
         *
         * Обход по живым, и только когда заявки вообще есть: в устоявшемся состоянии их
         * нет, и проход не делается вовсе. */
        /* Индекс двигается ВРУЧНУЮ: conn_drop переставляет в g_live последний элемент на
         * место освободившегося, и обычный li++ проскочил бы его не глядя. Один раз это уже
         * стоило соединений, живших до таймаута вместо разбора. */
        for (int li = 0; pend && li < g_live_n; ) {
            struct conn *c = &g_conns[g_live[li]];
            if (!c->pending || !__atomic_load_n(&c->done, __ATOMIC_ACQUIRE)) { li++; continue; }
            c->pending = 0;
            pend--;
            c->fd = SESS(c)->v.fd;
            if (c->rc != 0) {
                /* С причиной, а не «не открылся»: код различает «TCP не соединился»,
                 * «сервер не признал ключ» и «сервер не согласился на HTTP/2». */
                fprintf(stderr, LOG_W "поток к %s не открылся: %s (rc=%d)\n",
                        node->host, vless_strerror(c->rc), c->rc);
                /* RST, а не молчание: клиент иначе ждёт до таймаута. Молчать я пробовал —
                 * страница с видео перестала открываться вовсе, потому что браузер
                 * использует быстрый отказ лучше, чем ожидание. */
                unsigned char rst[64];
                size_t rl = tcp_build(rst, sizeof(rst), c->key.dst, c->key.src,
                                      c->key.dport, c->key.sport,
                                      0, c->client_seq, TCP_RST | TCP_ACK, NULL, 0, 0, 0, -1);
                if (rl) tun_write_ctl(&tun, rst, rl);
                conn_drop(c);
                continue;                       /* слот занял другой — не двигаем индекс */
            }
            unsigned char sa[64];
            size_t sl = tcp_build(sa, sizeof(sa), c->key.dst, c->key.src,
                                  c->key.dport, c->key.sport,
                                  c->our_seq++, c->client_seq, TCP_SYN | TCP_ACK,
                                  NULL, 0, 65535, TUN_MSS, OUR_WSCALE);
            if (sl) tun_write_ctl(&tun, sa, sl);
            c->last = g_now_s;
            TR("SYN-ACK отправлен (seq=%u ack=%u)\n", c->our_seq - 1, c->client_seq);
            li++;
        }

        /* Готовность TUN ищем среди событий. Разбираем его ПЕРВЫМ, до чтения у серверов:
         * подтверждения клиента открывают окно, и разобрав их раньше, мы в этом же витке
         * успеваем взять у сервера следующую порцию. */
        int tun_ready = 0;
        for (int i = 0; i < r; i++)
            if (evs[i].data.u32 == TUN_TOKEN) { tun_ready = 1; break; }

        if (tun_ready) {
            /* ВЫЧЕРПЫВАЕМ устройство, а не читаем по пакету за проход.
             *
             * Во время скачивания из TUN приходят подтверждения клиента, и именно они
             * открывают окно. Читая по одному за проход, мы ограничивали скорость числом
             * проходов цикла: замерено 1900 проходов в секунду × ~2920 байт на
             * подтверждение = 5,5 МБ/с, ровно тот потолок, который и наблюдался.
             *
             * Устройство переведено в неблокирующий режим, поэтому «больше нечего» приходит
             * как EAGAIN, а не как сон. Предел на проход всё равно нужен: иначе поток
             * пакетов от одного клиента не даст дойти до чтения у серверов. */
            for (int k = 0; k < TUN_DRAIN_MAX; k++) {
                uint64_t t0 = g_stats ? now_ns() : 0;
                ssize_t rn = tun_read_packet(&tun, pkt, sizeof(pkt));
                uint64_t t1 = g_stats ? now_ns() : 0;
                if (rn <= 0) break;
                if (g_stats) { g_st.tun_reads++; g_st.tun_read_ns += t1 - t0; }
                handle_packet(&tun, node, pkt, (size_t)rn);
                if (g_stats) g_st.pkt_ns += now_ns() - t1;
            }
            flush_acks(&tun);
        }
        for (int i = 0; i < r; i++) {
            if (evs[i].data.u32 == TUN_TOKEN) continue;
            struct conn *c = &g_conns[evs[i].data.u32];
            /* Слот мог освободиться в этом же витке — на FIN или RST от клиента — и даже
             * достаться новому соединению. Новое всегда pending, поэтому две эти проверки и
             * закрывают весь случай: иначе мы полезли бы в сессию, которую прямо сейчас
             * заполняет установщик. */
            if (!c->used || c->pending) continue;
            /* Уже прочитанное разбирает второй проход ниже — здесь пропускаем, чтобы одно
             * соединение не получило двойную порцию за виток и не отняло её у остальных. */
            if (c->rx_ready) continue;
            /* Готовность посчитана ДО разбора порции из TUN, а в ней могло приехать
             * подтверждение с меньшим окном. Читать в этом случае нельзя: отданное за окно
             * приёмник молча выбросит, и закрывать дыру придётся повтором. Проверка стоит
             * копейки и снимает зависимость от того, успел ли epoll узнать о снятии. */
            if (c->srv_closed || !client_can_take_record(c)) continue;
            drain_conn(c, node, &tun);
        }

        /* Соединения, у которых данные уже лежат в буфере: ядро о них не сообщит, и без
         * этого прохода запись ждала бы новых байт от сервера. Проход делается только когда
         * такие есть — их число посчитано перед ожиданием. */
        for (int li = 0; forced && li < g_live_n; li++) {
            struct conn *c = &g_conns[g_live[li]];
            if (!c->rx_ready || c->pending) continue;
            forced--;
            drain_conn(c, node, &tun);
        }

        /* Один проход на все сроки: повтор, закрытие после сервера, уборка задержавшихся.
         * Раньше это были три отдельных обхода ВСЕЙ таблицы — то есть три прохода по 5,8 МБ
         * ради нескольких соединений.
         *
         * Время обновляем: между ожиданием и этим местом мог пройти весь разбор порции из
         * TUN и чтение у серверов, то есть миллисекунды. */
        g_now_ns = now_ns();
        g_now_s = (time_t)(g_now_ns / 1000000000ull);
        now = g_now_ns;
        for (int li = 0; li < g_live_n; ) {
            struct conn *c = &g_conns[g_live[li]];
            if (c->pending) { li++; continue; }  /* установщик пишет в сессию — не трогать */

            /* Истёкшие сроки — повторяем. После обработки пакетов, а не до: подтверждение,
             * приехавшее в этом же витке, могло снять надобность. */
            if (c->rtx.len && c->rtx_at &&
                (now - c->rtx_at) / 1000000 >= c->rto_ms)
                rtx_resend(c, &tun, "истёк таймаут");

            /* Закрытые сервером: как только клиент подтвердил всё — FIN и закрываем. Если не
             * подтвердил за отведённое время, закрываем всё равно: клиент мог уйти совсем. */
            if (c->srv_closed) {
                int drained = c->rtx.len == 0;
                if (!drained && (now - c->closed_at) / 1000000 < CLOSE_DRAIN_MS) { li++; continue; }
                if (!drained)
                    TR("conn#%ld: клиент не подтвердил %u байт за %d мс, закрываю\n",
                       (long)(c - g_conns), c->rtx.len, CLOSE_DRAIN_MS);
                /* FIN, иначе клиент будет ждать данных, которых больше не будет. */
                unsigned char fin[64];
                size_t fl = tcp_build(fin, sizeof(fin), c->key.dst, c->key.src,
                                      c->key.dport, c->key.sport,
                                      c->our_seq, c->client_seq, TCP_FIN | TCP_ACK,
                                      NULL, 0, 0, 0, -1);
                if (fl) tun_write_ctl(&tun, fin, fl);
                conn_drop(c);
                continue;                        /* на место этого встал другой */
            }

            /* Пустое кольцо отдаём обратно системе. Соединение при этом полностью рабочее:
             * при следующих данных кольцо появится снова. Именно после простоя, а не сразу по
             * опустошении, — иначе на каждом залпе подтверждений шли бы malloc и free. */
            if (c->rtx.cap && !c->rtx.len && g_now_s - c->last > 5) rtx_done(&c->rtx);

            /* Уборка задержавшихся: без неё таблица заполняется соединениями, которые клиент
             * бросил без FIN, и новые перестают открываться.
             *
             * Порог — тот же IDLE_EVICT_S, что и у вытеснения: «мёртвое соединение» должно
             * означать одно и то же в обоих местах. Пробовал шестьдесят, рассчитывая
             * освобождать слоты раньше, — и получил RST по живым соединениям HTTP/2, которые
             * браузер переиспользует после минуты простоя.
             *
             * RST обязателен. Прежде здесь было молчаливое conn_drop, и клиент оставался с
             * соединением, которое считает открытым: следующий запрос по нему уходил в
             * пустоту и ждал таймаута — то есть наша уборка выглядела как зависший сайт. */
            if (g_now_s - c->last > IDLE_EVICT_S) {
                unsigned char rst[64];
                size_t rl = tcp_build(rst, sizeof(rst), c->key.dst, c->key.src,
                                      c->key.dport, c->key.sport,
                                      c->our_seq, c->client_seq, TCP_RST | TCP_ACK,
                                      NULL, 0, 0, 0, -1);
                if (rl) tun_write_ctl(&tun, rst, rl);
                conn_drop(c);
                continue;
            }
            li++;
        }
    }
    /* Сначала отпустить установщиков, только потом закрывать сессии: иначе закрываем то,
     * с чем они работают. Почему это важно — у connq_release. */
    if (connq_release(g_conns) == 0)
        while (g_live_n) conn_drop(&g_conns[g_live[0]]);
    close(ep);
    close(tun_fd);
    return NULL;
}

/* Сколько потоков поднимать.
 *
 * По числу ядер, но не больше MAX_WORKERS: на двухъядерной коробке третий поток только
 * добавил бы переключений. Один поток на ядро, а не больше, потому что цикл почти всё время
 * либо ждёт в poll, либо считает — очередь на процессоре ему не помогает.
 *
 * STEER_TUN_THREADS задаёт число вручную. Нужно ровно для того же, для чего STEER_TUN_NOGSO:
 * «стало быстрее от второго ядра» — утверждение, которое надо уметь перепроверить, вернувшись
 * к одному потоку на том же железе. */
#define MAX_WORKERS 4

static int worker_count(void) {
    const char *env = getenv("STEER_TUN_THREADS");
    if (env) {
        int n = atoi(env);
        if (n >= 1) return n < MAX_WORKERS ? n : MAX_WORKERS;
    }
    long cpus = sysconf(_SC_NPROCESSORS_ONLN);
    if (cpus < 1) cpus = 1;
    return cpus < MAX_WORKERS ? (int)cpus : MAX_WORKERS;
}

int tunnel_run(struct output *o, const struct vless_node *node) {
    const char *dev = o->device;
    g_trace = getenv("STEER_TUN_TRACE") != NULL;
    g_stats = getenv("STEER_TUN_STATS") != NULL;

    static struct worker workers[MAX_WORKERS];
    struct tun_dev queues[MAX_WORKERS];
    int want = worker_count();
    int n = tun_open(queues, want, dev);
    /* Код выхода — ОДИН, и он положительный. Возвращая сюда -40 или -41, движок отдавал
     * их main, а тот отдавал ядру: отрицательное обрезается до байта, и procd получал 216
     * или 215. Число, которое ничего не значит ни для человека, ни для splify2. Причину
     * называет tun_open своим сообщением, здесь остаётся признак отказа. */
    if (n < 0) return 1;

    for (int i = 0; i < n; i++) {
        /* Неблокирующее чтение: цикл вычерпывает устройство до EAGAIN, и без этого флага
         * последнее чтение засыпало бы, останавливая все соединения. */
        int fl = fcntl(queues[i].fd, F_GETFL, 0);
        if (fl >= 0) fcntl(queues[i].fd, F_SETFL, fl | O_NONBLOCK);
        workers[i].tun = queues[i];
        workers[i].node = node;
        workers[i].id = i;
    }
    tun_bring_up(dev, o->table);

    /* Привязываем таблицу выхода к устройству ЗДЕСЬ, а не в apply.
     *
     * Apply уже прошёл к этому моменту и, не найдя устройства, поставил запрет — иначе и
     * нельзя: пока туннеля нет, пускать в него трафик некуда. Дождаться устройства снаружи
     * невозможно: procd запускает этот процесс только после того, как init-скрипт вернул
     * управление, то есть уже после apply. Значит привязать может только тот, кто знает
     * момент готовности, — а это мы. */
    bind_device(o, dev);
    fprintf(stderr, LOG_I "%s привязан к таблице %d\n", dev, o->table);
    fprintf(stderr, LOG_I "%s -> %s (%s:%u %s%s)\n", dev, node->name,
            node->host, node->port, node->type, node->flow[0] ? " +vision" : "");
    /* Печатается всегда: без разгрузки и без второй очереди скорость падает в разы, и знать,
     * что именно досталось, надо до замеров, а не после. */
    fprintf(stderr, LOG_I "разгрузка записи в %s %s; потоков %d из %d запрошенных\n",
            dev, queues[0].gso ? "включена (сегменты до 16 КБ, суммы считает ядро)"
                               : "НЕДОСТУПНА — нарезаем по 1460 и считаем суммы сами",
            n, want);
    if (n < want)
        fprintf(stderr, LOG_W "очередей меньше запрошенного — ядро без "
                        "IFF_MULTI_QUEUE, работаем в один поток\n");

    /* Потоки со второго по последний — отдельными, первый работает в этом же. Так процесс
     * остаётся тем, чем был для procd: если цикл завершится, завершится и процесс. */
    for (int i = 0; i < n; i++) workers[i].served = 0;
    pthread_t tids[MAX_WORKERS];
    int started = 0;
    for (int i = 1; i < n; i++) {
        if (pthread_create(&tids[started], NULL, worker_loop, &workers[i]) != 0) {
            fprintf(stderr, LOG_W "поток %d не создался, работаем без него\n", i);
            close(workers[i].tun.fd);
            continue;
        }
        started++;
    }
    worker_loop(&workers[0]);
    for (int i = 0; i < started; i++) pthread_join(tids[i], NULL);

    /* Досюда мы доходим ТОЛЬКО когда все очереди завершились, а завершиться они могут
     * лишь по ошибке: успешного выхода у worker_loop нет ни одного. Штатное окончание
     * работы выглядит иначе — procd присылает сигнал, и процесс умирает, не возвращаясь
     * сюда вовсе.
     *
     * Поэтому ноль здесь неверен всегда. Возвращая его, движок сообщал procd и splify2
     * «завершился успешно» в тот момент, когда туннель не нёс трафик: интерфейс показывал
     * выход настроенным, журнал — ни одной жалобы, а сайты не открывались. Ровно тот
     * тихий сбой, который в этом коде вычищен везде, кроме этой строки. */
    int served = 0;
    for (int i = 0; i < n; i++) served += workers[i].served;
    if (!served)
        fprintf(stderr, LOG_W "%s не поднялся ни одной очередью из %d\n", dev, n);
    else
        fprintf(stderr, LOG_W "%s больше не несёт трафик — все очереди (%d) "
                        "завершились\n", dev, n);
    return 1;
}

/* ---- подкоманда steer vless -------------------------------------------------
 *
 * Поднимает TUN для выхода kind=vless из спеки. Отдельный процесс, а не поток внутри
 * apply: apply должен завершаться, а туннель — жить. Init-скрипт держит по экземпляру
 * procd на каждый такой выход, поэтому падение одного не уносит остальные.
 */
#define MAX_NODES 128
static struct vless_node g_nodes[MAX_NODES];

/* Найти выход и разобрать его подписку. Одно место на все три команды: иначе «как
 * читается подписка» разошлось бы между подъёмом, списком и проверкой — а расхождение
 * здесь означало бы, что человек выбирает в интерфейсе не тот узел, который поднимется. */
static int load_nodes(const char *spec_path, const char *out_name, struct output **out,
                      size_t *cnt, size_t *skipped, size_t *foreign) {
    load_spec(spec_path);
    struct output *o = out_by_name(out_name);
    if (!o) { fprintf(stderr, LOG_W2 "выхода %s нет в спеке\n", out_name); return 2; }
    if (o->kind != OUT_VLESS) {
        fprintf(stderr, LOG_W2 "выход %s не vless (kind другой)\n", out_name);
        return 2;
    }
    *out = o;

    /* Подписка читается с диска: скачивание — дело управляющего слоя. */
    FILE *f = fopen(o->sub_file, "r");
    if (!f) { fprintf(stderr, LOG_W2 "%s не читается\n", o->sub_file); return 2; }
    static char raw[262144], dec[262144];
    size_t n = fread(raw, 1, sizeof(raw) - 1, f);
    raw[n] = '\0';
    fclose(f);
    const char *text = raw;
    if (!strstr(raw, "://")) { b64_decode(raw, n, dec, sizeof(dec)); text = dec; }

    *cnt = vless_parse_sub(text, g_nodes, MAX_NODES, skipped, foreign);
    return 0;
}

/* Строка JSON с экранированием. Имена узлов приходят из подписки и содержат что угодно —
 * кавычки в них ломали бы весь ответ, а не только своё поле. */
static void json_str(const char *s) {
    putchar('"');
    for (const unsigned char *p = (const unsigned char *)s; *p; p++) {
        if (*p == '"' || *p == '\\') { putchar('\\'); putchar(*p); }
        else if (*p < 0x20) printf("\\u%04x", *p);
        else putchar(*p);
    }
    putchar('"');
}

static void node_json(const struct vless_node *n, int index) {
    printf("{\"index\":%d,", index);
    printf("\"name\":"); json_str(n->name);
    printf(",\"host\":"); json_str(n->host);
    printf(",\"port\":%u,\"type\":", n->port);
    json_str(n->type);
    printf(",\"security\":"); json_str(n->security);
    printf(",\"vision\":%s", n->flow[0] ? "true" : "false");
    if (n->mode[0]) { printf(",\"mode\":"); json_str(n->mode); }
    printf("}");
}

/* Перечислить узлы подписки.
 *
 * Индекс здесь — это индекс среди ПРИГОДНЫХ узлов, и он же понимается движком в поле
 * `node` спеки. Одно значение слова «номер узла» на весь проект: если бы список включал
 * непригодные, человек выбрал бы номер 5, а поднялся бы другой узел — и понять это было
 * бы невозможно, потому что оба списка выглядят правдоподобно. Непригодные считаются
 * отдельно и объясняются причиной, но номеров не занимают. */
int cmd_vless_nodes(const char *spec_path, const char *out_name) {
    struct output *o = NULL;
    size_t cnt = 0, skipped = 0, foreign = 0;
    int rc = load_nodes(spec_path, out_name, &o, &cnt, &skipped, &foreign);
    if (rc) return rc;

    printf("{\"output\":");
    json_str(out_name);
    printf(",\"sub_file\":");
    json_str(o->sub_file);
    printf(",\"node\":%d,\"usable\":%zu,\"skipped\":%zu,\"foreign\":%zu,\"nodes\":[",
           o->node_index, cnt, skipped, foreign);
    for (size_t i = 0; i < cnt; i++) {
        if (i) putchar(',');
        node_json(&g_nodes[i], (int)i);
    }
    printf("]}\n");
    return 0;
}

/* Проверить узел и измерить задержку.
 *
 * node >= 0 — только этот узел. node < 0 — по порядку до первого рабочего, то есть ровно
 * то, что сделает движок при подъёме выхода.
 *
 * По одному узлу за вызов не случайно: проверка узла упирается в таймаут, и «проверить
 * все» на подписке из двадцати шести узлов заняло бы минуты — дольше, чем живёт вызов
 * ubus. Интерфейс спрашивает по одному и заполняет таблицу постепенно. */
int cmd_vless_probe(const char *spec_path, const char *out_name, int node, int timeout_s) {
    struct output *o = NULL;
    size_t cnt = 0, skipped = 0, foreign = 0;
    int rc = load_nodes(spec_path, out_name, &o, &cnt, &skipped, &foreign);
    if (rc) return rc;
    if (!cnt) {
        printf("{\"ok\":false,\"error\":\"в подписке нет пригодных узлов\","
               "\"skipped\":%zu,\"foreign\":%zu}\n", skipped, foreign);
        return 1;
    }
    if (node >= (int)cnt) {
        printf("{\"ok\":false,\"error\":\"узла %d нет, всего %zu\"}\n", node, cnt);
        return 1;
    }

    size_t from = node >= 0 ? (size_t)node : 0;
    size_t to = node >= 0 ? (size_t)node + 1 : cnt;
    int found = -1;
    printf("{\"output\":");
    json_str(out_name);
    printf(",\"results\":[");
    for (size_t i = from; i < to; i++) {
        char why[256] = "";
        int hs = -1, ttfb = -1;
        int pr = vless_probe_timed(&g_nodes[i], timeout_s, why, sizeof(why), &hs, &ttfb);
        if (i > from) putchar(',');
        printf("{\"index\":%zu,\"name\":", i);
        json_str(g_nodes[i].name);
        printf(",\"type\":");
        json_str(g_nodes[i].type);
        printf(",\"ok\":%s,\"handshake_ms\":%d,\"ttfb_ms\":%d,\"why\":",
               pr == 0 ? "true" : "false", hs, ttfb);
        json_str(why);
        printf("}");
        if (pr == 0) { found = (int)i; if (node < 0) break; }
    }
    printf("],\"working\":%d}\n", found);
    return found >= 0 ? 0 : 1;
}

int cmd_vless(const char *spec_path, const char *out_name) {
    struct output *o = NULL;
    size_t cnt = 0, skipped = 0, foreign = 0;
    int rc = load_nodes(spec_path, out_name, &o, &cnt, &skipped, &foreign);
    if (rc) return rc;
    struct vless_node *nodes = g_nodes;
    if (!cnt) {
        fprintf(stderr, LOG_W2 "в подписке нет пригодных узлов "
                        "(пропущено %zu, чужих протоколов %zu)\n", skipped, foreign);
        return 1;
    }
    fprintf(stderr, LOG_I2 "узлов %zu (пропущено %zu, чужих %zu)\n", cnt, skipped, foreign);

    /* Выбор узла. node=-1 означает «первый рабочий», и это умолчание не из лени: номер
     * узла в подписке меняется при её обновлении, а проверка находит живой сама. */
    int chosen = -1;
    if (o->node_index >= 0) {
        if ((size_t)o->node_index >= cnt) {
            fprintf(stderr, LOG_W2 "узла %d нет (всего %zu)\n", o->node_index, cnt);
            return 1;
        }
        chosen = o->node_index;
    } else {
        for (size_t i = 0; i < cnt; i++) {
            char why[256];
            if (vless_probe(&nodes[i], 8, why, sizeof(why)) == 0) {
                fprintf(stderr, LOG_I2 "выбран %s (%s)\n", nodes[i].name, why);
                chosen = (int)i;
                break;
            }
            fprintf(stderr, LOG_I2 "%s — %s\n", nodes[i].name, why);
        }
    }
    if (chosen < 0) {
        fprintf(stderr, LOG_W2 "ни один узел подписки не отвечает\n");
        return 1;
    }

    /* Реестр — чтобы узнать таблицу выхода: из неё берётся адрес устройства. Вызов
     * идемпотентен и с apply не спорит: тот же файл, те же номера. */
    registry_assign();
    return tunnel_run(o, &nodes[chosen]);
}
