/* ---- журнал с уровнем --------------------------------------------------------
 *
 * Формат: `steer[warn] tunnel: …`. Уровень идёт РОВНО в этом виде и первым — это контракт с
 * интерфейсом, а не украшение. Прежде все строки уходили в stderr, procd помечал их как
 * daemon.err, и «поток не открылся» стояло рядом с «узлов 26» одинаково красным: интерфейс не
 * мог их различить, а человек не мог понять, на что смотреть.
 *
 * Разбирать прозу движка интерфейсу нельзя — формулировки меняются, и разбор молча отваливается.
 * Поэтому уровень выделен в отдельное поле фиксированной формы: меняться будет текст, а не
 * префикс.
 *
 * Уровни всего два. `warn` — то, из-за чего трафик пошёл не так или не пошёл вовсе. `info` —
 * то, что случилось при штатной работе. Третий уровень («ошибка») не нужен: процесс, которому
 * совсем плохо, завершается с ненулевым кодом, и это видно иначе.
 */
#define LOG_W  "steer[warn] tunnel: "
#define LOG_I  "steer[info] tunnel: "
/* Без слова tunnel: подъём выхода и разбор подписки — это ещё не туннель. */
#define LOG_W2 "steer[warn]: "
#define LOG_I2 "steer[info]: "

/* Сколько соединений держим одновременно. Каждое — это сокет к серверу плюс TLS-состояние,
 * то есть около 3 КБ; 64 соединения это ~200 КБ, что для роутера с 15 МБ приемлемо, а для
 * домашней сети более чем достаточно. Упираться в предел лучше заметно (новые соединения
 * получают отказ), чем незаметно съесть память и быть убитым OOM. */
/* Сколько соединений держим одновременно.
 *
 * Шестидесяти четырёх не хватало, и не в теории: браузер держит соединения живыми между
 * запросами, и при широком списке (включённый Cloudflare — это половина интернета) два
 * открытых сайта занимали таблицу целиком. Сто двадцать восемь при кольце в 64 КБ стоят
 * ровно столько же памяти, сколько прежние шестьдесят четыре при 128 КБ, — то есть предел
 * поднят без единого лишнего байта. */
#define MAX_CONNS 320

/* Сколько секунд соединение должно молчать, чтобы его разрешили вытеснить.
 *
 * Сто двадцать, и это исправление моей же ошибки. Сначала здесь стояло десять — с
 * рассуждением «заметно больше круга до сервера и заметно меньше keep-alive браузера».
 * Вторая половина оказалась неверна: HTTP/2 у YouTube держит соединение живым десятками
 * секунд и потом ПЕРЕИСПОЛЬЗУЕТ его, причём в одном соединении едут все запросы страницы
 * сразу. Вытеснив такое, мы отправляли RST, и браузер получал ERR_CONNECTION_CLOSED
 * залпом — по всем мультиплексированным запросам за раз. Со стороны это выглядело как
 * «опять ничего не открывается», хотя туннель работал и отдавал видео.
 *
 * Простой длиннее двух минут означает, что соединение не переиспользуют: столько не держит
 * ни один браузер. Порог совпадает с уборкой задержавшихся ниже — одно понятие «мёртвого
 * соединения» на весь файл, а не два разных числа, спорящих друг с другом. */
#define IDLE_EVICT_S 120

/* ---- таблица соединений: горячее отдельно от толстого -----------------------
 *
 * Раньше это была одна структура, и в ней рядом лежали флаг `used` (1 байт, читается на
 * каждом проходе цикла) и `struct vless_conn` (18 832 байта: буфер записей TLS, контексты
 * шифров, состояние HTTP/2). Запись выходила 19 056 байт, и горячие поля оказывались по
 * ОБОИМ её краям: `used` в начале, `rtx`, `last` и `srv_closed` в конце — то есть на двух
 * разных страницах в 18 КБ друг от друга.
 *
 * Чего это стоило. Один виток цикла проходил таблицу целиком четырнадцать раз: сборка
 * набора для poll, подсчёт живых, подсчёт заявок, поиск ближайшего срока повтора, разбор
 * готовых заявок, рассылка отложенных подтверждений, истёкшие сроки, закрытые сервером,
 * уборка задержавшихся. Триста двадцать записей × две страницы × четырнадцать проходов —
 * это 4480 обращений в память НА ВИТОК, и все они мимо кэша: 320 × 19 КБ = 5,8 МБ, а L1
 * на MIPS 24Kc — 32 КБ, второго уровня нет вовсе. Каждое обращение — поход в память со
 * промахом TLB заодно.
 *
 * Замерено на x86_64 (там кэш огромный и промахи прячет L3, то есть это НИЖНЯЯ оценка):
 * при восьми занятых слотах из 320 холостой обход стоил 3,4 мкс на виток против 0,15 мкс
 * по компактной таблице живых — в 23 раза. На 24Kc, где каждое из 4480 обращений это
 * настоящая задержка памяти (~150 нс), те же обходы дают 0,67 мс на виток, то есть сами
 * по себе ограничивают цикл 1500 витками в секунду — ровно тот потолок «1300–2000
 * проходов», который здесь и наблюдался, и ровно та работа, которой не видно ни в одном
 * счётчике: она вне таймеров poll, recv и разбора.
 *
 * Отсюда три решения, и они держатся друг за друга:
 *
 *   1. толстая половина живёт в ОТДЕЛЬНОМ массиве (struct sess). Проход цикла её не
 *      касается вовсе, а страницы под неё берутся только теми соединениями, по которым
 *      реально идёт ввод-вывод — простаивающий слот больше не стоит двух резидентных
 *      страниц;
 *   2. горячая половина — 112 байт, то есть две строки кэша, и поля прохода собраны в
 *      первой;
 *   3. проходов по ВСЕЙ таблице не осталось ни одного: цикл идёт по g_live, где лежат
 *      только занятые слоты, а поиск по потоку — через хэш, а не перебором.
 *
 * Порядок важен: сам по себе список живых не помог бы, пока запись занимает 19 КБ, — при
 * 320 живых соединениях обход всё равно упирался бы в память. И наоборот. */

/* Толстая половина: нужна только тому соединению, по которому идёт ввод-вывод. */
struct sess {
    struct vless_conn v;
    struct vision vis;
    /* Разобранный UUID узла: нужен один раз на соединение — в заголовке запроса VLESS и
     * при заводе Vision. В горячей половине ему делать нечего. */
    unsigned char uuid[16];
};

struct conn {
    /* Первая строка кэша — ровно то, что читает проход цикла. Порядок полей здесь не
     * косметика: разложив их как попало, мы вернули бы вторую строку в каждый обход. */
    uint8_t used;
    /* Рукопожатие к узлу идёт в отдельном потоке, и пока идёт — соединение НЕДОТРОЖИМО.
     *
     * Зачем это вообще. Рукопожатие стоит 250-400 мс, и делалось оно прямо в цикле: цикл
     * стоял, ничего не обслуживая. На многоядерной коробке это делили несколько потоков, на
     * одноядерной поток один — и соединения выстраивались в очередь. Замерено на ютубе:
     * ответ в 146 байт приходил через 1769 мс при шести одновременных соединениях против
     * 58 мс мимо туннеля. Столько Chrome не ждёт: он бросал запрос, а с ним умирало всё
     * HTTP/2-соединение, по которому запросы шли мультиплексом, — отсюда залп одинаковых
     * ERR_CONNECTION_CLOSED при живом туннеле, отдающем видео.
     *
     * pending=1 означает: заявка отдана установщику, ответа ещё нет. В этом состоянии
     * соединение нельзя ни закрыть, ни вытеснить, ни убрать по простою — установщик пишет
     * в сессию, и освободить запись под ним значит писать в освобождённую память. Проверка
     * стоит во всех трёх местах, где conn удаляется. */
    uint8_t pending;
    /* Сервер закрыл поток, но у нас ещё есть неподтверждённое клиенту. Подробности ниже,
     * у closed_at; здесь поле стоит потому, что его читает проход цикла. */
    uint8_t srv_closed;
    /* Дескриптор соединения сейчас в epoll и ждёт готовности к чтению.
     *
     * Нужен, чтобы epoll_ctl вызывался только на ИЗМЕНЕНИЕ состояния, а не на каждом
     * витке. Состояние меняется редко (окно клиента открылось или закрылось), а витков
     * тысячи в секунду — вызывать системный вызов на каждый значило бы заменить обход
     * таблицы обходом ядра. */
    uint8_t armed;
    /* В буфере записей уже лежит ЦЕЛАЯ запись, а мы прервались (упёрлись в предел порции
     * или в окно клиента).
     *
     * Без этого флага такая запись зависала до следующих данных от сервера: epoll молчит —
     * сокет-то пуст, всё уже прочитано у него в наш буфер, — и виток цикла не приходил.
     * С poll поведение было тем же, просто ошибка не бросалась в глаза: на выгрузке данные
     * идут потоком и следующее чтение всё разгребало, а вот ХВОСТ ответа мог простоять до
     * таймаута повтора у клиента. */
    uint8_t rx_ready;
    uint8_t header_sent;      /* заголовок VLESS уже ушёл серверу */
    uint8_t established;
    /* Клиенту причитается подтверждение, но мы его отложили до конца разбора порции из
     * TUN. Подтверждать каждый пакет отдельно — это лишняя запись в устройство на каждый
     * пакет выгрузки, притом что все они подтверждаются одним ACK с последним номером. */
    uint8_t ack_due;
    uint8_t dup_acks;         /* подряд идущие подтверждения того же номера */
    /* Быстрый повтор уже сделан и нового подтверждения ещё не было.
     *
     * Без этого флага повтор сам себя разгоняет: на повторную порцию клиент отвечает
     * подтверждением с тем же номером (данные-то он уже принял), три таких — и мы повторяем
     * снова. Один быстрый повтор на одно продвижение подтверждения — то же правило, по
     * которому это работает в TCP. */
    uint8_t fast_done;
    uint8_t client_wscale;    /* множитель из опций SYN: окно = client_win << wscale */
    /* Сколько из отправленного клиент подтвердил и сколько он готов принять. */
    uint16_t client_win;
    /* Место в g_live и следующий в цепочке хэша. Индексы, а не указатели: два байта против
     * восьми, и вся горячая запись обязана влезть в две строки кэша. */
    int16_t livepos;
    int16_t hnext;
    /* Порядковые номера с точки зрения КЛИЕНТА: what we ack, what we send. */
    uint32_t our_seq;         /* следующий, который отправим клиенту */
    uint32_t client_ack;
    uint32_t client_seq;      /* следующий ожидаемый от клиента */
    /* ---- повторная передача клиенту ----
     *
     * Начало кольца — это ровно client_ack, а его длина — ровно our_seq - client_ack:
     * другого места, где неподтверждённые байты живут, у нас нет, поэтому разойтись эти
     * величины не могут по определению.
     *
     * Выделяется на SYN и освобождается на закрытии. malloc, а не массив внутри struct
     * conn: 128 КБ × 64 — это 8 МБ, и в BSS они значили бы, что тронутые страницы больше
     * никогда не вернутся системе. У malloc такого размера страницы приходят из mmap и
     * занимают память только там, где по ним реально писали, — соединение, передавшее
     * 10 КБ, стоит 10 КБ. */
    struct rtx rtx;
    /* Когда отправили самый старый неподтверждённый байт (или когда повторили его в
     * последний раз). Ноль означает «неподтверждённого нет». */
    uint64_t rtx_at;
    uint32_t rto_ms;          /* текущий таймаут, растёт вдвое на каждый повтор */
    time_t last;
    /* --- дальше то, что проход цикла НЕ читает: только работа с пакетом и установка. --- */
    struct flow_key key;
    int fd;                   /* копия сокета сессии: нужна при снятии с epoll */
    int done;                 /* установщик закончил: читать только с ACQUIRE */
    int rc;                   /* его результат: 0 или код ошибки vless_* */
    /* Когда сервер закрылся: предел ожидания подтверждений.
     *
     * Закрывать соединение в этот момент НЕЛЬЗЯ, и это ровно та ошибка, из-за которой
     * повторная передача не помогала под потерями: вместе с соединением уничтожалось кольцо,
     * то есть последний потерянный кусок становилось нечем повторить. Клиент оставался с
     * дырой и ждал до своего таймаута — на стенде это давало 121 секунду там, где один поток
     * при вдвое больших потерях доезжал за две.
     *
     * Поэтому: сервера больше не читаем, но живём и повторяем, пока клиент не подтвердит
     * всё. FIN уходит после этого. */
    uint64_t closed_at;
};

/* Горячая запись обязана оставаться маленькой — в этом весь смысл разделения. Проверка
 * сборкой, а не обещанием в комментарии: буфер, добавленный сюда «на время отладки», иначе
 * вернёт таблицу к 5,8 МБ, и заметить это можно будет только по скорости на роутере. */
typedef char conn_hot_size_check[sizeof(struct conn) <= 192 ? 1 : -1];

/* Сколько ждём подтверждений после закрытия сервером. Секунды, а не «сколько понадобится»:
 * клиент мог уйти совсем, и тогда кольцо не опустеет никогда. */
#define CLOSE_DRAIN_MS 5000

/* Сколько неподтверждённых байт храним на соединение — и, тем самым, каков наш предел
 * «в пути».
 *
 * Это одно число, а не два: держать в пути больше, чем можем повторить, значит вернуться
 * к тому, что было, — потерянный сегмент подвесит соединение навсегда. Поэтому окно
 * отправки равно размеру этого буфера, и увеличить одно без другого нельзя.
 *
 * Почему 64 КБ хватает. Скорость равна «в пути, поделённое на задержку подтверждения».
 * Клиент здесь за роутером, круг до него меньше миллисекунды, а наш цикл на замерах
 * крутится 1300-2000 раз в секунду, то есть подтверждение разбирается за 0,5-0,8 мс.
 * 64 КБ при 0,7 мс — это 90 МБ/с на ОДНО соединение, то есть предел не здесь.
 *
 * Было 128 КБ, и обмен сделан осознанно: буфер выделяется на каждое соединение при SYN, и
 * при 128 КБ шестьдесят четыре соединения стоили восемь мегабайт — на роутере с шестьюдесятью
 * это и был потолок числа соединений. Половинный буфер при вдвое большем пределе стоит той
 * же памяти, а не хватало именно СОЕДИНЕНИЙ: с включённым Cloudflare браузер занимал всю
 * таблицу за два сайта. Терять полосу при этом нечего — 90 МБ/с на соединение на роутере,
 * где весь туннель отдаёт 3-10, это запас в десять раз. */
#define RTX_CAP (64 * 1024)

/* Кольцо, с которым соединение РОЖДАЕТСЯ. До полного дорастает только то, по которому
 * реально пошли данные (rtx_grow в emit_to_client).
 *
 * Зачем: кольцо выделяется на каждый SYN, и простаивающее соединение стоило столько же,
 * сколько качающее на полной скорости. Браузер держит десятки соединений живыми, ничего по
 * ним не передавая, — за них платилась память, которой потом не хватало на новые. Теперь
 * сотня простаивающих стоит 3 МБ вместо 6,5, и предел числа соединений упирается в
 * процессор, а не в память.
 *
 * Не меньше: значение обязано покрывать CLIENT_ROOM_RESERVE (запас под целую запись плюс
 * буфер) с местом на продвижение. Взяв меньше, мы получили бы «клиент не может принять
 * запись» с первой же попытки — то есть соединение, которое не читает у сервера НИКОГДА и
 * до роста не доживает. */
#define RTX_START (32 * 1024)

/* Таймаут повтора. Растёт вдвое до секунды — на случай, если клиент действительно ушёл.
 *
 * Нижний порог — 200 мс, как минимум RTO в самом Linux, и это исправление, а не осторожность.
 * Раньше здесь стояло 50 мс с рассуждением «клиент за роутером, круг меньше миллисекунды,
 * ждать двести значит отдать скорость впустую». Рассуждение верное про сеть и неверное про
 * НАС: подтверждение клиента приходит быстро, но разбираем его мы — на своём проходе цикла.
 *
 * На слабом роутере проход длинный: измерено 22 прохода в секунду, то есть 45 мс, потому что
 * почти всё время уходит на расшифровку записей. Отправленный сегмент к моменту следующего
 * взгляда на устройство оказывается старше 50 мс — и таймаут срабатывал не на потере, а на
 * нашей же занятости. В отчёте это выглядело как «повторов 11/с (169 КБ/с)»: четырнадцать
 * процентов полосы уходило на пересылку того, что клиент давно получил, плюс расшифровка
 * этих же байт заново.
 *
 * Терять от большого порога нечего: настоящую потерю ловит не таймер, а три одинаковых
 * подтверждения (DUP_ACK_TRIGGER) — за один круг. Таймер нужен только для последнего
 * сегмента, за которым подтверждений больше не будет, и там 200 мс против 50 незаметны. */
#define RTO_MIN_MS 200
#define RTO_MAX_MS 1000

/* Но и 200 мс мало, если проход цикла сам длиннее. Порог = четыре прохода, потому что за
 * один проход мы можем только УВИДЕТЬ подтверждение; запас нужен на то, что проход перед
 * этим был занят другим соединением. Период прохода считаем сглаженно, по факту. */
#define RTO_LOOP_FACTOR 4

/* Сколько подтверждений одного номера подряд считаем признаком потери. Три — как в TCP:
 * клиент присылает их, получая данные не по порядку, то есть дыру он уже видит. Ждать
 * таймаута в этом случае незачем — потеря известна на круг раньше. */
#define DUP_ACK_TRIGGER 3

/* Замерено, почему предел «в пути» вообще нужен и почему одного его мало: без него передача
 * на роутере вставала на втором мегабайте; с ним, но без вычерпывания сокета — 3 Мбит/с;
 * с вычерпыванием и 32 КБ — 42 Мбит/с. Порядок важен: увеличивать окно, не научившись
 * вычерпывать, бессмысленно, и первая попытка это подтвердила — стало хуже. Сам предел
 * теперь равен RTX_CAP. */

/* Масштаб окна, который объявляем клиенту МЫ.
 *
 * Ноль — и это не «забыли поставить». Опция обязана присутствовать в SYN-ACK, потому что
 * масштабирование по RFC 7323 включается только при обоюдном согласии: клиент применит
 * множитель к СВОЕМУ объявленному окну лишь тогда, когда получит эту опцию от нас. Без неё
 * его окно остаётся честными 16 битами, то есть не больше 65535 байт, — а мы всё это время
 * читали множитель из его SYN и умножали на него.
 *
 * Ошибка была ровно в этом: окно клиента считалось до 128 раз больше настоящего, и мы
 * держали в пути мегабайт там, где приёмник объявил 64 килобайта. Всё за окном приёмник
 * отбрасывает молча, повторной передачи у нас нет, и закрыть дыру нечем. Отсюда и «три
 * секунды по 85 Мбит/с, дальше ровные нули», и потеря 40% при восьми потоках — то есть
 * симптом выглядел как нехватка скорости, а был нарушением протокола.
 *
 * Своё окно при этом оставляем немасштабированным: значение множителя в опции относится
 * только к окнам, которые объявляем мы, а нам 65535 достаточно — данные клиента уходят
 * серверу сразу, копить их у себя мы не умеем и не собираемся. */
#define OUR_WSCALE 0

/* Сколько клиент готов принять СЕЙЧАС, с учётом множителя окна и нашего предела. Одна
 * функция вместо трёх копий одного вычисления: разойдясь, они дали бы либо остановку на
 * пустом месте, либо обгон клиента с потерей сегмента. */
static uint32_t client_room(const struct conn *c) {
    uint32_t win = (uint32_t)c->client_win << c->client_wscale;
    /* Предел — ФАКТИЧЕСКАЯ ёмкость кольца, а не RTX_CAP: кольцо теперь растёт по мере
     * надобности, и обещать окно больше того, что мы можем повторить, значит вернуться к
     * потерянному сегменту, который нечем закрыть. */
    uint32_t cap = c->rtx.cap ? c->rtx.cap : RTX_START;
    return win < cap ? win : cap;
}

/* Запас, который обязан оставаться свободным в окне клиента, прежде чем мы возьмём у
 * сервера ещё одну запись.
 *
 * Прочитав запись, отдать её клиенту НАДО ЦЕЛИКОМ: деть её больше некуда, буфера на
 * соединение у нас нет. Значит решать «читать или нет» надо заранее, с местом под целую
 * запись, а не «пока в окне есть хоть байт».
 *
 * Без этого запаса мы перебирали окно на длину записи: замерено «окно 262144, в пути
 * 268876». Всё, что за окном, приёмник отбрасывает молча — и поток встаёт НАВСЕГДА,
 * потому что повторной передачи у нас нет и дыру закрыть нечем. В iperf3 это выглядело
 * так: три секунды по 85 Мбит/с, дальше ровные нули; при восьми потоках терялось 40%
 * отправленного.
 *
 * Считается от TUNNEL_BUF, а не от размера записи TLS: в режиме прямого копирования одно
 * чтение отдаёт всё, что влезло в буфер, — это 18448 байт, а не 16384. Прежний запас был
 * посчитан от записи и на 1040 байт не покрывал именно этот случай. */
#define CLIENT_ROOM_RESERVE (TUNNEL_BUF + 1024)

/* Готов ли клиент принять ещё одну запись целиком. */
static int client_can_take_record(const struct conn *c) {
    uint32_t room = client_room(c);
    uint32_t inflight = c->our_seq - c->client_ack;
    return room > inflight && room - inflight >= CLIENT_ROOM_RESERVE;
}

/* Сколько берём у одного соединения за проход цикла — в БАЙТАХ, а не в чтениях.
 *
 * Предел по числу чтений выглядел разумно, пока записи были по 8 КБ. Но после перехода
 * сервера на прямое копирование (команда direct в Vision) чтения становятся мелкими — по
 * 300 байт, — и «восемь чтений» превращались в 2,4 КБ за проход: замерено 3600 чтений/с
 * при 1,1 МБ/с, то есть предел упирался не в данные, а в собственную арифметику.
 *
 * Байтовый предел ведёт себя одинаково при любом размере чтения. Второй предел, по числу
 * чтений, оставлен большим — он страхует от бесконечного цикла на потоке из однобайтовых
 * порций, а не ограничивает скорость. */
#define DRAIN_MAX_BYTES  (192 * 1024)
#define DRAIN_MAX_READS  256

/* Сколько пакетов забираем из TUN за один проход. Подтверждения клиента идут густо, и по
 * одному за проход они ограничивали скорость числом проходов цикла. Предел оставлен, чтобы
 * поток от одного клиента не заморозил чтение у серверов. */
#define TUN_DRAIN_MAX 64

/* ВСЁ изменяемое состояние — у каждого потока своё (__thread).
 *
 * Это и есть вся многопоточность здесь: ядро раскладывает пакеты по очередям устройства,
 * хэшируя поток симметрично, поэтому обе половины одного TCP-соединения всегда попадают
 * одному и тому же потоку (см. tun_open). Значит делить между потоками нечего — ни таблицу
 * соединений, ни счётчики, ни буферы, — и ни одной блокировки в цикле нет.
 *
 * Общая таблица под мьютексом означала бы замок на каждый пакет, а пакетов семьсот на
 * мегабайт: второе ядро ушло бы на борьбу за первое. */
static __thread struct conn g_conns[MAX_CONNS];
static __thread struct sess g_sess[MAX_CONNS];
/* Сессия соединения. Считается по индексу, а НЕ хранится указателем: указатель это восемь
 * байт в горячей записи, которых ей взять негде.
 *
 * Годится только внутри потока-владельца: g_conns и g_sess — __thread, и у другого потока
 * своя база. Установщик поэтому получает указатель на сессию в самой заявке, а не считает
 * его сам — иначе он адресовал бы чужую таблицу по индексу из нашей. */
#define SESS(c) (&g_sess[(size_t)((c) - g_conns)])

/* Занятые слоты, плотно. Все проходы цикла идут ТОЛЬКО по этому массиву — зачем, написано
 * выше у struct conn. */
static __thread uint16_t g_live[MAX_CONNS];
static __thread int g_live_n;
/* Свободные слоты. Без него поиск места был бы перебором таблицы на каждый SYN. */
static __thread uint16_t g_freelist[MAX_CONNS];
static __thread int g_free_n;

/* Хэш потока -> слот. Открытых цепочек, а не проб: удаление из цепочки не оставляет
 * «надгробий», которые при 320 слотах и десятках тысяч соединений в час превратили бы
 * таблицу в линейный перебор.
 *
 * 512 корзин на 320 слотов — заполнение 0,63, то есть средняя цепочка короче полутора
 * записей. Память: 1 КБ, влезает в L1 целиком.
 *
 * Зачем вообще: conn_find вызывается на КАЖДЫЙ пакет из TUN, а их до семи тысяч в секунду.
 * Перебором это 320 сравнений по записи в 19 КБ — то есть 320 промахов кэша на пакет,
 * 2,2 миллиона в секунду. Хэш даёт одно обращение. */
#define CONN_BUCKETS 512
static __thread int16_t g_bucket[CONN_BUCKETS];

static inline unsigned flow_hash(const struct flow_key *k) {
    /* Порты вместе с адресами: соединения к одному узлу отличаются только исходным портом,
     * и хэш без него сложил бы все соединения браузера в одну корзину. */
    uint32_t h = k->src ^ (k->dst * 0x9E3779B1u) ^
                 ((uint32_t)k->sport << 16) ^ (uint32_t)k->dport;
    h ^= h >> 15;
    h *= 0x2545F491u;
    h ^= h >> 13;
    return h & (CONN_BUCKETS - 1);
}

/* Номер потока — только для диагностики: по нему видно, раскладывает ли ядро нагрузку или
 * всё село в одну очередь. Без этого «стало быстрее вдвое» и «работает один поток из двух»
 * в отчёте выглядят одинаково. */
static __thread int g_worker;

/* Время, снятое ОДИН раз за виток цикла.
 *
 * Раньше clock_gettime и time вызывались из каждого места, где нужна метка: по два на
 * пакет из TUN (а их до семи тысяч в секунду), по одному на каждую отправку клиенту, плюс
 * по одному в каждом из обходов таблицы. На x86 это vDSO и почти бесплатно, а на mipsel
 * ядра OpenWrt vDSO для clock_gettime нет вовсе — то есть каждый вызов был настоящим
 * системным вызовом с переключением режима.
 *
 * Точности виток не портит: всё, что этими метками измеряется, — сроки в сотнях
 * миллисекунд (порог повтора не меньше 200 мс, простой 120 с), а виток длится доли
 * миллисекунды. Счётчики диагностики по-прежнему берут время сами: они мерят как раз то,
 * что внутри витка, и усреднённая метка сделала бы их бессмысленными. */
static __thread uint64_t g_now_ns;
static __thread time_t g_now_s;

/* ---- счётчики цикла ---------------------------------------------------------
 *
 * Включаются STEER_TUN_STATS=1, печатаются раз в две секунды. Появились не «на всякий
 * случай»: скорость упиралась в потолок при 14% одного ядра и криптографии, которая на
 * этом железе держит 800 Мбит/с. Когда процессор свободен, а быстрее не едет — значит мы
 * где-то ЖДЁМ, и найти это место можно только измерив.
 *
 * Считаем то, что различает возможные ответы: сколько раз прошли цикл, сколько простояли в
 * poll, сколько прочитали у сервера и какими порциями, сколько записали клиенту и по чём,
 * и сколько раз не стали читать из-за окна клиента. */
static int g_stats;
/* Считается ВСЕГДА, а не только с диагностикой: по нему цикл решает, был ли проход
 * пустым. Привязать это к счётчикам статистики значило бы, что без неё поведение другое. */
static __thread uint64_t g_rx_total;

/* Сглаженный период прохода цикла в миллисекундах — из него берётся нижний порог RTO.
 * Начинаем с RTO_MIN_MS/RTO_LOOP_FACTOR, то есть «как будто проход уже длинный»: первые
 * проходы после старта самые долгие (рукопожатия), и занижать порог именно там опаснее. */
static __thread uint32_t g_loop_ms = RTO_MIN_MS / RTO_LOOP_FACTOR;

/* Нижняя граница таймаута повтора для этого потока. */
static uint32_t rto_floor(void) {
    uint32_t byloop = g_loop_ms * RTO_LOOP_FACTOR;
    uint32_t f = byloop > RTO_MIN_MS ? byloop : RTO_MIN_MS;
    return f > RTO_MAX_MS ? RTO_MAX_MS : f;
}
static __thread struct {
    uint64_t iters, poll_ns, tun_reads, tun_writes, tun_write_ns;
    uint64_t recs, rec_bytes, win_skips, drain_full;
    uint64_t recv_ns, pkt_ns, tun_read_ns;
    /* Повторы. Ноль здесь означает «клиент получает всё с первого раза», а не «повтор не
     * работает», и различить это можно только имея число рядом с потерями. */
    uint64_t rtx_sends, rtx_bytes;
    /* Сколько соединений было живо на последнем проходе: «поток встал» и «поток закрылся»
     * в остальных числах выглядят одинаково — оба дают нули. */
    uint32_t conns;
    /* Окно клиента, каким мы его посчитали, и сколько было в пути в момент отказа: без
     * этих двух чисел «ждали окна» не отличить от «неверно прочитали окно». */
    uint32_t win_min, win_max, inflight_max;
    uint8_t wscale_seen;
} g_st;


static uint64_t now_ns(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (uint64_t)ts.tv_sec * 1000000000ull + (uint64_t)ts.tv_nsec;
}

