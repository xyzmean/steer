/* Диагностика включается переменной окружения: в обычной работе поток пакетов заливает
 * лог, а при разборе «почему соединение не встаёт» видеть каждый шаг необходимо. */
static int g_trace;
#define TR(...) do { if (g_trace) fprintf(stderr, "tun: " __VA_ARGS__); } while (0)

static struct conn *conn_find(const struct flow_key *k) {
    for (int i = 0; i < MAX_CONNS; i++) {
        struct conn *c = &g_conns[i];
        if (!c->used) continue;
        if (c->key.src == k->src && c->key.dst == k->dst &&
            c->key.sport == k->sport && c->key.dport == k->dport)
            return c;
    }
    return NULL;
}

static void conn_drop(struct conn *c);

/* Свободное место в таблице, а если его нет — освободить самое давнее.
 *
 * Прежде здесь стоял отказ: «предел, клиент повторит SYN». Рассуждение выглядело безобидно
 * и оказалось худшим из возможных. Браузер держит соединения ЖИВЫМИ между запросами
 * (keep-alive), минутами и не посылая ни байта. Убирались такие только по общему правилу
 * «молчит 120 секунд». Значит при широком списке — например, включённом Cloudflare, за
 * которым стоит половина интернета, — шестьдесят четыре слота занимались за два открытых
 * сайта, и дальше ВСЕ новые соединения молча отбрасывались.
 *
 * Снаружи это выглядело ровно как «steer завис намертво»: процесс жив, счётчики растут,
 * туннель поднят, в логе тишина, и ни одна страница не открывается. Тишина здесь и была
 * главной ошибкой — отказ, о котором никто не узнаёт.
 *
 * Теперь новое соединение важнее самого давнего простаивающего, и это верный порядок: то,
 * что человек открывает сейчас, нужнее висящего keep-alive к сайту, закрытому пять минут
 * назад. Клиенту вытесненного посылается RST — он поймёт и переоткроет, а молчание оставило
 * бы его ждать ответа, которого не будет.
 *
 * Возвращает NULL только если вытеснять нечего, то есть все соединения свежие. */
static struct conn *conn_new(const struct tun_dev *tun) {
    for (int i = 0; i < MAX_CONNS; i++)
        if (!g_conns[i].used) return &g_conns[i];

    time_t now = time(NULL);
    struct conn *old = NULL;
    for (int i = 0; i < MAX_CONNS; i++) {
        struct conn *c = &g_conns[i];
        /* Закрытые сервером — первые кандидаты в любом возрасте: они уже ничего не принесут,
         * а живут только чтобы додать клиенту остаток. */
        int cheap = c->srv_closed != 0;
        /* Остальные — только если ДЕЙСТВИТЕЛЬНО простаивают. Порог не осторожность, а
         * исправление: без него вытеснялось самое давнее из ЖИВЫХ, и это оказалось хуже
         * прежнего молчаливого отказа. Каждый новый SYN стоит блокирующего рукопожатия
         * (100-400 мс), и приняв его ценой ещё работающего соединения, мы на одном ядре
         * получаем молотилку: цикл занят рукопожатиями, обслуживать существующие некогда,
         * клиенты повторяют, SYN'ов больше. На роутере это выглядело как «вообще ничего не
         * открывается», и в логе шла ровно эта строка по десять раз в секунду.
         *
         * Если простаивающих нет, честный ответ — отказать. Отказ дёшев: клиент повторит
         * SYN через секунду, и к тому времени место, скорее всего, освободится. */
        if (!cheap && now - c->last < IDLE_EVICT_S) continue;
        if (!old || cheap > (old->srv_closed != 0) ||
            (cheap == (old->srv_closed != 0) && c->last < old->last))
            old = c;
    }
    if (!old) {
        /* Молчать нельзя — именно за это пришлось искать причину полдня, — но и писать на
         * каждый пакет тоже: одна строка в две секунды. */
        static __thread time_t said;
        if (now != said && now - said >= 2) {
            said = now;
            fprintf(stderr, "steer tunnel: все %d соединений заняты и активны, новые "
                            "отклоняются — список слишком широк для этого роутера\n", MAX_CONNS);
        }
        return NULL;
    }

    unsigned char rst[64];
    size_t rl = tcp_build(rst, sizeof(rst), old->key.dst, old->key.src,
                          old->key.dport, old->key.sport,
                          old->our_seq, old->client_seq, TCP_RST | TCP_ACK, NULL, 0, 0, 0, -1);
    if (rl) tun_write_ctl(tun, rst, rl);
    /* В лог — не чаще раза в десять секунд. Вытеснение мёртвого соединения это уборка, а не
     * событие: на живом роутере таких строк набегало по тридцать шесть за сорок секунд, и все
     * они сообщали «всё хорошо» тревожным тоном. Лог, который кричит в норме, перестают
     * читать — и тогда он молчит и в настоящей беде. */
    static __thread time_t said_evict;
    if (now - said_evict >= 10) {
        said_evict = now;
        fprintf(stderr, "steer tunnel: таблица полна (%d), вытесняю ещё живые соединения "
                        "(последнее молчало %lu с) — список слишком широк для этого роутера\n",
                MAX_CONNS, (unsigned long)(now - old->last));
    }
    conn_drop(old);
    return old;
}

static void conn_drop(struct conn *c) {
    TR("закрываю conn#%ld fd=%d\n", (long)(c - g_conns), c->v.fd);
    if (c->used) vless_close(&c->v);
    rtx_done(&c->rtx);
    memset(c, 0, sizeof(*c));
}

/* Отправить серверу данные в правильной форме: с заголовком VLESS на первом кадре и в
 * обёртке Vision, если узел её требует.
 *
 * Три исхода, а не два: «ушло», «сейчас нельзя, повторите» и «всё сломалось». Средний
 * появился вместе с HTTP/2, где закрытое окно — нормальное состояние, а не сбой, и
 * путать его с отказом значит разрывать рабочее соединение. */
#define SEND_OK    0
#define SEND_AGAIN 1
#define SEND_FATAL (-1)

static int upstream_send(struct conn *c, const struct vless_node *node,
                         const unsigned char *data, size_t n) {
    static __thread unsigned char out[TUNNEL_BUF];
    size_t len = 0;

    if (!c->header_sent) {
        /* Адрес назначения берём из пакета: имени у нас нет, клиент уже разрешил его сам
         * (или через наш резолвер, который вернул fake-IP и подменит адрес в DNAT). */
        unsigned char ip4[4];
        memcpy(ip4, &c->key.dst, 4);
        /* dport уже в хостовом порядке — см. комментарий в tun.h. */
        len = vless_build_request(c->uuid, VLESS_CMD_TCP, NULL, ip4,
                                  c->key.dport, node->flow, out, sizeof(out));
        if (!len) return SEND_FATAL;
    }

    if (node->flow[0]) {
        static __thread unsigned char framed[TUNNEL_BUF];
        size_t fn = vision_wrap(&c->vis, data, n, framed, sizeof(framed));
        if (!fn) return SEND_FATAL;
        if (len + fn > sizeof(out)) return SEND_FATAL;
        memcpy(out + len, framed, fn);
        len += fn;
    } else {
        if (len + n > sizeof(out)) return SEND_FATAL;
        memcpy(out + len, data, n);
        len += n;
    }

    /* Через vless_send: упаковку транспорта знает клиент, а не туннель. */
    int rc = vless_send(&c->v, out, len);
    if (rc == H2_EWINDOW) {
        /* Окно HTTP/2 закрыто: сервер не успевает принимать. Это НЕ отказ — это то, для
         * чего управление потоком и существует. Ничего не ушло (h2_write либо отправляет
         * всё, либо ничего), поэтому достаточно не подтверждать пакет: клиент повторит
         * его сам, как при потере, и повторит уже тогда, когда окно откроется.
         *
         * Первая версия считала это ошибкой и разрывала соединение. Выглядело как
         * «выгрузка обрывается на случайном месте» — месте, где сервер впервые не успел. */
        return SEND_AGAIN;
    }
    if (rc) return SEND_FATAL;
    /* Заголовок отмечаем отправленным только теперь: пометить раньше значило бы, что
     * повторная попытка уйдёт без него, и сервер не поймёт, куда соединять. */
    c->header_sent = 1;
    return SEND_OK;
}

/* Отдать клиенту кусок потока как TCP.
 *
 * Один вызов на кусок, без промежуточного буфера: данные уходят в устройство прямо оттуда,
 * где лежат после расшифровки. Прежняя версия собирала их в отдельный массив, потом
 * копировала оттуда в пакет — то есть каждый байт трафика проходил по памяти трижды.
 *
 * Размер куска определяет разгрузка. С ней одним вызовом уходит вся запись целиком, а
 * нарезку по MSS делает ядро; без неё режем сами по 1460 и платим за каждый сегмент
 * отдельным вызовом и отдельным проходом по данным ради контрольной суммы. */
static int emit_to_client(struct conn *c, const struct tun_dev *tun,
                          const unsigned char *p, size_t n) {
    /* Копия для повтора — ДО отправки. Место проверено заранее (client_can_take_record), и
     * если его вдруг нет, отправлять нельзя: отправленное без копии повторить нечем, а
     * именно это и подвешивало соединения. */
    /* Кольцо появляется здесь — при первых данных, а не при SYN, — и растёт по надобности.
     * Отказ выделения безопасен: мы просто не отправляем, то есть и не читаем дальше у
     * сервера, а значит ничего не теряем. Отказ роста тоже не ошибка: работаем с прежним
     * кольцом, окно просто меньше. */
    if (!c->rtx.cap && rtx_init(&c->rtx, RTX_START) != 0) {
        TR("нет памяти на кольцо повтора — не отправляю %zu байт\n", n);
        return -1;
    }
    if (rtx_room(&c->rtx) < n && c->rtx.cap < RTX_CAP) rtx_grow(&c->rtx, RTX_CAP);
    if (rtx_room(&c->rtx) < n) {
        TR("буфер повтора полон (%u из %u) — не отправляю %zu байт\n",
           c->rtx.len, c->rtx.cap, n);
        return -1;
    }
    if (!c->rtx.len) { c->rtx_at = now_ns(); c->rto_ms = rto_floor(); }
    rtx_push(&c->rtx, p, (uint32_t)n);

    size_t seg = tun->gso ? (size_t)TUN_GSO_MAX : (size_t)TUN_MSS;
    size_t sent = 0;
    while (sent < n) {
        size_t chunk = n - sent > seg ? seg : n - sent;
        unsigned char hdr[TUN_HDR_LEN];
        /* Отвечаем от имени сервера: адреса и порты наоборот. */
        tcp_hdr_build(hdr, c->key.dst, c->key.src, c->key.dport, c->key.sport,
                      c->our_seq, c->client_seq, TCP_ACK | TCP_PSH, chunk, 65535);
        uint64_t w0 = g_stats ? now_ns() : 0;
        if (tun_write_data(tun, hdr, p + sent, chunk) != 0) {
            TR("запись в TUN не удалась (%zu байт): %s\n", chunk, strerror(errno));
            return -1;
        }
        if (g_stats) { g_st.tun_writes++; g_st.tun_write_ns += now_ns() - w0; }
        c->our_seq += (uint32_t)chunk;
        sent += chunk;
        /* Данные несут подтверждение в своём заголовке, поэтому отдельный ACK клиенту
         * больше не нужен. */
        c->ack_due = 0;
    }
    return 0;
}

/* Отправить заново с начала неподтверждённого.
 *
 * Один сегмент, а не весь буфер: посылать 128 КБ на каждый таймаут — это лавина, которая
 * сама себе создаёт потери. TCP так и делает, и по той же причине. Если потеряно больше,
 * следующий круг подтверждений покажет это, и повтор пойдёт дальше.
 *
 * Размер сегмента — тот же, каким отправляли: при разгрузке потеряться могла вся
 * шестнадцатикилобайтная порция, и повторять её по 1460 байт значило бы растянуть
 * восстановление на десять таймаутов. */
static void rtx_resend(struct conn *c, const struct tun_dev *tun, const char *why) {
    uint32_t seg = tun->gso ? (uint32_t)TUN_GSO_MAX : (uint32_t)TUN_MSS;
    const unsigned char *body = NULL;
    uint32_t n = rtx_peek(&c->rtx, seg, &body);
    if (!n) return;

    unsigned char hdr[TUN_HDR_LEN];
    tcp_hdr_build(hdr, c->key.dst, c->key.src, c->key.dport, c->key.sport,
                  c->client_ack, c->client_seq, TCP_ACK | TCP_PSH, n, 65535);
    TR("повтор conn#%ld: %u байт с seq=%u (%s)\n",
       (long)(c - g_conns), n, c->client_ack, why);
    if (tun_write_data(tun, hdr, body, n) != 0) return;
    if (g_stats) { g_st.rtx_sends++; g_st.rtx_bytes += n; }
    c->rtx_at = now_ns();
    c->rto_ms = c->rto_ms * 2 > RTO_MAX_MS ? RTO_MAX_MS : c->rto_ms * 2;
}

/* Прочитать у сервера и отдать клиенту как TCP-пакет. */
static int downstream_pump(struct conn *c, const struct vless_node *node,
                           const struct tun_dev *tun) {
    /* Статический, а не на стеке: буфер размером с запись TLS — это шестнадцать килобайт
     * стека на каждый вызов, а поток обработки здесь один. */
    static __thread unsigned char buf[TUNNEL_BUF];
    size_t got = 0;
    /* Через vless_recv, а не tls13_read напрямую: у grpc и xhttp между TLS и VLESS лежит
     * HTTP/2, и чтение мимо него отдавало бы кадры вместо данных. Прямой вызов работал,
     * пока транспорт был единственный, и это ровно тот случай, когда «работает» и
     * «правильно» разошлись молча. */
    TR("чтение conn#%ld fd=%d\n", (long)(c - g_conns), c->v.fd);
    uint64_t r0 = g_stats ? now_ns() : 0;
    int rc = vless_recv(&c->v, buf, sizeof(buf), &got);
    if (g_stats) g_st.recv_ns += now_ns() - r0;
    g_rx_total += got;
    if (g_stats) { g_st.recs++; g_st.rec_bytes += got; }
    if (rc) { TR("чтение от сервера: rc=%d\n", rc); return rc; }
    /* Ноль байт — законно: приехал служебный кадр HTTP/2, данных пока нет. Принять это за
     * конец потока значило бы разрывать соединение на первом же SETTINGS. */
    if (!got) { TR("служебный кадр, данных нет\n"); return 0; }
    TR("от сервера %zu байт\n", got);

    /* Порядок разбора: сначала заголовок ОТВЕТА VLESS, потом кадры Vision.
     *
     * Сервер отвечает так: [версия|длина_доп|доп] и только ДАЛЬШЕ поток в кадрах Vision.
     * Заголовок ответа обёрткой не покрыт, и первая версия пыталась развернуть его как
     * кадр: получала «00 00 96 67 ad» (версия 0, длина 0, начало данных), длины кадра
     * выходили бессмысленные, unwrap возвращал EAGAIN, и ответ терялся целиком.
     *
     * Это зеркало ошибки на отправке: там заголовок ЗАПРОСА тоже идёт до кадра, а не
     * внутри него. Один и тот же принцип, который я дважды прочитал наоборот. */
    const unsigned char *cur = buf;
    size_t left = got;

    if (!c->established) {
        size_t skip = 0;
        if (vless_parse_response(cur, left, &skip) != 0) {
            TR("ответ VLESS не разобран (%zu байт)\n", left);
            return -1;
        }
        cur += skip;
        left -= skip;
        c->established = 1;
        TR("заголовок ответа снят (%zu байт), осталось %zu\n", skip, left);
    }

    size_t total = 0;

    while (left) {
        const unsigned char *p = cur;
        size_t pn = left;

        if (node->flow[0]) {
            size_t used = 0;
            const unsigned char *pl = NULL;
            size_t pl_n = 0;
            int ur = vision_unwrap(&c->vis, cur, left, &used, &pl, &pl_n);
            if (ur != 0 || !used) {
                /* Разбор больше не может «не хватить данных»: он потоковый и переносит
                 * состояние между вызовами. Сюда попадаем только на настоящей ошибке —
                 * недопустимой команде в кадре. */
                TR("кадр не разобран: ur=%d осталось %zu\n", ur, left);
                break;
            }
            p = pl;
            pn = pl_n;
            cur += used;
            left -= used;

        } else {
            cur += left;
            left = 0;
        }

        /* Отдаём кадр сразу, а не складываем в общий буфер: складывать было незачем — всё
         * равно потом нарезали, — а стоило это копии всего трафика и предела «не влезло». */
        if (pn) {
            if (emit_to_client(c, tun, p, pn) != 0) return -1;
            total += pn;
        }
    }

    /* Сервер объявил прямое копирование — сообщаем об этом соединению, чтобы следующее
     * чтение шло мимо расшифровки. Ставится ЗДЕСЬ, потому что команда живёт в кадрах
     * Vision, а про них знает только этот код. */
    if (c->vis.recv_direct && !c->v.rx_direct) {
        c->v.rx_direct = 1;
        TR("сервер перешёл на прямое копирование — читаем сокет как есть\n");
    }

    if (!total) { TR("после разбора данных нет\n"); return 0; }
    TR("клиенту %zu байт (seq до %u)\n", total, c->our_seq);
    return 0;
}

/* Один пакет из TUN. */
static void handle_packet(const struct tun_dev *tun, const struct vless_node *node,
                          const unsigned char *pkt, size_t n) {
    struct flow_key k;
    size_t off = 0;
    if (ip_parse(pkt, n, &k, &off) != 0) { TR("пакет не разобран (%zu байт)\n", n); return; }
    TR("%u.%u.%u.%u:%u -> %u.%u.%u.%u:%u proto=%u flags=0x%02x len=%zu\n",
       k.src&255,(k.src>>8)&255,(k.src>>16)&255,(k.src>>24)&255, k.sport,
       k.dst&255,(k.dst>>8)&255,(k.dst>>16)&255,(k.dst>>24)&255, k.dport,
       k.proto, k.tcp_flags, n - off);

    /* UDP и прочее не пересылаем: VLESS UDP требует отдельной обёртки, а основной UDP,
     * который важен для маршрутизации, — это DNS, и его перехватывает резолвер steer.
     *
     * Но и НЕ МОЛЧИМ. Прежде такой пакет просто выбрасывался, и это стоило целых сайтов:
     * браузер идёт к Cloudflare по QUIC, то есть UDP на 443, и тишину понимает как «ещё не
     * ответили», а не «нельзя». Он ждёт и повторяет, и на сайтах, настойчиво предпочитающих
     * QUIC, страница не открывалась вовсе — при живом туннеле, где TCP до тех же адресов
     * проходил за 250 мс семь раз из семи. ICMP-отказ превращает ожидание в мгновенный
     * переход на TCP, который у нас работает.
     *
     * Проверка dport на 53 — чтобы не отвечать отказом на DNS: его перехватывает резолвер,
     * и попавший сюда запрос означает, что перехват не настроен. Отказ там сломал бы
     * разрешение имён вместо того, чтобы просто не помочь. */
    if (k.proto != 6) {
        if (!(k.proto == 17 && k.dport == 53)) {
            unsigned char un[128];
            size_t ul = icmp_unreach_build(un, sizeof(un), pkt, n);
            if (ul) tun_write_ctl(tun, un, ul);
        }
        TR("не TCP (proto=%u), отказ\n", k.proto);
        return;
    }

    struct conn *c = conn_find(&k);

    if (k.tcp_flags & TCP_SYN) {
        if (c) return;                              /* повтор SYN — уже открываем */
        c = conn_new(tun);
        if (!c) return;                             /* все соединения свежие — клиент повторит */
        memset(c, 0, sizeof(*c));
        c->used = 1;
        c->key = k;
        c->client_seq = k.seq + 1;                  /* SYN занимает один номер */
        c->our_seq = 1;                             /* свой поток начинаем с 1 */
        c->client_ack = 1;                          /* столько он уже подтвердил (SYN-ACK) */
        c->client_win = k.window ? k.window : 8192;
        c->client_wscale = k.wscale;
        c->rto_ms = rto_floor();
        c->last = time(NULL);
        /* Кольцо повтора НЕ выделяется на SYN. Прежде выделялось, и рассуждение было такое:
         * лениво означало бы, что отказ выделения приходит посреди передачи, когда отвечать
         * клиенту уже нечем. Рассуждение верное для кольца, которое обязано существовать, —
         * и неверное для нашего.
         *
         * Кольцо хранит НЕПОДТВЕРЖДЁННЫЕ байты. Пока их нет, хранить нечего, и буфер не нужен
         * вовсе. А отказ выделения приходит не «посреди передачи», а РОВНО ПЕРЕД чтением у
         * сервера: не смогли выделить — не читаем, и терять нечего, потому что мы ещё ничего
         * не взяли. Клиенту при этом врать не приходится.
         *
         * Зачем так: браузер держит десятки соединений живыми, ничего по ним не передавая
         * (HTTP/2 keep-alive), и за каждое платилось 32 КБ, которых потом не хватало на новые.
         * Теперь простаивающее соединение стоит только своей записи в таблице. */
        if (vless_uuid_parse(node->uuid, c->uuid) != 0) { conn_drop(c); return; }
        vision_init(&c->vis, c->uuid);

        TR("SYN: открываю поток к серверу\n");
        int cr = vless_connect(node, &c->v, 8);
        if (cr != 0) {
            /* С причиной, а не «не открылся». Без неё разбор упирается в стену: код
             * различает «TCP не соединился», «сервер не признал ключ» и «сервер не
             * согласился на HTTP/2», а в логе всё это выглядело одинаково. */
            fprintf(stderr, "steer tunnel: поток к %s не открылся: %s (rc=%d)\n",
                    node->host, vless_strerror(cr), cr);
            /* Сервер недоступен — отвечаем RST, а не молчим: клиент иначе будет ждать
             * до таймаута, и «сайт не открывается» вместо «отказано в соединении».
             *
             * Я пробовал молчать, рассчитывая, что клиент повторит SYN сам и попадёт в
             * удачную попытку: узел отбивал 11 соединений из 19, а RST браузер понимает как
             * окончательное «отказано». Стало ХУЖЕ — страница с видео перестала открываться
             * вовсе. Молчание не даёт браузеру перейти к следующему адресу, а он на это
             * рассчитывает: у него самого есть и повтор, и запасные адреса, и наш быстрый
             * отказ он использует лучше, чем мы его ожидание. Проверено на живом роутере,
             * возвращено обратно. */
            unsigned char rst[64];
            size_t rl = tcp_build(rst, sizeof(rst), k.dst, k.src, k.dport, k.sport,
                                  0, c->client_seq, TCP_RST | TCP_ACK, NULL, 0, 0, 0, -1);
            if (rl) tun_write_ctl(tun, rst, rl);
            conn_drop(c);
            return;
        }
        /* SYN-ACK: подтверждаем соединение клиенту. */
        unsigned char sa[64];
        size_t sl = tcp_build(sa, sizeof(sa), k.dst, k.src, k.dport, k.sport,
                              c->our_seq++, c->client_seq, TCP_SYN | TCP_ACK,
                              NULL, 0, 65535, TUN_MSS, OUR_WSCALE);
        if (sl) tun_write_ctl(tun, sa, sl);
        TR("SYN-ACK отправлен (seq=%u ack=%u)\n", c->our_seq - 1, c->client_seq);
        return;
    }

    if (!c) return;                                 /* данные без соединения — игнор */
    c->last = time(NULL);

    /* Учитываем подтверждения и окно клиента с ЛЮБОГО его пакета, включая чистые ACK: без
     * этого мы не знаем, сколько он принял, и продолжаем лить в устройство. Именно чистые
     * ACK и приходят во время скачивания — данных от клиента там нет вовсе. */
    size_t data_n = n - off;

    if (k.tcp_flags & TCP_ACK) {
        /* Сравнение с учётом переполнения счётчика: разность как знаковая. */
        if ((int32_t)(k.ack - c->client_ack) > 0) {
            rtx_drop(&c->rtx, k.ack - c->client_ack);   /* ДО сдвига: отсчёт от старого */
            c->client_ack = k.ack;
            c->dup_acks = 0;
            c->fast_done = 0;
            /* Есть продвижение — таймаут снова короткий, и он отсчитывается от нового
             * самого старого байта, а не от прежнего. */
            c->rtx_at = c->rtx.len ? now_ns() : 0;
            c->rto_ms = rto_floor();
        } else if (k.ack == c->client_ack && c->rtx.len && !data_n && !c->fast_done &&
                   k.window == c->client_win && !(k.tcp_flags & (TCP_SYN | TCP_FIN))) {
            /* Дубликат подтверждения по определению из RFC 5681: тот же номер, без данных,
             * БЕЗ ИЗМЕНЕНИЯ ОКНА и при неподтверждённых данных в пути.
             *
             * Условие про окно — не формальность. Пока клиент читает принятое, его ядро
             * шлёт обновления окна: тот же номер подтверждения, окно больше. Считать их
             * дубликатами значит повторять данные на каждой третьей такой пачке посреди
             * исправной передачи — то есть тратить полосу ровно там, где всё в порядке. */
            if (++c->dup_acks >= DUP_ACK_TRIGGER) {
                c->dup_acks = 0;
                c->fast_done = 1;
                rtx_resend(c, tun, "три подтверждения одного номера");
            }
        }
        c->client_win = k.window;
    }

    if (k.tcp_flags & (TCP_RST | TCP_FIN)) {
        if (k.tcp_flags & TCP_FIN) {
            /* Подтверждаем FIN и закрываем: половинчатое закрытие не поддержано, потому
             * что требует хранить, какая сторона ещё пишет. */
            unsigned char fa[64];
            size_t fl = tcp_build(fa, sizeof(fa), k.dst, k.src, k.dport, k.sport,
                                  c->our_seq, k.seq + 1, TCP_ACK | TCP_FIN, NULL, 0, 0, 0, -1);
            if (fl) tun_write_ctl(tun, fa, fl);
        }
        conn_drop(c);
        return;
    }

    if (!data_n) return;                            /* чистый ACK */

    /* Не по порядку — отбрасываем. Буфер переупорядочивания на каждое соединение это как
     * раз та память, которой на слабой коробке нет; клиент повторит. */
    if (k.seq != c->client_seq) return;

    TR("данные клиента %zu байт -> серверу\n", data_n);
    int sr = upstream_send(c, node, pkt + off, data_n);
    if (sr == SEND_AGAIN) {
        /* Окно закрыто. Прежде чем перекладывать задержку на клиента, разберём то, что уже
         * лежит в сокете: WINDOW_UPDATE приходит именно оттуда и обычно УЖЕ там — сервер
         * присылает его, как только освободил буфер.
         *
         * Без этой попытки каждое закрытие окна стоило бы таймаута повторной передачи у
         * клиента, то есть двухсот миллисекунд на каждые 64 КБ. Замер: выгрузка через
         * grpc шла 200 КБ/с вместо мегабайта.
         *
         * Читаем через downstream_pump, а не сами: только он умеет отдать пришедшие данные
         * клиенту. Читать «на выброс» здесь означало бы потерять ответ сервера. */
        /* Пять миллисекунд ожидания, а не ноль. Кадр WINDOW_UPDATE обычно уже в сокете, но
         * иногда отстаёт на доли круга — и тогда нулевое ожидание отдаёт задержку клиенту,
         * у которого таймаут повторной передачи двести миллисекунд. Пять против двухсот.
         *
         * Больше нельзя: цикл здесь один на все соединения, и каждая миллисекунда ожидания
         * — это миллисекунда, на которую стоят остальные. */
        struct pollfd sp = { .fd = c->v.fd, .events = POLLIN };
        if (poll(&sp, 1, 5) > 0 && (sp.revents & POLLIN)) {
            if (downstream_pump(c, node, tun) != 0) { conn_drop(c); return; }
            sr = upstream_send(c, node, pkt + off, data_n);
        }
    }
    if (sr == SEND_AGAIN) {
        /* Всё ещё нельзя: не подтверждаем и не двигаем счётчик — пакет для нас как бы не
         * приходил. Клиент повторит его сам, и это единственный способ придержать поток,
         * не храня недоотправленное у себя. */
        TR("окно закрыто, пакет не подтверждён — клиент повторит\n");
        return;
    }
    if (sr != SEND_OK) {
        TR("отправка серверу не удалась\n");
        conn_drop(c);
        return;
    }
    c->client_seq += (uint32_t)data_n;

    /* Подтверждение ОТКЛАДЫВАЕМ до конца разбора порции из TUN. Без ACK клиент повторит
     * пакет, считая его потерянным, — но подтверждать каждый пакет отдельной записью в
     * устройство незачем: за проход их приезжает до шестидесяти четырёх, и все они
     * подтверждаются одним ACK с последним номером. */
    c->ack_due = 1;
}

/* Разослать отложенные подтверждения. Вызывается после разбора порции пакетов из TUN. */
static void flush_acks(const struct tun_dev *tun) {
    for (int i = 0; i < MAX_CONNS; i++) {
        struct conn *c = &g_conns[i];
        if (!c->used || !c->ack_due) continue;
        c->ack_due = 0;
        unsigned char ackp[64];
        size_t al = tcp_build(ackp, sizeof(ackp), c->key.dst, c->key.src,
                              c->key.dport, c->key.sport,
                              c->our_seq, c->client_seq, TCP_ACK, NULL, 0, 65535, 0, -1);
        if (al) tun_write_ctl(tun, ackp, al);
    }
}

int run_quiet(const char *const argv[]);   /* из steer.c */

/* Поднять устройство и дать ему адрес.
 *
 * Делает это движок, а не управляющий слой, потому что устройство создаёт тоже движок:
 * между «TUN появился» и «TUN готов нести трафик» нет никого, кому это можно было бы
 * поручить. Без этого apply не находит рабочего устройства, ставит blackhole (при
 * on_fail=drop) и трафик стоит — притом что процесс запущен, узел выбран и в логе всё
 * выглядит успешным. Ровно тот случай, когда «настроено» и «работает» расходятся молча.
 *
 * Адрес нужен не нам: наш клиент читает из TUN пакеты и открывает по ним потоки, source
 * в них не участвует вовсе. Нужен он ядру и фаерволу — маршрут на устройство без адреса
 * ядро считает непригодным для локально порождённых пакетов.
 *
 * 198.51.100.0/24 — это TEST-NET-2 из RFC 5737: диапазон, отведённый под документацию и
 * НЕ маршрутизируемый в интернете. Поэтому он не может столкнуться ни с чужим сервисом,
 * ни с локальной сетью, которую кто-то себе выбрал. Пул fake-IP (198.18.0.0/15) здесь
 * брать нельзя — он занят под другую задачу, и пересечение перепутало бы одно с другим.
 *
 * Номер адреса берётся из таблицы маршрутизации выхода: она уже уникальна и уже лежит в
 * реестре, то есть переживает перезагрузку. Выдумывать для этого второй счётчик значило
 * бы завести второе место, где номера могут разъехаться. */
static void tun_bring_up(const char *dev, int table) {
    char addr[40];
    snprintf(addr, sizeof(addr), "198.51.100.%d/32", 1 + (table % 200));
    const char *a[] = { "ip", "addr", "replace", addr, "dev", dev, NULL };
    run_quiet(a);
    const char *u[] = { "ip", "link", "set", "dev", dev, "up", NULL };
    run_quiet(u);
    /* Очередь устройства — 500 пакетов по умолчанию, а мы пишем в него по семь тысяч
     * пакетов в секунду. Полная очередь означает EAGAIN и ожидание на каждой записи, то
     * есть скорость, определяемую не каналом, а нашими паузами. Четыре тысячи пакетов —
     * это 5,8 МБ, меньше секунды буферизации на быстром канале и никакой памяти зря:
     * очередь занимает столько, сколько в ней реально лежит. */
    const char *q[] = { "ip", "link", "set", "dev", dev, "txqueuelen", "4096", NULL };
    run_quiet(q);
}

/* Что нужно потоку, чтобы работать: своя очередь устройства, узел и свой номер. Больше
 * ничего — остальное состояние у него собственное (__thread). */
struct worker {
    struct tun_dev tun;
    const struct vless_node *node;
    int id;
};

static void *worker_loop(void *arg) {
    struct worker *w = arg;
    struct tun_dev tun = w->tun;
    const struct vless_node *node = w->node;
    int tun_fd = tun.fd;
    g_worker = w->id;

    g_st.win_min = 0xFFFFFFFFu;
    uint64_t stats_at = g_stats ? now_ns() : 0;
    uint64_t loop_at = 0;   /* когда вернулся прошлый poll — для оценки периода прохода */
    memset(g_conns, 0, sizeof(g_conns));
    unsigned char pkt[TUNNEL_BUF];

    for (;;) {
        struct pollfd pf[1 + MAX_CONNS];
        struct conn *map[MAX_CONNS];
        int nf = 0;
        pf[nf].fd = tun_fd;
        pf[nf].events = POLLIN;
        nf++;
        for (int i = 0; i < MAX_CONNS; i++) {
            if (!g_conns[i].used) continue;
            /* У закрытых сервером читать нечего — они живут только чтобы додать клиенту. */
            if (g_conns[i].srv_closed) continue;
            /* Не спрашиваем сервер о новых данных, пока клиент не разгрёб прежние.
             *
             * Это и есть управление потоком, которого у нас иначе нет: прочитав, мы обязаны
             * сразу записать в устройство, а очередь устройства не бесконечна. Переполнив
             * её, мы теряем сегмент — и без повторной передачи соединение подвисает
             * навсегда: клиент подтверждает старое, мы отдаём новое, и никто не сходится.
             *
             * Замер: на роутере без этой проверки передача вставала на втором мегабайте. */
            /* Окно и «в пути» пишем ВСЕГДА, а не только когда отказались читать.
             *
             * Прежде они считались внутри ветки отказа, и при «ждали окна 0/с» в отчёте
             * стояли нули — то есть ровно там, где надо понять, почему поток встал, чисел
             * не было вовсе. А встать он может и не упираясь в окно: сегмент, отброшенный
             * приёмником, мы не повторим никогда, и выглядит это как тишина при свободном
             * окне. Различить два случая можно только видя оба числа. */
            if (g_stats) {
                uint32_t room = client_room(&g_conns[i]);
                uint32_t infl = g_conns[i].our_seq - g_conns[i].client_ack;
                if (room < g_st.win_min) g_st.win_min = room;
                if (room > g_st.win_max) g_st.win_max = room;
                if (infl > g_st.inflight_max) g_st.inflight_max = infl;
                g_st.wscale_seen = g_conns[i].client_wscale;
            }
            if (!client_can_take_record(&g_conns[i])) {
                if (g_stats) g_st.win_skips++;
                continue;
            }
            pf[nf].fd = g_conns[i].v.fd;
            pf[nf].events = POLLIN;
            map[nf - 1] = &g_conns[i];
            nf++;
        }
        if (g_stats) {
            uint32_t live = 0;
            for (int i = 0; i < MAX_CONNS; i++) if (g_conns[i].used) live++;
            g_st.conns = live;
        }

        /* Паузы на «пустой проход» здесь БЫЛА и убрана. Она душила одиночное соединение:
         * недособранная запись стоила миллисекунды, то есть ~8 МБ/с потолка — замерено
         * 9 Мбит/с на одном потоке против 192 на восьми. Остаток записи теперь добирается
         * коротким ожиданием на самом сокете (см. read_record), поэтому холостых проходов
         * не остаётся и тормозить цикл незачем. */
        /* Таймаут poll — до ближайшего срока повтора, а не всегда секунда.
         *
         * Иначе повтор через 50 мс ждал бы, пока цикл проснётся сам: при живом трафике это
         * происходит сразу, а при потере последнего сегмента просыпаться уже нечему —
         * ровно тот случай, для которого таймер и нужен. */
        uint64_t now = now_ns();

        /* Период прохода: сколько прошло с прошлого места ожидания. Считаем РАБОЧУЮ часть,
         * а не время в poll: порог RTO должен закрывать то, на что мы заняты, а сон в poll
         * прерывается пришедшим подтверждением сразу. Сглаживание 1/8 — как в оценке RTT в
         * TCP, чтобы одна долгая итерация не задирала порог надолго. */
        if (loop_at) {
            uint64_t busy64 = (now - loop_at) / 1000000;
            uint32_t busy = busy64 > 5000 ? 5000 : (uint32_t)busy64;
            /* Вверх с округлением вверх — то есть заметив занятость, порог поднимается сразу
             * хотя бы на миллисекунду. Вниз с округлением вниз, чтобы не дёргаться. */
            if (busy > g_loop_ms) g_loop_ms += (busy - g_loop_ms + 7) / 8;
            else                  g_loop_ms -= (g_loop_ms - busy) / 8;
        }

        int wait_ms = 1000;
        for (int i = 0; i < MAX_CONNS; i++) {
            const struct conn *c = &g_conns[i];
            if (!c->used || !c->rtx.len || !c->rtx_at) continue;
            int64_t left = (int64_t)c->rto_ms - (int64_t)((now - c->rtx_at) / 1000000);
            if (left < 0) left = 0;
            if (left < wait_ms) wait_ms = (int)left;
        }

        int r = poll(pf, (unsigned)nf, wait_ms);
        uint64_t after_poll = now_ns();
        loop_at = after_poll;
        if (g_stats) {
            g_st.poll_ns += after_poll - now;
            g_st.iters++;
            if (after_poll - stats_at >= 2000000000ull) {
                stats_dump(after_poll - stats_at);
                stats_at = after_poll;
            }
        }
        if (r < 0) {
            if (errno == EINTR) continue;
            break;
        }

        if (pf[0].revents & POLLIN) {
            /* ВЫЧЕРПЫВАЕМ устройство, а не читаем по пакету за проход.
             *
             * Во время скачивания из TUN приходят подтверждения клиента, и именно они
             * открывают окно. Читая по одному за проход, мы ограничивали скорость числом
             * проходов цикла: замерено 1900 проходов в секунду × ~2920 байт на
             * подтверждение = 5,5 МБ/с, ровно тот потолок, который и наблюдался.
             *
             * Устройство переведено в неблокирующий режим, поэтому «больше нечего» приходит
             * как EAGAIN, а не как сон. Предел на проход всё равно нужен: иначе поток
             * пакетов от одного клиента не даст дойти до чтения у серверов. */
            for (int k = 0; k < TUN_DRAIN_MAX; k++) {
                uint64_t t0 = g_stats ? now_ns() : 0;
                ssize_t rn = tun_read_packet(&tun, pkt, sizeof(pkt));
                uint64_t t1 = g_stats ? now_ns() : 0;
                if (rn <= 0) break;
                if (g_stats) { g_st.tun_reads++; g_st.tun_read_ns += t1 - t0; }
                handle_packet(&tun, node, pkt, (size_t)rn);
                if (g_stats) g_st.pkt_ns += now_ns() - t1;
            }
            flush_acks(&tun);
        }
        for (int i = 1; i < nf; i++) {
            if (!(pf[i].revents & (POLLIN | POLLHUP | POLLERR))) continue;
            struct conn *c = map[i - 1];
            if (!c->used) continue;

            /* ВЫЧЕРПЫВАЕМ сокет, а не читаем по одной записи за проход цикла.
             *
             * Разница принципиальная. Пока мы не читаем, у сервера закрывается окно, и
             * заново открыть его стоит круга до сервера — десятки миллисекунд. Читая по
             * одной записи на итерацию, мы получаем скорость «запись за круг», то есть
             * задержку вместо полосы: замерено 3 Мбит/с там, где криптография держит 800.
             *
             * Предел здесь двойной: окно клиента (иначе потеряем сегмент, а повторной
             * передачи нет) и число записей за проход — чтобы одно активное соединение не
             * заморозило остальные. */
            int reads = 0;
            uint64_t drained_from = g_rx_total;
            for (;;) {
                if (downstream_pump(c, node, &tun) != 0) {
                    /* Сервер закрыл. Соединение НЕ закрываем, пока клиент не подтвердит всё
                     * отправленное: пока в кольце есть неподтверждённое, его надо повторять,
                     * а закрыв соединение, мы уничтожим и кольцо. FIN уйдёт в fin_if_drained. */
                    c->srv_closed = 1;
                    c->closed_at = now_ns();
                    TR("сервер закрыл conn#%ld, ждём подтверждения %u байт\n",
                       (long)(c - g_conns), c->rtx.len);
                    break;
                }
                if (++reads >= DRAIN_MAX_READS ||
                    g_rx_total - drained_from >= DRAIN_MAX_BYTES) {
                    if (g_stats) g_st.drain_full++;
                    break;
                }
                if (!client_can_take_record(c)) break;
                /* Есть ли ещё что читать. Без этой проверки следующее чтение заблокируется
                 * на таймауте сокета и остановит весь цикл на секунды. */
                struct pollfd sp = { .fd = c->v.fd, .events = POLLIN };
                if (poll(&sp, 1, 0) <= 0 || !(sp.revents & POLLIN)) break;
            }
        }

        /* Истёкшие сроки — повторяем. После обработки пакетов, а не до: подтверждение,
         * приехавшее в этом же проходе, могло снять надобность. */
        now = now_ns();
        for (int i = 0; i < MAX_CONNS; i++) {
            struct conn *c = &g_conns[i];
            if (!c->used || !c->rtx.len || !c->rtx_at) continue;
            if ((now - c->rtx_at) / 1000000 >= c->rto_ms)
                rtx_resend(c, &tun, "истёк таймаут");
        }

        /* Закрытые сервером: как только клиент подтвердил всё — FIN и закрываем. Если не
         * подтвердил за отведённое время, закрываем всё равно: клиент мог уйти совсем. */
        for (int i = 0; i < MAX_CONNS; i++) {
            struct conn *c = &g_conns[i];
            if (!c->used || !c->srv_closed) continue;
            int drained = c->rtx.len == 0;
            if (!drained && (now - c->closed_at) / 1000000 < CLOSE_DRAIN_MS) continue;
            if (!drained)
                TR("conn#%ld: клиент не подтвердил %u байт за %d мс, закрываю\n",
                   (long)(c - g_conns), c->rtx.len, CLOSE_DRAIN_MS);
            /* FIN, иначе клиент будет ждать данных, которых больше не будет. */
            unsigned char fin[64];
            size_t fl = tcp_build(fin, sizeof(fin), c->key.dst, c->key.src,
                                  c->key.dport, c->key.sport,
                                  c->our_seq, c->client_seq, TCP_FIN | TCP_ACK,
                                  NULL, 0, 0, 0, -1);
            if (fl) tun_write_ctl(&tun, fin, fl);
            conn_drop(c);
        }

        /* Уборка задержавшихся: без неё таблица заполняется соединениями, которые клиент
         * бросил без FIN, и новые перестают открываться.
         *
         * Порог — тот же IDLE_EVICT_S, что и у вытеснения: «мёртвое соединение» должно
         * означать одно и то же в обоих местах. Пробовал шестьдесят, рассчитывая освобождать
         * слоты раньше, — и получил RST по живым соединениям HTTP/2, которые браузер
         * переиспользует после минуты простоя.
         *
         * RST обязателен. Прежде здесь было молчаливое conn_drop, и клиент оставался с
         * соединением, которое считает открытым: следующий запрос по нему уходил в пустоту
         * и ждал таймаута — то есть наша уборка выглядела для человека как зависший сайт. */
        time_t stale = time(NULL);
        for (int i = 0; i < MAX_CONNS; i++) {
            struct conn *c = &g_conns[i];
            /* Пустое кольцо отдаём обратно системе. Соединение при этом полностью рабочее:
             * при следующих данных кольцо появится снова. Именно здесь, а не сразу по
             * опустошении, — иначе на каждом залпе подтверждений шли бы malloc и free. */
            if (c->used && c->rtx.cap && !c->rtx.len && stale - c->last > 5) rtx_done(&c->rtx);
            if (!c->used || stale - c->last <= IDLE_EVICT_S) continue;
            unsigned char rst[64];
            size_t rl = tcp_build(rst, sizeof(rst), c->key.dst, c->key.src,
                                  c->key.dport, c->key.sport,
                                  c->our_seq, c->client_seq, TCP_RST | TCP_ACK, NULL, 0, 0, 0, -1);
            if (rl) tun_write_ctl(&tun, rst, rl);
            conn_drop(c);
        }
    }
    for (int i = 0; i < MAX_CONNS; i++)
        if (g_conns[i].used) conn_drop(&g_conns[i]);
    close(tun_fd);
    return NULL;
}

/* Сколько потоков поднимать.
 *
 * По числу ядер, но не больше MAX_WORKERS: на двухъядерной коробке третий поток только
 * добавил бы переключений. Один поток на ядро, а не больше, потому что цикл почти всё время
 * либо ждёт в poll, либо считает — очередь на процессоре ему не помогает.
 *
 * STEER_TUN_THREADS задаёт число вручную. Нужно ровно для того же, для чего STEER_TUN_NOGSO:
 * «стало быстрее от второго ядра» — утверждение, которое надо уметь перепроверить, вернувшись
 * к одному потоку на том же железе. */
#define MAX_WORKERS 4

static int worker_count(void) {
    const char *env = getenv("STEER_TUN_THREADS");
    if (env) {
        int n = atoi(env);
        if (n >= 1) return n < MAX_WORKERS ? n : MAX_WORKERS;
    }
    long cpus = sysconf(_SC_NPROCESSORS_ONLN);
    if (cpus < 1) cpus = 1;
    return cpus < MAX_WORKERS ? (int)cpus : MAX_WORKERS;
}

int tunnel_run(struct output *o, const struct vless_node *node) {
    const char *dev = o->device;
    g_trace = getenv("STEER_TUN_TRACE") != NULL;
    g_stats = getenv("STEER_TUN_STATS") != NULL;

    static struct worker workers[MAX_WORKERS];
    struct tun_dev queues[MAX_WORKERS];
    int want = worker_count();
    int n = tun_open(queues, want, dev);
    if (n < 0) return n;

    for (int i = 0; i < n; i++) {
        /* Неблокирующее чтение: цикл вычерпывает устройство до EAGAIN, и без этого флага
         * последнее чтение засыпало бы, останавливая все соединения. */
        int fl = fcntl(queues[i].fd, F_GETFL, 0);
        if (fl >= 0) fcntl(queues[i].fd, F_SETFL, fl | O_NONBLOCK);
        workers[i].tun = queues[i];
        workers[i].node = node;
        workers[i].id = i;
    }
    tun_bring_up(dev, o->table);

    /* Привязываем таблицу выхода к устройству ЗДЕСЬ, а не в apply.
     *
     * Apply уже прошёл к этому моменту и, не найдя устройства, поставил запрет — иначе и
     * нельзя: пока туннеля нет, пускать в него трафик некуда. Дождаться устройства снаружи
     * невозможно: procd запускает этот процесс только после того, как init-скрипт вернул
     * управление, то есть уже после apply. Значит привязать может только тот, кто знает
     * момент готовности, — а это мы. */
    bind_device(o, dev);
    fprintf(stderr, "steer tunnel: %s привязан к таблице %d\n", dev, o->table);
    fprintf(stderr, "steer tunnel: %s -> %s (%s:%u %s%s)\n", dev, node->name,
            node->host, node->port, node->type, node->flow[0] ? " +vision" : "");
    /* Печатается всегда: без разгрузки и без второй очереди скорость падает в разы, и знать,
     * что именно досталось, надо до замеров, а не после. */
    fprintf(stderr, "steer tunnel: разгрузка записи в %s %s; потоков %d из %d запрошенных\n",
            dev, queues[0].gso ? "включена (сегменты до 16 КБ, суммы считает ядро)"
                               : "НЕДОСТУПНА — нарезаем по 1460 и считаем суммы сами",
            n, want);
    if (n < want)
        fprintf(stderr, "steer tunnel: очередей меньше запрошенного — ядро без "
                        "IFF_MULTI_QUEUE, работаем в один поток\n");

    /* Потоки со второго по последний — отдельными, первый работает в этом же. Так процесс
     * остаётся тем, чем был для procd: если цикл завершится, завершится и процесс. */
    pthread_t tids[MAX_WORKERS];
    int started = 0;
    for (int i = 1; i < n; i++) {
        if (pthread_create(&tids[started], NULL, worker_loop, &workers[i]) != 0) {
            fprintf(stderr, "steer tunnel: поток %d не создался, работаем без него\n", i);
            close(workers[i].tun.fd);
            continue;
        }
        started++;
    }
    worker_loop(&workers[0]);
    for (int i = 0; i < started; i++) pthread_join(tids[i], NULL);
    return 0;
}

/* ---- подкоманда steer vless -------------------------------------------------
 *
 * Поднимает TUN для выхода kind=vless из спеки. Отдельный процесс, а не поток внутри
 * apply: apply должен завершаться, а туннель — жить. Init-скрипт держит по экземпляру
 * procd на каждый такой выход, поэтому падение одного не уносит остальные.
 */
#define MAX_NODES 128
static struct vless_node g_nodes[MAX_NODES];

/* Найти выход и разобрать его подписку. Одно место на все три команды: иначе «как
 * читается подписка» разошлось бы между подъёмом, списком и проверкой — а расхождение
 * здесь означало бы, что человек выбирает в интерфейсе не тот узел, который поднимется. */
static int load_nodes(const char *spec_path, const char *out_name, struct output **out,
                      size_t *cnt, size_t *skipped, size_t *foreign) {
    load_spec(spec_path);
    struct output *o = out_by_name(out_name);
    if (!o) { fprintf(stderr, "steer: выхода %s нет в спеке\n", out_name); return 2; }
    if (o->kind != OUT_VLESS) {
        fprintf(stderr, "steer: выход %s не vless (kind другой)\n", out_name);
        return 2;
    }
    *out = o;

    /* Подписка читается с диска: скачивание — дело управляющего слоя. */
    FILE *f = fopen(o->sub_file, "r");
    if (!f) { fprintf(stderr, "steer: %s не читается\n", o->sub_file); return 2; }
    static char raw[262144], dec[262144];
    size_t n = fread(raw, 1, sizeof(raw) - 1, f);
    raw[n] = '\0';
    fclose(f);
    const char *text = raw;
    if (!strstr(raw, "://")) { b64_decode(raw, n, dec, sizeof(dec)); text = dec; }

    *cnt = vless_parse_sub(text, g_nodes, MAX_NODES, skipped, foreign);
    return 0;
}

/* Строка JSON с экранированием. Имена узлов приходят из подписки и содержат что угодно —
 * кавычки в них ломали бы весь ответ, а не только своё поле. */
static void json_str(const char *s) {
    putchar('"');
    for (const unsigned char *p = (const unsigned char *)s; *p; p++) {
        if (*p == '"' || *p == '\\') { putchar('\\'); putchar(*p); }
        else if (*p < 0x20) printf("\\u%04x", *p);
        else putchar(*p);
    }
    putchar('"');
}

static void node_json(const struct vless_node *n, int index) {
    printf("{\"index\":%d,", index);
    printf("\"name\":"); json_str(n->name);
    printf(",\"host\":"); json_str(n->host);
    printf(",\"port\":%u,\"type\":", n->port);
    json_str(n->type);
    printf(",\"security\":"); json_str(n->security);
    printf(",\"vision\":%s", n->flow[0] ? "true" : "false");
    if (n->mode[0]) { printf(",\"mode\":"); json_str(n->mode); }
    printf("}");
}

/* Перечислить узлы подписки.
 *
 * Индекс здесь — это индекс среди ПРИГОДНЫХ узлов, и он же понимается движком в поле
 * `node` спеки. Одно значение слова «номер узла» на весь проект: если бы список включал
 * непригодные, человек выбрал бы номер 5, а поднялся бы другой узел — и понять это было
 * бы невозможно, потому что оба списка выглядят правдоподобно. Непригодные считаются
 * отдельно и объясняются причиной, но номеров не занимают. */
int cmd_vless_nodes(const char *spec_path, const char *out_name) {
    struct output *o = NULL;
    size_t cnt = 0, skipped = 0, foreign = 0;
    int rc = load_nodes(spec_path, out_name, &o, &cnt, &skipped, &foreign);
    if (rc) return rc;

    printf("{\"output\":");
    json_str(out_name);
    printf(",\"sub_file\":");
    json_str(o->sub_file);
    printf(",\"node\":%d,\"usable\":%zu,\"skipped\":%zu,\"foreign\":%zu,\"nodes\":[",
           o->node_index, cnt, skipped, foreign);
    for (size_t i = 0; i < cnt; i++) {
        if (i) putchar(',');
        node_json(&g_nodes[i], (int)i);
    }
    printf("]}\n");
    return 0;
}

/* Проверить узел и измерить задержку.
 *
 * node >= 0 — только этот узел. node < 0 — по порядку до первого рабочего, то есть ровно
 * то, что сделает движок при подъёме выхода.
 *
 * По одному узлу за вызов не случайно: проверка узла упирается в таймаут, и «проверить
 * все» на подписке из двадцати шести узлов заняло бы минуты — дольше, чем живёт вызов
 * ubus. Интерфейс спрашивает по одному и заполняет таблицу постепенно. */
int cmd_vless_probe(const char *spec_path, const char *out_name, int node, int timeout_s) {
    struct output *o = NULL;
    size_t cnt = 0, skipped = 0, foreign = 0;
    int rc = load_nodes(spec_path, out_name, &o, &cnt, &skipped, &foreign);
    if (rc) return rc;
    if (!cnt) {
        printf("{\"ok\":false,\"error\":\"в подписке нет пригодных узлов\","
               "\"skipped\":%zu,\"foreign\":%zu}\n", skipped, foreign);
        return 1;
    }
    if (node >= (int)cnt) {
        printf("{\"ok\":false,\"error\":\"узла %d нет, всего %zu\"}\n", node, cnt);
        return 1;
    }

    size_t from = node >= 0 ? (size_t)node : 0;
    size_t to = node >= 0 ? (size_t)node + 1 : cnt;
    int found = -1;
    printf("{\"output\":");
    json_str(out_name);
    printf(",\"results\":[");
    for (size_t i = from; i < to; i++) {
        char why[256] = "";
        int hs = -1, ttfb = -1;
        int pr = vless_probe_timed(&g_nodes[i], timeout_s, why, sizeof(why), &hs, &ttfb);
        if (i > from) putchar(',');
        printf("{\"index\":%zu,\"name\":", i);
        json_str(g_nodes[i].name);
        printf(",\"type\":");
        json_str(g_nodes[i].type);
        printf(",\"ok\":%s,\"handshake_ms\":%d,\"ttfb_ms\":%d,\"why\":",
               pr == 0 ? "true" : "false", hs, ttfb);
        json_str(why);
        printf("}");
        if (pr == 0) { found = (int)i; if (node < 0) break; }
    }
    printf("],\"working\":%d}\n", found);
    return found >= 0 ? 0 : 1;
}

int cmd_vless(const char *spec_path, const char *out_name) {
    struct output *o = NULL;
    size_t cnt = 0, skipped = 0, foreign = 0;
    int rc = load_nodes(spec_path, out_name, &o, &cnt, &skipped, &foreign);
    if (rc) return rc;
    struct vless_node *nodes = g_nodes;
    if (!cnt) {
        fprintf(stderr, "steer: в подписке нет пригодных узлов "
                        "(пропущено %zu, чужих протоколов %zu)\n", skipped, foreign);
        return 1;
    }
    fprintf(stderr, "steer: узлов %zu (пропущено %zu, чужих %zu)\n", cnt, skipped, foreign);

    /* Выбор узла. node=-1 означает «первый рабочий», и это умолчание не из лени: номер
     * узла в подписке меняется при её обновлении, а проверка находит живой сама. */
    int chosen = -1;
    if (o->node_index >= 0) {
        if ((size_t)o->node_index >= cnt) {
            fprintf(stderr, "steer: узла %d нет (всего %zu)\n", o->node_index, cnt);
            return 1;
        }
        chosen = o->node_index;
    } else {
        for (size_t i = 0; i < cnt; i++) {
            char why[256];
            if (vless_probe(&nodes[i], 8, why, sizeof(why)) == 0) {
                fprintf(stderr, "steer: выбран %s (%s)\n", nodes[i].name, why);
                chosen = (int)i;
                break;
            }
            fprintf(stderr, "steer: %s — %s\n", nodes[i].name, why);
        }
    }
    if (chosen < 0) {
        fprintf(stderr, "steer: ни один узел подписки не отвечает\n");
        return 1;
    }

    /* Реестр — чтобы узнать таблицу выхода: из неё берётся адрес устройства. Вызов
     * идемпотентен и с apply не спорит: тот же файл, те же номера. */
    registry_assign();
    return tunnel_run(o, &nodes[chosen]);
}
