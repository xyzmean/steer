/* Диагностика включается переменной окружения: в обычной работе поток пакетов заливает
 * лог, а при разборе «почему соединение не встаёт» видеть каждый шаг необходимо. */
static int g_trace;
#define TR(...) do { if (g_trace) fprintf(stderr, "tun: " __VA_ARGS__); } while (0)

/* ---- пул установщиков ------------------------------------------------------
 *
 * Рукопожатие вынесено из цикла в отдельные потоки. Пул, а не поток на соединение, по двум
 * причинам: поток на каждое соединение это сотни потоков на пачке запросов страницы, и —
 * важнее — адрес узла, сработавший в прошлый раз, кэшируется в client.c как __thread. Живя
 * в потоке-однодневке, этот кэш терялся бы на каждом соединении, и перебор мёртвых адресов
 * начинался бы заново.
 *
 * Очередь короткая СОЗНАТЕЛЬНО. Полная очередь означает «столько одновременных рукопожатий
 * этот процессор не переварит», и честный ответ на это — отказать в SYN: клиент повторит
 * через секунду, к тому времени место освободится. Принять больше, чем можем обслужить,
 * значит вернуться к очереди, только уже невидимой. */
/* Четыре, а не больше. Восемь проверены и не дали ничего: двенадцатое соединение приходило
 * за 1798 мс против 1693 при четырёх — то есть в пределах разброса. Значит упор уже не в
 * ожидание сети, которое потоки и перекрывают, а в само ядро: X25519 и AEAD рукопожатия.
 * Держать вдвое больше потоков за тот же результат незачем. */
#define CONNECTORS 4
#define CONNQ 32

/* Сессия передаётся указателем, а не считается установщиком по индексу: g_sess у каждого
 * потока своя, и SESS() в чужом потоке адресовал бы чужую таблицу. Ошибка была бы из тех,
 * что проявляются перепутанными кусками чужого соединения раз в сутки. */
struct connjob { struct conn *c; struct vless_conn *v; const struct vless_node *node; };
static struct {
    struct connjob q[CONNQ];
    unsigned head, n;
    pthread_mutex_t mu;
    pthread_cond_t cv;
    int started;
} g_cq = { .mu = PTHREAD_MUTEX_INITIALIZER, .cv = PTHREAD_COND_INITIALIZER };

static void *connector(void *arg) {
    (void)arg;
    for (;;) {
        pthread_mutex_lock(&g_cq.mu);
        while (g_cq.n == 0) pthread_cond_wait(&g_cq.cv, &g_cq.mu);
        struct connjob j = g_cq.q[g_cq.head];
        g_cq.head = (g_cq.head + 1) % CONNQ;
        g_cq.n--;
        pthread_mutex_unlock(&g_cq.mu);

        int rc = vless_connect(j.node, j.v, 8);
        j.c->rc = rc;
        /* RELEASE: цикл читает done с ACQUIRE, и всё, что записано в сессию выше, обязано
         * быть видно ему к этому моменту. Без барьера это ровно та ошибка, которая
         * проявляется раз в сутки на другой архитектуре. */
        __atomic_store_n(&j.c->done, 1, __ATOMIC_RELEASE);
    }
    return NULL;
}

/* Снять из очереди заявки этого потока и дождаться тех, что уже в работе.
 *
 * Нужно на выходе из цикла — а он выходит, если epoll вернул ошибку. Без этого слив таблицы
 * закрывал сессию, с которой в тот момент работает установщик, и дальше происходили сразу две
 * разные беды:
 *
 *   - vless_close отдавал ядру дескриптор, которым установщик ещё пользуется. Номер тут же
 *     достаётся другому потоку, и куски чужого соединения уезжают не туда — ровно тот класс
 *     ошибок, ради которого заявка и несёт указатель на сессию, а не индекс;
 *   - g_conns и g_sess живут в TLS потока-владельца. Он возвращается из worker_loop, TLS
 *     освобождается, а установщик продолжает писать по прежнему адресу.
 *
 * Необслуженные заявки просто выбрасываем: установщик их ещё не брал, ждать нечего. Ждать
 * приходится только взятых, их не больше CONNECTORS, и каждая ограничена таймаутом connect.
 *
 * Возвращает 0, если отпустили всех, и -1, если кто-то так и не доложил. По -1 таблицу
 * сливать НЕЛЬЗЯ — освобождать её под работающим установщиком это и есть то, от чего мы тут
 * защищаемся. Тогда честнее утечь: путь и так предсмертный, а процесс перезапустит procd. */
static int connq_release(struct conn *base) {
    pthread_mutex_lock(&g_cq.mu);
    unsigned kept = 0;
    for (unsigned i = 0; i < g_cq.n; i++) {
        struct connjob j = g_cq.q[(g_cq.head + i) % CONNQ];
        if (j.c >= base && j.c < base + MAX_CONNS) {
            j.c->pending = 0;            /* нашу запись больше никто не тронет */
            continue;
        }
        g_cq.q[(g_cq.head + kept++) % CONNQ] = j;
    }
    g_cq.n = kept;
    pthread_mutex_unlock(&g_cq.mu);

    /* Взятые в работу: ждём доклада. Предел щедрый — таймаут установления восемь секунд, и
     * пережидать его дешевле, чем разбираться в порче памяти на живом роутере. */
    for (int spin = 0; spin < 1500; spin++) {
        int busy = 0;
        for (int i = 0; i < MAX_CONNS; i++)
            if (base[i].used && base[i].pending &&
                !__atomic_load_n(&base[i].done, __ATOMIC_ACQUIRE)) busy++;
        if (!busy) return 0;
        struct timespec ts = { .tv_sec = 0, .tv_nsec = 10 * 1000 * 1000 };
        nanosleep(&ts, NULL);
    }
    fprintf(stderr, LOG_W "установщик не доложил за 15 с, таблица не освобождается\n");
    return -1;
}

/* Поставить заявку. 0 — принята, -1 — очередь полна. */
static int conn_submit(struct conn *c, const struct vless_node *node) {
    pthread_mutex_lock(&g_cq.mu);
    if (!g_cq.started) {
        g_cq.started = 1;
        pthread_attr_t a;
        pthread_attr_init(&a);
        /* Стек скромный: рукопожатие держит крупные буферы в __thread, а не на стеке. */
        pthread_attr_setstacksize(&a, 128 * 1024);
        pthread_attr_setdetachstate(&a, PTHREAD_CREATE_DETACHED);
        for (int i = 0; i < CONNECTORS; i++) {
            pthread_t t;
            if (pthread_create(&t, &a, connector, NULL) != 0) break;
        }
        pthread_attr_destroy(&a);
    }
    if (g_cq.n == CONNQ) { pthread_mutex_unlock(&g_cq.mu); return -1; }
    g_cq.q[(g_cq.head + g_cq.n) % CONNQ] =
        (struct connjob){ .c = c, .v = &SESS(c)->v, .node = node };
    g_cq.n++;
    pthread_cond_signal(&g_cq.cv);
    pthread_mutex_unlock(&g_cq.mu);
    return 0;
}

/* Таблица заводится один раз на поток: свободны все слоты, корзины пусты. */
static void conn_table_init(void) {
    g_live_n = 0;
    g_free_n = 0;
    for (int i = MAX_CONNS - 1; i >= 0; i--) {
        g_conns[i].livepos = -1;
        g_conns[i].hnext = -1;
        g_freelist[g_free_n++] = (uint16_t)i;
    }
    for (int i = 0; i < CONN_BUCKETS; i++) g_bucket[i] = -1;
}

static struct conn *conn_find(const struct flow_key *k) {
    for (int16_t i = g_bucket[flow_hash(k)]; i >= 0; i = g_conns[i].hnext) {
        struct conn *c = &g_conns[i];
        if (c->key.src == k->src && c->key.dst == k->dst &&
            c->key.sport == k->sport && c->key.dport == k->dport)
            return c;
    }
    return NULL;
}

/* Внести слот в список живых и в хэш. Вызывается одним местом — рождением соединения. */
static void conn_link(struct conn *c) {
    int16_t idx = (int16_t)(c - g_conns);
    c->livepos = (int16_t)g_live_n;
    g_live[g_live_n++] = (uint16_t)idx;
    unsigned b = flow_hash(&c->key);
    c->hnext = g_bucket[b];
    g_bucket[b] = idx;
}

/* Убрать из списка живых и из хэша. Дыра в g_live закрывается последним элементом: порядок
 * обхода никому не важен, а сдвиг хвоста стоил бы тем дороже, чем больше соединений. */
static void conn_unlink(struct conn *c) {
    int16_t idx = (int16_t)(c - g_conns);
    if (c->livepos >= 0) {
        int last = --g_live_n;
        uint16_t moved = g_live[last];
        g_live[c->livepos] = moved;
        g_conns[moved].livepos = c->livepos;
        c->livepos = -1;
    }
    unsigned b = flow_hash(&c->key);
    int16_t *slot = &g_bucket[b];
    while (*slot >= 0) {
        if (*slot == idx) { *slot = c->hnext; break; }
        slot = &g_conns[*slot].hnext;
    }
    c->hnext = -1;
}

static void conn_drop(struct conn *c);

/* Свободное место в таблице, а если его нет — освободить самое давнее.
 *
 * Прежде здесь стоял отказ: «предел, клиент повторит SYN». Рассуждение выглядело безобидно
 * и оказалось худшим из возможных. Браузер держит соединения ЖИВЫМИ между запросами
 * (keep-alive), минутами и не посылая ни байта. Убирались такие только по общему правилу
 * «молчит 120 секунд». Значит при широком списке — например, включённом Cloudflare, за
 * которым стоит половина интернета, — шестьдесят четыре слота занимались за два открытых
 * сайта, и дальше ВСЕ новые соединения молча отбрасывались.
 *
 * Снаружи это выглядело ровно как «steer завис намертво»: процесс жив, счётчики растут,
 * туннель поднят, в логе тишина, и ни одна страница не открывается. Тишина здесь и была
 * главной ошибкой — отказ, о котором никто не узнаёт.
 *
 * Теперь новое соединение важнее самого давнего простаивающего, и это верный порядок: то,
 * что человек открывает сейчас, нужнее висящего keep-alive к сайту, закрытому пять минут
 * назад. Клиенту вытесненного посылается RST — он поймёт и переоткроет, а молчание оставило
 * бы его ждать ответа, которого не будет.
 *
 * Возвращает NULL только если вытеснять нечего, то есть все соединения свежие. */
static struct conn *conn_new(const struct tun_dev *tun) {
    if (g_free_n) return &g_conns[g_freelist[--g_free_n]];

    time_t now = g_now_s;
    struct conn *old = NULL;
    for (int li = 0; li < g_live_n; li++) {
        struct conn *c = &g_conns[g_live[li]];
        /* Закрытые сервером — первые кандидаты в любом возрасте: они уже ничего не принесут,
         * а живут только чтобы додать клиенту остаток. */
        if (c->pending) continue;        /* установщик пишет в эту запись — не трогать */
        int cheap = c->srv_closed != 0;
        /* Остальные — только если ДЕЙСТВИТЕЛЬНО простаивают. Порог не осторожность, а
         * исправление: без него вытеснялось самое давнее из ЖИВЫХ, и это оказалось хуже
         * прежнего молчаливого отказа. Каждый новый SYN стоит блокирующего рукопожатия
         * (100-400 мс), и приняв его ценой ещё работающего соединения, мы на одном ядре
         * получаем молотилку: цикл занят рукопожатиями, обслуживать существующие некогда,
         * клиенты повторяют, SYN'ов больше. На роутере это выглядело как «вообще ничего не
         * открывается», и в логе шла ровно эта строка по десять раз в секунду.
         *
         * Если простаивающих нет, честный ответ — отказать. Отказ дёшев: клиент повторит
         * SYN через секунду, и к тому времени место, скорее всего, освободится. */
        if (!cheap && now - c->last < IDLE_EVICT_S) continue;
        if (!old || cheap > (old->srv_closed != 0) ||
            (cheap == (old->srv_closed != 0) && c->last < old->last))
            old = c;
    }
    if (!old) {
        /* Молчать нельзя — именно за это пришлось искать причину полдня, — но и писать на
         * каждый пакет тоже: одна строка в две секунды. */
        static __thread time_t said;
        if (now != said && now - said >= 2) {
            said = now;
            fprintf(stderr, LOG_W "все %d соединений заняты и активны, новые "
                            "отклоняются — список слишком широк для этого роутера\n", MAX_CONNS);
        }
        return NULL;
    }

    unsigned char rst[64];
    size_t rl = tcp_build(rst, sizeof(rst), old->key.dst, old->key.src,
                          old->key.dport, old->key.sport,
                          old->our_seq, old->client_seq, TCP_RST | TCP_ACK, NULL, 0, 0, 0, -1);
    if (rl) tun_write_ctl(tun, rst, rl);
    /* В лог — не чаще раза в десять секунд. Вытеснение мёртвого соединения это уборка, а не
     * событие: на живом роутере таких строк набегало по тридцать шесть за сорок секунд, и все
     * они сообщали «всё хорошо» тревожным тоном. Лог, который кричит в норме, перестают
     * читать — и тогда он молчит и в настоящей беде. */
    static __thread time_t said_evict;
    if (now - said_evict >= 10) {
        said_evict = now;
        fprintf(stderr, LOG_W "таблица полна (%d), вытесняю ещё живые соединения "
                        "(последнее молчало %lu с) — список слишком широк для этого роутера\n",
                MAX_CONNS, (unsigned long)(now - old->last));
    }
    conn_drop(old);
    /* conn_drop вернул слот в список свободных — забираем его оттуда же, а не по прежнему
     * указателю. Иначе слот остался бы и у нас, и в списке, и следующий SYN получил бы
     * ЗАНЯТУЮ запись: одно соединение под двумя потоками, перепутанные данные, и найти это
     * можно только по симптому «иногда приходит чужая страница». */
    return &g_conns[g_freelist[--g_free_n]];
}

/* Освободить слот. Из epoll дескриптор уходит сам при close — отдельного epoll_ctl не
 * нужно, и делать его после close значило бы ходить в ядро с закрытым номером. */
static void conn_drop(struct conn *c) {
    TR("закрываю conn#%ld fd=%d\n", (long)(c - g_conns), c->fd);
    if (c->used) {
        vless_close(&SESS(c)->v);
        conn_unlink(c);
        g_freelist[g_free_n++] = (uint16_t)(c - g_conns);
    }
    rtx_done(&c->rtx);
    /* Толстую половину НЕ трём целиком: 18,8 КБ memset на каждое закрытие это 18,8 КБ,
     * прогнанных через кэш ради нулей, которые всё равно перепишет vless_connect (он
     * начинается с memset своей структуры). Здесь достаточно обнулить то, что читаем сами. */
    memset(c, 0, sizeof(*c));
    c->livepos = -1;
    c->hnext = -1;
    memset(&SESS(c)->vis, 0, sizeof(SESS(c)->vis));
}

/* Отправить серверу данные в правильной форме: с заголовком VLESS на первом кадре и в
 * обёртке Vision, если узел её требует.
 *
 * Три исхода, а не два: «ушло», «сейчас нельзя, повторите» и «всё сломалось». Средний
 * появился вместе с HTTP/2, где закрытое окно — нормальное состояние, а не сбой, и
 * путать его с отказом значит разрывать рабочее соединение. */
#define SEND_OK    0
#define SEND_AGAIN 1
#define SEND_FATAL (-1)

static int upstream_send(struct conn *c, const struct vless_node *node,
                         const unsigned char *data, size_t n) {
    struct sess *s = SESS(c);
    /* Буфер нужен ТОЛЬКО чтобы приклеить заголовок или кадр Vision к данным одной записью.
     * Когда клеить нечего — а это обычный случай, потому что заголовок уходит один раз на
     * соединение, а Vision заканчивает набивку первым же кадром, — данные отдаются прямо из
     * пакета, без копии вовсе. */
    static __thread unsigned char out[TUNNEL_BUF];
    const unsigned char *body = data;
    size_t len = 0;

    if (!c->header_sent) {
        /* Адрес назначения берём из пакета: имени у нас нет, клиент уже разрешил его сам
         * (или через наш резолвер, который вернул fake-IP и подменит адрес в DNAT). */
        unsigned char ip4[4];
        memcpy(ip4, &c->key.dst, 4);
        /* dport уже в хостовом порядке — см. комментарий в tun.h. */
        len = vless_build_request(s->uuid, VLESS_CMD_TCP, NULL, ip4,
                                  c->key.dport, node->flow, out, sizeof(out));
        if (!len) return SEND_FATAL;
    }

    /* Оборачивать нужно только пока Vision не закончил набивку. После кадра end vision_wrap
     * сводится к копированию данных на месте — а копию мы делали ДВАЖДЫ: сначала в framed,
     * потом из него в out. То есть каждый байт выгрузки проходил по памяти трижды (третий
     * раз — внутри tls13_write, где он обязателен: шифрование идёт на месте в записи).
     * Теперь до шифрования копий ноль или одна. */
    /* Состояние Vision снимается ДО обёртки и возвращается, если отправка не удалась.
     *
     * Иначе первый кадр терялся безвозвратно при закрытом окне HTTP/2: vision_wrap уже
     * пометил бы UUID отправленным и набивку законченной, а h2_write не отправил НИЧЕГО
     * (он либо всё, либо ничего). Клиент повторяет тот же пакет, мы отправляем его уже без
     * кадра и без UUID — сервер такого не ждёт и закрывает поток. Снаружи это выглядело бы
     * как «узел с vision и grpc иногда не работает», причём «иногда» означало бы «когда
     * сервер не успел принять», то есть на быстром канале чаще.
     *
     * Шестьдесят четыре байта копии против невоспроизводимой поломки протокола. */
    struct vision vis_before = s->vis;
    if (node->flow[0] && !s->vis.sent_end) {
        size_t fn = vision_wrap(&s->vis, data, n, out + len, sizeof(out) - len);
        if (!fn) return SEND_FATAL;
        len += fn;
        body = out;
    } else if (len) {
        /* Заголовок уже лежит в out — данные приклеиваем к нему. */
        if (len + n > sizeof(out)) return SEND_FATAL;
        memcpy(out + len, data, n);
        len += n;
        body = out;
    } else {
        len = n;
    }

    /* Через vless_send: упаковку транспорта знает клиент, а не туннель. */
    int rc = vless_send(&s->v, body, len);
    if (rc == H2_EWINDOW) {
        /* Окно HTTP/2 закрыто: сервер не успевает принимать. Это НЕ отказ — это то, для
         * чего управление потоком и существует. Ничего не ушло (h2_write либо отправляет
         * всё, либо ничего), поэтому достаточно не подтверждать пакет: клиент повторит
         * его сам, как при потере, и повторит уже тогда, когда окно откроется.
         *
         * Первая версия считала это ошибкой и разрывала соединение. Выглядело как
         * «выгрузка обрывается на случайном месте» — месте, где сервер впервые не успел. */
        s->vis = vis_before;                /* кадр не ушёл — обёртка как бы не делалась */
        return SEND_AGAIN;
    }
    if (rc) return SEND_FATAL;
    /* Заголовок отмечаем отправленным только теперь: пометить раньше значило бы, что
     * повторная попытка уйдёт без него, и сервер не поймёт, куда соединять. */
    c->header_sent = 1;
    return SEND_OK;
}

/* Отдать клиенту кусок потока как TCP.
 *
 * Один вызов на кусок, без промежуточного буфера: данные уходят в устройство прямо оттуда,
 * где лежат после расшифровки. Прежняя версия собирала их в отдельный массив, потом
 * копировала оттуда в пакет — то есть каждый байт трафика проходил по памяти трижды.
 *
 * Размер куска определяет разгрузка. С ней одним вызовом уходит вся запись целиком, а
 * нарезку по MSS делает ядро; без неё режем сами по 1460 и платим за каждый сегмент
 * отдельным вызовом и отдельным проходом по данным ради контрольной суммы. */
static int emit_to_client(struct conn *c, const struct tun_dev *tun,
                          const unsigned char *p, size_t n) {
    /* Копия для повтора — ДО отправки. Место проверено заранее (client_can_take_record), и
     * если его вдруг нет, отправлять нельзя: отправленное без копии повторить нечем, а
     * именно это и подвешивало соединения. */
    /* Кольцо появляется здесь — при первых данных, а не при SYN, — и растёт по надобности.
     * Отказ выделения безопасен: мы просто не отправляем, то есть и не читаем дальше у
     * сервера, а значит ничего не теряем. Отказ роста тоже не ошибка: работаем с прежним
     * кольцом, окно просто меньше. */
    if (!c->rtx.cap && rtx_init(&c->rtx, RTX_START) != 0) {
        TR("нет памяти на кольцо повтора — не отправляю %zu байт\n", n);
        return -1;
    }
    if (rtx_room(&c->rtx) < n && c->rtx.cap < RTX_CAP) rtx_grow(&c->rtx, RTX_CAP);
    if (rtx_room(&c->rtx) < n) {
        TR("буфер повтора полон (%u из %u) — не отправляю %zu байт\n",
           c->rtx.len, c->rtx.cap, n);
        return -1;
    }
    if (!c->rtx.len) { c->rtx_at = g_now_ns; c->rto_ms = rto_floor(); }
    rtx_push(&c->rtx, p, (uint32_t)n);

    size_t seg = tun->gso ? (size_t)TUN_GSO_MAX : (size_t)TUN_MSS;
    size_t sent = 0;
    while (sent < n) {
        size_t chunk = n - sent > seg ? seg : n - sent;
        unsigned char hdr[TUN_HDR_LEN];
        /* Отвечаем от имени сервера: адреса и порты наоборот. */
        tcp_hdr_build(hdr, c->key.dst, c->key.src, c->key.dport, c->key.sport,
                      c->our_seq, c->client_seq, TCP_ACK | TCP_PSH, chunk, 65535);
        uint64_t w0 = g_stats ? now_ns() : 0;
        if (tun_write_data(tun, hdr, p + sent, chunk) != 0) {
            TR("запись в TUN не удалась (%zu байт): %s\n", chunk, strerror(errno));
            return -1;
        }
        if (g_stats) { g_st.tun_writes++; g_st.tun_write_ns += now_ns() - w0; }
        c->our_seq += (uint32_t)chunk;
        sent += chunk;
        /* Данные несут подтверждение в своём заголовке, поэтому отдельный ACK клиенту
         * больше не нужен. */
        c->ack_due = 0;
    }
    return 0;
}

/* Отправить заново с начала неподтверждённого.
 *
 * Один сегмент, а не весь буфер: посылать 128 КБ на каждый таймаут — это лавина, которая
 * сама себе создаёт потери. TCP так и делает, и по той же причине. Если потеряно больше,
 * следующий круг подтверждений покажет это, и повтор пойдёт дальше.
 *
 * Размер сегмента — тот же, каким отправляли: при разгрузке потеряться могла вся
 * шестнадцатикилобайтная порция, и повторять её по 1460 байт значило бы растянуть
 * восстановление на десять таймаутов. */
static void rtx_resend(struct conn *c, const struct tun_dev *tun, const char *why) {
    uint32_t seg = tun->gso ? (uint32_t)TUN_GSO_MAX : (uint32_t)TUN_MSS;
    const unsigned char *body = NULL;
    uint32_t n = rtx_peek(&c->rtx, seg, &body);
    if (!n) return;

    unsigned char hdr[TUN_HDR_LEN];
    tcp_hdr_build(hdr, c->key.dst, c->key.src, c->key.dport, c->key.sport,
                  c->client_ack, c->client_seq, TCP_ACK | TCP_PSH, n, 65535);
    TR("повтор conn#%ld: %u байт с seq=%u (%s)\n",
       (long)(c - g_conns), n, c->client_ack, why);
    if (tun_write_data(tun, hdr, body, n) != 0) return;
    if (g_stats) { g_st.rtx_sends++; g_st.rtx_bytes += n; }
    c->rtx_at = g_now_ns;
    c->rto_ms = c->rto_ms * 2 > RTO_MAX_MS ? RTO_MAX_MS : c->rto_ms * 2;
}

/* Прочитать у сервера и отдать клиенту как TCP-пакет. */
static int downstream_pump(struct conn *c, const struct vless_node *node,
                           const struct tun_dev *tun) {
    /* Статический, а не на стеке: буфер размером с запись TLS — это шестнадцать килобайт
     * стека на каждый вызов, а поток обработки здесь один. */
    static __thread unsigned char buf[TUNNEL_BUF];
    size_t got = 0;
    /* Через клиента, а не tls13_read напрямую: у grpc и xhttp между TLS и VLESS лежит
     * HTTP/2, и чтение мимо него отдавало бы кадры вместо данных. Прямой вызов работал,
     * пока транспорт был единственный, и это ровно тот случай, когда «работает» и
     * «правильно» разошлись молча.
     *
     * Вариант _zc отдаёт указатель на расшифрованную запись там, где копия не нужна: на
     * голом tcp данные так и остаются в буфере соединения. Буфер buf при этом всё равно
     * нужен — под транспорты поверх HTTP/2, где кадр собирается из нескольких записей. */
    struct sess *s = SESS(c);
    TR("чтение conn#%ld fd=%d\n", (long)(c - g_conns), c->fd);
    uint64_t r0 = g_stats ? now_ns() : 0;
    const unsigned char *rx = buf;
    int rc = vless_recv_zc(&s->v, buf, sizeof(buf), &rx, &got);
    if (g_stats) g_st.recv_ns += now_ns() - r0;
    g_rx_total += got;
    if (g_stats) { g_st.recs++; g_st.rec_bytes += got; }
    if (rc) { TR("чтение от сервера: rc=%d\n", rc); return rc; }
    /* Ноль байт — законно: приехал служебный кадр HTTP/2, данных пока нет. Принять это за
     * конец потока значило бы разрывать соединение на первом же SETTINGS. */
    if (!got) { TR("служебный кадр, данных нет\n"); return 0; }
    TR("от сервера %zu байт\n", got);

    /* Порядок разбора: сначала заголовок ОТВЕТА VLESS, потом кадры Vision.
     *
     * Сервер отвечает так: [версия|длина_доп|доп] и только ДАЛЬШЕ поток в кадрах Vision.
     * Заголовок ответа обёрткой не покрыт, и первая версия пыталась развернуть его как
     * кадр: получала «00 00 96 67 ad» (версия 0, длина 0, начало данных), длины кадра
     * выходили бессмысленные, unwrap возвращал EAGAIN, и ответ терялся целиком.
     *
     * Это зеркало ошибки на отправке: там заголовок ЗАПРОСА тоже идёт до кадра, а не
     * внутри него. Один и тот же принцип, который я дважды прочитал наоборот. */
    const unsigned char *cur = rx;
    size_t left = got;

    if (!c->established) {
        size_t skip = 0;
        if (vless_parse_response(cur, left, &skip) != 0) {
            TR("ответ VLESS не разобран (%zu байт)\n", left);
            return -1;
        }
        cur += skip;
        left -= skip;
        c->established = 1;
        TR("заголовок ответа снят (%zu байт), осталось %zu\n", skip, left);
    }

    size_t total = 0;

    while (left) {
        const unsigned char *p = cur;
        size_t pn = left;

        if (node->flow[0]) {
            size_t used = 0;
            const unsigned char *pl = NULL;
            size_t pl_n = 0;
            int ur = vision_unwrap(&s->vis, cur, left, &used, &pl, &pl_n);
            if (ur != 0 || !used) {
                /* Разбор больше не может «не хватить данных»: он потоковый и переносит
                 * состояние между вызовами. Сюда попадаем только на настоящей ошибке —
                 * недопустимой команде в кадре. */
                TR("кадр не разобран: ur=%d осталось %zu\n", ur, left);
                break;
            }
            p = pl;
            pn = pl_n;
            cur += used;
            left -= used;

        } else {
            cur += left;
            left = 0;
        }

        /* Отдаём кадр сразу, а не складываем в общий буфер: складывать было незачем — всё
         * равно потом нарезали, — а стоило это копии всего трафика и предела «не влезло». */
        if (pn) {
            if (emit_to_client(c, tun, p, pn) != 0) return -1;
            total += pn;
        }
    }

    /* Сервер объявил прямое копирование — сообщаем об этом соединению, чтобы следующее
     * чтение шло мимо расшифровки. Ставится ЗДЕСЬ, потому что команда живёт в кадрах
     * Vision, а про них знает только этот код. */
    if (s->vis.recv_direct && !s->v.rx_direct) {
        s->v.rx_direct = 1;
        TR("сервер перешёл на прямое копирование — читаем сокет как есть\n");
    }

    if (!total) { TR("после разбора данных нет\n"); return 0; }
    TR("клиенту %zu байт (seq до %u)\n", total, c->our_seq);
    return 0;
}

/* Один пакет из TUN. */
static void handle_packet(const struct tun_dev *tun, const struct vless_node *node,
                          const unsigned char *pkt, size_t n) {
    struct flow_key k;
    size_t off = 0;
    if (ip_parse(pkt, n, &k, &off) != 0) { TR("пакет не разобран (%zu байт)\n", n); return; }
    TR("%u.%u.%u.%u:%u -> %u.%u.%u.%u:%u proto=%u flags=0x%02x len=%zu\n",
       k.src&255,(k.src>>8)&255,(k.src>>16)&255,(k.src>>24)&255, k.sport,
       k.dst&255,(k.dst>>8)&255,(k.dst>>16)&255,(k.dst>>24)&255, k.dport,
       k.proto, k.tcp_flags, n - off);

    /* UDP и прочее не пересылаем: VLESS UDP требует отдельной обёртки, а основной UDP,
     * который важен для маршрутизации, — это DNS, и его перехватывает резолвер steer.
     *
     * Но и НЕ МОЛЧИМ. Прежде такой пакет просто выбрасывался, и это стоило целых сайтов:
     * браузер идёт к Cloudflare по QUIC, то есть UDP на 443, и тишину понимает как «ещё не
     * ответили», а не «нельзя». Он ждёт и повторяет, и на сайтах, настойчиво предпочитающих
     * QUIC, страница не открывалась вовсе — при живом туннеле, где TCP до тех же адресов
     * проходил за 250 мс семь раз из семи. ICMP-отказ превращает ожидание в мгновенный
     * переход на TCP, который у нас работает.
     *
     * Проверка dport на 53 — чтобы не отвечать отказом на DNS: его перехватывает резолвер,
     * и попавший сюда запрос означает, что перехват не настроен. Отказ там сломал бы
     * разрешение имён вместо того, чтобы просто не помочь. */
    if (k.proto != 6) {
        if (!(k.proto == 17 && k.dport == 53)) {
            unsigned char un[128];
            size_t ul = icmp_unreach_build(un, sizeof(un), pkt, n);
            if (ul) tun_write_ctl(tun, un, ul);
        }
        TR("не TCP (proto=%u), отказ\n", k.proto);
        return;
    }

    struct conn *c = conn_find(&k);

    if (k.tcp_flags & TCP_SYN) {
        if (c) return;                              /* повтор SYN — уже открываем */
        c = conn_new(tun);
        if (!c) return;                             /* все соединения свежие — клиент повторит */
        memset(c, 0, sizeof(*c));
        c->used = 1;
        c->key = k;
        c->fd = -1;
        /* Место в списках — ПОСЛЕ memset и ПОСЛЕ ключа: хэш считается по ключу, а memset
         * обнулил бы отметки о месте в цепочке. */
        conn_link(c);
        c->client_seq = k.seq + 1;                  /* SYN занимает один номер */
        c->our_seq = 1;                             /* свой поток начинаем с 1 */
        c->client_ack = 1;                          /* столько он уже подтвердил (SYN-ACK) */
        c->client_win = k.window ? k.window : 8192;
        c->client_wscale = k.wscale;
        c->rto_ms = rto_floor();
        c->last = g_now_s;
        /* Кольцо повтора НЕ выделяется на SYN. Прежде выделялось, и рассуждение было такое:
         * лениво означало бы, что отказ выделения приходит посреди передачи, когда отвечать
         * клиенту уже нечем. Рассуждение верное для кольца, которое обязано существовать, —
         * и неверное для нашего.
         *
         * Кольцо хранит НЕПОДТВЕРЖДЁННЫЕ байты. Пока их нет, хранить нечего, и буфер не нужен
         * вовсе. А отказ выделения приходит не «посреди передачи», а РОВНО ПЕРЕД чтением у
         * сервера: не смогли выделить — не читаем, и терять нечего, потому что мы ещё ничего
         * не взяли. Клиенту при этом врать не приходится.
         *
         * Зачем так: браузер держит десятки соединений живыми, ничего по ним не передавая
         * (HTTP/2 keep-alive), и за каждое платилось 32 КБ, которых потом не хватало на новые.
         * Теперь простаивающее соединение стоит только своей записи в таблице. */
        if (vless_uuid_parse(node->uuid, SESS(c)->uuid) != 0) { conn_drop(c); return; }
        vision_init(&SESS(c)->vis, SESS(c)->uuid);

        TR("SYN: заявка установщику\n");
        /* Рукопожатие уходит в пул, SYN-ACK отправится, когда поток будет готов (см. ниже,
         * в цикле). Клиент до SYN-ACK не пришлёт ни байта, поэтому буферизовать нечего —
         * ровно поэтому подтверждение и отложено, а не отправлено сразу оптимистично. */
        if (conn_submit(c, node) != 0) {
            /* Очередь полна: столько рукопожатий разом процессор не переварит. Молча
             * отбрасывать SYN нельзя — за это уже пришлось расплатиться однажды, — поэтому
             * говорим в лог и отпускаем запись: клиент повторит SYN сам. */
            static __thread time_t said_q;
            time_t nw = g_now_s;
            if (nw - said_q >= 5) {
                said_q = nw;
                fprintf(stderr, LOG_W "очередь установки соединений полна (%d), "
                                "SYN отклонён — процессор не успевает\n", CONNQ);
            }
            conn_drop(c);
            return;
        }
        c->pending = 1;
        return;
    }

    if (c && c->pending) {
        /* Клиент повторяет SYN, пока мы устанавливаем. Молчим: ответить нечем, а закрывать
         * нельзя — установщик работает с этой записью. */
        return;
    }


    if (!c) return;                                 /* данные без соединения — игнор */
    c->last = g_now_s;

    /* Учитываем подтверждения и окно клиента с ЛЮБОГО его пакета, включая чистые ACK: без
     * этого мы не знаем, сколько он принял, и продолжаем лить в устройство. Именно чистые
     * ACK и приходят во время скачивания — данных от клиента там нет вовсе. */
    size_t data_n = n - off;

    if (k.tcp_flags & TCP_ACK) {
        /* Сравнение с учётом переполнения счётчика: разность как знаковая. */
        if ((int32_t)(k.ack - c->client_ack) > 0) {
            rtx_drop(&c->rtx, k.ack - c->client_ack);   /* ДО сдвига: отсчёт от старого */
            c->client_ack = k.ack;
            c->dup_acks = 0;
            c->fast_done = 0;
            /* Есть продвижение — таймаут снова короткий, и он отсчитывается от нового
             * самого старого байта, а не от прежнего. */
            c->rtx_at = c->rtx.len ? g_now_ns : 0;
            c->rto_ms = rto_floor();
        } else if (k.ack == c->client_ack && c->rtx.len && !data_n && !c->fast_done &&
                   k.window == c->client_win && !(k.tcp_flags & (TCP_SYN | TCP_FIN))) {
            /* Дубликат подтверждения по определению из RFC 5681: тот же номер, без данных,
             * БЕЗ ИЗМЕНЕНИЯ ОКНА и при неподтверждённых данных в пути.
             *
             * Условие про окно — не формальность. Пока клиент читает принятое, его ядро
             * шлёт обновления окна: тот же номер подтверждения, окно больше. Считать их
             * дубликатами значит повторять данные на каждой третьей такой пачке посреди
             * исправной передачи — то есть тратить полосу ровно там, где всё в порядке. */
            if (++c->dup_acks >= DUP_ACK_TRIGGER) {
                c->dup_acks = 0;
                c->fast_done = 1;
                rtx_resend(c, tun, "три подтверждения одного номера");
            }
        }
        c->client_win = k.window;
    }

    if (k.tcp_flags & (TCP_RST | TCP_FIN)) {
        if (k.tcp_flags & TCP_FIN) {
            /* Подтверждаем FIN и закрываем: половинчатое закрытие не поддержано, потому
             * что требует хранить, какая сторона ещё пишет. */
            unsigned char fa[64];
            size_t fl = tcp_build(fa, sizeof(fa), k.dst, k.src, k.dport, k.sport,
                                  c->our_seq, k.seq + 1, TCP_ACK | TCP_FIN, NULL, 0, 0, 0, -1);
            if (fl) tun_write_ctl(tun, fa, fl);
        }
        conn_drop(c);
        return;
    }

    if (!data_n) return;                            /* чистый ACK */

    /* Не по порядку — отбрасываем. Буфер переупорядочивания на каждое соединение это как
     * раз та память, которой на слабой коробке нет; клиент повторит. */
    if (k.seq != c->client_seq) return;

    TR("данные клиента %zu байт -> серверу\n", data_n);
    int sr = upstream_send(c, node, pkt + off, data_n);
    if (sr == SEND_AGAIN) {
        /* Окно закрыто. Прежде чем перекладывать задержку на клиента, разберём то, что уже
         * лежит в сокете: WINDOW_UPDATE приходит именно оттуда и обычно УЖЕ там — сервер
         * присылает его, как только освободил буфер.
         *
         * Без этой попытки каждое закрытие окна стоило бы таймаута повторной передачи у
         * клиента, то есть двухсот миллисекунд на каждые 64 КБ. Замер: выгрузка через
         * grpc шла 200 КБ/с вместо мегабайта.
         *
         * Читаем через downstream_pump, а не сами: только он умеет отдать пришедшие данные
         * клиенту. Читать «на выброс» здесь означало бы потерять ответ сервера. */
        /* Пять миллисекунд ожидания, а не ноль. Кадр WINDOW_UPDATE обычно уже в сокете, но
         * иногда отстаёт на доли круга — и тогда нулевое ожидание отдаёт задержку клиенту,
         * у которого таймаут повторной передачи двести миллисекунд. Пять против двухсот.
         *
         * Больше нельзя: цикл здесь один на все соединения, и каждая миллисекунда ожидания
         * — это миллисекунда, на которую стоят остальные. */
        struct pollfd sp = { .fd = c->fd, .events = POLLIN };
        if (poll(&sp, 1, 5) > 0 && (sp.revents & POLLIN)) {
            if (downstream_pump(c, node, tun) != 0) { conn_drop(c); return; }
            sr = upstream_send(c, node, pkt + off, data_n);
        }
    }
    if (sr == SEND_AGAIN) {
        /* Всё ещё нельзя: не подтверждаем и не двигаем счётчик — пакет для нас как бы не
         * приходил. Клиент повторит его сам, и это единственный способ придержать поток,
         * не храня недоотправленное у себя. */
        TR("окно закрыто, пакет не подтверждён — клиент повторит\n");
        return;
    }
    if (sr != SEND_OK) {
        TR("отправка серверу не удалась\n");
        conn_drop(c);
        return;
    }
    c->client_seq += (uint32_t)data_n;

    /* Подтверждение ОТКЛАДЫВАЕМ до конца разбора порции из TUN. Без ACK клиент повторит
     * пакет, считая его потерянным, — но подтверждать каждый пакет отдельной записью в
     * устройство незачем: за проход их приезжает до шестидесяти четырёх, и все они
     * подтверждаются одним ACK с последним номером. */
    c->ack_due = 1;
}

/* Разослать отложенные подтверждения. Вызывается после разбора порции пакетов из TUN. */
static void flush_acks(const struct tun_dev *tun) {
    for (int li = 0; li < g_live_n; li++) {
        struct conn *c = &g_conns[g_live[li]];
        if (!c->ack_due) continue;
        c->ack_due = 0;
        unsigned char ackp[64];
        size_t al = tcp_build(ackp, sizeof(ackp), c->key.dst, c->key.src,
                              c->key.dport, c->key.sport,
                              c->our_seq, c->client_seq, TCP_ACK, NULL, 0, 65535, 0, -1);
        if (al) tun_write_ctl(tun, ackp, al);
    }
}

