/* xsteer: куда отдать пакет — поиск пира по адресу и поиск сессии по четвёрке.
 *
 * ДВЕ ЗАДАЧИ, ДВА РЕШЕНИЯ, И РАЗНИЦА НЕ В КРАСОТЕ, А В ЧАСТОТЕ ВЫЗОВА.
 *
 * Поиск пира по AllowedIPs — линейный обход, и это правильно. Тридцать два пира по два-три
 * префикса дают около шестидесяти проверок вида (dst & mask) == net, то есть порядка
 * семидесяти циклов. Против 124 микросекунд, которые на MIPS 24Kc стоит один проход
 * ChaCha20-Poly1305 по пакету (см. замеры в reality.c), это 0,05%. Дерево или хеш здесь
 * были бы кодом, который экономит эти 0,05% и добавляет место для ошибки в
 * МАРШРУТИЗАЦИИ — то есть для тихого «трафик ушёл не тому пиру», который по симптому не
 * ищется вовсе. Вместо структуры данных: префиксы разложены по длине по убыванию (тогда
 * самое длинное совпадение получается само, без всякого дерева), пересечения между пирами
 * отвергнуты ещё разбором конфигурации (см. xsconf.c), и есть кэш на одну запись.
 *
 * Поиск сессии по четвёрке — НЕ линейный, и это тоже не вкусовщина. Он зовётся на КАЖДЫЙ
 * пакет: сто тысяч пакетов в секунду на сто двадцать восемь записей это шесть миллионов
 * сравнений в секунду мимо кэша процессора — ровно тот класс расхода, который в tunnel.c
 * уже стоил потолка производительности. Поэтому открытая адресация: одна хеш-функция, одно
 * попадание в память в обычном случае.
 *
 * ПОРЯДОК БАЙТОВ. Адреса здесь в ХОСТОВОМ порядке — маски так удобнее строить и сравнивать,
 * а цена ровно один ntohl на пакет против шестидесяти сравнений. Порядок назван в имени
 * параметров (`_host`), потому что именно на нём в этом проекте уже ломались порты в
 * flow_key (см. tun.h): перевёрнутое дважды значение выглядит как «сервер не отвечает».
 *
 * Ни сокетов, ни mbedtls: всё здесь — чистые функции, и стенд (tests/xsroutematch.c)
 * проверяет их без сети и без прав root.
 */
#ifndef STEER_XSROUTE_H
#define STEER_XSROUTE_H
#include <stdint.h>
#include <stddef.h>
#include "xsconf.h"

/* ---- поиск пира по адресу назначения --------------------------------------- */

#define XS_ROUTE_MAX (XS_PEERS_MAX * XS_ALLOWED_MAX)

struct xs_route_ent {
    uint32_t net, mask;
    int16_t  peer;
    uint8_t  plen;
};

struct xs_router {
    struct xs_route_ent ent[XS_ROUTE_MAX];
    size_t   n;
};

/* Кэш на ОДНУ запись. Всплески трафика идут потоками — подряд летят пакеты к тому же
 * адресу, — поэтому попадание около девяти случаев из десяти, а стоит кэш одного
 * сравнения. Больше одной записи не нужно: второй уровень уже сравним по цене с самим
 * обходом.
 *
 * ЛЕЖИТ СНАРУЖИ РОУТЕРА, И ЭТО НЕ КОСМЕТИКА. Роутер на хабе один на процесс, а поиск
 * зовётся из всех воркеров сразу; изменяемые поля внутри общей структуры — это гонка, у
 * которой последствие ровно то, от которого предостерегает шапка этого файла. Окно узкое:
 * поток A записал новый адрес и не успел записать пира, поток B с тем же адресом видит
 * совпадение и получает пира от ПРЕДЫДУЩЕГО адреса. Пакет уезжает в туннель чужого пира,
 * зашифрованный его ключами, — то есть не потеря, а выдача трафика не тому. По симптому
 * такое не ищется вовсе.
 *
 * Поэтому кэш — собственность вызывающего: у каждого воркера свой экземпляр, и между
 * потоками он не передаётся. Ровно то же решение уже принято в парной реализации на Go
 * (xsteer/route/route.go, тип Cache передаётся в Lookup параметром) — здесь оно
 * догоняет её. */
struct xs_route_cache {
    uint32_t dst;
    int16_t  peer;
    int      valid;
};

/* Разложить префиксы всех пиров по длине по убыванию. Зовётся один раз при загрузке
 * конфигурации и при её перечитывании. */
void xs_router_build(struct xs_router *r, const struct xs_peer *peers, size_t peer_n);

/* Кому принадлежит этот адрес. Возвращает индекс пира или -1.
 *
 * -1 означает ОТБРОСИТЬ. Отдать такой пакет «первому пиру» было бы утечкой трафика между
 * пирами в звезде, поэтому отсутствие совпадения — это решение, а не повод искать
 * запасной вариант. Закреплено стендом.
 *
 * Кэш передаётся вызывающим и может быть NULL — тогда идёт честный обход. NULL нужен и
 * стенду (сверка «с кэшем и без дают одно и то же»), и любому пути, где кэшу негде жить. */
int xs_route(const struct xs_router *r, uint32_t dst_host, struct xs_route_cache *c);

/* Имеет ли пир право отправлять пакеты с этого адреса источника.
 *
 * ОБЯЗАТЕЛЬНАЯ проверка на хабе, а не гигиеническая: без неё любой пир маршрутизирует от
 * чужого имени — то есть достаточно одной скомпрометированной пира, чтобы подделать
 * трафик любой другой. Это та же «маршрутизация по ключам», что у WireGuard: право на
 * адрес даёт конфигурация, а не сам пакет. */
int xs_src_ok(const struct xs_peer *p, uint32_t src_host);

/* ---- уменьшить TTL --------------------------------------------------------- */

/* 0 — можно нести дальше, -1 — отбросить (TTL истёк или пакет негоден).
 *
 * Нужно потому, что хаб пересылает пакет между пирами САМ, не отдавая его ядру: без
 * уменьшения TTL петля маршрутизации в звезде живёт вечно и находится только по нагрузке
 * на канал. */
int xs_ttl_dec(uint8_t *ip, size_t n);

/* Подрезать MSS в проходящем SYN до того, что несёт туннель: `mtu` — MTU туннеля, ответ 1,
 * если поле поправлено. Смысл — снять класс отказа «мелкие пакеты ходят, большие пропадают»
 * для того трафика, который его и создаёт, не полагаясь на ICMP: узел, объявивший MSS 1460,
 * сам построит слишком большой сегмент, а сообщение «нужна фрагментация» на пути к нему
 * запросто отфильтровано. Ровно это делает `iptables --clamp-mss-to-pmtu` на каждом втором
 * роутере, и делает по той же причине.
 *
 * Предел — `mtu - 40` (заголовки IP и TCP), БЕЗ запаса на опции TCP: по RFC 6691 объявленный
 * MSS означает максимум ДАННЫХ, и на длину опций сегмент уменьшает сам отправитель. Запас
 * стоил бы 12 байт на каждом сегменте всего трафика туннеля. */
int xs_mss_clamp(uint8_t *ip, size_t n, int mtu);

/* Хеш ВНУТРЕННЕГО потока: адреса и порты расшифрованного пакета. Нужен там, где к одному пиру
 * ведёт несколько соединений (пир открывает по одному на воркер): выбирать соединение
 * случайно нельзя — пакеты одного потока TCP пошли бы разными путями и приезжали бы
 * переставленными, а это для получателя выглядит как потери и рушит скорость. Один поток —
 * всегда одно и то же соединение, пока их число не изменилось. */
uint32_t xs_flow_hash(const uint8_t *ip, size_t n);

/* ---- поиск сессии по четвёрке ---------------------------------------------- */

#define XS_SIDX_SLOTS 1024      /* степень двойки: маска вместо деления */

struct xs_sidx_ent {
    uint32_t addr;              /* хостовый порядок */
    uint16_t port;
    int16_t  idx;               /* индекс сессии у вызывающего */
    uint8_t  state;             /* 0 — пусто, 1 — занято, 2 — надгробие */
};

struct xs_sidx {
    struct xs_sidx_ent slot[XS_SIDX_SLOTS];
    uint16_t used, dead;
};

static inline unsigned xs_sess_hash(uint32_t addr, uint16_t port) {
    uint32_t h = addr * 2654435761u ^ ((uint32_t)port * 40503u);
    return (h ^ (h >> 13)) & (XS_SIDX_SLOTS - 1);
}

void xs_sidx_reset(struct xs_sidx *x);
int  xs_sidx_find(const struct xs_sidx *x, uint32_t addr, uint16_t port);   /* -1 — нет */
int  xs_sidx_insert(struct xs_sidx *x, uint32_t addr, uint16_t port, int idx);
void xs_sidx_remove(struct xs_sidx *x, uint32_t addr, uint16_t port);

#endif
