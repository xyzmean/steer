/* xsteer: поддельное TCP-соединение поверх сырого сокета.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Соединение нужно ОБЕИМ половинам — пиру и хабу, — и это ровно
 * тот случай, когда копия хуже общего кода: номера последовательности, отложенные
 * подтверждения и правило про «номер двигается только вперёд» одинаковы у обеих сторон, а
 * ошибка в любом из них означает молчаливую потерю пакетов. Сам файл о протоколе xsteer не
 * знает ничего: он переносит куски байтов, а что в них — дело xshake.c и вызывающего.
 *
 * ЧТО ЗДЕСЬ НЕ ПОВТОРЯЕТСЯ ИЗ obfs.c. Сборка и разбор сегмента, контрольная сумма и
 * арифметика номеров берутся оттуда (obfs.h) — они уже проверены стендом obfsmatch. Сырой
 * сокет, фильтры cBPF и правило против RST — тоже оттуда, вместе с четырьмя уроками,
 * записанными у их объявлений. Здесь только состояние соединения и цикл его поддержания.
 *
 * ГЛАВНЫЙ ИНВАРИАНТ. Смещение в потоке (seq минус начальный номер) служит nonce для AEAD,
 * поэтому он ОБЯЗАН двигаться только вперёд — даже когда отправка не удалась. Откат номера
 * ради «переиспользуем» означал бы повтор nonce, то есть полную потерю защиты. В obfs.c это
 * так по факту; здесь это несущая конструкция, и потому написано явно.
 */
#ifndef STEER_XSCONN_H
#define STEER_XSCONN_H
#include <stdint.h>
#include <stddef.h>
#include "../obfs.h"
#include "xswire.h"

enum xs_conn_state { XSC_CLOSED, XSC_SYN_SENT, XSC_SYN_RCVD, XSC_EST };

struct xs_conn {
    uint32_t saddr, daddr;      /* сетевой порядок, как в пакете */
    uint16_t sport, dport;      /* хостовый порядок */
    uint32_t isn_tx, isn_rx;    /* начальные номера: наш и его */
    uint32_t seq, ack;          /* хостовый порядок */
    int      state;
    int      fd;                /* сырой сокет этого соединения */
    int      syn_tries;
    int      unacked;           /* принято сегментов с прошлого нашего подтверждения */
    long long born, last_rx, last_tx, last_ack;
};

/* Шаг цикла и пороги. Значения взяты у obfs.c, кроме ACK_SEGS: там восемь выбраны из
 * экономии, а здесь двойка — из ПРАВДОПОДОБИЯ. Linux подтверждает примерно через сегмент, и
 * поток, подтверждающий раз в восемь, отличим от настоящего именно ритмом. Цена на обратном
 * пути загрузки — 40 байт на два сегмента по 1500, то есть 1,3%; при двустороннем трафике
 * голых подтверждений не нужно вовсе. */
#define XSC_TICK_MS      20
#define XSC_SYN_RETRY_MS 1000
#define XSC_SYN_RETRIES  6
#define XSC_ACK_SEGS     2
#define XSC_ACK_MS       40
/* Тишина при АКТИВНОЙ отправке, после которой путь считается мёртвым.
 *
 * Первая версия ставила три секунды «чтобы быстрее замечать», и живой стенд показал, чем это
 * кончается: трафик односторонний (пир отправляет, отвечать нечем), хаб молчит, и пир раз
 * в три секунды поднимает соединение заново — то есть сама себе устраивает простой вместо
 * того, чтобы работать. Отсюда же следствие, без которого порог не помогает вовсе: хаб ОБЯЗАН
 * присылать keepalive, получив данные, — иначе односторонняя отправка всегда выглядит как
 * мёртвый путь. Так же устроен и WireGuard: keepalive посылает принимающая сторона.
 *
 * ПОЧЕМУ СОРОК ПЯТЬ СЕКУНД, А НЕ ПЯТНАДЦАТЬ. Пятнадцать — порог WireGuard (keepalive 10 с
 * плюс таймаут перездоровки 5 с), и он был здесь ровно по этой причине. На живом роутере он
 * сработал ЛОЖНО: два посторонних процесса заняли оба ядра, наш процесс получил 4% времени,
 * входящие сегменты пролежали в очереди дольше порога — и туннель пересоздался на ровном
 * месте. У WireGuard такой порог безопасен потому, что он не РАЗРУШАЮЩИЙ: там начинается новое
 * рукопожатие, а прежняя сессия продолжает нести трафик. У нас переподключение рвёт поддельное
 * соединение TCP, то есть стоит нового рукопожатия и проверки пути.
 *
 * Сорок пять — это четыре пропущенных keepalive хаба (он присылает их каждые 10 с). veil
 * (engine/session.go) держит для того же 90 с с той же мотивировкой — «несколько пропущенных
 * keepalive, чтобы обычное дрожание не срабатывало», — и дополнительно масштабирует порог по
 * настроенному keepalive пира. Нам масштабировать не нужно: keepalive хаба свой и постоянный. */
#define XSC_DEAD_MS      45000

long long xs_now_ms(void);

/* MTU интерфейса, через который уходит трафик к адресу-источнику saddr, и его имя.
 *
 * Нужен обеим половинам: из него считается ВЕРХНЯЯ оценка MTU туннеля. Верхняя — потому что
 * путь может резать сильнее канала, и это выясняется только пробами (см. xswire.h). Живёт
 * здесь, а не в цикле пира, потому что то же самое считает хаб. */
int xs_egress_mtu(uint32_t saddr, char *ifname, size_t ifn);

/* Открыть соединение к хабу и отправить SYN. Возвращает 0 или -1. */
/* Открыть поддельное соединение. `shard` задаёт МЛАДШИЕ БИТЫ порта источника: порт выбираем мы
 * сами, а хаб раскладывает соединения по своим воркерам именно по этим битам
 * (obfs_filter_port_shard). Пир с несколькими соединениями обязана дать им РАЗНЫЕ значения —
 * иначе все его соединения достанутся одному воркеру хаба, и второе ядро там не заработает.
 * Отрицательное значение означает «любой порт». */
int xs_conn_open(struct xs_conn *c, uint32_t daddr, int dport, int shard);
void xs_conn_close(struct xs_conn *c);

/* Отправить служебный сегмент (SYN, ACK, RST) или короткую нагрузку. */
int xs_conn_send(struct xs_conn *c, uint8_t flags, const void *payload, size_t plen,
                 int with_mss);

/* Записать заголовок TCP ПЕРЕД нагрузкой, лежащей по row + XS_HDR_ROOM, и вернуть указатель
 * на начало сегмента. Копий нет: сегмент уходит с того места, где уже лежит шифротекст.
 * Двигает seq — то есть и смещение, из которого выводится nonce. */
uint8_t *xs_conn_ahead(struct xs_conn *c, uint8_t *row, size_t plen, size_t *seglen,
                       long long now);

/* Смещение, с которым уйдёт СЛЕДУЮЩИЙ пакет данных: им шифруется его же нагрузка.
 * Читается ДО xs_conn_ahead — она номер уже двинет. */
static inline uint32_t xs_conn_rel_next(const struct xs_conn *c) {
    return c->seq - c->isn_tx;
}

/* Смещение принятого сегмента. */
static inline uint32_t xs_conn_rel_of(const struct xs_conn *c, uint32_t seq) {
    return xs_rel(seq, c->isn_rx);
}

/* Учесть принятый сегмент: подтверждения, состояние, счётчики. Возвращает 1, если сегмент
 * несёт данные, которые надо разобрать, 0 — если служебный, -1 — если соединение закрылось
 * (пришёл RST). */
int xs_conn_on_seg(struct xs_conn *c, const struct obfs_seg *s, long long now);

/* Раз в тик: повторить SYN, отправить отложенное подтверждение, сказать про мёртвый путь.
 * Возвращает 1, если путь считается мёртвым и соединение надо поднимать заново. */
int xs_conn_tick(struct xs_conn *c, long long now, int sending);

#endif
