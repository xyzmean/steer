/* xsteer: ссылка xs:// — та же конфигурация, но в одну строку.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Разбор файла (xsconf.c) линкует стенд diagsim и читает демон на
 * каждом подъёме; ссылка нужна только командной строке и управляющему слою (splify2 отдаёт её
 * человеку и принимает от него). Держать её рядом значило бы носить разбор недоверенной строки
 * и процентную запись туда, где они не нужны.
 *
 * ФОРМАТ ОПИСАН ОДИН РАЗ — в реализации на Go (xsteer/conf/link.go) и в docs/xsteer.md. Здесь
 * ровно тот же формат: пары проверяются побайтовым стендом (tests/xslinkmatch.c) на тех же
 * векторах, что и там, потому что ссылку, выданную одной половиной, обязана принимать другая.
 *
 * ВИД:
 *
 *     xs://<приватный ключ пира>@<хост>:<порт>?pk=<публичный ключ хаба>&ip=<адрес/длина>#<имя>
 *
 * В ССЫЛКЕ ЛЕЖИТ ПРИВАТНЫЙ КЛЮЧ — это не оплошность формата, а его суть: ссылка и есть выданный
 * доступ, целиком. Отсюда следствие для вызывающих: аргументом команды её передавать нельзя
 * (аргументы видны в списке процессов), поэтому командная строка читает её со стандартного
 * ввода. */
#ifndef STEER_XSLINK_H
#define STEER_XSLINK_H
#include <stddef.h>
#include "xsconf.h"

/* Имя из фрагмента — только для человека: поля «имя» в конфигурации нет. */
#define XS_LINK_NAME_MAX 128
/* Предел длины ссылки — тот же, что у файла, и по той же причине: разбирать частично нельзя, а
 * без предела строка из недоверенного источника становится способом занять память. */
/* Имя XS_URI_MAX, а не XS_LINK_MAX: последнее в этом движке давно занято и означает совсем другое —
 * предел MTU КАНАЛА (xswire.h). Два смысла на одно имя однажды сошлись бы в одном файле. */
#define XS_URI_MAX      XS_CONF_MAX

/* Разобрать ссылку в ту же структуру, что и файл. 0 — разобрано, -1 — отказ с объяснением в err.
 *
 * Проверки НЕ ПЕРЕПИСАНЫ здесь заново: ссылка собирается в текст конфигурации и разбирается общим
 * xs_conf_parse. Так исключено расхождение «ссылка приняла то, что файл отвергает» — самый
 * неприятный вид разницы между двумя представлениями одного понятия. */
int xs_link_parse(const char *s, enum xs_role role, struct xs_conf *c, struct xs_secrets *sec,
                  char *name, size_t namen, char *err, size_t errn);

/* Напечатать конфигурацию пира одной строкой xs://. name может быть NULL или пустым. */
int xs_link_render(const struct xs_conf *c, const struct xs_secrets *sec, const char *name,
                   char *out, size_t outn, char *err, size_t errn);

/* Это ссылка xs://, а не путь. Проверка ПО СХЕМЕ, а не по наличию «://»: файл с таким именем
 * завести можно, и спутать их значило бы читать файл как ссылку. */
int xs_is_link(const char *s);

/* Принять то, что дал человек: путь к файлу, ссылку xs:// или «-» (читать со стандартного ввода).
 * name получает имя из ссылки — для файла остаётся пустым.
 *
 * ЗАЧЕМ «-». Ссылка содержит приватный ключ, а аргументы команды видны в списке процессов всякому,
 * кто есть на машине, и остаются в истории оболочки. На своём ноутбуке это неважно, на общем
 * сервере — важно, и единственный честный ответ на это не предупреждение в справке, а работающий
 * способ передать ссылку иначе. Со стандартного ввода принимается и ссылка, и целый файл: они
 * различаются первыми знаками, а не ключом командной строки.
 *
 * Ровно тот же договор, что у conf.LoadAny половины на Go, — чтобы «настроено» не зависело от
 * того, какой половиной настраивали. */
/* was_link (может быть NULL) получает 1, если прочитана ССЫЛКА, и 0, если файл. Отдельным
 * значением, а не выводом из побочных признаков: со стандартного ввода приходит и то, и другое, а
 * угадывать по «пришло ли имя из фрагмента» нельзя — имени в ссылке может не быть вовсе. */
int xs_conf_load_any(const char *what, enum xs_role role, struct xs_conf *c,
                     struct xs_secrets *sec, char *name, size_t namen, int *was_link,
                     char *err, size_t errn);

/* Напечатать конфигурацию пира ФАЙЛОМ в стиле wg. Пара к xs_link_render: присланную ссылку часто
 * надо превратить в файл, и наоборот. */
int xs_conf_render(const struct xs_conf *c, const struct xs_secrets *sec,
                   char *out, size_t outn, char *err, size_t errn);

#endif
