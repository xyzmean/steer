/* xsteer: конфигурация в стиле WireGuard.
 *
 * ФОРМАТ ВЗЯТ У WG НАРОЧНО. Человек, поднимавший WireGuard, уже знает этот файл, а
 * значит не изучает новый синтаксис ради того же смысла. Отсюда и пределы разумного
 * заимствования: ключи, которых мы не обслуживаем, ОТВЕРГАЮТСЯ с объяснением, а не
 * принимаются молча (см. таблицу в xsconf.c) — иначе `Table = off`, скопированный из
 * рабочего wg-quick, означал бы «настроено», не настроив ничего.
 *
 * РАЗБОР СТРОГИЙ, в отличие от разбора spec.json. Там неизвестный КЛЮЧ пропускается, и
 * это верно: спеку пишет управляющий слой, который может быть новее движка, и запас
 * вперёд защищает не обновлённый роутер. Здесь файл пишет человек руками или печатает наш
 * же хаб, защищать нечего, а опечатка в `AllowedIPs`, исчезнувшая молча, — это «туннель
 * поднялся, половина маршрутов пропала». Поэтому неизвестный ключ это отказ с номером
 * строки, и там, где можно, с подсказкой — тот же выбор, что у разбора флагов в cli.c.
 *
 * СЕКРЕТЫ ОТДЕЛЕНЫ ТИПОМ, А НЕ ДИСЦИПЛИНОЙ. struct xs_conf не содержит приватного ключа
 * вовсе, и печатает наружу (status, diag, xsteer-peers) только она. Обещание «секретов в
 * выводе нет» держится не на внимательности того, кто добавит новое поле в JSON, а на
 * том, что дотянуться до них из этой структуры нечем. Приватный ключ живёт в
 * struct xs_secrets, попадает только в криптографию и затирается xs_conf_wipe.
 *
 * Файл НЕ ВКЛЮЧАЕТ mbedtls, и это ограничение, а не совпадение: его линкует build/diagsim
 * (стенд diagmatch проверяет, что diag читает конфигурацию), а тот собирается без
 * библиотеки. Отсюда же следует, чего здесь нет: проверок, требующих арифметики на кривой
 * — «публичный ключ пира равен своему» и «ключ даёт нулевой общий секрет» — они живут
 * там, где выводится публичная половина, то есть в xshake.c. Здесь проверяется всё, что
 * можно проверить по тексту.
 */
#ifndef STEER_XSCONF_H
#define STEER_XSCONF_H
#include <stdint.h>
#include <stddef.h>
#include <stdio.h>

/* Пиров в звезде на один хаб. Тридцать два, а не тысяча: это домашние роутеры, а поиск
 * пира по статическому ключу линейный (он зовётся раз на рукопожатие, то есть примерно
 * раз в двадцать минут на пира). Переполнение — ОТКАЗ, а не отбрасывание лишних: пир,
 * молча не попавший в таблицу, это пир, которая «настроена и не работает». */
#define XS_PEERS_MAX   32
/* Префиксов на пира. Домашнему пиру хватает двух-трёх (его LAN и адрес внутри туннеля), но
 * полный туннель С ИСКЛЮЧЕНИЯМИ — обычное дело: «весь трафик, кроме локальных и корпоративных
 * сетей» калькулятор AllowedIPs раскладывает в два-три десятка префиксов (0.0.0.0/0 минус
 * 10/8, 172/8, 100/8 — уже девятнадцать). Шестьдесят четыре покрывают любой разумный список;
 * держится тем же числом на порте Go (conf.AllowedMax), чтобы конфиг был переносим между
 * реализациями. Внимание: список едет ОДНОЙ строкой, поэтому буфер строки в разборе поднят
 * заодно (см. raw[] в xsconf.c). */
#define XS_ALLOWED_MAX 64
/* Предел файла. Зеркально правилу про 256 КиБ у спеки: больший файл отвергается, а не
 * читается частично. */
#define XS_CONF_MAX    (16 * 1024)
/* Ключ на 32 байта в base64 — ровно 44 символа с одним '='. Формат тот же, что печатает
 * `wg genkey`, и проверяется он СТРОГО: 43 символа означают ключ, усечённый на байт, а
 * молча принятый короткий ключ это тихо ослабленная криптография. */
#define XS_KEY_B64     44

/* Роли: хаб слушает, пир соединяется. В коде вторая называется SPOKE по той же причине, что
 * `struct spoke` в xsclient.c: имя `peer` в этом файле занято описанием пира из конфигурации. */
enum xs_role { XS_ROLE_SPOKE, XS_ROLE_HUB };

/* Префикс в ХОСТОВОМ порядке: маски удобнее строить и сравнивать так, а на пути данных
 * это стоит одного ntohl на пакет (одна инструкция) против шестидесяти четырёх сравнений
 * — см. xsroute.h. Порядок назван здесь, чтобы вопрос не возникал: ровно на нём в этом
 * проекте уже ломались порты в flow_key (см. tun.h). */
struct xs_allowed { uint32_t net, mask; int plen; };

struct xs_peer {
    uint8_t pub[32];
    /* Только литерал IPv4. Имя пришлось бы разрешать через DNS, а он сам может быть
     * направлен в этот же туннель — тогда туннель не поднимется никогда, и рассказать об
     * этом сможет только diag, то есть уже после факта. То же правило и по той же причине
     * действует для obfs.server (см. spec.c). Разрешает имя тот, кто пишет файл. */
    char    endpoint[64];
    int     endpoint_port;      /* 0 — Endpoint не задан (так у хаба: пир позвонит сам) */
    struct xs_allowed allowed[XS_ALLOWED_MAX];
    size_t  allowed_n;
    int     keepalive;          /* секунды; 0 — выключено */
    /* Ключ был в файле. Нужен потому, что «нет ключа» и «PersistentKeepalive = 0» — это
     * РАЗНЫЕ вещи: первое означает «поставь умолчание», второе — «выключи». Без этого
     * признака выключить keepalive было нечем: ноль молча превращался в умолчание, и
     * человек, написавший 0, получал ровно то, от чего отказывался. */
    int     keepalive_set;
};

/* Всё, что можно печатать. Секретов здесь нет ни одного — см. заголовок файла. */
struct xs_conf {
    uint32_t addr;              /* адрес внутри туннеля, хостовый порядок */
    int      addr_plen;
    int      mtu;               /* 0 — вывести из MTU канала через xs_mtu() */
    int      listen_port;       /* 0 — не слушать (пир) */
    char     sni[128];          /* маскировочный домен для ClientHello */
    char     device[32];        /* имя устройства TUN у хаба; пусто — умолчание xshub0. Нужно,
                                 * чтобы на одной машине уживались два хаба (например, рядом с
                                 * отдельным хабом режима потока), не столкнувшись за имя. */
    struct xs_peer peer[XS_PEERS_MAX];
    size_t   peer_n;
    /* Сколько неизвестных ключей встретилось. Всегда 0 у принятого файла — разбор строгий,
     * — но поле есть, чтобы стенд мог утверждать это, а не подразумевать. */
    int      unknown_n;
};

struct xs_secrets { uint8_t priv[32]; int has_priv; };

/* Разобрать текст. 0 — разобрано, -1 — отказ, и тогда в err лежит объяснение с номером
 * строки. Чистая функция: ни файлов, ни времени, ни exit() — поэтому её и проверяет стенд
 * литералами (tests/xsconfmatch.c). Это единственное место, куда в движок попадает текст,
 * написанный человеком руками. */
int xs_conf_parse(const char *text, size_t n, enum xs_role role,
                  struct xs_conf *c, struct xs_secrets *s, char *err, size_t errn);

/* Открыть, проверить ПРАВА, прочитать, разобрать. Только эта функция обращается к ОС —
 * поэтому она же и не проверяется стендом в памяти. */
int xs_conf_load(const char *path, enum xs_role role,
                 struct xs_conf *c, struct xs_secrets *s, char *err, size_t errn);

/* Затереть приватный ключ. Через volatile-указатель: explicit_bzero есть не во всякой
 * musl, а обычный memset по памяти, которая больше не читается, компилятор вправе
 * выбросить целиком. */
void xs_conf_wipe(struct xs_secrets *s);

/* Ключ в base64 и обратно, СТРОГО. Возвращают 0 или -1. */
int xs_key_decode(const char *b64, uint8_t out[32]);
void xs_key_encode(const uint8_t key[32], char out[XS_KEY_B64 + 1]);

/* Отпечаток публичного ключа для журнала и диагностики: первые восемь символов base64.
 * Публичный ключ секретом не является (его печатает и `wg show`), но полный ключ в каждой
 * строке журнала — это шум, в котором перестают читать сами строки. */
void xs_key_fp(const uint8_t pub[32], char out[12]);

/* Конфигурация в JSON, без секретов. Принимает struct xs_conf, а не путь: дотянуться до
 * приватного ключа отсюда нечем ПО ПОСТРОЕНИЮ, и это то самое обещание из заголовка. */
void xs_conf_json(FILE *out, const struct xs_conf *c);

#endif
