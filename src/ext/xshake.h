/* xsteer: рукопожатие. Noise IK, спрятанный внутри ClientHello с обликом Chrome.
 *
 * ПОЧЕМУ NOISE IK, А НЕ СВОЁ РАСПИСАНИЕ. Две причины, обе практические. Первая: свойства
 * паттерна IK разобраны и доказаны не нами — взаимная аутентификация статическими ключами,
 * прямая секретность после второго сообщения, скрытие личности инициатора, один круг до
 * данных. Ровно на нём стоит WireGuard. Вторая: цепочка ключей Noise И ЕСТЬ HKDF —
 * MixKey(x) это HKDF(ck, x, 2), то есть mbedtls_hkdf_extract плюс mbedtls_hkdf_expand на 64
 * байта, буква в букву. «Своё расписание» дало бы то же самое, но со своей ошибкой в
 * склейке метки, и проверить его было бы нечем, кроме себя самого.
 *
 * ОТЛИЧИЙ ОТ ВАНИЛЬНОГО NOISE РОВНО ДВА, и оба — конструкция TLS 1.3, а не изобретение:
 *   1. транспортный nonce не плоский счётчик Noise, а iv XOR смещение в потоке (xswire.h);
 *   2. Split() отдаёт не два ключа по 32 байта, а 88 байт: ключ и iv на каждое направление.
 *
 * ЧТО ГДЕ ЛЕЖИТ НА ПРОВОДЕ. Ни одного нового расширения и ни одного лишнего байта — всё
 * едет в полях, которые у браузера уже есть:
 *
 *   key_share x25519 (32)  →  эфемерный ключ e. Ровно там, где он и был бы в TLS 1.3.
 *   набивка ECH (176)      →  статический ключ пира под es (32+16) и подтверждение
 *                             полезной нагрузки (16); остальные 128 байт — случайный шум,
 *                             как у Chrome без настроенного ECH.
 *   legacy_session_id (32) →  аутентификатор по ВСЕМУ Hello: 16 байт открыто (версия,
 *                             флаги, MTU, время) и 16 байт тега. Приём взят у Reality, и
 *                             он же служит хабу дешёвым предфильтром: один X25519 против
 *                             сканерного шума, до всякой длинной арифметики.
 *   cipher_suites          →  СОГЛАСОВАНИЕ ШИФРА. Выбор делает пир, потому что узкое
 *                             место всегда роутер, а не VPS: на MIPS AES-GCM в шесть с
 *                             лишним раз медленнее ChaCha20 (замеры в reality.c). Хаб
 *                             читает первый набор TLS 1.3 из её списка, пропуская GREASE.
 *
 * Шифротекст от шума неотличим, поэтому GREASE-ECH настоящего Chrome и наш msg1 внутри
 * него — одна и та же строка байтов с точки зрения наблюдателя. Отпечаток сохраняется
 * побайтово: стенд tests/hellofreeze.c сверяет собранный Hello с заморозкой.
 *
 * КАК ХАБ УЗНАЁТ, ЧЕЙ ЭТО ПИР. Он этого не делает до расшифровки — и это лучше
 * альтернативы. В IK статический ключ инициатора едет зашифрованным под es = DH(e, S_хаба):
 * хабу нужен только его собственный статический ключ, один на всех пиров. Он расшифровывает
 * 32 байта, ПОЛУЧАЕТ личность и только потом ищет её в таблице. Явный индекс пира на проводе
 * был бы хуже дважды: он раскрывает постоянный идентификатор на фиксированном смещении в
 * каждом рукопожатии — ровно тот признак, по которому опознаётся WireGuard, — и стоит байт.
 *
 * NONCE НОЛЬ ЗАНЯТ ПОДТВЕРЖДЕНИЕМ, И ЭТО ИНВАРИАНТ. Записи данных выводят nonce из
 * смещения в потоке, а оно начинается с единицы (начальный номер занят самим SYN). Значит
 * нулевой nonce свободен ровно для одной операции на направление — им и подписывается
 * «Finished». Отдельного ключа для подтверждения поэтому не нужно, а повтора nonce не
 * возникает: смещение никогда не равно нулю, и соединение уходит из работы задолго до
 * заворота (xs_retire_due).
 */
#ifndef STEER_XSHAKE_H
#define STEER_XSHAKE_H
#include <stdint.h>
#include <stddef.h>
#include "tls13.h"
#include "xsconf.h"

#define XS_PROTO_VER 1

/* Коды отказа. Разные НАРОЧНО: «не сошёлся тег» и «это не наш клиент» требуют разных
 * действий, а один код на всё означает «не работает, и почему — неизвестно». */
#define XS_EFORMAT   (-60)   /* не Hello, не наша форма, битые длины */
#define XS_EAUTH     (-61)   /* аутентификатор или тег не сошлись — не наш собеседник */
#define XS_ECRYPTO   (-62)   /* сбой примитива или источника случайности */
#define XS_EPEER     (-63)   /* пир опознан, но его нет в конфигурации */
#define XS_EREPLAY   (-64)   /* метка времени не новее прошлой от этого пира */
#define XS_ESMALL    (-65)   /* не влезло в буфер */
#define XS_EVERSION  (-66)   /* другая версия протокола на той стороне */

/* Полезная нагрузка рукопожатия — 16 байт, помещающихся в аутентификатор session_id.
 *
 * MTU едет ЗДЕСЬ, а не отдельным служебным кадром: рассогласование MTU — это класс отказов,
 * который server/README.md называет самым трудным в диагностике («маленькие пакеты ходят,
 * большие пропадают»), и узнать о нём надо до того, как пойдёт первый пакет, а не после. */
struct xs_payload {
    uint8_t  ver;
    /* Младшие три бита — НОМЕР СОЕДИНЕНИЯ пира (0..XS_CONNS_MAX-1). Он едет внутри
     * аутентификатора session_id, то есть на проводе не виден и подделке не подлежит; хабу он
     * нужен, чтобы положить сессию на своё место в наборе пира, а не вытеснить соседнюю. */
    uint8_t  flags;
    uint16_t mtu;            /* MTU туннеля на этой стороне */
    uint64_t stamp;          /* секунды эпохи: защита от воспроизведения msg1 */
};

/* Состояние рукопожатия. Живёт от начала до Split и затирается сразу после. */
struct xs_hs {
    uint8_t h[32];           /* транскрипт */
    uint8_t ck[32];          /* цепочка ключей */
    uint8_t k[32];           /* текущий ключ шага */
    struct tls13_keys hk;    /* он же в форме, которую понимает AEAD из tls13.c */
    enum tls13_aead aead;
    uint8_t e_priv[32], e_pub[32];
    /* Наш СТАТИЧЕСКИЙ приватный: пиру он нужен на шаге se (его статический и эфемерный
     * сервера), то есть уже после сборки Hello. Хранится здесь, а не передаётся вторым
     * аргументом, чтобы вызывающему не приходилось держать секрет живым до конца
     * рукопожатия; затирается xs_hs_wipe вместе со всем остальным. */
    uint8_t s_priv[32];
    /* Статический публичный ИНИЦИАТОРА, расшифрованный из msg1. Заполняет только хаб: ему
     * этот ключ нужен на шаге se, и он же — личность пира. */
    uint8_t peer_static[32];
    uint8_t rs[32];          /* статический публичный второй стороны (у хаба — свой) */
    uint8_t sid[32];         /* аутентификатор: у пира отправленный, у хаба принятый */
    struct xs_payload peer;  /* что прислала вторая сторона */
    int role_init;           /* 1 — пир (инициатор), 0 — хаб */
    /* Корни эпох, выведенные Split: по одному на направление, названы от инициатора (см.
     * xsepoch.h). Живут здесь до xs_hs_wipe; забирает их xs_hs_roots. Нужны только режиму
     * потока — в поддельном TCP эпох нет, и там эти байты просто затираются неиспользованными. */
    uint8_t root_i2r[32], root_r2i[32];
};

/* ---- пир ----------------------------------------------------------------- */

/* Собрать ClientHello, несущий msg1. Возвращает 0; out получает готовую ЗАПИСЬ TLS. */
int xs_hs_client_hello(struct xs_hs *hs, const struct xs_secrets *sec,
                       const uint8_t hub_pub[32], const char *sni, int mtu, int conn_id,
                       uint8_t *out, size_t cap, size_t *out_n);

/* Разобрать ответ хаба (ServerHello + ChangeCipherSpec + две записи) и получить ключи.
 * consumed — сколько байт потока израсходовано; остаток принадлежит уже данным. */
int xs_hs_client_finish(struct xs_hs *hs, const uint8_t *in, size_t n,
                        struct tls13_keys *tx, struct tls13_keys *rx, size_t *consumed);

/* Собрать своё подтверждение («Finished»). Отправляется сразу за разбором ответа. */
int xs_hs_client_confirm(struct xs_hs *hs, struct tls13_keys *tx,
                         uint8_t *out, size_t cap, size_t *out_n);

/* ---- хаб ------------------------------------------------------------------- */

/* Разобрать ClientHello и узнать, чей это пир. peer_static получает 32 байта статического
 * ключа инициатора — по нему вызывающий ищет пира в своей таблице. */
int xs_hs_server_read(struct xs_hs *hs, const struct xs_secrets *sec,
                      const uint8_t *rec, size_t n, uint8_t peer_static[32]);

/* Собрать ответный поток и получить ключи. */
int xs_hs_server_write(struct xs_hs *hs, int mtu, uint8_t *out, size_t cap, size_t *out_n,
                       struct tls13_keys *tx, struct tls13_keys *rx);

/* Проверить подтверждение пира. */
int xs_hs_server_confirm(struct xs_hs *hs, struct tls13_keys *rx,
                         const uint8_t *in, size_t n, size_t *consumed);

/* Корни эпох ДЛЯ ЭТОЙ СТОРОНЫ: tx_root — направление, в которое мы шифруем, rx_root — из
 * которого расшифровываем. Разложение по ролям делает эта функция, а не вызывающий: перепутать
 * их местами — это «рукопожатие прошло, а на 64-м мегабайте туннель умер молча», то есть отказ,
 * который не проявится ни на стенде рукопожатия, ни в первую минуту работы.
 *
 * Зовётся ПОСЛЕ xs_hs_client_finish (или xs_hs_server_write) и ДО xs_hs_wipe. */
void xs_hs_roots(const struct xs_hs *hs, uint8_t tx_root[32], uint8_t rx_root[32]);

/* Пришёл ли ответ хаба ЦЕЛИКОМ. Определяется по одной лишь рамке записей: без криптографии,
 * без ключей и без изменения состояния.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, ЕСЛИ ЕСТЬ КОД ОТКАЗА XS_EFORMAT. Потому что xs_hs_client_finish
 * ВБИРАЕТ прочитанное в транскрипт по мере разбора: на неполном ответе mix_hash над
 * ServerHello уже выполнен, а до подтверждения дело не дошло, — и повторный вызов на
 * дособранном ответе посчитает ServerHello ДВАЖДЫ. Тег после этого не сойдётся при
 * совершенно верной криптографии. Пока ответ хаба влезал в один сегмент, это не проявлялось
 * ни разу; на канале с меньшим MSS проявилось бы как «хаб не признал нас», и искать причину
 * пришлось бы в ключах. Поэтому границу ответа определяет ЭТА функция, а finish зовётся ровно
 * один раз на целом ответе.
 *
 * Граница — запись-подтверждение: тип 0x17 и длина ровно XS_FIN_BODY. «Сертификат» тоже
 * 0x17, но его длина заведомо больше (нагрузка плюс сотни байт набивки), так что спутать
 * нельзя; ServerHello (0x16) обязан встретиться раньше. */
int xs_hs_response_complete(const uint8_t *in, size_t n);

/* Затереть состояние рукопожатия. Обязательно после Split: в нём лежат ck и k, из которых
 * выводятся транспортные ключи. */
void xs_hs_wipe(struct xs_hs *hs);

/* Отказать неузнанному так, как это сделал бы настоящий сервер TLS: fatal
 * handshake_failure. Честно говоря, от активного зондирования это не спасает (см.
 * docs/xsteer.md) — но молчание в ответ на настоящий ClientHello отличимо ещё сильнее. */
size_t xs_hs_alert(uint8_t *out, size_t cap);

/* Выбор шифра по железу: тот же вопрос и тем же способом, что задаёт reality.c (и что
 * задаёт сам браузер), потому что ответ на него определяет порядок наборов в Hello. */
enum tls13_aead xs_aead_for_cpu(void);

#endif
