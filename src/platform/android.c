/* Телефон Android (прошивка DerpFest, Android.bp): тот же движок, у которого другие пути,
 * другое поле метки и приоритеты ip rule, каналы на сам телефон и NAT правилом iptables.
 *
 * Режим nft для старого ядра к платформе НЕ привязан: он определяется пробой ядра при apply
 * (nft_compat, src/compile/nftcompat.c), потому что телефоны на Android 17 придут с ядрами
 * новее 5.2, и навсегда запаянная старая раскладка отняла бы у них настоящие наборы со сроками.
 *
 * ---- где движок живёт на диске ---------------------------------------------------------
 *
 * На телефоне /etc и /var — часть системного раздела только для чтения, а /tmp нет вовсе;
 * писать туда значило бы, что каждый apply падает на mkstemp, а резолвер не может сохранить
 * раздачу поддельных адресов.
 *
 * /data/misc/steer — каталог, который обязан создать init-скрипт сборки (rc-файл), владелец
 * root; state и tmp внутри него, а не в /data/local/tmp: тот доступен shell-пользователю, и
 * чужой процесс мог бы подложить туда файл до нашего mkstemp или прочитать ruleset.
 *
 * Ключи сборки -D переопределяют корни так же, как у роутера (см. шапку openwrt.c): стенду
 * Android-сборки на обычном Linux (tests/run-via.sh, хост и vm49) нужны каталоги в /tmp и
 * узел TUN по роутерному пути, а подделывать /dev/tun в чужой системе незачем. */
#include <stdlib.h>
#include <unistd.h>
#include "platform.h"

#ifdef STEER_ETC_DIR
#define ETC STEER_ETC_DIR
#else
#define ETC "/data/misc/steer"
#endif
#ifdef STEER_STATE_DIR
#define STATE STEER_STATE_DIR
#else
#define STATE "/data/misc/steer/state"
#endif
#ifdef STEER_TMP_DIR
#define TMP STEER_TMP_DIR
#else
#define TMP "/data/misc/steer/tmp"
#endif
/* Каталог файлов, которые приложение заливает командой put-file управляющего сокета
 * (src/daemon/ctl.c): списки доменов и подсетей, файл подписки — всё, на что ссылается
 * собранная им спека.
 *
 * Внутри каталога спеки, а не в каталоге состояния: это ДАННЫЕ настройки человека, такие же,
 * как сама спека, — резервная копия и перенос на другое устройство берут их вместе, а каталог
 * состояния движок вправе вычистить (down, смена раскладки) без потери того, что выбрал
 * человек. SELinux-метку каталог получает ту же, что всё под /data/misc/steer
 * (steerd_data_file, file_contexts vendor/der), и приложению он закрыт так же, как спека.
 * Создаёт его сам сервер при первом put-file (права 0700), а не init: каталог нужен только
 * приложению, и пока оно ничего не залило, пустой каталог ничего не даёт. */
#ifdef STEER_LISTS_DIR
#define LISTS STEER_LISTS_DIR
#else
#define LISTS ETC "/lists"
#endif
/* Узел TUN. ueventd создаёт его как /dev/tun (system/core/rootdir/ueventd.rc: «/dev/tun 0660
 * system vpn», метка tun_device), а /dev/net/tun там нет вовсе: открытие по роутерному пути
 * кончалось ENOENT, то есть «нет модуля tun» на ядре, где он встроен. Подсказка при отказе
 * тоже своя: kmod-tun — это пакет OpenWrt, на телефоне ставить нечего, TUN даёт ядро
 * прошивки. */
#ifdef STEER_TUN_DEV
#define TUN STEER_TUN_DEV
#else
#define TUN "/dev/tun"
#endif

/* Системное хранилище корней для узлов security=tls (src/proto/vless/client.c, cert_roots):
 * каталоги по порядку предпочтения, первый, где нашёлся хоть один файл, и есть хранилище.
 * Ключом сборки — чтобы стенд (tests/androidroots.c, сборка в tests/ext-test.sh) подставил
 * свои. */
#ifndef STEER_ANDROID_CA_DIRS
#define STEER_ANDROID_CA_DIRS "/apex/com.android.conscrypt/cacerts", "/system/etc/security/cacerts"
#endif
static const char *const android_ca_dirs[] = { STEER_ANDROID_CA_DIRS, NULL };

/* Признаки среды Android: переменная ANDROID_ROOT, которую init ставит каждому процессу, и
 * /system/build.prop. На роутере нет ни того, ни другого. */
static int android_detect(void) {
    const char *r = getenv("ANDROID_ROOT");
    if (r && *r) return 1;
    return access("/system/build.prop", F_OK) == 0;
}

const struct platform_ops plat_android = {
    .name = "android",
    .detect = android_detect,

    .etc_dir = ETC,
    .state_dir = STATE,
    .tmp_dir = TMP,
    .lists_dir = LISTS,
    .spec_path = ETC "/spec.json",
    .ctl_sock = ETC "/steer.sock",
    /* Каталога iproute2 в /etc нет и быть не может: /etc — ссылка в системный раздел только
     * для чтения. Имена таблиц — удобство диагностики, и mkdir в чужой системный каталог при
     * каждом status пробовать незачем. */
    .rt_tables_d = NULL,
    .tun_dev = TUN,
    .tun_hint = "в ядре прошивки нет CONFIG_TUN",
    .ca_dirs = android_ca_dirs,

    /* ПОЛЕ СДВИНУТО ВВЕРХ И СУЖЕНО: биты 22-27 вместо 20-27.
     *
     * Слово метки здесь занято системой куда плотнее, чем на роутере. netd кладёт в fwmark
     * каждого сокета свою раскладку (system/netd/include/Fwmark.h, сверено с
     * android-16.0.0_r4): номер сети — биты 0-15, explicitlySelected — 16, protectedFromVpn —
     * 17, права — 18-19, uidBillingDone — 20; дальше восемь бит reserved (21-28), два бита
     * vendor (29-30, отданы производителю) и ingress_cpu_wakeup — 31. Его ip rule сравнивают
     * эти поля масками, и наша запись в бит 20 переводила бы пакет в другое правило учёта — то
     * есть телефон ходил бы не туда в обход нашей же таблицы. Бит 21 тоже свободен: поле
     * выбиралось по неверному прочтению Fwmark.h (там стоял ingress_cpu_wakeup в бите 21), а
     * шести бит хватает, так что двигать базу — значит менять метки ради одного лишнего бита.
     *
     * Сверху поле упирается в то же, что и на роутере: бит 28 у мини-сборки, 29 и 30 у zapret.
     * Остаётся шесть бит (22-27, внутри reserved netd) — 63 ненулевых значения при
     * шестнадцати выходах (STEER_MARK_SLOTS), запас тот же по смыслу.
     *
     * Биты zapret 29-30 (ZAPRET_SKIP_MARK и ZAPRET_OWN_MARK, marks.h) совпадают с битами
     * vendor netd, поэтому zapret здесь нет вовсе (.zapret = 0) и бит пропуска не ставится
     * (out_skips_zapret, spec.h) — в битах производителя движок не пишет ничего. Всё
     * остальное (маска, номер очереди, порт моста, проверки чужого диапазона в реестре)
     * выводится из этих двух чисел. */
    .mark_base = 0x00400000u,
    .mark_bits = 6,
    .mark_mask = PLAT_MARK_MASK(0x00400000u, 6),
    /* ПРИОРИТЕТ ПРАВИЛ ip rule. netd держит свою лестницу правил с 10000 и выше
     * (legacy_system, явный выбор сети, VPN, сеть по умолчанию, в конце 32000 unreachable), а
     * правила ядро перебирает по возрастанию номера: чьё меньше, тот и решает. Без явного pref
     * ядро поставило бы наше правило на 9999, потом 9998 и так далее — случайно верно, но
     * держалось бы на том, что ниже 10000 никто больше ничего не ставит. Явное 9000 ставит все
     * правила движка ДО лестницы netd: пакет с нашей меткой уходит в таблицу выхода, а без
     * метки — идёт к netd как обычно. Одно число на все выходы законно: правила различаются
     * меткой и друг друга не перекрывают.
     *
     * Проба здоровья (правило «from <адрес туннеля>» у сторожа) — рядом и тоже ниже 10000,
     * иначе ping через туннель решала бы лестница netd, а не наша таблица пробы. */
    .rule_pref = 9000,
    .probe_pref = 8999,
    /* БИТ ПЕРЕМАРШРУТИЗАЦИИ — только для каналов на сам телефон (from_is_local) в старой
     * раскладке.
     *
     * Пакет, который телефон порождает сам, маршрут уже получил: его выбрал connect(). Ядро
     * пересматривает маршрут на выходе, только если метку сменила цепочка ТИПА route, и
     * только своя: nft_chain_route сравнивает метку до и после ЭТОЙ цепочки. На 4.9 цепочки
     * route есть лишь в таблицах ip и ip6, а наборы каналов (их пополняет резолвер) живут в
     * inet. Поэтому разметка идёт в inet (цепочка filter, там наборы) и ставит вместе с меткой
     * выхода этот бит, а цепочка route в таблице ip следом снимает его — метка сменилась
     * внутри route-цепочки, и ядро ищет маршрут заново уже по метке выхода (legacy.c, шаг 2).
     *
     * Бит 21: в раскладке netd (Fwmark.h) это резерв, никем не занятый, и он вне нашего поля
     * 22-27. Снаружи цепочек бит не живёт — снимается на том же пакете. */
    .reroute_bit = 0x00200000u,
    /* СОБСТВЕННЫЙ ТРАФИК ДВИЖКА: значение поля метки «все биты» (место 63, то есть
     * маска поля этой раскладки, 0x0fc00000). Выходу его не выдают никогда (мест 16,
     * STEER_MARK_SLOTS), и правила маршрутизации на него нет — пакет идёт обычным путём. Им
     * метит свой сокет резолвер (запрос наверх), и заворот DNS на output его пропускает:
     * заворачивать приходится всех, включая root, — DnsResolver (netd) шлёт запросы
     * приложений со своего сокета, и для nft (meta skuid берёт fsuid файла сокета, а не
     * sk_uid, который меняет fchown) это root. */
    .self_mark = PLAT_MARK_MASK(0x00400000u, 6),
    /* СОБСТВЕННЫЙ ТРАФИК ТУННЕЛЯ ЧЕРЕЗ via: бит 28 рядом с меткой выхода-цели.
     *
     * Сокет наверх туннеля с `via` несёт метку ЦЕЛИ (out_underlay_mark): по ней ip rule цели
     * ведёт его в её таблицу. Но по одной метке его не отличить ни от помеченного каналом
     * трафика приложений того же выхода, ни от чего-то ещё, а заворот DNS на output
     * (local_dns_redirect в generate.c) пропускает мимо себя только значение «сам движок».
     * Если сервер туннеля слушает 53-й порт — а UDP/53 и TCP/53 как раз и выбирают, чтобы
     * пройти там, где режут остальное, — заворот забрал бы соединение туннеля к нашему
     * резолверу, и туннель через via не встал бы вовсе. Исключить помощников по UID нельзя:
     * заворот обязан брать и root — запросы приложений шлёт DnsResolver, и для nft это root
     * (см. выше); ядерный сокет WireGuard (awg) владельца-файла не имеет вовсе, и
     * `meta skuid` на нём не совпадает ни с чем.
     *
     * Поэтому туннель через via метит свой сокет меткой цели ПЛЮС этим битом, а заворот
     * пропускает пакеты с ним. Бит вне поля движка (STEER_MARK_MASK) и потому ничего не меняет
     * в маршрутизации: ip rule сравнивает `mark & маска`, masquerade выхода — тоже. Бит 28 — в
     * reserved netd (биты 21-28 никем не заняты, Fwmark.h сверен с android-16.0.0_r4), рядом с
     * битом перемаршрутизации 21; на роутере он занят мини-сборкой, но там заворота на output
     * нет и бит не ставится (.tunnel_bit = 0 у openwrt). */
    .tunnel_bit = 0x10000000u,
    /* Первый UID приложений Android (AID_APP_START): "self" — это приложения, а не системные
     * демоны. Демоны ниже этого числа (clatd, netd, dns_tether, network_stack) обязаны ходить
     * напрямую: clatd, например, несёт IPv4 телефона на сетях только с IPv6, включая сам
     * туннель. */
    .app_uid_min = 10000u,

    /* Каналы на сам телефон — решение владельца: «каналы и на весь телефон, и на
     * приложение». zapret не нужен: «zapret не надо». */
    .local_channels = 1,
    .zapret = 0,
    /* fw4 нет: трафик раздачи транслирует netd через iptables, и проверки зоны и masquerade по
     * дампу nftables говорили бы «устройство не упомянуто в firewall» на каждом apply. */
    .fw4 = 0,
    /* Нет ни netifd (ifdown/ifup), ни procd с ubus: интерфейс туннеля поднимает тот, кто его
     * завёл, — приложение VPN или наш же процесс. Сторож говорит и ждёт. */
    .netifd = 0,
    /* masquerade выходов — правилом iptables: на 4.9 цепочка nat nft и таблица nat iptables
     * netd не делят один хук (подробно — у iptables_masq_drop_all в apply.c). */
    .iptables_masq = 1,
    /* Раздача интернета идёт без моста Linux: приговор про br_netfilter отвечал бы на вопрос,
     * которого здесь никто не задаёт. */
    .lan_bridge = 0,
    /* Таблица nat iptables есть всегда, но PREROUTING в ней у netd — пустая oem_nat_pre, и
     * предупреждать о ней не о чем. */
    .warn_iptables_nat = 0,
    /* Сокет управления открыт приложению splify2 по его домену SELinux (vendor/der/sepolicy). */
    .ctl_allow_domain = "splify2_app",

    /* /etc/openwrt_release нет, а «OpenWrt» в заголовке подписки было бы неправдой, по которой
     * панель провайдера посчитала бы устройство роутером. Версию Android без libc-свойств
     * (property_get) не прочесть, а тянуть ради заголовка bionic-зависимость незачем: имени
     * системы панели достаточно. Модель ядро отдаёт из дерева устройств. */
    .os_release = NULL,
    .os_name = "Android",
    .model_path = "/proc/device-tree/model",
    .model_fallback = "android",
};
