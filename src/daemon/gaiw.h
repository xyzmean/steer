/* getaddrinfo без ожидания в цикле: рабочий поток на одну пачку имён.
 *
 * Зачем. Починка туннеля awg разрешает имя Endpoint заново (переезд сервера по DNS), а
 * getaddrinfo блокирует: резолвер libc ждёт ответа секунды, а без сети — до своего срока на
 * каждый сервер. Сторож в демоне работает на цикле событий (docs/architecture.md, «4а»), и
 * такое ожидание остановило бы демон целиком — status, subscribe, apply.
 *
 * Как. Неблокирующего getaddrinfo нет ни в musl, ни в bionic (getaddrinfo_a — только glibc), а
 * свой резолвер повторял бы то, что libc уже умеет с /etc/hosts, nsswitch и resolv.conf.
 * Поэтому — поток: пачка имён копируется ему целиком, он разрешает их по очереди обычным
 * getaddrinfo и отдаёт ответы одним куском в сокет-пару, конец которой лежит в epoll цикла.
 * Поток отсоединён и ничего общего с демоном не трогает: у него своя копия имён, а после ответа
 * он закрывает свой конец и уходит. Отмена — закрыть свой конец: запись потока получит отказ
 * (MSG_NOSIGNAL — без SIGPIPE), поток освободит своё и уйдёт сам. Поток живёт, пока идёт
 * разрешение, — раз в починку, а починка не чаще раза в пять минут на устройство.
 *
 * Сигналы цикла в потоке заблокированы по наследству от основного (loop_new блокирует их в
 * процессе до создания потока), и signalfd по-прежнему получает их все.
 *
 * Поток не создался (нет памяти, предел потоков) — имена разрешаются тут же, синхронно: редкий
 * отказ лучше, чем туннель без эндпоинта. */
#ifndef STEER_GAIW_H
#define STEER_GAIW_H

#include <stddef.h>
#include "kind.h"

struct loop;
struct gaiw;

/* Ответы: names (n штук) с заполненными rc/addr. Живут до возврата из вызова. */
typedef void (*gaiw_cb)(void *arg, const struct kind_name *names, size_t n);

/* Разрешить names. NULL — разрешено сразу (поток не создался), ответы — в names, обратного
 * вызова не будет. Иначе cb позовётся один раз (если не отменено). */
struct gaiw *gaiw_start(struct loop *l, struct kind_name *names, size_t n, gaiw_cb cb, void *arg);
void gaiw_cancel(struct gaiw *g);

/* Разрешить одно имя синхронно — то же, что делает поток. */
void gaiw_resolve(struct kind_name *nm);

#endif
