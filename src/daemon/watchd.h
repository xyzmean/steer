/* Сторож выходов в демоне (`steer daemon --watch`) — устройство и доводы в шапке watchd.c. */
#ifndef STEER_WATCHD_H
#define STEER_WATCHD_H

struct steerd;
struct watchd;

struct watchd_conf {
    int period_s;                /* период прохода в тишине, секунд */
    /* Включён ли движок (выключатель телефона). NULL — всегда. Выключен — проход не идёт:
     * демон работает и при выключенном движке, а трогать маршрутизацию тогда нельзя. */
    int (*enabled)(void);
    /* Идёт изменяющая команда (apply, reload): проход откладывается — он и apply пишут одни и те
     * же правила и таблицы. NULL — не спрашивать. */
    int (*busy)(void *arg);
    void *busy_arg;
};

/* Завести сторожа. Память выходов — в d->outs. NULL — не вышло (причина в журнале).
 *   on   — движок включён: первый проход сразу (или после watchd_release), дальше по периоду и
 *          по событиям сети. Выключен — ни таймера, ни сокета событий: сторож спит, пока его не
 *          включат (watchd_enable);
 *   hold — первый проход ждёт watchd_release: демон применяет спеку при старте (--apply), и
 *          проход до применения видел бы ядро без правил. */
struct watchd *watchd_start(struct steerd *d, const struct watchd_conf *c, int on, int hold);
/* Движок включили или выключили (apply, reload, SIGHUP сказали, в каком он положении).
 * Включили — проход сразу, таймер и сокет событий заводятся; выключили — идущий проход
 * прерывается, таймер и сокет снимаются. То же положение, что было, — ничего. */
void watchd_enable(struct watchd *w, int on);
/* Стартовое применение кончилось (успешно или нет): первый проход — сейчас. */
void watchd_release(struct watchd *w);
/* Спека в памяти демона сменилась (apply, reload, SIGHUP): внеочередной проход. */
void watchd_spec_changed(struct watchd *w);
/* Помощник выхода (--supervise) поднялся или упал: внеочередной проход, как по событию сети.
 * NULL — сторожа нет, ничего. */
void watchd_helper_changed(struct watchd *w);
/* Демон уходит: идущий проход прерывается (правило пробы снимается, команда оживления
 * убивается). */
void watchd_stop(struct watchd *w);

#endif
