/* Ожидания сторожа на цикле событий: пробы устройств и внешние команды оживления.
 *
 * Проход сторожа (failover.c) — конечный автомат на цикле loop.h: всё, чего он ждёт, он ждёт
 * здесь, а по готовности получает обратный вызов и делает следующий шаг. Ни одна функция этого
 * файла не блокирует: проба — это неблокирующий сокет в epoll с таймером срока, команда — это
 * ребёнок, выход которого приходит через loop_child. Отсюда и главное свойство: цикл демона во
 * время пробы свободен, а сама проба не стоит процесса.
 *
 * ПРОБА TCP (выходы с KC_TCP_PROBE, замер задержки) — неблокирующий connect с SO_BINDTODEVICE:
 * соединение идёт именно через проверяемое устройство, не полагаясь на метки и таблицы. Срок —
 * таймером цикла; задержка — время до установления соединения по CLOCK_MONOTONIC.
 *
 * ПРОБА ICMP (выходы kind=interface) — эхо-запрос из процесса, по возможности без ping:
 *   1) сырой сокет SOCK_RAW/IPPROTO_ICMP — демон и сторож работают под root (CAP_NET_RAW);
 *   2) если его не дают (EPERM/EACCES: на телефоне сырой сокет может запретить SELinux), —
 *      ping-сокет SOCK_DGRAM/IPPROTO_ICMP (net.ipv4.ping_group_range);
 *   3) если нет и его — внешний `ping -c 1 -W <срок> -I <устройство>` ребёнком. Это процесс на
 *      ПРОБУ, а не на проход, и последний откат: о нём пишется в журнал один раз за процесс,
 *      а неудавшиеся способы больше не пробуются, чтобы не платить за отказ на каждой пробе.
 * Сокет в обоих первых случаях привязан к устройству (SO_BINDTODEVICE) и к адресу источника
 * устройства (bind) — так же, как это делает ping из iputils с `-I <устройство>`: адрес
 * источника нужен правилу пробы (`from <адрес> lookup 299`, его ставит failover.c), которое
 * ведёт пробу и ответ на неё через проверяемое устройство. Почему правило остаётся и при
 * SO_BINDTODEVICE — в шапке device_healthy (failover.c).
 *
 * КОМАНДА — fork+exec с выброшенным выводом (как run_quiet), в своей группе процессов, выход —
 * через loop_child, срок — таймером: по сроку группа получает SIGKILL.
 *
 * ОТМЕНА. Каждое ожидание можно отменить (проход прерван: демон уходит, проход дольше предела).
 * Отменённая проба закрывает сокет и снимает таймер сразу; отменённая команда получает SIGKILL,
 * а её запись доживает до того, как цикл пожнёт ребёнка, — обратный вызов после отмены не
 * зовётся никогда. */
#ifndef STEER_FOPROBE_H
#define STEER_FOPROBE_H

struct loop;
struct foprobe;
struct fospawn;

/* Итог пробы: ok — ответ пришёл; ms — задержка (у TCP) или -1. */
typedef void (*foprobe_cb)(void *arg, int ok, int ms);

/* Соединение TCP с host:port через устройство dev. NULL — проба кончилась сразу (сокет не
 * открылся, соединилось мгновенно), итог — в *ok и *ms, обратного вызова не будет. Иначе —
 * идёт, и cb позовётся один раз (если проба не отменена). */
struct foprobe *foprobe_tcp(struct loop *l, const char *dev, const char *host, int port,
                            int timeout_ms, foprobe_cb cb, void *arg, int *ok, int *ms);

/* Эхо ICMP к host через устройство dev с адреса src. Договор — как у foprobe_tcp. */
struct foprobe *foprobe_icmp(struct loop *l, const char *dev, const char *src, const char *host,
                             int timeout_ms, foprobe_cb cb, void *arg, int *ok);

void foprobe_cancel(struct foprobe *p);

/* Итог команды: код выхода, -1 — убита (срок, сигнал) или не запустилась. */
typedef void (*fospawn_cb)(void *arg, int rc);

/* Запустить argv (поиск по PATH) с выброшенным выводом. NULL — не запустилась (fork), итог — в
 * *rc; иначе cb позовётся один раз. */
struct fospawn *fospawn_start(struct loop *l, const char *const argv[], int timeout_ms,
                              fospawn_cb cb, void *arg, int *rc);
void fospawn_cancel(struct fospawn *s);

#endif
