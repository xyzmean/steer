/* Выход, у которого есть устройство и своя таблица маршрутизации. vless сюда входит:
 * его TUN — такое же устройство, и вся логика меток, маршрутов и проверок к нему
 * применима без изменений. Одна функция вместо повторения условия в пяти местах —
 * иначе добавление нового вида требовало бы найти их все, а забытое место означало бы
 * выход, который настроен, но не маршрутизируется. */
static inline int out_has_device(const struct output *o) {
    return o->kind == OUT_INTERFACE || o->kind == OUT_VLESS || o->kind == OUT_XSTEER
        || o->kind == OUT_AWG;
}

/* Выход, которому нужна СВОЯ МЕТКА, чтобы его трафик можно было узнать в ядре.
 *
 * Не то же самое, что out_has_device, и разошлись они на kind=zapret: у того устройства нет
 * и таблицы маршрутизации нет (пакет уходит обычным маршрутом), а метка есть — по ней
 * цепочка postrouting отдаёт пакет нужному экземпляру nfqws. Пока условие было одно на две
 * надобности, добавление такого вида означало бы выход, помеченный ничем: правило канала
 * встало бы, а трафик в очередь не попал бы, и понять это было бы нечем — правила выглядят
 * применёнными.
 *
 * direct метки не получает по-прежнему: заявлять пакет ничем не нужно, он и так идёт туда. */
static inline int out_needs_mark(const struct output *o) {
    return o->kind == OUT_INTERFACE || o->kind == OUT_VLESS || o->kind == OUT_XSTEER
        || o->kind == OUT_ZAPRET || o->kind == OUT_TGWS || o->kind == OUT_AWG;
}

/* Выход, которому нужна метка СОЕДИНЕНИЯ, а не только метка пакета.
 *
 * Отдельно от out_needs_mark, потому что метка соединения живёт НЕ В НАШЕМ ФАЙЛЕ И НЕ В
 * НАШЕЙ ТАБЛИЦЕ. Она лежит в записи conntrack ядра и переживает и перезапуск службы, и
 * `nft delete table`, и удаление пакета целиком — снять её оттуда нечем, кроме как выждав
 * срок жизни записи. Значит ставить её можно только тем выходам, которым она ДЕЙСТВИТЕЛЬНО
 * нужна, а не всем подряд «на всякий случай».
 *
 * Кому нужна. Выходу kind=zapret — по ней цепочка postrouting узнаёт соединение после
 * хука forward, где метку пакета переписывают чужие (Tailscale). Выходам с устройством —
 * из-за выгрузки потоков: после установления соединения наша цепочка видит единицы пакетов
 * вместо тысяч, и пересмотреть маршрут (или применить запрет on_fail=drop) можно только по
 * метке соединения.
 *
 * Кому НЕ нужна — kind=tgws, и это не экономия, а починенная поломка. Перехват стоит в nat
 * prerouting и решает по метке ПАКЕТА, которую ставит наша же цепочка на десять приоритетов
 * раньше; ни таблицы маршрутизации, ни очереди у такого выхода нет, а соединение
 * заканчивается на самом роутере — то есть в forward не попадает и выгружено быть не может.
 * Метка соединения ему не нужна была никогда, а вреда приносила много: к нашему биту
 * добавляется ZAPRET_SKIP_MARK (см. out_skips_zapret), и он означает «этот трафик не твой»
 * для системного обхода. После удаления микропакета tgws правила исчезают, а записи
 * conntrack с этим битом остаются — и подхватившие Telegram podkop или splify2 получают
 * трафик, уже помеченный «мимо обхода». Снаружи это ровно то, о чём сказал владелец:
 * «удалил stgws — другие сервисы не могут нормально маршрутизировать Telegram». */
static inline int out_needs_ctmark(const struct output *o) {
    return out_needs_mark(o) && o->kind != OUT_TGWS;
}

/* Выход, устройство которого создаёт и обслуживает НАШ процесс, а не netifd.
 *
 * Отдельно от out_has_device, потому что из этого следуют другие вещи: ждать устройство
 * снаружи нельзя (его ещё нет), ifdown/ifup бесполезны (netifd про него не знает —
 * «Interface … not found», и на живом роутере это вечный холостой цикл в журнале), а
 * поднимает замену procd. */
static inline int out_engine_managed(const struct output *o) {
    return o->kind == OUT_VLESS || o->kind == OUT_XSTEER || o->kind == OUT_AWG;
}

/* Выход, которому masquerade не нужен: наружу он ходит от своего имени.
 *
 * Причины у vless и xsteer РАЗНЫЕ, и объединять их формулировкой нельзя — только
 * следствием. У vless адреса клиентов границу не переходят вовсе: клиент завершает TCP у
 * себя и соединяется с сервером обычным сокетом. У xsteer они переходят, но переходят к
 * хабу внутри туннеля, где транслировать их нечем и не нужно; более того, NAT там ВРЕДЕН
 * — он скрывает, от какой пира пришёл пакет, и ломает обратный поиск по AllowedIPs.
 * Отсюда одна функция для решения и разные тексты в сообщениях. */
static inline int out_self_natting(const struct output *o) {
    return o->kind == OUT_VLESS || o->kind == OUT_XSTEER;
}

/* Выход, трафик которого общий обход DPI трогать НЕ должен.
 *
 * Это все виды, кроме kind=direct, и исключение здесь ровно одно — оно же и есть смысл
 * прямого канала: там общий обход обязан работать, для этого канал и заводят.
 *
 * ПОЧЕМУ ОСТАЛЬНЫМ ОБХОД ВРЕДЕН, а не просто бесполезен. Пакет, уходящий в туннель, DPI
 * видит снаружи как сам туннель: разбирать его полезную нагрузку невозможно, и стратегия
 * обхода работает не с тем, для чего написана. Но nfqws при этом рассинхронизирует и режет
 * ВНЕШНИЕ пакеты — то есть трогает транспорт туннеля, и рукопожатие может не сойтись. Плюс
 * лишний проход через очередь на каждый пакет.
 *
 * Мост Telegram (kind=tgws) здесь по той же причине: его трафик разбирает наш собственный
 * обработчик, и второй разбиратель поверх — это два обхода на один пакет, то есть не то,
 * что выбрал человек, ни в одном из двух смыслов.
 *
 * ОДНОЙ ФУНКЦИЕЙ, а не `case` по kind на месте: спрашивают об этом генератор правил и
 * (со временем) диагностика, а две копии перечня разошлись бы при появлении следующего
 * вида выхода — и разошлись бы молча, потому что правила у обоих выглядят исправно. */
static inline int out_skips_zapret(const struct output *o) {
#ifdef STEER_ANDROID
    /* На телефоне zapret нет (решение владельца: «zapret не надо») — ни системного, которому
     * бит говорит «не твоё», ни своего kind=zapret (спека его отвергает, см. spec.c). Бит
     * ставить некому читать, а стоит он в бите 30 — там, где netd отдаёт производителю два
     * бита метки (Fwmark.h: vendor, 29-30). Ноль здесь снимает и бит в правилах разметки, и
     * цепочку failopen, которая существует только ради него (out_failopen_capable ниже). */
    (void)o;
    return 0;
#else
    return o->kind != OUT_DIRECT;
#endif
}

/* ВЫХОД УПАЛ, ТРАФИК ПУЩЕН НАПРЯМУЮ — И ОН СНОВА ОБЫЧНЫЙ ТРАФИК РОУТЕРА.
 *
 * Бит ZAPRET_SKIP_MARK ставит правило разметки в prerouting_mark, и ставит БЕЗУСЛОВНО: оно
 * ничего не знает о том, жив ли туннель. Пока выход работает, так и надо (см. out_skips_zapret
 * выше). Но при отказе с on_fail=direct или on_fail=zapret сторож снимает правило fwmark, и
 * помеченный пакет уходит по таблице main — через WAN, открытым путём, — а бит на нём
 * остаётся. Общий обход видит «не мой» и такой пакет не трогает. То есть «напрямую» на деле
 * значило «напрямую и мимо zapret»: сайты, которые без обхода не открываются, у человека с
 * упавшим туннелем не открывались и там, где весь остальной роутер их открывает. А у
 * on_fail=zapret, который ровно обходом и обещает, это было прямое расхождение с обещанием.
 *
 * Выбранное решение: СОСТОЯНИЕ «УПАЛ И ПУЩЕН НАПРЯМУЮ» ЛЕЖИТ В ЯДРЕ, в наборе FAILOPEN_SET
 * нашей таблицы (метки выходов), а отдельная цепочка prerouting_failopen сразу после
 * разметки (mangle + 2) снимает бит с пакетов, чья метка в наборе. Метку в набор кладёт и
 * вынимает тот, кто и так меняет маршрут выхода: сторож в apply_failed (кладёт при
 * direct/zapret, вынимает при drop) и в bind_device (вынимает при привязке к живому
 * устройству), apply — когда устройства для выхода нет вовсе (apply_routing в steer.c). Сверка
 * сторожа это же и чинит: apply пересоздаёт таблицу с пустым набором, но заодно возвращает
 * правило fwmark, и первый же проход видит у упавшего выхода расхождение и зовёт apply_failed.
 *
 * Почему не «ставить бит только при живом выходе» прямо в правиле разметки: правило одно на
 * группу каналов и знает о выходе только его метку, а переписывать правила на каждом отказе
 * значило бы пересобирать цепочку из сторожа. Почему не по устройству в postrouting («бит —
 * только тем, кто уходит в туннель»): список устройств у выхода меняется, у vless и xsteer
 * устройство заводит наш же процесс, и промах в перечне означал бы тихо вернувшийся обход
 * внешних пакетов туннеля. Набор же отвечает ровно на вопрос «пущен ли выход напрямую», и
 * ответ на него уже есть у сторожа.
 *
 * Только выходы с устройством (interface, vless, xsteer): у kind=zapret on_fail выражает
 * флаг bypass очереди (см. generate), у tgws on_fail бывает только drop. Цепочка и набор
 * ставятся, лишь если в спеке есть такой выход с on_fail не drop, — остальным на каждый
 * пакет лишний поиск ни к чему. */
#define FAILOPEN_SET "failopen"
static inline int out_failopen_capable(const struct output *o) {
    return out_has_device(o) && out_skips_zapret(o) && o->on_fail != FAIL_DROP;
}

