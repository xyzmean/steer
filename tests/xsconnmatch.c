/* Поддельное соединение xsteer: порог мёртвого пути и учёт СВОЕЙ незанятости.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ СТЕНДОМ. Порог тишины опущен с сорока пяти секунд до восьми, и опустить его
 * стало можно ровно по одной причине: tick теперь замечает, что не вызывали ЕГО САМОГО, и это
 * время в тишину не засчитывает. Раньше эти две вещи были неразличимы — «путь молчит» и «мы не
 * работали», — и именно смешение однажды пересоздало живой туннель на ровном месте, когда
 * посторонние процессы заняли оба ядра и наш получил 4% времени.
 *
 * Свойство, которое здесь проверяется, поэтому такое: при перерывах в вызовах tick порог НЕ
 * достигается, а без перерывов — достигается точно на своём числе. Проверить это иначе нечем:
 * воспроизводить голодание по процессору в стенде нельзя, а верить рассуждению — значит вернуть
 * ровно ту ошибку, из-за которой порог поднимали.
 *
 * Ни сети, ни прав root: время в xs_conn_tick приходит аргументом, а отправка при закрытом
 * дескрипторе просто не удаётся и на решение о мёртвом пути не влияет. Стенд входит в обычный
 * make test. */
/* _GNU_SOURCE до любых системных заголовков: struct mmsghdr (её использует xs_conn_split_mm)
 * объявляется только под ним. Обычная сборка получает его из CFLAGS пакета, а стенд собирается
 * своей строкой. */
#ifndef _GNU_SOURCE
#define _GNU_SOURCE
#endif
#include <stdio.h>
#include <string.h>

#include "../src/proto/xsteer/xsconn.c"

/* Заглушки внешних символов. Стенд не зовёт ни подъём соединения (ему нужен xc_random), ни
 * настройку интерфейсов (run_quiet), но линковщик обязан их найти: xsconn.c и obfs.c подключены
 * целиком. Так же поступает obfsmatch. */
int run_quiet(const char *const argv[]) { (void)argv; return 0; }
int xc_random(unsigned char *out, size_t n) { memset(out, 0x5A, n); return 0; }

static int fails;

static void check(const char *what, long want, long got) {
    printf("%-62s %s\n", what, want == got ? "ok" : "ПРОВАЛ");
    if (want != got) {
        printf("     хочу: %ld\n     есть:  %ld\n", want, got);
        fails++;
    }
}

/* Соединение в рабочем состоянии, без настоящего сокета: fd = -1, отправка не удаётся, а нас
 * интересуют только решения по времени. */
static void conn_ready(struct xs_conn *c, long long now) {
    memset(c, 0, sizeof(*c));
    c->fd = -1;
    c->state = XSC_EST;
    c->born = c->last_rx = c->last_tx = now;
}

int main(void) {
    long long t0 = 1000000;

    /* 1. Тишина при активной отправке и РОВНОМ ходе цикла: порог обязан сработать точно на
     *    XSC_DEAD_MS, а до него — нет. Ровный ход — это тик раз в двадцать миллисекунд, как у
     *    настоящего цикла пира. */
    {
        struct xs_conn c;
        conn_ready(&c, t0);
        int dead_at = 0;
        for (long long t = t0; t <= t0 + XSC_DEAD_MS + 200; t += XSC_TICK_MS) {
            if (xs_conn_tick(&c, t, 1)) { dead_at = (int)(t - t0); break; }
        }
        check("ровный ход: путь мёртв не раньше порога", 1, dead_at > XSC_DEAD_MS);
        check("ровный ход: путь мёртв не позже порога плюс тик", 1,
              dead_at > 0 && dead_at <= XSC_DEAD_MS + XSC_TICK_MS);
    }

    /* 2. ТО ЖЕ ВРЕМЯ, но цикл не работал: между вызовами tick проходит по две секунды. Столько
     *    же тишины, а решения быть не должно — тишину создали не путь, а мы. */
    {
        struct xs_conn c;
        conn_ready(&c, t0);
        int dead = 0;
        for (long long t = t0; t <= t0 + XSC_DEAD_MS + 2000; t += 2000) {
            if (xs_conn_tick(&c, t, 1)) { dead = 1; break; }
        }
        check("голодание по процессору не считается мёртвым путём", 0, dead);
    }

    /* 3. Смешанный случай: цикл голодал, потом пошёл ровно. Запас, накопленный голоданием,
     *    ОБЯЗАН сдвинуть порог, а не исчезнуть, — иначе после всплеска нагрузки туннель
     *    пересоздавался бы «за компанию». */
    {
        struct xs_conn c;
        conn_ready(&c, t0);
        long long t = t0;
        for (int i = 0; i < 3; i++) { t += 2000; xs_conn_tick(&c, t, 1); }   /* 6 с без вызовов */
        /* Сдвиг проверяется ТОЧНЫМ числом, и оно на один перерыв меньше, чем кажется: первый вызов
         * tick сравнивать не с чем (tick_at ещё нулевой), поэтому он только заводит отсчёт. Три
         * вызова через две секунды дают ДВА измеренных перерыва, то есть запас 4000 мс. Записать
         * здесь 6000 значило бы закрепить в стенде своё предположение вместо поведения. */
        check("запас — сумма ИЗМЕРЕННЫХ перерывов, а не всех", 4000, (long)c.stall);
        int dead_at = 0;
        for (; t <= t0 + 2 * XSC_DEAD_MS + 6000; t += XSC_TICK_MS) {
            if (xs_conn_tick(&c, t, 1)) { dead_at = (int)(t - t0); break; }
        }
        check("порог сдвинут ровно на запас", 1,
              dead_at > XSC_DEAD_MS + 4000 && dead_at <= XSC_DEAD_MS + 4000 + XSC_TICK_MS);
    }

    /* 4. Принятый сегмент обнуляет запас: он относится к ТЕКУЩЕЙ тишине, а не копится за всё
     *    время жизни соединения. Иначе соединение, однажды поголодавшее час, стало бы
     *    бессмертным — и мёртвый путь не замечался бы вовсе. */
    {
        struct xs_conn c;
        conn_ready(&c, t0);
        long long t = t0;
        for (int i = 0; i < 30; i++) { t += 2000; xs_conn_tick(&c, t, 1); }  /* 60 с голодания */
        check("запас накопился", 1, c.stall > 30000);
        struct obfs_seg seg;
        memset(&seg, 0, sizeof(seg));
        seg.flags = TH_ACK;
        xs_conn_on_seg(&c, &seg, t);
        check("принятый сегмент обнулил запас", 0, (long)c.stall);
        int dead_at = 0;
        for (long long u = t; u <= t + XSC_DEAD_MS + 200; u += XSC_TICK_MS) {
            if (xs_conn_tick(&c, u, 1)) { dead_at = (int)(u - t); break; }
        }
        check("после приёма порог снова обычный", 1,
              dead_at > XSC_DEAD_MS && dead_at <= XSC_DEAD_MS + XSC_TICK_MS);
    }

    /* 5. Молчание НА ПОКОЕ мёртвым путём не считается никогда: sending == 0. */
    {
        struct xs_conn c;
        conn_ready(&c, t0);
        int dead = 0;
        for (long long t = t0; t <= t0 + 10 * XSC_DEAD_MS; t += XSC_TICK_MS)
            if (xs_conn_tick(&c, t, 0)) { dead = 1; break; }
        check("молчание на покое — это покой, а не поломка", 0, dead);
    }

    /* 6. ПОКОЙ ДОЛЬШЕ ПОРОГА, а потом отправка: у пути обязан быть ПОЛНЫЙ срок на ответ.
     *
     * Так живёт всякий туннель на покое, и числа тут не выдуманные. Пир шлёт keepalive раз в
     * двадцать пять секунд (PersistentKeepalive в конфигурации), а хаб отвечает голым ACK и
     * дальше молчит, пока ему нечего сказать: свой keepalive он отправляет только «получал, но
     * сам давно не отправлял». То есть к моменту, когда пиру впервые есть что сказать, тишина
     * длится уже дольше XSC_DEAD_MS — вся она накопилась НА ПОКОЕ, когда мы и не спрашивали.
     *
     * Мерка «сколько прошло с последнего приёма» объявляла такой путь мёртвым ПЕРВЫМ ЖЕ тиком
     * после отправки, не дав хабу ни миллисекунды на круг. Наружу это выглядело так: живой
     * туннель на живом канале переподнимал соединение каждые пятнадцать-двадцать пять секунд, и
     * тем чаще, чем МЕНЬШЕ по нему шло трафика. Поймано на живой связи роутер↔VPS, а не
     * рассуждением: в стенде и в пространствах имён трафик идёт непрерывно, и покоя дольше
     * восьми секунд там не бывает вовсе.
     *
     * Правильная точка отсчёта — «когда мы НАЧАЛИ говорить в тишину», то есть первая отправка
     * после последнего приёма. */
    {
        struct xs_conn c;
        conn_ready(&c, t0);
        long long t = t0;
        int died_on_idle = 0;
        for (; t <= t0 + 25000; t += XSC_TICK_MS)
            if (xs_conn_tick(&c, t, 0)) { died_on_idle = 1; break; }
        check("покой в двадцать пять секунд сам по себе не убивает", 0, died_on_idle);
        /* Появился пакет — с этого мига отправка активна. */
        int dead_at = 0;
        for (long long u = t; u <= t + 2 * XSC_DEAD_MS; u += XSC_TICK_MS)
            if (xs_conn_tick(&c, u, 1)) { dead_at = (int)(u - t); break; }
        /* Срок полный — с точностью до тика, и эта точность здесь названа, а не спрятана:
         * покой засчитывается по ВЫЗОВАМ tick, поэтому последние двадцать миллисекунд покоя
         * (от последнего тика на покое до первого тика с отправкой) в запас не попадают. Одна
         * двадцатая процента порога; требовать больше значило бы требовать от учёта по тикам
         * точности, которой у него нет по построению. */
        check("после покоя у пути полный срок на ответ", 1, dead_at >= XSC_DEAD_MS);
        /* И порог не пропал вовсе: молчащий в ответ путь всё равно обязан умереть, и умереть
         * вовремя, а не когда-нибудь. */
        check("а умереть он всё-таки обязан, и в свой срок", 1,
              dead_at > 0 && dead_at <= XSC_DEAD_MS + XSC_TICK_MS);
    }

    /* 7. ГОЛОЕ ПОДТВЕРЖДЕНИЕ — НЕ РАЗГОВОР, и это самый дорогой случай из всех здешних.
     *
     * Сторона, которая приняла запись и подтвердила её, ничего у пути не спрашивала:
     * подтверждения не подтверждают ни у нас, ни в настоящем стеке, поэтому ответа не будет
     * никогда. Пока меркой был last_tx, такое подтверждение считалось отправкой — и сторона,
     * только подтвердившая принятое и замолчавшая, через порог объявляла живой путь мёртвым.
     *
     * На хабе половины на Go это уносило простаивающую сессию за восемь секунд: он подтверждал
     * последнюю запись пира, дальше оба молчали (своего keepalive хаб на покое не шлёт), сессия
     * освобождалась, и на следующую запись пира хаб не отвечал уже ничем — ни записью, ни RST.
     * Пир видел только собственную тишину и переподнимал соединение каждые двадцать-сорок
     * секунд. Здесь же закреплено и ВЫРАЖЕНИЕ, которым вызывающий считает активную отправку:
     * оно обязано смотреть на last_data_tx, иначе поле есть, а толку от него нет. */
    {
        struct xs_conn c;
        conn_ready(&c, t0);
        c.last_rx = t0;                /* приняли запись */
        c.last_tx = t0 + 5;            /* и подтвердили её голым ACK */
        c.last_data_tx = t0 - 1000;    /* а нагрузку отправляли давно, ещё до приёма */
        int dead = 0;
        for (long long t = t0; t <= t0 + 10 * XSC_DEAD_MS; t += XSC_TICK_MS)
            if (xs_conn_tick(&c, t, c.last_data_tx > c.last_rx)) { dead = 1; break; }
        check("голое подтверждение — не разговор, путь остаётся жив", 0, dead);
    }

    /* 8. Порог обязан совпадать с реализацией на Go (link.DeadMS = 8000): по нему хаб выбирает
     *    срок вытеснения, и расхождение означало бы, что один и тот же пир на одном хабе
     *    принимается, а на другом нет. Число закреплено здесь, чтобы правка в одной реализации
     *    не прошла молча в другой. */
    check("порог тот же, что у реализации на Go", 8000, XSC_DEAD_MS);

    /* 9. RST принимается только с ОЖИДАЕМЫМ номером.
     *
     * Четвёрка «адрес-порт ↔ адрес-порт» наблюдаема на всём пути, адрес источника подделывается
     * свободно, и никакой аутентификации на служебном сегменте нет по построению — обфускатор
     * притворяется TCP, а не защищает его. Пока RST снимал сессию, не спрашивая номера, один
     * пакет с угаданной четвёркой рвал живой туннель, и повторять его можно сколько угодно.
     *
     * Проверяемое правило — то же, что у настоящего стека после RFC 5961: годен только RST с
     * номером, которого приёмник ЖДЁТ (RCV.NXT). Слепому попадание в 32-битный номер стоит
     * 2^32 попыток, тогда как правило «в пределах окна» стоило бы 2^32/8 МиБ ≈ 512: окно мы
     * объявляем с масштабом, и «в окне» здесь означает восемь мегабайт номеров.
     *
     * Законный RST при этом обязан проходить, и он один: хаб не отвечает на порту (упал,
     * переехал, порт закрыт правилом). Ядро той стороны отвечает на наш сегмент RST'ом, у
     * которого номер равен полю подтверждения нашего сегмента — то есть ровно c->ack; на наш
     * SYN, у которого поля подтверждения нет, — RST с нулевым номером и подтверждением нашего
     * ISN + 1. Обе формы стенд и проверяет. */
    {
        struct xs_conn c;

        /* Живая сессия: приняли запись, ждём следующую с номером c.ack. */
        conn_ready(&c, t0);
        c.isn_rx = 4000;
        c.ack = 5000;
        struct obfs_seg seg;
        memset(&seg, 0, sizeof(seg));
        seg.flags = TH_RST;
        seg.seq = 999999;                       /* мимо: слепая подделка */
        check("поддельный RST мимо номера сессию не снимает", 0, xs_conn_on_seg(&c, &seg, t0));
        check("поддельный RST состояние не тронул", XSC_EST, c.state);

        /* Соседний номер — тоже мимо: правило именно «тот, которого ждём», а не «около». */
        seg.seq = 5001;
        check("RST на соседнем номере не годится", 0, xs_conn_on_seg(&c, &seg, t0));

        /* Ожидаемый номер — законный RST, сессия закрывается. */
        seg.seq = 5000;
        check("RST с ожидаемым номером сессию снимает", -1, xs_conn_on_seg(&c, &seg, t0));

        /* Рукопожатие: ответ ядра на наш SYN. Номера другой стороны мы ещё не знаем, поэтому
         * проверяется подтверждение нашего ISN. */
        conn_ready(&c, t0);
        c.state = XSC_SYN_SENT;
        c.isn_tx = 7000;
        c.seq = 7001;
        c.ack = 0;
        memset(&seg, 0, sizeof(seg));
        seg.flags = TH_RST | TH_ACK;
        seg.seq = 0;
        seg.ack = 7001;                          /* ISN + 1 */
        check("RST на SYN с подтверждением нашего ISN — законный", -1,
              xs_conn_on_seg(&c, &seg, t0));

        conn_ready(&c, t0);
        c.state = XSC_SYN_SENT;
        c.isn_tx = 7000;
        c.seq = 7001;
        memset(&seg, 0, sizeof(seg));
        seg.flags = TH_RST | TH_ACK;
        seg.ack = 12345;                         /* чужой ISN — подделка */
        check("RST на SYN с чужим подтверждением не годится", 0, xs_conn_on_seg(&c, &seg, t0));

        conn_ready(&c, t0);
        c.state = XSC_SYN_SENT;
        c.isn_tx = 7000;
        c.seq = 7001;
        memset(&seg, 0, sizeof(seg));
        seg.flags = TH_RST;                      /* без подтверждения вовсе */
        check("RST на SYN без подтверждения не годится", 0, xs_conn_on_seg(&c, &seg, t0));
    }

    /* 10. ОТВЕРГНУТЫЙ RST — НЕ ПРИЗНАК ЖИВОГО ПУТИ, и это стоило туннелю тринадцати минут.
     *
     * Хаб, у которого нашей сессии больше нет (её убрало обслуживание по простою, или хаб
     * перезапустили), отвечает RST'ом на КАЖДЫЙ наш сегмент. Номер в таком RST — не тот,
     * которого мы ждём, поэтому сессию он не снимает, и это правильно: иначе один угаданный
     * пакет рвал бы живой туннель. Но время последнего приёма он обновлял — оно ставилось
     * первой же строкой, ДО проверки номера, — и получалось, что чужой отказ доказывает
     * живость пути. Порог тишины при этом не достигался никогда, и пир сидел на соединении,
     * которое не несёт ни байта, пока его не пересоздаст смена ключей: на живом роутере это
     * тринадцать минут, в течение которых проба пути не получала эха ни на одном размере, а в
     * журнале не было ни строки.
     *
     * Проверяемое правило: RST не обновляет ни время приёма, ни запас незанятости — ни
     * отвергнутый, ни принятый. Отвергнутый по-прежнему не трогает состояние (случай 9). */
    {
        struct xs_conn c;
        conn_ready(&c, t0);
        c.ack = 5000;                  /* ждём именно этот номер */
        c.last_rx = t0;
        c.last_data_tx = t0 + 1;       /* нагрузку отправили: путь обязан ответить */
        struct obfs_seg seg;
        memset(&seg, 0, sizeof(seg));
        seg.flags = TH_RST;
        seg.seq = 1234;                /* не тот номер — RST отвергается */
        int dead = 0;
        long long t = t0;
        for (; t <= t0 + 4 * XSC_DEAD_MS; t += XSC_TICK_MS) {
            xs_conn_on_seg(&c, &seg, t);
            if (xs_conn_tick(&c, t, c.last_data_tx > c.last_rx)) { dead = 1; break; }
        }
        check("поток отвергнутых RST путь живым не делает", 1, dead);
        check("мёртвый путь замечен на своём пороге", 1,
              dead && t - t0 <= XSC_DEAD_MS + 4 * XSC_TICK_MS);
        check("отвергнутый RST по-прежнему не трогает состояние", XSC_EST, c.state);
    }

    /* 11. KEEPALIVE СЧИТАЕТСЯ ОТ ПОСЛЕДНЕЙ ЗАПИСИ, А НЕ ОТ ПОСЛЕДНЕГО СЕГМЕНТА.
     *
     * Соединение, по которому идёт одна загрузка, отправляет только голые подтверждения — по
     * одному на два принятых сегмента, то есть каждые десятки миллисекунд. Пока срок keepalive
     * отсчитывался от last_tx, эти подтверждения его и сбрасывали: пустая запись не уходила
     * НИКОГДА. А хаб считает простой сессии по ПОДТВЕРЖДЁННЫМ КАДРАМ (last_auth у движка на C,
     * lastAuth у половины на Go) — голое подтверждение для него не жизнь, — и через три минуты
     * освобождал сессию пира, который всё это время исправно принимал его же трафик.
     *
     * Отсюда и весь дальнейший отказ: слот пира на хабе пуст, наши записи получают RST, а RST
     * (случай 10) не давал заметить тишину. Поэтому мерка здесь одна и та же с обеих сторон:
     * жизнь — это ЗАПИСЬ, а не сегмент. */
    {
        struct xs_conn c;
        conn_ready(&c, t0);
        c.last_data_tx = t0;           /* последняя запись — сейчас */
        c.last_rx = t0 + 24000;        /* принимаем непрерывно */
        c.last_tx = t0 + 24990;        /* и подтверждаем голыми ACK каждые десятки мс */
        check("пока запись свежа, keepalive не нужен", 0,
              xs_conn_need_keepalive(&c, 25000, t0 + 24999));
        check("голые подтверждения срок keepalive не сбрасывают", 1,
              xs_conn_need_keepalive(&c, 25000, t0 + 25000));
        check("без настройки keepalive не шлётся вовсе", 0,
              xs_conn_need_keepalive(&c, 0, t0 + 1000000));
    }

    printf(fails ? "\nПРОВАЛОВ: %d\n" : "\nвсё сошлось\n", fails);
    return fails ? 1 : 0;
}
