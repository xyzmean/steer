/* Проверка кольца повторной передачи на границах.
 *
 * Зачем отдельно, а не «проверим на роутере»: ошибка в арифметике по модулю не выглядит как
 * ошибка. Кольцо провернётся не туда, клиент получит вместо повтора чужие байты, TCP их
 * отбросит — и снаружи это будет «иногда встаёт передача», то есть тот же симптом, что и
 * вовсе без повторной передачи. Различить их на живом трафике нечем.
 *
 * Проверяется то, что легко сломать и невозможно заметить: заворот за край, подтверждение
 * больше отправленного, непрерывность куска для повтора, полный оборот кольца.
 */
#include <stdio.h>
#include <string.h>
#include <stdlib.h>

#include "../src/ext/rtx.h"

static int fails;

static void check(int ok, const char *what) {
    if (!ok) { printf("FAIL %s\n", what); fails++; }
}

/* Байт номер i в потоке. Значение зависит от номера, поэтому «отдали не то место»
 * обнаруживается, а не выглядит как совпадение. */
static unsigned char byte_at(uint64_t i) {
    return (unsigned char)(i * 131u + 17u);
}

/* Собрать через повторы весь неподтверждённый остаток и сверить с потоком. */
static void verify_unacked(struct rtx *r, uint64_t base, const char *what) {
    uint32_t off = 0;
    struct rtx copy = *r;                   /* peek не меняет кольцо, но drop меняет */
    uint32_t left = r->len;
    while (left) {
        const unsigned char *p = NULL;
        uint32_t n = rtx_peek(&copy, left, &p);
        if (!n) { check(0, what); return; }
        for (uint32_t i = 0; i < n; i++) {
            if (p[i] != byte_at(base + off + i)) {
                printf("FAIL %s: байт %u не тот (смещение %llu)\n",
                       what, off + i, (unsigned long long)(base + off + i));
                fails++;
                return;
            }
        }
        off += n;
        left -= n;
        /* Дальше остаток лежит с начала кольца — двигаем голову копии. */
        rtx_drop(&copy, n);
    }
    check(off == r->len, what);
}

int main(void) {
    const uint32_t CAP = 1000;              /* НЕ степень двойки: маскирование вместо
                                             * деления сломалось бы именно здесь */
    struct rtx r;
    if (rtx_init(&r, CAP) != 0) { printf("нет памяти\n"); return 2; }

    static unsigned char stream[100000];
    for (size_t i = 0; i < sizeof(stream); i++) stream[i] = byte_at(i);

    /* ---- пустое кольцо ---- */
    const unsigned char *p = NULL;
    check(rtx_room(&r) == CAP, "пустое: место == вся ёмкость");
    check(rtx_peek(&r, 100, &p) == 0, "пустое: повторять нечего");
    check(rtx_drop(&r, 50) == 0, "пустое: подтверждать нечего");

    /* ---- заполнение без заворота ---- */
    rtx_push(&r, stream, 400);
    check(r.len == 400, "после 400: длина");
    check(rtx_room(&r) == CAP - 400, "после 400: место");
    check(rtx_peek(&r, 1000, &p) == 400, "после 400: повтор отдаёт всё");
    verify_unacked(&r, 0, "после 400: содержимое");

    /* ---- частичное подтверждение ---- */
    check(rtx_drop(&r, 150) == 150, "подтверждение 150");
    check(r.len == 250, "после подтверждения: длина");
    verify_unacked(&r, 150, "после подтверждения: содержимое");

    /* ---- заворот за край ---- */
    rtx_push(&r, stream + 400, 700);        /* 250 + 700 = 950 <= 1000 */
    check(r.len == 950, "заворот: длина");
    /* Голова на 150, значит непрерывно до края лежит 850 байт, а не все 950. */
    check(rtx_peek(&r, 950, &p) == 850, "заворот: повтор отдаёт только непрерывное");
    verify_unacked(&r, 150, "заворот: содержимое");

    /* ---- подтверждение больше отправленного ---- */
    check(rtx_drop(&r, 5000) == 950, "подтверждение вперёд отправленного обрезается");
    check(r.len == 0, "после обрезанного подтверждения кольцо пусто");

    /* ---- переполнение не портит кольцо ---- */
    rtx_push(&r, stream, 900);
    uint32_t before = r.len;
    rtx_push(&r, stream, 200);               /* больше, чем осталось места */
    check(r.len == before, "переполнение: длина не изменилась");
    verify_unacked(&r, 0, "переполнение: содержимое цело");
    rtx_drop(&r, 900);

    /* ---- много оборотов подряд, как на настоящей передаче ----
     *
     * Кусками неровного размера: ровные легли бы на край кольца одинаково, и заворот
     * посреди куска не проверился бы ни разу. */
    uint64_t sent = 0, acked = 0;
    for (int step = 0; step < 5000; step++) {
        uint32_t n = 1 + (uint32_t)((step * 37) % 400);
        if (n > rtx_room(&r)) n = rtx_room(&r);
        if (n) {
            rtx_push(&r, stream + (sent % 50000), n);
            /* Поток здесь не непрерывный (мы берём из stream по кругу), поэтому содержимое
             * сверяем не по byte_at, а по тому же выражению — ниже. */
            sent += n;
        }
        /* Подтверждаем меньше, чем отправили, чтобы кольцо жило заполненным. */
        uint32_t a = (uint32_t)((step * 29) % 350);
        if (a > r.len) a = r.len;
        acked += rtx_drop(&r, a);
        check(r.len <= CAP, "оборот: длина в пределах ёмкости");
        check(r.head < CAP, "оборот: голова в пределах ёмкости");
    }
    check(sent - acked == r.len, "оборот: отправлено минус подтверждено == длина");
    printf("оборотов кольца примерно %llu\n", (unsigned long long)(sent / CAP));

    /* ---- заворот ровно на краю ---- */
    rtx_drop(&r, r.len);
    r.head = CAP - 10;                       /* поставим голову к самому краю */
    rtx_push(&r, stream, 10);
    check(rtx_peek(&r, 10, &p) == 10, "край: 10 байт до края непрерывны");
    check(memcmp(p, stream, 10) == 0, "край: содержимое до края");
    rtx_push(&r, stream + 10, 10);           /* эти лягут с нуля */
    check(rtx_peek(&r, 20, &p) == 10, "край: за краем повтор обрывается");
    rtx_drop(&r, 10);
    check(rtx_peek(&r, 10, &p) == 10, "край: после подтверждения отдаём хвост");
    check(memcmp(p, stream + 10, 10) == 0, "край: содержимое за краем");

    rtx_done(&r);

    /* ---- рост кольца ----
     *
     * Проверяется ровно то, из-за чего рост опасен: содержимое, лежащее ЗА КРАЕМ. Скопировать
     * буфер как есть при увеличении размера нельзя — край окажется в другом месте, и повтор
     * отдаст клиенту чужие байты. Снаружи это выглядело бы как «иногда встаёт передача», то
     * есть неотличимо от полного отсутствия повтора. */
    struct rtx g;
    check(rtx_init(&g, 64) == 0, "рост: малое кольцо выделено");
    rtx_push(&g, stream, 60);
    rtx_drop(&g, 50);                        /* голова уехала к краю: осталось 10 байт */
    rtx_push(&g, stream + 60, 40);           /* 14 до края, остальное с нуля */
    check(g.len == 50, "рост: до увеличения 50 неподтверждённых");
    check(rtx_peek(&g, 50, &p) < 50, "рост: до увеличения кусок разорван краем");

    check(rtx_grow(&g, 4096) == 0, "рост: увеличение удалось");
    check(g.cap == 4096 && g.len == 50 && g.head == 0, "рост: кольцо выпрямлено");
    check(rtx_peek(&g, 50, &p) == 50, "рост: теперь весь кусок непрерывен");
    check(memcmp(p, stream + 50, 50) == 0, "рост: содержимое сохранено В ПОРЯДКЕ");
    check(rtx_grow(&g, 100) == -1, "рост: уменьшение отвергнуто");
    /* И кольцо после отказа обязано остаться рабочим — на отказ роста мы полагаемся. */
    check(g.cap == 4096 && rtx_peek(&g, 50, &p) == 50, "рост: отказ не испортил кольцо");
    rtx_done(&g);

    printf("%s\n", fails ? "FAIL" : "PASS: кольцо повтора держит границы");
    return fails ? 1 : 0;
}
