#!/bin/sh
# Чтение скомпилированных наборов правил sing-box (`.srs`) — стенд.
#
# ЗАЧЕМ ЭТОТ СТЕНД И ПОЧЕМУ ОБРАЗЦЫ НАСТОЯЩИЕ. Формат двоичный, и ошибка в его разборе не
# падает: succinct-дерево читается без единой жалобы и отдаёт правдоподобные, но НЕ ТЕ имена.
# Заметить это можно только сравнением с независимым эталоном — иначе стенд проверяет моё
# понимание формата против моей же реализации, то есть ничего.
#
# Поэтому образцы в tests/srs — НАСТОЯЩИЕ файлы из релиза itdoginfo/allow-domains, а эталон
# рядом — плоские списки того же издателя из дерева его ветки, из которых он эти `.srs` и
# собирает. Проверка стоит на его тексте, а не на нашем представлении о правильном ответе.
# Ровно тот же приём, что в splify2/tests/zapret: образец Flowseal и его ожидаемый разбор.
#
# Сети стенду не нужно: файлы лежат в репозитории, все шесть вместе — меньше двух килобайт.
#
# Что стенд НЕ проверяет: сопоставление имён. Оно живёт в dnsd и проверяется dnsmatch —
# здесь только то, что из двоичного файла вышел ровно тот список, который издатель написал
# текстом, и в нашем синтаксисе.
#
# Запуск: sh tests/srsmatch.sh
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 2
STEER="${STEER:-$ROOT/build/steer}"
FIX=tests/srs
[ -x "$STEER" ] || { echo "нет $STEER — соберите: make all"; exit 2; }

pass=0 fail=0
check() {
    if [ "$2" = "$3" ]; then
        pass=$((pass + 1))
    else
        fail=$((fail + 1))
        printf 'FAIL %s\n  ожидалось: %s\n  получено:  %s\n' "$1" "$2" "$3"
    fi
}

T="$(mktemp -d /tmp/srsmatch.XXXXXX)"
trap 'rm -rf "$T"' EXIT INT TERM

# Наш синтаксис снимается обратно в голые имена: обычная строка — суффикс, `=имя` — точное,
# `*образец` — шаблон. Эталон издателя нормализуется тем же способом: ведущая точка в его
# записи означает буквальный суффикс, у нас она же приезжает как `*.ua`.
norm_ours() { sed -e 's/^=//' -e 's/^\*//' "$1" | sed 's/^\.//' | grep . | sort -u; }
norm_ref()  { tr -d '\r' < "$1" | sed 's/^\.//' | grep . | sort -u; }

# ---- youtube: только домены -----------------------------------------------------------
"$STEER" srs-read "$FIX/youtube.srs" --out "$T/yt.dom" --prefixes-out "$T/yt.pfx" 2>"$T/yt.err"
check "youtube: разобран" "0" "$?"
norm_ours "$T/yt.dom" > "$T/yt.ours"; norm_ref "$FIX/youtube.lst" > "$T/yt.ref"
check "youtube: список совпал с эталоном издателя" "" "$(diff "$T/yt.ours" "$T/yt.ref")"
check "youtube: подсетей в наборе нет" "0" "$(grep -c . "$T/yt.pfx")"
# Все записи издателя — суффиксы домена, значит в нашем синтаксисе это ОБЫЧНЫЕ строки.
# Если бы терминатор 0x0A читался как «точное имя», здесь было бы 18 строк с `=`, и ни один
# поддомен больше не ловился бы — при полностью совпадающем списке имён.
check "youtube: записи вышли суффиксами, а не точными именами" "0" \
    "$(grep -c '^=' "$T/yt.dom")"

# ---- telegram: домены и подсети в РАЗНЫЕ файлы ----------------------------------------
"$STEER" srs-read "$FIX/telegram.srs" --out "$T/tg.dom" --prefixes-out "$T/tg.pfx" 2>"$T/tg.err"
check "telegram: разобран" "0" "$?"
norm_ours "$T/tg.dom" > "$T/tg.ours"; norm_ref "$FIX/telegram.lst" > "$T/tg.ref"
check "telegram: домены совпали с эталоном" "" "$(diff "$T/tg.ours" "$T/tg.ref")"
# Подсети в наборе лежат ДИАПАЗОНАМИ [от, до], а не префиксами, и обратно раскладываются в
# минимальный набор префиксов. Сверяется с тем же издателем: Subnets/IPv4/telegram.lst.
sort -u "$T/tg.pfx" | grep . > "$T/tg.pours"
norm_ref "$FIX/telegram-subnets.lst" > "$T/tg.pref"
check "telegram: подсети совпали с эталоном" "" "$(diff "$T/tg.pours" "$T/tg.pref")"
check "telegram: домены не уехали в файл подсетей" "0" "$(grep -c '[a-z]' "$T/tg.pfx")"
check "telegram: подсети не уехали в файл доменов" "0" "$(grep -c '/[0-9]*$' "$T/tg.dom")"

# ---- discord: сужение по протоколу и портам уходит третьим потоком --------------------
#
# Единственный набор этого издателя без доменов вовсе: подсеть Cloudflare плюс ограничение
# по протоколу и портам. До схемы 2 у канала не было ни того измерения, ни другого, и набор
# отвергался целиком — иначе его подсети уехали бы в туннель без «только udp», то есть весь
# TCP к 104.16.0.0/12 молча.
#
# Теперь измерение есть, и сужение печатается ГОТОВЫМ К ПЕРЕНОСУ в канал. Отдельным потоком,
# а не строкой в списке: список читают dnsd и компилятор набора, и обоим `proto=udp` — мусор.
"$STEER" srs-read "$FIX/discord.srs" --out "$T/dc.dom" --prefixes-out "$T/dc.pfx" \
    --meta-out "$T/dc.meta" 2>"$T/dc.err"
check "discord: разобран" "0" "$?"
# Набор несёт ВСЕ ТРИ вида сразу — домены, подсети и сужение, — и это единственный такой
# файл у издателя. Проверяется, что ни один из трёх не потерялся и не уехал в чужой поток:
# домены нужны dnsd, подсети — набору nftables, сужение — каналу.
check "discord: домены есть и их 20" "20" "$(grep -c . "$T/dc.dom")"
check "discord: подсети есть" "yes" \
    "$([ "$(grep -c . "$T/dc.pfx")" -gt 5 ] && echo yes || echo no)"
check "discord: подсети не уехали в файл доменов" "0" "$(grep -c '/[0-9]*$' "$T/dc.dom")"
check "discord: домены не уехали в файл подсетей" "0" "$(grep -c '[a-z]' "$T/dc.pfx")"
check "discord: протокол назван" "proto=udp" "$(grep '^proto=' "$T/dc.meta")"
# Порты переведены в НАШУ запись: у sing-box `50000:65535`, у нас через тире — та же форма,
# которой записан диапазон адресов в списках.
check "discord: порты в нашей записи, через тире" "yes" \
    "$(grep -q '^ports=50000-65535,19000-20000$' "$T/dc.meta" && echo yes || echo no)"
check "discord: двоеточий чужой формы не осталось" "0" "$(grep -c ':' "$T/dc.meta")"

# БЕЗ --meta-out ТАКОЙ НАБОР ОТВЕРГАЕТСЯ, и это главная проверка раздела: отдать подсети,
# потеряв сужение, значит сделать ровно то, чего вся эта работа и должна избежать.
"$STEER" srs-read "$FIX/discord.srs" --out /dev/null --prefixes-out /dev/null 2>"$T/dc.err2"
check "без --meta-out сужение не теряется молча — отказ" "2" "$?"
check "и сказано, чем это кончится" "yes" \
    "$(grep -q 'уедут в туннель' "$T/dc.err2" && echo yes || echo no)"

# Набор БЕЗ сужения третьего потока не требует: --meta-out для него необязателен.
"$STEER" srs-read "$FIX/youtube.srs" --out /dev/null --prefixes-out /dev/null 2>/dev/null
check "набор без сужения не требует --meta-out" "0" "$?"

# ---- отказы на испорченном ------------------------------------------------------------
printf 'NOTSRS\0\0\0\0\0\0' > "$T/bad.magic"
"$STEER" srs-read "$T/bad.magic" >/dev/null 2>"$T/e1"
check "чужой файл отвергнут" "1" "$?"
check "и сказано, что нет подписи" "yes" "$(grep -q 'SRS' "$T/e1" && echo yes || echo no)"

# Версия за пределами известных: набор мог быть собран новее нашей сборки, и разобрать его
# «как получится» значило бы применить правила, которых мы не поняли.
printf 'SRS\377' > "$T/bad.ver"; cat "$FIX/youtube.srs" | tail -c +5 >> "$T/bad.ver"
"$STEER" srs-read "$T/bad.ver" >/dev/null 2>"$T/e2"
check "неизвестная версия отвергнута" "1" "$?"
check "и версия названа" "yes" "$(grep -q '255' "$T/e2" && echo yes || echo no)"

# Обрезанный файл: zlib не доедет до конца, и это обязано быть отказом, а не половиной списка.
head -c 120 "$FIX/youtube.srs" > "$T/bad.trunc"
"$STEER" srs-read "$T/bad.trunc" >/dev/null 2>"$T/e3"
check "обрезанный файл отвергнут" "1" "$?"

# Тело не zlib: подпись и версия на месте, дальше мусор.
printf 'SRS\001' > "$T/bad.body"; printf 'мусормусормусор' >> "$T/bad.body"
"$STEER" srs-read "$T/bad.body" >/dev/null 2>"$T/e4"
check "тело не zlib — отказ" "1" "$?"

# ---- пути вывода ----------------------------------------------------------------------
# Без --prefixes-out подсети идут туда же, куда домены: так набор можно посмотреть одной
# командой, и именно поэтому такой файл объявлен негодным к применению.
"$STEER" srs-read "$FIX/telegram.srs" > "$T/one.txt" 2>/dev/null
check "без --prefixes-out всё в один поток" "30" "$(grep -c . "$T/one.txt")"
# Непишущийся путь называется до разбора, а не после.
"$STEER" srs-read "$FIX/youtube.srs" --out /nonexistent-dir/x.lst >/dev/null 2>"$T/e5"
check "непишущийся путь — отказ" "1" "$?"
check "и путь назван" "yes" \
    "$(grep -q 'nonexistent-dir' "$T/e5" && echo yes || echo no)"

printf '\n%d проверок пройдено' "$pass"
if [ "$fail" -gt 0 ]; then printf ', %d ПРОВАЛЕНО\n' "$fail"; exit 1; fi
printf '\nвсе проверки прошли\n'
