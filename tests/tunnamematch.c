/* Имя устройства TUN: движок обязан работать ровно с тем именем, о котором просил.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ СТЕНДОМ. Ошибка здесь не выглядит ошибкой ни в одной точке. Ядро молча
 * усекает имя длиннее IFNAMSIZ-1 (15 значащих символов) и создаёт устройство с ДРУГИМ
 * именем — измерено: xs-abcdefghijklm превращается в xs-abcdefghijkl. Дескрипторы при этом
 * открываются, туннель на уровне очередей работает, в журнале печатается штатное
 * «<dev> -> <узел>». А адрес, txqueuelen и привязка таблицы уезжают на имя из настроек,
 * которого в системе нет: tun_bring_up зовёт три `ip` через run_quiet, и все три отказа
 * проглатываются по устройству самой функции. Снаружи это «интерфейс поднят, трафика нет»
 * (I-107). Реализация на Go так не расходится: tun/tun_linux.go читает имя обратно из ifreq
 * и дальше пользуется полученным.
 *
 * Проверяется ровно одно утверждение: имя, которое вернуло ядро, совпадает с запрошенным —
 * иначе tun_open ОТКАЗЫВАЕТ. Отказ, а не «взять имя ядра», потому что на имя устройства
 * ссылаются ещё зона firewall, таблица маршрутизации и обработчик netifd, и всё это
 * заведено управляющим слоем по имени из настроек.
 *
 * ОБСТАНОВКА. Нужно настоящее устройство: TUNSETIFF — единственное место, где ядро
 * сообщает выбранное имя, и подделать его нечем. Значит нужен CAP_NET_ADMIN и /dev/net/tun.
 * Нет их — стенд пропускается ВСЛУХ и с кодом 0: молчаливый пропуск читается как «прошло»,
 * и ровно так стенд однажды превращается в фикцию (тот же приём, что в tests/ext-test.sh).
 * Устройство непостоянное (без TUNSETPERSIST), поэтому исчезает с закрытием дескрипторов —
 * убирать за собой отдельно нечего, но существование проверяется по /sys/class/net.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

#include "../src/ext/tun.c"

/* Имена выбраны так, чтобы усечение длинного НЕ совпало с коротким: иначе стенд проверял бы
 * сам себя. 15 символов — предел, который обязан работать; 16 — первый, который не влезает. */
#define NAME_OK   "xs-namechk-ok15"
#define NAME_LONG "xs-namechk-long6"
#define NAME_CUT  "xs-namechk-long"   /* во что ядро усекает NAME_LONG */

static int fails;

static void check(const char *what, long want, long got) {
    printf("%-62s %s\n", what, want == got ? "ok" : "ПРОВАЛ");
    if (want != got) {
        printf("   ожидалось %ld, получено %ld\n", want, got);
        fails++;
    }
}

/* Существует ли устройство с таким именем. Через /sys, а не if_nametoindex: <net/if.h>
 * конфликтует с <linux/if.h>, который уже включён через tun.c. */
static int dev_exists(const char *name) {
    char path[128];
    struct stat st;
    snprintf(path, sizeof(path), "/sys/class/net/%s", name);
    return stat(path, &st) == 0;
}

static void close_all(struct tun_dev *q, int n) {
    for (int i = 0; i < n; i++) close(q[i].fd);
}

int main(void) {
    struct tun_dev q[4];

    /* Проба доступности: тот же вызов, что делает движок, но с заведомо коротким именем.
     * Отказ здесь означает отсутствие прав или модуля, а не находку. */
    int probe = tun_open(q, 1, NAME_OK);
    if (probe < 0) {
        printf("ПРОПУЩЕН: TUNSETIFF недоступен (нет /dev/net/tun или CAP_NET_ADMIN)\n");
        printf("Стенд проверяет, что движок не работает с ДРУГИМ именем устройства, чем просил.\n");
        return 0;
    }
    check("имя в 15 символов принято", 1, probe >= 1);
    check("устройство с этим именем создано", 1, dev_exists(NAME_OK));
    close_all(q, probe);

    /* Главный случай: 16 символов. До правки tun_open возвращал число очередей, то есть
     * успех, и движок продолжал работать с именем NAME_LONG, которого в системе нет. */
    int n = tun_open(q, 1, NAME_LONG);
    check("имя в 16 символов отвергнуто", 1, n < 0);
    if (n > 0) close_all(q, n);
    check("устройства с усечённым именем не осталось", 0, dev_exists(NAME_CUT));
    check("устройства с запрошенным именем нет и не было", 0, dev_exists(NAME_LONG));

    printf("\n");
    if (fails) {
        printf("ЕСТЬ ПРОВАЛЫ: %d\n", fails);
        return 1;
    }
    printf("все проверки прошли\n");
    return 0;
}
