/* Поддельный TCP: проверка того, что уезжает на провод.
 *
 * Зачем отдельным стендом. Обфускатор — единственное место в движке, которое САМО
 * собирает заголовки и само же их разбирает. Ошибка в контрольной сумме или в
 * арифметике номеров не видна как сбой: сегмент уходит, вторая сторона молча его
 * отбрасывает (или отбрасывает conntrack по дороге, пометив поток недействительным), и
 * снаружи это выглядит как «туннель не поднимается» без единой строки в журнале.
 * Поэтому проверяется именно провод, а не поведение цикла.
 *
 * ГРАНИЦА СТЕНДА. Сюда входит всё, что чистое: сборка сегмента, разбор, контрольные
 * суммы, движение ack, разбор «адрес:порт». Циклов клиента и сервера здесь нет
 * намеренно — им нужны сырые сокеты, то есть root и живая сеть, а пространства имён в
 * среде агента запрещены. Их проверка — стенд на живом роутере, и это записано прямо
 * здесь, чтобы «зелёный make test» не читался как «обфускация проверена целиком».
 *
 * Исходник включается напрямую (как в dnsmatch.c и specmatch.c): половина проверяемого
 * — статические функции, и добавлять ради них подкоманду в движок было бы хуже. Из-за
 * этого в тест приезжают и сетевые части файла, но ни одна из них не вызывается.
 */
/* До любых системных заголовков: obfs.c объявляет _GNU_SOURCE у себя, но здесь его
 * включают ПОСЛЕ stdio, и тогда объявление опаздывает — recvmmsg/sendmmsg исчезают,
 * а компилятор советует sendmsg. */
#define _GNU_SOURCE
#include <stdio.h>
#include <string.h>
#include <arpa/inet.h>

/* Запуск внешних команд живёт в failover.c и нужен здесь ровно одному месту — правилу
 * против RST, которого стенд не ставит. Заглушка, а не линковка с failover.c: тащить
 * ради одного символа сторожа с его сокетами значило бы проверять не то. */
int run_quiet(const char *const argv[]) { (void)argv; return 0; }

#include "../src/obfs.c"

static int fails;

static void check(const char *what, long want, long got) {
    printf("%-62s %s\n", what, want == got ? "ok" : "ПРОВАЛ");
    if (want != got) {
        printf("     хочу: %ld\n     есть: %ld\n", want, got);
        fails++;
    }
}

static void check_str(const char *what, const char *want, const char *got) {
    int same = strcmp(want, got) == 0;
    printf("%-62s %s\n", what, same ? "ok" : "ПРОВАЛ");
    if (!same) {
        printf("     хочу: \"%s\"\n     есть: \"%s\"\n", want, got);
        fails++;
    }
}

/* Пакет для разбора: обфускатор читает с IP-заголовка, потому что сырой сокет отдаёт
 * пакет целиком. Собираем его так же, как это сделало бы ядро. */
static size_t wrap_ip(uint8_t *pkt, uint32_t saddr, uint32_t daddr,
                      const uint8_t *seg, size_t seglen) {
    struct ip4_hdr *ip = (struct ip4_hdr *)pkt;
    memset(ip, 0, sizeof(*ip));
    ip->vhl = 0x45;
    ip->len = htons((uint16_t)(sizeof(*ip) + seglen));
    ip->ttl = 64;
    ip->proto = 6;
    ip->src = saddr;
    ip->dst = daddr;
    memcpy(pkt + sizeof(*ip), seg, seglen);
    return sizeof(*ip) + seglen;
}

int main(void) {
    uint32_t A = inet_addr("192.0.2.1");        /* «мы» */
    uint32_t B = inet_addr("203.0.113.10");     /* сервер обфускации */
    uint8_t seg[60 + OBFS_MAX_PAYLOAD], pkt[OBFS_PKT_MAX];

    /* ---- сборка ------------------------------------------------------------- */
    {
        size_t n = obfs_build(seg, A, B, 40000, 4567, 1000, 2000, TH_PSH | TH_ACK, 0,
                              "hello", 5);
        struct tcp_hdr *t = (struct tcp_hdr *)seg;
        check("данные: длина сегмента = заголовок + нагрузка", 25, (long)n);
        check("данные: заголовок 20 байт (без опций)", 5, t->off >> 4);
        check("данные: исходный порт", 40000, ntohs(t->sport));
        check("данные: порт назначения", 4567, ntohs(t->dport));
        check("данные: номер последовательности", 1000, (long)ntohl(t->seq));
        check("данные: подтверждение", 2000, (long)ntohl(t->ack));
        check("данные: флаги PSH|ACK", TH_PSH | TH_ACK, t->flags);
        check("данные: окно объявлено максимальное", 65535, ntohs(t->win));
        check("данные: нагрузка на месте", 0, memcmp(seg + 20, "hello", 5));
        /* Сумма, посчитанная поверх готового сегмента, обязана давать ноль — это то же
         * действие, которое сделает стек на той стороне. */
        check("данные: контрольная сумма сходится", 0, obfs_tcp_csum(A, B, seg, n));
    }
    {
        size_t n = obfs_build(seg, A, B, 40000, 4567, 7, 0, TH_SYN, 1, NULL, 0);
        struct tcp_hdr *t = (struct tcp_hdr *)seg;
        check("SYN: длина с опцией MSS", 24, (long)n);
        check("SYN: длина заголовка 6 слов", 6, t->off >> 4);
        check("SYN: опция — MSS", 2, seg[20]);
        check("SYN: длина опции", 4, seg[21]);
        check("SYN: значение MSS = 1460", 1460, (seg[22] << 8) | seg[23]);
        check("SYN: сумма сходится с опцией", 0, obfs_tcp_csum(A, B, seg, n));
    }
    {
        /* Нечётная длина нагрузки — классическое место, где контрольная сумма
         * считается неверно: последний байт дополняется нулём справа, а не слева. */
        size_t n = obfs_build(seg, A, B, 1, 2, 0, 0, TH_ACK, 0, "abc", 3);
        check("нечётная нагрузка: сумма сходится", 0, obfs_tcp_csum(A, B, seg, n));
    }

    /* ---- сумма считается словами: сверка с независимым эталоном --------------
     *
     * «Сумма поверх готового сегмента даёт ноль» — проверка самосогласованности: она
     * прошла бы и в том случае, если бы обе стороны считали ОДИНАКОВО НЕВЕРНО, а стек
     * той стороны такой пакет молча выбросил бы. Поэтому здесь стоит второй, заведомо
     * правильный счёт — построчный по парам байт, как в RFC 1071, — и сверяется с тем,
     * что выдаёт рабочая реализация из obfs.c, читающая память словами.
     *
     * Перебираются все длины до 300 и смещения 0..3: невыровненное начало, нечётный
     * хвост и граница разворота по 16 байт — ровно те места, где такая правка ломается.
     * Байты неслучайные, но неповторяющиеся по позиции, поэтому перестановка любых двух
     * половин суммы была бы заметна. */
    {
        static uint8_t buf[512];
        for (size_t i = 0; i < sizeof(buf); i++) buf[i] = (uint8_t)(i * 37 + (i >> 3) * 11 + 1);
        int bad_len = -1;
        for (size_t off = 0; off < 4 && bad_len < 0; off++) {
            for (size_t len = 0; len <= 300; len++) {
                const uint8_t *p = buf + off;
                /* Эталон: пары байт в сетевом порядке, дополнение нулём справа. */
                uint32_t ref = 0;
                for (size_t k = 0; k + 1 < len; k += 2) ref += (uint32_t)((p[k] << 8) | p[k + 1]);
                if (len & 1) ref += (uint32_t)(p[len - 1] << 8);
                while (ref >> 16) ref = (ref & 0xFFFF) + (ref >> 16);
                uint16_t want = (uint16_t)(~ref & 0xFFFF);
                if (csum_fin(csum_add(p, len, 0)) != want) { bad_len = (int)(off * 1000 + len); break; }
            }
        }
        check("сумма словами совпадает с эталоном на всех длинах и смещениях", -1, bad_len);
    }
    {
        /* Накопитель переживает склейку из двух вызовов — так его и зовёт
         * obfs_tcp_csum: сначала псевдозаголовок, потом сегмент. */
        static uint8_t a[12], b[101];
        for (size_t i = 0; i < sizeof(a); i++) a[i] = (uint8_t)(i * 13 + 7);
        for (size_t i = 0; i < sizeof(b); i++) b[i] = (uint8_t)(i * 29 + 3);
        static uint8_t both[sizeof(a) + sizeof(b)];
        memcpy(both, a, sizeof(a));
        memcpy(both + sizeof(a), b, sizeof(b));
        check("сумма двух кусков равна сумме склейки",
              csum_fin(csum_add(both, sizeof(both), 0)),
              csum_fin(csum_add(b, sizeof(b), csum_add(a, sizeof(a), 0))));
    }

    /* ---- разбор ------------------------------------------------------------- */
    {
        size_t sn = obfs_build(seg, B, A, 4567, 40000, 5000, 1005, TH_PSH | TH_ACK, 0,
                               "wireguard", 9);
        size_t pn = wrap_ip(pkt, B, A, seg, sn);
        struct obfs_seg s;
        check("разбор: пакет принят", 0, obfs_parse(pkt, pn, &s));
        check("разбор: адрес источника", (long)B, (long)s.saddr);
        check("разбор: адрес назначения", (long)A, (long)s.daddr);
        check("разбор: порт источника", 4567, s.sport);
        check("разбор: порт назначения", 40000, s.dport);
        check("разбор: номер", 5000, (long)s.seq);
        check("разбор: подтверждение", 1005, (long)s.ack);
        check("разбор: длина нагрузки", 9, (long)s.plen);
        check("разбор: нагрузка та самая", 0, memcmp(s.payload, "wireguard", 9));
    }
    {
        /* Битая сумма обязана отвергаться: сегмент, принятый за данные, уехал бы в
         * WireGuard и был бы отброшен уже там — с диагнозом не о том. */
        size_t sn = obfs_build(seg, B, A, 4567, 40000, 1, 1, TH_ACK, 0, "xy", 2);
        size_t pn = wrap_ip(pkt, B, A, seg, sn);
        pkt[sizeof(struct ip4_hdr) + 20] ^= 0xFF;        /* портим байт нагрузки */
        struct obfs_seg s;
        check("разбор: битая сумма отвергнута", -1, obfs_parse(pkt, pn, &s));
    }
    {
        /* Обрезанные пакеты: сырой сокет слышит и чужое, и мусор, поэтому короткое
         * должно отвергаться, а не читаться за границей буфера. */
        struct obfs_seg s;
        size_t sn = obfs_build(seg, B, A, 4567, 40000, 1, 1, TH_ACK, 0, NULL, 0);
        size_t pn = wrap_ip(pkt, B, A, seg, sn);
        check("разбор: пустой пакет отвергнут", -1, obfs_parse(pkt, 0, &s));
        check("разбор: короче IP-заголовка отвергнут", -1, obfs_parse(pkt, 12, &s));
        check("разбор: IP без TCP отвергнут", -1, obfs_parse(pkt, sizeof(struct ip4_hdr), &s));
        check("разбор: обрезанный TCP отвергнут", -1, obfs_parse(pkt, pn - 4, &s));
        pkt[0] = 0x65;                                    /* ihl=5, версия 6 */
        check("разбор: не IPv4 отвергнут", -1, obfs_parse(pkt, pn, &s));
        pkt[0] = 0x45;
        pkt[9] = 17;                                      /* UDP */
        check("разбор: не TCP отвергнут", -1, obfs_parse(pkt, pn, &s));
    }
    {
        /* Опции в чужом SYN не должны съезжать в нагрузку: длина берётся из заголовка,
         * а не считается от начала. Ровно на этом ломается разбор, написанный «по
         * памяти», и ломается тихо — WireGuard получит лишние четыре байта. */
        size_t sn = obfs_build(seg, B, A, 4567, 40000, 9, 10, TH_SYN | TH_ACK, 1, NULL, 0);
        size_t pn = wrap_ip(pkt, B, A, seg, sn);
        struct obfs_seg s;
        check("разбор: SYN-ACK с опциями принят", 0, obfs_parse(pkt, pn, &s));
        check("разбор: у SYN-ACK нет нагрузки", 0, (long)s.plen);
        check("разбор: флаги SYN|ACK", TH_SYN | TH_ACK, s.flags);
    }

    /* ---- движение подтверждений ---------------------------------------------- */
    {
        check("ack: сдвигается вперёд", 1010, (long)obfs_next_ack(1000, 1000, 10));
        check("ack: не откатывается назад", 1010, (long)obfs_next_ack(1010, 500, 10));
        check("ack: повтор не двигает", 1010, (long)obfs_next_ack(1010, 1000, 10));
        /* Переполнение uint32 наступает на четырёх гигабайтах трафика. Сравнение «в
         * лоб» откатило бы ack к началу, и conntrack по дороге счёл бы весь поток
         * недействительным — то есть туннель ложился бы примерно раз в 4 ГиБ. */
        check("ack: переполнение через ноль", 9,
              (long)obfs_next_ack(0xFFFFFFF0u, 0xFFFFFFFFu, 10));
        /* Зеркальный случай: номера уже перевалили через ноль, а приехал сегмент
         * из «до переполнения». В кольце номеров он позади, и ack двигать нельзя —
         * иначе одна задержавшаяся датаграмма отбрасывала бы подтверждения на 4 ГиБ
         * назад. Сравнение знаковой разностью различает эти два случая, простое
         * «больше/меньше» — нет. */
        check("ack: старый сегмент после переполнения не двигает", 0x10,
              (long)obfs_next_ack(0x10u, 0xFFFFFFF0u, 10));
    }

    /* ---- разбор «адрес:порт» -------------------------------------------------- */
    {
        char host[64];
        int port = 0;
        check("адрес:порт разобран", 0, obfs_split_hostport("203.0.113.10:4567", host,
                                                            sizeof(host), &port));
        check_str("адрес:порт — адрес", "203.0.113.10", host);
        check("адрес:порт — порт", 4567, port);
        check("адрес без порта — отказ", -1,
              obfs_split_hostport("203.0.113.10", host, sizeof(host), &port));
        check("порт 0 — отказ", -1,
              obfs_split_hostport("203.0.113.10:0", host, sizeof(host), &port));
        check("порт больше 65535 — отказ", -1,
              obfs_split_hostport("203.0.113.10:70000", host, sizeof(host), &port));
        check("мусор вместо порта — отказ", -1,
              obfs_split_hostport("203.0.113.10:80x", host, sizeof(host), &port));
        check("пустой адрес — отказ", -1,
              obfs_split_hostport(":4567", host, sizeof(host), &port));
    }

    /* ---- опции в SYN: MSS и масштаб окна -------------------------------------
     *
     * Масштаб окна — не украшение. Без него conntrack по дороге ограничивает поток 64 КиБ в
     * полёте, и на живом роутере это стоило 2,15 Мбит/с против 63 (см. объяснение в obfs.h).
     * Поэтому проверяется и наличие опции, и то, что в сегментах данных её НЕТ: опция вне
     * SYN — это отличие от всякого настоящего TCP. */
    {
        uint8_t buf[128];
        size_t n = obfs_build(buf, 0x0100007F, 0x0200007F, 1111, 443, 100, 0,
                              0x02 /* SYN */, OBFS_OPT_SCALE, NULL, 0);
        check("SYN с масштабом: длина заголовка 28 байт", 28, (long)n);
        check("SYN: опция MSS на месте", 2, buf[20]);
        check("SYN: длина опции MSS", 4, buf[21]);
        check("SYN: MSS 1460", 1460, ((long)buf[22] << 8) | buf[23]);
        check("SYN: NOP перед масштабом", 1, buf[24]);
        check("SYN: опция масштаба окна", 3, buf[25]);
        check("SYN: длина опции масштаба", 3, buf[26]);
        check("SYN: множитель 7 (65535 << 7 = 8 МиБ)", OBFS_WSCALE, buf[27]);
        check("SYN: длина заголовка в поле off", 7, buf[12] >> 4);

        n = obfs_build(buf, 0x0100007F, 0x0200007F, 1111, 443, 100, 0,
                       0x02, OBFS_OPT_MSS, NULL, 0);
        check("SYN только с MSS: 24 байта, как было раньше", 24, (long)n);

        uint8_t pay[4] = { 1, 2, 3, 4 };
        n = obfs_build(buf, 0x0100007F, 0x0200007F, 1111, 443, 100, 0,
                       0x18 /* PSH|ACK */, OBFS_OPT_NONE, pay, sizeof(pay));
        check("сегмент данных: опций нет", 24, (long)n);
        check("сегмент данных: заголовок 20 байт", 5, buf[12] >> 4);
        check("сегмент данных: нагрузка сразу за заголовком", 1, buf[20]);
    }

    /* ---- имя цепочки ---------------------------------------------------------- */
    {
        /* Имя выхода приходит из спеки, а уезжает в аргумент nft. Движок имена не
         * ограничивает (это делает интерфейс), поэтому всё, что не буква и не цифра,
         * заменяется — иначе правило против RST не встанет, и это увидят только по
         * оборванным сессиям. */
        char c[64];
        chain_name('o', "wg_de", c, sizeof(c));
        check_str("цепочка: обычное имя", "o_wg_de", c);
        chain_name('o', "wg-de 1", c, sizeof(c));
        check_str("цепочка: чужие символы заменены", "o_wg_de_1", c);
        char longname[80];
        memset(longname, 'a', sizeof(longname) - 1);
        longname[sizeof(longname) - 1] = '\0';
        chain_name('o', longname, c, sizeof(c));
        check("цепочка: длинное имя обрезано по буферу", 63, (long)strlen(c));
        /* Буква вида различает цепочки обфускатора и xsteer в ОДНОЙ таблице. Без неё
         * выход из одного процесса снимал бы правило против RST у другого — и тот
         * продолжал бы работать, пока его сессии не начнёт рвать собственное ядро. */
        chain_name('x', "vpn", c, sizeof(c));
        check_str("цепочка: вид xsteer отличается от обфускатора", "x_vpn", c);
        chain_name('o', "vpn", c, sizeof(c));
        check_str("цепочка: тот же выход у обфускатора — другое имя", "o_vpn", c);
    }

    printf("\n%s\n", fails ? "ЕСТЬ ПРОВАЛЫ" : "все проверки прошли");
    return fails ? 1 : 0;
}
