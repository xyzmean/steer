#!/bin/sh
# Идентификатор роутера (HWID) — стенд.
#
# ЗАЧЕМ ЭТОТ СТЕНД И ПОЧЕМУ ЭТАЛОН НЕ НАШ. Значение уже разошлось по панелям подписок:
# человек видит там свою коробку строкой «splify2-…» и по ней освобождает слот, когда
# устройств больше, чем позволено. Изменить в вычислении хоть один шаг — значит объявить
# каждый заведённый роутер НОВЫМ устройством, и заметить это можно будет только по жалобам.
#
# Поэтому эталон здесь — `sha256sum` оболочки, а не наш же код и не записанная в стенд
# строка: до движка идентификатор считался именно так («sha256sum от splify2:<mac>, первые
# двадцать знаков»), и сверка с ним — единственная проверка, которая ловит расхождение с
# ПРЕЖНИМ поведением, а не с нашим представлением о нём.
#
# ГЛАВНОЕ СВОЙСТВО, РАДИ КОТОРОГО ФАЙЛ ПЕРЕЕХАЛ: `sub-hwid` обязан отвечать в БАЗОВОЙ
# сборке. Прежде он лежал в расширенной части и отвечал там отказом «нужен пакет
# steer-extended» — а телеметрии он нужен как раз на роутере, где расширенной сборки нет.
# Стенд гоняет именно базовый build/steer, и в этом половина его смысла.
#
# Запуск: sh tests/hwidmatch.sh
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 2
STEER="${STEER:-$ROOT/build/steer}"
SUM="${SUM:-$ROOT/build/hwidsum}"
[ -x "$STEER" ] || { echo "нет $STEER — соберите: make all"; exit 2; }
[ -x "$SUM" ] || { echo "нет $SUM — соберите: make build/hwidsum"; exit 2; }
command -v sha256sum >/dev/null 2>&1 || { echo "нужен sha256sum: эталон берётся у него"; exit 2; }

pass=0 fail=0
check() {
    if [ "$2" = "$3" ]; then pass=$((pass + 1)); else
        fail=$((fail + 1))
        printf 'FAIL %s\n  ожидалось: %s\n  получено:  %s\n' "$1" "$2" "$3"
    fi
}
T="$(mktemp -d /tmp/hwidmatch.XXXXXX)"
trap 'rm -rf "$T"' EXIT INT TERM

# ---- сам хеш против эталона оболочки ---------------------------------------------------
# Векторы взяты не наугад: пустая строка и «abc» напечатаны в самом стандарте, строка из 56
# байт переходит границу блока (56 + 1 + 8 > 64), а длинная проверяет несколько блоков.
# Без последних двух дополнение осталось бы непроверенным вовсе.
for s in "" "abc" "splify2:10:bb:cc:dd:ee:ff" \
         "abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq" \
         "0123456789012345678901234567890123456789012345678901234567890123456789"; do
    want="$(printf '%s' "$s" | sha256sum | cut -d' ' -f1)"
    got="$("$SUM" "$s")"
    check "sha256 совпал с эталоном оболочки: «$(printf '%.24s' "$s")»" "$want" "$got"
done

# ---- идентификатор целиком -------------------------------------------------------------
# АДРЕСА В ОБРАЗЦАХ — ГЛОБАЛЬНО НАЗНАЧЕННЫЕ, и это не мелочь: первая редакция стенда взяла
# «aa:bb:…», привычное по документации, и получила пустой ответ на КАЖДОЙ проверке. Пустой
# верно: 0xaa — это 1010 1010, второй младший бит первого октета стоит, значит адрес
# локальный и для постоянного идентификатора не годится. Годная вторая шестнадцатеричная
# цифра — из 0,1,4,5,8,9,c,d.
mkdev() {  # ИМЯ MAC ФИЗИЧЕСКОЕ(1/0)
    mkdir -p "$T/net/$1"
    printf '%s\n' "$2" > "$T/net/$1/address"
    [ "$3" = 1 ] && : > "$T/net/$1/device"
    return 0
}
hwid_of() { STEER_SYSNET="$T/net" "$STEER" sub-hwid | sed -n 's/.*"hwid":"\([^"]*\)".*/\1/p'; }
expect_hwid() {  # MAC -> ожидаемая строка, посчитанная эталоном
    printf 'splify2-%s' "$(printf 'splify2:%s' "$1" | sha256sum | cut -c1-20)"
}

rm -rf "$T/net"; mkdev eth0 "10:bb:cc:dd:ee:ff" 1
check "идентификатор совпал с эталоном оболочки" "$(expect_hwid 10:bb:cc:dd:ee:ff)" "$(hwid_of)"
# Приставка — не украшение: по ней человек узнаёт свой роутер среди телефонов в списке
# устройств панели.
check "приставка на месте" "yes" \
      "$(case "$(hwid_of)" in splify2-*) echo yes ;; *) echo no ;; esac)"
check "длина ровно как у прежнего cut -c1-20" "28" \
      "$(printf '%s' "$(hwid_of)" | wc -c | tr -d ' ')"

# ПОРЯДОК ПОРТОВ. Имена сортируются, потому что readdir отдаёт их в порядке файловой
# системы: без сортировки идентификатор менялся бы от перезагрузки к перезагрузке на коробке
# с несколькими портами. Проверяется тем, что имена созданы в ОБРАТНОМ порядке.
rm -rf "$T/net"
mkdev eth2 "10:00:00:00:00:02" 1
mkdev eth1 "10:00:00:00:00:01" 1
mkdev eth0 "10:00:00:00:00:00" 1
check "из нескольких портов берётся первый по алфавиту" "$(expect_hwid 10:00:00:00:00:00)" "$(hwid_of)"

# Семейство имён: eth важнее lan, lan важнее wan, wan важнее прочего.
rm -rf "$T/net"; mkdev wan "10:00:00:00:00:0a" 1; mkdev lan "10:00:00:00:00:0b" 1
check "lan старше wan" "$(expect_hwid 10:00:00:00:00:0b)" "$(hwid_of)"
rm -rf "$T/net"; mkdev lan "10:00:00:00:00:0b" 1; mkdev eth0 "10:00:00:00:00:0c" 1
check "eth старше lan" "$(expect_hwid 10:00:00:00:00:0c)" "$(hwid_of)"

# ЛОКАЛЬНО НАЗНАЧЕННЫЙ АДРЕС НЕ ГОДИТСЯ: его выдумывает ядро (так бывает у wifi-чипов и
# USB-адаптеров), и после перезагрузки он другой. Признак — второй младший бит первого
# октета, то есть вторая шестнадцатеричная цифра из 2,3,6,7,a,b,e,f.
for bad in 02 06 0a 0e 12 f2; do
    rm -rf "$T/net"; mkdev eth0 "$bad:11:22:33:44:55" 1; mkdev eth1 "10:00:00:00:00:99" 1
    check "локальный адрес $bad:… пропущен" "$(expect_hwid 10:00:00:00:00:99)" "$(hwid_of)"
done
# Нули и широковещательный — не адреса, а признак того, что драйвер ещё не дал настоящего.
rm -rf "$T/net"; mkdev eth0 "00:00:00:00:00:00" 1; mkdev eth1 "10:00:00:00:00:99" 1
check "нулевой адрес пропущен" "$(expect_hwid 10:00:00:00:00:99)" "$(hwid_of)"
rm -rf "$T/net"; mkdev eth0 "ff:ff:ff:ff:ff:ff" 1; mkdev eth1 "10:00:00:00:00:99" 1
check "широковещательный пропущен" "$(expect_hwid 10:00:00:00:00:99)" "$(hwid_of)"

# РЕГИСТР ПРИВОДИТСЯ К НИЖНЕМУ: sysfs отдаёт адрес строчными, но не всякий драйвер. Прежний
# счёт в оболочке приводил его тем же способом, и расхождение здесь означало бы другой
# идентификатор у той же коробки.
rm -rf "$T/net"; mkdev eth0 "C4:41:1E:DD:EE:01" 1
check "прописные буквы в адресе приведены к строчным" "$(expect_hwid c4:41:1e:dd:ee:01)" "$(hwid_of)"
check "и в самом идентификаторе только строчные" "20" \
      "$(printf '%s' "$(hwid_of)" | sed 's/^splify2-//' | grep -c '^[0-9a-f]\{20\}$' >/dev/null && printf '%s' "$(hwid_of)" | sed 's/^splify2-//' | wc -c | tr -d ' ' || echo нет)"

# И обратное: адрес глобального назначения берётся, а не отбрасывается заодно.
rm -rf "$T/net"; mkdev eth0 "04:11:22:33:44:55" 1
check "глобальный адрес не отброшен заодно" "$(expect_hwid 04:11:22:33:44:55)" "$(hwid_of)"

# ВИРТУАЛЬНЫЕ ИНТЕРФЕЙСЫ ПРОПУСКАЮТСЯ — у моста, туннеля и wifi-ap ссылки `device` нет.
# Без этого идентификатор менялся бы при заведении выхода: у `tun-vless` свой MAC.
rm -rf "$T/net"; mkdev br-lan "10:00:00:00:00:b0" 0; mkdev eth0 "10:00:00:00:00:e0" 1
check "мост без device пропущен" "$(expect_hwid 10:00:00:00:00:e0)" "$(hwid_of)"

# НЕ ИЗ ЧЕГО СЧИТАТЬ — законное состояние, и ответом обязана быть пустота, а не выдумка:
# пустой идентификатор значит «заголовок не уходит», и об этом говорит sub-fetch отдельно.
rm -rf "$T/net"; mkdir -p "$T/net"
check "нет портов — пустая строка" "" "$(hwid_of)"
STEER_SYSNET="$T/net" "$STEER" sub-hwid >/dev/null 2>&1
check "и это не ошибка — код 0" "0" "$?"
rm -rf "$T/net"; mkdev br-lan "10:00:00:00:00:b0" 0
check "одни виртуальные — тоже пустая строка" "" "$(hwid_of)"
rm -rf "$T/net"; mkdev eth0 "02:11:22:33:44:55" 1
check "одни локальные адреса — тоже пустая строка" "" "$(hwid_of)"
# Каталога устройств нет вовсе (шов указывает в никуда): не падение и не выдумка.
check "каталога устройств нет — пустая строка" "" \
      "$(STEER_SYSNET="$T/нет-такого" "$STEER" sub-hwid | sed -n 's/.*"hwid":"\([^"]*\)".*/\1/p')"

# ---- идентификатор телеметрии (dev-id) -------------------------------------------------
#
# ОТДЕЛЬНОЕ ЗНАЧЕНИЕ, И ЭТО ГЛАВНОЕ ЕГО СВОЙСТВО. HWID роутер отправляет ЧУЖОМУ серверу —
# заголовком `x-hwid` панели подписки. Тот же ключ в нашей базе означал бы, что продавец
# подписок, увидев её, сопоставит записи со своими платящими клиентами. Проверка на
# несовпадение поэтому не косметическая: она сторожит именно это свойство.
#
# Число проходов здесь занижено швом (STEER_DEVID_ITERS): полный счёт — 0,6 с на x86 и
# десятки секунд на слабом роутере, и гонять его в каждой проверке незачем. Правильность
# самого PBKDF2 проверяется ниже известными ответами RFC 6070, а не через идентификатор.
rm -rf "$T/net"; mkdev eth0 "10:bb:cc:dd:ee:ff" 1
tid_of() { STEER_SYSNET="$T/net" STEER_DEVID_ITERS=1000 "$STEER" dev-id | \
           sed -n 's/.*"tid":"\([^"]*\)".*/\1/p'; }
check "идентификатор телеметрии посчитан" "yes" \
      "$(case "$(tid_of)" in sp-????????????????????????????????) echo yes ;; *) echo no ;; esac)"
check "он НЕ равен HWID" "yes" \
      "$([ "$(tid_of)" != "$(hwid_of)" ] && echo yes || echo no)"
# И не является его переделкой: hwid внутри tid не встречается ни целиком, ни хвостом.
check "и не содержит HWID в себе" "0" \
      "$(printf '%s' "$(tid_of)" | grep -c "$(printf '%s' "$(hwid_of)" | sed 's/^splify2-//')" || true)"
# РЕЦЕПТУРА ЦЕЛИКОМ, ПРОТИВ НЕЗАВИСИМОГО СЧЁТА. Проверка ловит любое изменение любого шага:
# прообраз, соль, длину вывода, приставку. Без неё «прообраз tid сделали таким же, как у
# hwid» проходило бы незамеченным — мутация это показала.
check "идентификатор телеметрии совпал с независимым счётом" \
      "sp-$("$SUM" --pbkdf2 "splify2-telemetry:10:bb:cc:dd:ee:ff" "splify2-telemetry-id/1" 1000 16)" \
      "$(tid_of)"
check "одинаков при повторном вызове" "yes" \
      "$([ "$(tid_of)" = "$(tid_of)" ] && echo yes || echo no)"
first="$(tid_of)"
rm -rf "$T/net"; mkdev eth0 "10:bb:cc:dd:ee:fe" 1
check "другой адрес — другой идентификатор" "yes" \
      "$([ "$(tid_of)" != "$first" ] && echo yes || echo no)"
rm -rf "$T/net"; mkdir -p "$T/net"
check "не из чего считать — пустая строка, а не выдумка" "" "$(tid_of)"
STEER_SYSNET="$T/net" STEER_DEVID_ITERS=1000 "$STEER" dev-id >/dev/null 2>&1
check "и это не ошибка — код 0" "0" "$?"
# ЧИСЛО ПРОХОДОВ ШВОМ НЕ ПОДНИМАЕТСЯ ВЫШЕ НАСТОЯЩЕГО: шов заведён ради стенда, и ослабить
# счёт на роутере через переменную окружения он давать не должен... а вот занизить — должен,
# иначе стенд платит секунды за каждую проверку. Проверяется, что значения дают РАЗНЫЕ
# результаты, то есть шов действительно доходит до счёта.
rm -rf "$T/net"; mkdev eth0 "10:bb:cc:dd:ee:ff" 1
a="$(STEER_SYSNET="$T/net" STEER_DEVID_ITERS=1000 "$STEER" dev-id)"
b="$(STEER_SYSNET="$T/net" STEER_DEVID_ITERS=2000 "$STEER" dev-id)"
check "число проходов доходит до счёта" "yes" "$([ "$a" != "$b" ] && echo yes || echo no)"
# Мусор в шве не должен ослаблять счёт молча: непонятное значение означает «считай полностью».
c="$(STEER_SYSNET="$T/net" STEER_DEVID_ITERS=привет "$STEER" dev-id)"
d="$(STEER_SYSNET="$T/net" "$STEER" dev-id)"
check "непонятное значение шва — полный счёт" "yes" "$([ "$c" = "$d" ] && echo yes || echo no)"

# ---- PBKDF2 против известных ответов RFC 6070 -----------------------------------------
# Эталон опять не наш: это векторы из самого RFC, и они ловят ошибку в дополнении, в
# счётчике блоков и в порядке XOR — то есть ровно то, что в PBKDF2 и ошибаются.
check "RFC 6070, 1 проход" \
      "120fb6cffcf8b32c43e7225256c4f837a86548c92ccc35480805987cb70be17b" \
      "$("$SUM" --pbkdf2 password salt 1 32)"
check "RFC 6070, 2 прохода" \
      "ae4d0c95af6b46d32d0adff928f06dd02a303f8ef3c251dfd6e2d85a95474c43" \
      "$("$SUM" --pbkdf2 password salt 2 32)"
check "RFC 6070, 4096 проходов" \
      "c5e478d59288c841aa530db6845c4c8d962893a001ce4e11a4963873aa98134a" \
      "$("$SUM" --pbkdf2 password salt 4096 32)"
# Длина вывода больше 32 байт — второй блок, то есть счётчик блоков в игре.
check "RFC 6070, вывод в два блока" \
      "348c89dbcbd32b2f32d814b8116e84cf2b17347ebc1800181c4e2a1fb8dd53e1c635518c7dac47e9" \
      "$("$SUM" --pbkdf2 passwordPASSWORDpassword saltSALTsaltSALTsaltSALTsaltSALTsalt 4096 40)"

# ---- описание устройства ---------------------------------------------------------------
rm -rf "$T/net"; mkdev eth0 "10:bb:cc:dd:ee:ff" 1
printf "DISTRIB_RELEASE='24.10.0'\n" > "$T/release"
printf 'Xiaomi AX3000T\n' > "$T/model"
out="$(STEER_SYSNET="$T/net" STEER_OPENWRT_RELEASE="$T/release" STEER_SYSINFO_MODEL="$T/model" \
       "$STEER" sub-hwid)"
check "версия системы прочитана и кавычки сняты" "OpenWrt 24.10.0" \
      "$(printf '%s' "$out" | sed -n 's/.*"os":"\([^"]*\)".*/\1/p')"
check "модель прочитана" "Xiaomi AX3000T" \
      "$(printf '%s' "$out" | sed -n 's/.*"model":"\([^"]*\)".*/\1/p')"
# Файлов нет — умолчания, а не пустота: «router» и «OpenWrt» человеку в панели полезнее
# пустой строки, и именно так отвечал прежний код.
out="$(STEER_SYSNET="$T/net" STEER_OPENWRT_RELEASE="$T/нет" STEER_SYSINFO_MODEL="$T/нет" \
       "$STEER" sub-hwid)"
check "без файла версии — просто OpenWrt" "OpenWrt" \
      "$(printf '%s' "$out" | sed -n 's/.*"os":"\([^"]*\)".*/\1/p')"
check "без файла модели — router" "router" \
      "$(printf '%s' "$out" | sed -n 's/.*"model":"\([^"]*\)".*/\1/p')"
# ЧУЖОЙ ФАЙЛ — ЧУЖОЙ ВВОД. Модель читается с диска, а пишет её туда прошивка, и ответ
# движка после этого уезжает в JSON. Проверяется ПОЛНАЯ строка ответа, а не выдержка из неё:
# выдержка через sed сама спотыкается о кавычки и зеленела бы на испорченном выводе.
#
# Что именно остаётся от «Zлой "роутер"<таб><0x01>»: непечатаемое и всё, что вне ASCII,
# выброшено (кириллица тоже — заголовок HTTP её не переживёт), кавычки сохранены и
# ЭКРАНИРОВАНЫ. То есть значение испорчено не молча, а по объявленному правилу.
printf 'Zлой "роутер"\t\001\n' > "$T/model"
out="$(STEER_SYSNET="$T/net" STEER_SYSINFO_MODEL="$T/model" "$STEER" sub-hwid)"
check "чужая строка вычищена и экранирована целиком" \
      '{"hwid":"'"$(expect_hwid 10:bb:cc:dd:ee:ff)"'","os":"OpenWrt","model":"Z \"\""}' "$out"

printf '\n%d проверок пройдено' "$pass"
if [ "$fail" -gt 0 ]; then printf ', %d ПРОВАЛЕНО\n' "$fail"; exit 1; fi
printf '\nвсе проверки прошли\n'
