#!/bin/sh
# Верхний уровень `steer status`: то, по чему управляющий слой узнаёт ПОКОЛЕНИЕ движка,
# прежде чем писать в спеку поле, которого движок постарше не поймёт.
#
# Почему это отдельный стенд, а не строка в climatch.sh. Там проверяется РАЗБОР аргументов —
# что вызов splify2 не отвергнут; здесь — СОДЕРЖИМОЕ ответа, и ломается оно иначе: ответ
# приходит, разбирается, просто в нём нет признака. Тогда интерфейс считает движок старым и
# запирает возможности, которые есть, — или, что дороже, считает новым и пишет в спеку поле,
# которое будет пропущено молча (трафик через узел, которого никто не выбирал).
#
# Бинарник — build/diagsim: спеку с `kind: vless` базовая сборка отвергает парсером (и обязана
# отвергать), а именно у такого выхода печатается `nodes`. Тот же довод, что в diagmatch.sh.
set -u
BIN="${DIAG:-./build/diagsim}"
[ -x "$BIN" ] || { echo "not built: $BIN (make test)"; exit 2; }

pass=0 fail=0
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/state"

check() {
    if [ "$2" = "$3" ]; then pass=$((pass + 1)); else
        fail=$((fail + 1))
        printf 'FAIL %s\n  expected: %s\n  actual:   %s\n' "$1" "$2" "$3"
    fi
}

# nft не запущен: счётчики каналов при этом не читаются, а верхний уровень ответа от них не
# зависит вовсе — ровно то, что здесь проверяется.
mkdir -p "$tmp/bin"
printf '#!/bin/sh\nexit 1\n' > "$tmp/bin/nft"
chmod +x "$tmp/bin/nft"
PATH="$tmp/bin:$PATH"
export PATH

cat > "$tmp/spec.json" <<EOF
{
  "schema": 1,
  "lan_devices": ["tailscale0", "zt7bcxxxxx"],
  "outputs": {
    "loc": { "kind": "vless", "sub_file": "$tmp/sub.txt", "device": "lo" },
    "pool": { "kind": "interface", "devices": ["nodev0", "lo"], "on_fail": "drop" },
    "direct": { "kind": "direct" }
  },
  "channels": []
}
EOF

out="$($BIN status --spec "$tmp/spec.json" --state-dir "$tmp/state" 2>/dev/null)"

# ---- признак поколения ------------------------------------------------------
# Перечень умений печатается ВСЕГДА и верхним уровнем — то есть виден на роутере, где нет ни
# одного выхода kind=vless. До 1.3.0 признаком служило поле `nodes` у такого выхода, и там,
# где выхода подписки нет (xsteer плюс wireguard), узнать поколение было нечем — а именно там
# смешанный пул нужнее всего, и именно там старый движок молча уводит канал в blackhole.
check "перечень умений напечатан" "1" \
      "$(printf '%s' "$out" | grep -c '"features":\[')"
for f in lan_devices nodes pool active_device; do
    check "умение $f названо" "1" "$(printf '%s' "$out" | grep -c "\"$f\"")"
done
# schema остаётся единицей: перечень умений — не новая версия контракта, а рассказ о том, что
# внутри одной и той же. Сдвинуть здесь число значило бы, что всякий установленный
# управляющий слой немедленно объявит движок неподдерживаемым.
check "schema не тронута" "1" \
      "$(printf '%s' "$out" | sed -n 's/^{"schema":\([0-9]*\).*/\1/p')"

# ---- перечень устройств ------------------------------------------------------
# Устройства здесь нарочно отсутствующие: status рассказывает о ПРИМЕНЁННОМ, а не о том, что
# сейчас поднято, — присутствие проверяет diag. Заодно `lo` остаётся свободным под устройство
# выхода: выход в устройство из lan_devices — петля, и спека с ним отвергается загрузкой.
check "lan_devices отданы списком" "1" \
      "$(printf '%s' "$out" | grep -c '"lan_devices":\["tailscale0","zt7bcxxxxx"\]')"

# ---- выбранные узлы подписки -------------------------------------------------
# Печатается всегда, в том числе пустым списком: пустой `nodes` значит «первый рабочий среди
# всех пригодных», и отличить его от «поля нет» обязано быть можно.
check "nodes у выхода подписки печатаются пустыми" "1" \
      "$(printf '%s' "$out" | grep -c '"nodes":\[\]')"

# ---- устройство выхода: то, что несёт трафик СЕЙЧАС ---------------------------
# Сторож увёл пул на запасное устройство и записал это в active. Без чтения записи status
# отдавал первого кандидата — отсутствующий nodev0 с "up":false, то есть рисовал поломку на
# работающем выходе.
printf 'pool lo\n' > "$tmp/state/active"
outa="$($BIN status --spec "$tmp/spec.json" --state-dir "$tmp/state" 2>/dev/null)"
check "пул назван активным устройством" "1" \
      "$(printf '%s' "$outa" | grep -c '"pool":{"kind":"interface","device":"lo","up":true')"
check "список кандидатов при этом прежний" "1" \
      "$(printf '%s' "$outa" | grep -c '"devices":\["nodev0","lo"\]')"

printf '\n%d проверок пройдено' "$pass"
if [ "$fail" -gt 0 ]; then printf ', %d ПРОВАЛЕНО\n' "$fail"; exit 1; fi
printf '\nвсе проверки прошли\n'
